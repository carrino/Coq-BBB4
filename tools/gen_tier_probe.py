#!/usr/bin/env python3
"""Emit vm_compute probes asserting the census tiers catch machines
the Python sweeps caught (validation of the tier <-> sweep mirror).

Usage: gen_tier_probe.py OUT_V QHB_N LEX_N RW_N [SEED]

Samples QHB_N machines from qhbound_caught.tsv, LEX_N from
qhbound_lex_caught.tsv (try_qhb must return true) and RW_N from
repwl_residue_caught.tsv (try_rw must return true), using the census
ladders from Census/Run.v.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

DIRS = {'L': 'DL', 'R': 'DR'}


def tm_def(name, m):
    lines = [f"Definition {name} : TM := fun q s =>",
             "  match q, s with"]
    rows = m.split('_')
    for qi, part in enumerate(rows):
        for si in range(2):
            e = part[3 * si:3 * si + 3]
            pat = f"St{chr(65+qi)}, S{si}"
            if e == '---':
                lines.append(f"  | {pat} => None")
            else:
                lines.append(
                    f"  | {pat} => Some (mkTrans S{e[0]} {DIRS[e[1]]} "
                    f"St{e[2]})")
    lines.append("  end.")
    return "\n".join(lines)


def sample(path, n, rng, col=0, skip_header=True):
    rows = []
    with open(path) as f:
        if skip_header:
            next(f)
        for line in f:
            line = line.strip()
            if line:
                rows.append(line.split('\t')[col])
    return rng.sample(rows, min(n, len(rows)))


def main():
    out = sys.argv[1]
    qn, ln, rn = int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
    rng = random.Random(int(sys.argv[5]) if len(sys.argv) > 5 else 20260717)
    qhb = sample(os.path.join(HERE, "qhbound_caught.tsv"), qn, rng)
    lex = sample(os.path.join(HERE, "qhbound_lex_caught.tsv"), ln, rng)
    rw = []
    rwp = os.path.join(HERE, "repwl_residue_caught.tsv")
    if rn and os.path.exists(rwp):
        rw = sample(rwp, rn, rng)
    chunks = ["""(** Census tier <-> sweep mirror validation probe (generated by
    tools/gen_tier_probe.py; throwaway, not part of the build). *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import Decide RepWLSearch Run.
Import ListNotations.
"""]
    for tag, ms, expr in [
            ("qhb", qhb, "try_qhb 2000 200000 512 qhb_rungs_census"),
            ("qlx", lex, "try_qhb 2000 200000 512 qhb_rungs_census"),
            ("rw", rw, "try_rw rw_rungs_census rw_fuel_census")]:
        for i, m in enumerate(ms):
            name = f"tm_{tag}_{i:03d}"
            chunks.append(f"(* {m} *)")
            chunks.append(tm_def(name, m))
            chunks.append(
                f"Example chk_{tag}_{i:03d} : {expr} {name} = true.\n"
                f"Proof. vm_compute. reflexivity. Qed.\n")
    open(out, "w").write("\n".join(chunks) + "\n")
    print(f"wrote {out}: qhb={len(qhb)} lex={len(lex)} rw={len(rw)}")


if __name__ == "__main__":
    main()
