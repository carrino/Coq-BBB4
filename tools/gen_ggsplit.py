#!/usr/bin/env python3
"""Generate the great-grandchild split of the A0=1RB, B0=1LC census unit.

16 files theories/Census/Compute/GG_1LC_<w><d><nx>.v (one C1-fill each,
its own native queue walk) plus a replacement G_1RB_1LC.v that proves
the SAME lemma names as the monolithic version via Run_Split2's cover
lemma, so Census_Theorem.v is untouched.  The replacement is written to
G_1RB_1LC.v.split next to the original; install it only when retiring
the monolithic walk (they are interchangeable proofs of one statement).

Usage: gen_ggsplit.py OUTDIR [NITER]
"""
import sys, os

outdir = sys.argv[1]
niter = int(sys.argv[2]) if len(sys.argv) > 2 else 700
os.makedirs(outdir, exist_ok=True)

W = [('0', 'S0'), ('1', 'S1')]
D = [('L', 'DL'), ('R', 'DR')]
NX = [('A', 'StA'), ('B', 'StB'), ('C', 'StC'), ('D', 'StD')]

names = []
for w_t, w in W:
    for d_t, d in D:
        for nx_t, nx in NX:
            tag = f'{w_t}{d_t}{nx_t}'
            names.append((tag, w, d, nx))
            with open(os.path.join(outdir, f'GG_1LC_{tag}.v'), 'w') as f:
                f.write(f'''(** GENERATED by tools/gen_ggsplit.py -- do not edit.
    Census subtree: A0 = 1RB, B0 = 1LC, C1 = {w_t}{d_t}{nx_t}. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
From BBB4.Census Require Import Run_Split2.
Import ListNotations.

Lemma gg_{tag}_empty :
  Nat.iter {niter} q_suc (q_ggsub {w} {d} {nx}) = ([], []).
Proof.
  native_cast_no_check (eq_refl (@nil TNF_Node, @nil TNF_Node)).
Qed.

Lemma gg_{tag}_decided :
  NodeDecided B_census D_census (node_tm (ggchild {w} {d} {nx})).
Proof.
  exact (ggsub_decided {w} {d} {nx} {niter} eq_refl gg_{tag}_empty).
Qed.
''')

with open(os.path.join(outdir, 'G_1RB_1LC.v.split'), 'w') as f:
    f.write('''(** GENERATED by tools/gen_ggsplit.py -- do not edit.
    Census subtree: A0 = 1RB, B0 = 1LC -- assembled from the 16
    great-grandchild walks (GG_1LC_*.v) via Run_Split2, proving the
    same lemmas as the monolithic version of this file. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
From BBB4.Census Require Import Run_Split2.
''')
    for tag, *_ in names:
        f.write(f'From BBB4.Census.Compute Require Import GG_1LC_{tag}.\n')
    f.write('''Import ListNotations.

Lemma g_1RB_1LC_decided :
  NodeDecided B_census D_census (node_tm (gchild S1 S1 DL StC)).
Proof.
  apply gchild_from_ggchildren.
  intros w3 d3 nx3 Hok.
  destruct w3, d3, nx3;
    first
''')
    alts = []
    for tag, *_ in names:
        alts.append(f'exact gg_{tag}_decided')
    f.write('      [ ' + '\n      | '.join(alts) + ' ].\nQed.\n')
print(f'{len(names)} great-grandchild files + G_1RB_1LC.v.split')
