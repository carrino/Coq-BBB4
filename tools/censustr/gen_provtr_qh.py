#!/usr/bin/env python3
"""QH-side conveyor (UNTRUSTED bookkeeping around Checkers/WrapTr):
QHBoundTr certificates for quiet-instruction machines.

The in-walk tier (DecideTr [try_qhbtr]) pins the quiet instructions
at their last fires found within 16 x 1024 steps and tries the wrapped
n-gram closure at t <= 1024.  The deferred quiet machines mostly quiet
LATER than that, so this conveyor takes the exact last fires from a
long scan (scratch qh_scan.py: spec kind maxquiet nfired lf0..lf7,
lf = last fire per instruction (A,0),(A,1),...,(D,1); -1 = never) and
probes the same checker at t just past the last quiet fire.

  probe SCAN OUTDIR          -> OUTDIR/ProbeQH_NN.v (one Eval per (row, rung))
  stage SCAN PROBEDIR OUTDIR -> OUTDIR/ProvTr_QH_NN.v (pqh_NN + Forall)
Only rows the scan calls 'quiet' are probed.  A certificate is
(pins, n, t) with S t <= B_tr; the stage lemma is
  ngram_check_qhboundtr_sound tm pins n t FUEL ROUNDS  (+ qhboundtr_mono).
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_walk_shards import tm_lambda  # noqa: E402

FUEL = 200000
ROUNDS = 512
B_TR = 32779478
NS = (2, 3, 4)
TDELTAS = (1, 65, 1025)   # t = max quiet last fire + delta
KINDS = ('plain', 'lex')  # QHConveyorTr.qh_plain_at / qh_lex_at, plain first

HEADER = """From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.Checkers Require Import NGramTr WrapTr.
From BBB4.CensusTr Require Import TNF_QHTr QHConveyorTr.
Import ListNotations.
"""

STAGE_DOC = """(** GENERATED by tools/censustr/gen_provtr_qh.py -- DO NOT EDIT.

    Transition-level proven-QH stage QH {NN}: {CNT} quiet-instruction
    machines with a wrapped n-gram QHBoundTr certificate
    (Checkers/WrapTr [ngram_check_qhboundtr], plain or lex-gated via
    CensusTr/QHConveyorTr) at t < B_tr = 32779478
    (the literal, since B_tr lives in RunTr.v which imports the stages).
    Append [pqh_{NN}] to [provqh_tr] (CensusTr/RunTr.v). *)
"""

INSTRS = [(s, y) for s in 'ABCD' for y in (0, 1)]


def instr_term(i):
    return '(St%s, S%d)' % i


def rows(scanfile):
    """quiet rows: spec -> [(instr, lastfire)] for the quiet instructions, tmax."""
    out = []
    for l in open(scanfile):
        f = l.split()
        if len(f) < 12 or f[1] != 'quiet':
            continue
        sp = f[0]
        lf = [int(x) for x in f[4:12]]
        n = int(f[3])  # unused
        N2 = None
        # quiet = fired and last fire in the first half of the scan; the
        # scan's own verdict used N//2, recover it from maxquiet <= lf
        mx = int(f[2])
        quiet = [(INSTRS[k], lf[k]) for k in range(8) if 0 <= lf[k] <= mx]
        if not quiet or '---' in sp.replace('------', '') and False:
            continue
        out.append((sp, quiet, mx))
    return out


def probe(scanfile, outdir, chunk, start=0, ns=NS, tdeltas=TDELTAS, kinds=KINDS):
    os.makedirs(outdir, exist_ok=True)
    rs = rows(scanfile)
    n = start
    for ci in range(0, len(rs), chunk):
        with open(os.path.join(outdir, 'ProbeQH_%02d.v' % n), 'w') as f:
            f.write(HEADER)
            for i, (sp, quiet, mx) in enumerate(rs[ci:ci + chunk]):
                pins = '[' + '; '.join('(%s, %d)' % (instr_term(tg), s) for tg, s in quiet) + ']'
                f.write('(* %s  tmax=%d pins=%d *)\n%s\n' % (sp, mx, len(quiet), tm_lambda('tm_%d' % i, sp)))
                for kind in kinds:
                    for d in tdeltas:
                        t = mx + d
                        if t + 1 > B_TR:
                            continue
                        for nn in ns:
                            f.write('(* rung %s %s n=%d t=%d *)\nEval vm_compute in qh_%s_at tm_%d %s %d %d %d %d.\n'
                                    % (sp, kind, nn, t, kind, i, pins, nn, t, FUEL, ROUNDS))
                f.write('\n')
        n += 1
    sys.stderr.write('wrote %d probe file(s) (%d quiet rows) to %s\n' % (n - start, len(rs), outdir))


def read_verdicts(probedir):
    """spec -> (kind, n, t) of the first accepted rung, or None."""
    vs = {}
    for vf in glob.glob(os.path.join(probedir, 'ProbeQH_*.v')):
        rungs = re.findall(r'^\(\* rung ([0-9A-Z\-]{6}(?:_[0-9A-Z\-]{6}){3}) (plain|lex) n=(\d+) t=(\d+) \*\)', open(vf).read(), re.M)
        of = vf[:-2] + '.out'
        got = []
        if os.path.exists(of):
            got = [x == 'true' for x in re.findall(r'^\s*= (true|false)', open(of).read(), re.M)]
        for (sp, kind, nn, t), v in zip(rungs, got):
            vs.setdefault(sp, None)
            if v and vs[sp] is None:
                vs[sp] = (kind, int(nn), int(t))
    return vs


def stage(scanfile, probedir, outdir, chunk, start):
    rs = rows(scanfile)
    vs = read_verdicts(probedir)
    keep = [r for r in rs if vs.get(r[0])]
    os.makedirs(outdir, exist_ok=True)
    n = start
    man = []
    for ci in range(0, len(keep), chunk):
        nn = '%02d' % n
        cb = keep[ci:ci + chunk]
        names = []
        with open(os.path.join(outdir, 'ProvTr_QH_%s.v' % nn), 'w') as f:
            f.write(STAGE_DOC.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + HEADER + '\n')
            for sp, quiet, mx in cb:
                kind, w, t = vs[sp]
                nm = 'tm_' + sp.replace('---', 'XXX')
                pins = '[' + '; '.join('(%s, %d)' % (instr_term(tg), s) for tg, s in quiet) + ']'
                f.write('(* %s  %s n=%d t=%d *)\n%s\n' % (sp, kind, w, t, tm_lambda(nm, sp)))
                f.write('Lemma qhtr_%s : NonHalt %s /\\ QHBoundTr %d %s /\\ QuasiHaltsTr %s.\n'
                        'Proof.\n'
                        '  destruct (qh_%s_at_sound %s %s %d %d %d %d\n'
                        '              ltac:(vm_cast_no_check (eq_refl true))) as [Hnh [Hb Hq]].\n'
                        '  split; [exact Hnh | split; [exact (qh_bound_of %d %s %d ltac:(vm_cast_no_check (eq_refl true)) Hb) | exact Hq]].\n'
                        'Qed.\n\n'
                        % (nm[3:], nm, B_TR, nm, nm, kind, nm, pins, w, t, FUEL, ROUNDS, B_TR, nm, t))
                names.append(nm)
                man.append((sp, 'qhtr_%s' % nm[3:], 'ProvTr_QH_%s.v' % nn, '%s,%d,%d' % (kind, w, t)))
            f.write('Definition pqh_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join(names))
            f.write('].\n\n')
            term = '(Forall_nil _)'
            for x in reversed(names):
                term = '(Forall_cons _ qhtr_%s %s)' % (x[3:], term)
            f.write('Lemma pqh_%s_qhtr :\n  Forall (fun tm => NonHalt tm /\\ QHBoundTr %d tm /\\ QuasiHaltsTr tm) pqh_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, B_TR, nn, term))
        n += 1
    with open(os.path.join(outdir, 'provtr_qh_manifest.tsv'), 'w') as f:
        for r in man:
            f.write('\t'.join(r) + '\n')
    sys.stderr.write('staged %d machines into %d file(s) (of %d quiet rows; %d without a certificate)\n'
                     % (len(keep), n - start, len(rs), len(rs) - len(keep)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=None)
    ap.add_argument('--start', type=int, default=0)
    ap.add_argument('--ns', default=None, help='window ladder, e.g. 5,6 (default 2,3,4)')
    ap.add_argument('--tdeltas', default=None, help='t = tmax + delta ladder (default 1,65,1025)')
    ap.add_argument('--kinds', default=None, help='plain,lex (default both)')
    a = ap.parse_args()
    if a.phase == 'probe':
        probe(a.args[0], a.args[1], a.chunk or 10, a.start,
              tuple(int(x) for x in a.ns.split(',')) if a.ns else NS,
              tuple(int(x) for x in a.tdeltas.split(',')) if a.tdeltas else TDELTAS,
              tuple(a.kinds.split(',')) if a.kinds else KINDS)
    else:
        stage(a.args[0], a.args[1], a.args[2], a.chunk or 100, a.start)


if __name__ == '__main__':
    main()
