#!/usr/bin/env python3
"""Recheck the original instruction IRules certificates without state proofs.

Machine and certificate definitions are copied verbatim from the canonical
state boards. Every selected certificate still runs the instruction checker;
the state-level theorems are not premises of these proofs. The frozen row list
preserves the original 97 theorem names and order. RunTr's existing conversion
gate checks the complete machine list against the census computation data.
"""
import argparse
from pathlib import Path
import re

REPO = Path(__file__).resolve().parents[2]
MACHINES = REPO / 'theories/Machines'
ROWS = Path(__file__).with_name('irulestr_rows.txt')
CHUNK = 8
HEADER = '''From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement CTape.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta MetaTr.
Import ListNotations.
Open Scope Z_scope.
Local Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
'''


def read_rows(path=ROWS):
    rows = [s for s in path.read_text().splitlines() if s and not s.startswith('#')]
    if len(rows) != 97 or len(set(rows)) != 97:
        raise ValueError('expected the 97 unique original instruction certificates')
    if any(not re.fullmatch(r'(?:(?:[01][LR][ABCD]|XXX){2}_){3}(?:[01][LR][ABCD]|XXX){2}', s)
           for s in rows):
        raise ValueError('invalid instruction certificate name')
    return rows


def definitions(machines=MACHINES):
    found = {}
    for path in sorted(machines.glob('IRules_Batch_*.v')):
        for body, name, cert in re.findall(
                r'^(Definition tm_(\w+) : TM :=.*?\n  end\.\n)'
                r'\s*(Definition cert_\2 : IRCert :=.*?)(?=\nTheorem )',
                path.read_text(), re.M | re.S):
            if name in found:
                raise ValueError(f'duplicate source machine {name}')
            found[name] = body + '\n' + cert.rstrip() + '\n'
    return found


def theorem(sid, proof):
    return (f'Theorem irtr_{sid}_never_quasihalts_tr :\n'
            f'  NeverQuasiHaltsTr tm_{sid}.\nProof.\n{proof}\nQed.\n')


def render(rows=None, sources=None):
    rows = read_rows() if rows is None else rows
    sources = definitions() if sources is None else sources
    outputs, parts = {}, []
    for start in range(0, len(rows), CHUNK):
        part = f'IRulesTrPart_{start // CHUNK:02d}'
        parts.append(part)
        body = ['(** GENERATED by tools/censustr/gen_irulestr_parts.py.\n'
                '    Original certificate data, independently checked at instruction level. *)\n', HEADER]
        for sid in rows[start:start + CHUNK]:
            body.append(sources[sid])
            body.append(theorem(sid,
                f'  apply (irules_check_neverqhtr_sound tm_{sid} cert_{sid} 300000%nat).\n'
                '  native_cast_no_check (eq_refl true).'))
        outputs[MACHINES / 'IRulesTrParts' / f'{part}.v'] = '\n'.join(body)
    wrapper = [
        '(** GENERATED by tools/censustr/gen_irulestr_parts.py.\n'
        '    All 97 original instruction proofs, with their original public names.\n'
        '    State-level proofs are not prerequisites of instruction certification. *)',
        'From BBB4 Require Import BBBT4_Statement.',
        'From BBB4.Machines.IRulesTrParts Require Export ' + ' '.join(parts) + '.\n']
    for i, sid in enumerate(rows):
        wrapper.append(theorem(sid,
            f'  exact {parts[i // CHUNK]}.irtr_{sid}_never_quasihalts_tr.'))
    outputs[MACHINES / 'IRulesTr_Batch_01.v'] = '\n'.join(wrapper)
    return outputs


def generate(check=False):
    outputs = render()
    project = REPO / '_CoqProject'
    old = project.read_text().splitlines()
    part_paths = sorted(str(p.relative_to(REPO)) for p in outputs if p.parent.name == 'IRulesTrParts')
    keep = [p for p in old if not p.startswith('theories/Machines/IRulesTrParts/')]
    pos = keep.index('theories/Machines/IRulesTr_Batch_01.v')
    outputs[project] = '\n'.join(keep[:pos] + part_paths + keep[pos:]) + '\n'
    stale = set((MACHINES / 'IRulesTrParts').glob('*.v')) - outputs.keys()
    if stale:
        raise ValueError(f'unexpected parts: {sorted(stale)}')
    changed = [p for p, source in outputs.items() if not p.exists() or p.read_text() != source]
    if check and changed:
        raise ValueError(f'stale generated files: {changed}')
    if not check:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path])
    print(f'97 instruction certificates, 13 parts; {"checked" if check else "wrote"} {len(outputs)} files')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
