#!/usr/bin/env python3
"""Generate the kernel-checked re-walk units for the transition-level
census theorem (UNTRUSTED tooling -- the units are what the kernel
checks; this only writes them down).

The theorem is CensusTr/RunTr_Split.v's [census_tr_of_units]: N unit
facts [unit_ok N i 0 frontier_nodes_tr = true], one per residue class
of frontier-node index modulo N, each a single native computation that
walks every node of its class to an empty queue under [decider_tr]
with the frozen deferred list.  This emits

    theories/CensusTr/Compute/UnitTr_XX.v       (XX in 00..N-1)
    theories/CensusTr/Compute/Census_TheoremTr.v (the assembler)

Round-robin by index is the collection walk's own dealing
(gen_walk_shards.py), so unit costs track the measured shard costs.
Iterating past exhaustion is a no-op, so ITER_TR is a budget, not a
count.

Usage: gen_walk_units.py [--units N] [--outdir DIR] [--cast native|vm]
       (default 96 units, theories/CensusTr/Compute, native_cast_no_check;
        --cast vm is for an in-container smoke test of ONE cheap unit)
"""
import argparse
import os

HEADER = """(** GENERATED by tools/censustr/gen_walk_units.py -- do not edit.
    Re-walk unit {i} of {n}: every level-{lv} frontier node with index
    = {i} (mod {n}) walks to an empty queue under [decider_tr] with the
    frozen deferred list. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH.
From BBB4.CensusTr Require Import RunTr RunTr_Split.

Lemma unit_tr_{i:02d} : unit_ok {n} {i} 0 frontier_nodes_tr = true.
Proof.
  {cast} (eq_refl true).
Qed.
"""

ASM_HEAD = """(** GENERATED by tools/censustr/gen_walk_units.py -- do not edit.

    The transition-level census theorem, assembled from the {n}
    re-walk units (UnitTr_XX.v) through [census_tr_of_units]. *)
From Coq Require Import Arith Lia List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.Census Require Import TNF_QH.
From BBB4.CensusTr Require Import TNF_QHTr RunTr RunTr_Split.
"""

ASM_BODY = """
Theorem census_tr : forall tm, QHBoundTr B_tr tm \\/ Deferred D_tr tm.
Proof.
  apply (census_tr_of_units {n}); [lia |].
  intros i Hi.
{destructs}  exfalso; lia.
Qed.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--units', type=int, default=96)
    ap.add_argument('--outdir', default='theories/CensusTr/Compute')
    ap.add_argument('--cast', choices=['native', 'vm'], default='native')
    ap.add_argument('--levels', type=int, default=3,
                    help='documentation only: FRONTIER_LEVELS_TR')
    args = ap.parse_args()
    n = args.units
    cast = ('native_cast_no_check' if args.cast == 'native'
            else 'vm_cast_no_check')
    os.makedirs(args.outdir, exist_ok=True)
    for i in range(n):
        with open(os.path.join(args.outdir, f'UnitTr_{i:02d}.v'), 'w') as f:
            f.write(HEADER.format(i=i, n=n, lv=args.levels, cast=cast))
    with open(os.path.join(args.outdir, 'Census_TheoremTr.v'), 'w') as f:
        f.write(ASM_HEAD.format(n=n))
        for i in range(n):
            f.write(f'From BBB4.CensusTr.Compute Require Import UnitTr_{i:02d}.\n')
        destructs = ''.join(
            f'  destruct i as [|i]; [exact unit_tr_{i:02d} |].\n'
            for i in range(n))
        f.write(ASM_BODY.format(n=n, destructs=destructs))
    print(f'wrote {n} units + Census_TheoremTr.v to {args.outdir} ({cast})')


if __name__ == '__main__':
    main()
