#!/usr/bin/env python3
"""Transcribe harness irules certificates (v3/v5/v6/v7, BBB bin/irules
--cert-dir output) into TRANSITION-LEVEL proven-tier stage batches.

The Tr fork of tools/gen_irulesnqh_stage.py.  Same BIRCertP transcription
(gen_irulesblkpfx_certs.py's parser/emitters, reused by import); the
theorem is closed by the LANDED [irulesblkpfx_check_neverqhtr_sound]
(Checkers/IRules/MetaBlkPfxTr.v) and states [NeverQuasiHaltsTr].

Two phases, because the Tr prefix gate is STRICTLY stronger than the
state one and a certificate that passes MetaBlkPfx can fail here (the
machine is then a transition-QUASIHALTER -- a verdict flip, not an
error), and one failing Lemma would sink a whole stage file:

  --probe  OUTDIR CERT...      emit Probe_NN.v files that vm_compute the
                               checker for every cert (one Eval per cert,
                               in cert order) -- run them, then
  --stage  OUTDIR MANIFEST.tsv CHUNK --verdicts PROBE.out... CERT...
                               emit PTS_NN.v stage files for the certs
                               whose probe verdict was [true], plus the
                               manifest (machine, theorem, file, anchor,
                               cert_ver, verdict).

Each stage file defines [pts_NN : list TM] and
[pts_NN_nqhtr : Forall NeverQuasiHaltsTr pts_NN], ready to append to
[prov_tr] (CensusTr/RunTr.v) with [Forall_app].  UNTRUSTED like every
emitter: a wrong cert makes the kernel say false, never a wrong theorem.

Usage
  gen_irulesnqhtr_stage.py --probe OUTDIR [--per N] CERT...
  gen_irulesnqhtr_stage.py --stage OUTDIR MANIFEST CHUNK --verdicts OUT... -- CERT...
"""
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location(
    "genbp", os.path.join(HERE, "..", "gen_irulesblkpfx_certs.py"))
G = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(G)

CFUEL = 200000
FUEL = 300000

IMPORTS = '''From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement CTape.
From BBB4.Checkers Require Import Cycle.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
     EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx MetaBlkPfxTr.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
'''

HEADER = '''(** GENERATED by tools/censustr/gen_irulesnqhtr_stage.py -- DO NOT EDIT.

    Transition-level proven-tier stage, chunk {NN} ({CNT} machines):
    harness irules certificates (UNTRUSTED search output) re-checked by
    the verified [irulesblkpfx_check_neverqhtr_sound]
    (Checkers/IRules/MetaBlkPfxTr.v) + [vm_compute].  Each machine gets
    [NeverQuasiHaltsTr]; append [pts_{NN}] to [prov_tr]
    (CensusTr/RunTr.v). *)

''' + IMPORTS

PROBE_HEADER = '''(** GENERATED probe -- untrusted measurement: one verdict per cert. *)
''' + IMPORTS


def tm_and_cert(path, nm):
    c = G.parse_cert(path)
    m = c["machine"]
    a, b = c["meta_a"], c["meta_b"]
    s = []
    s.append("(* %s : anchor %d, ver %s *)"
             % (m, c["anchor_step"], c.get("ver", "?")))
    s.append("Definition tm_%s : TM := fun q s =>" % nm)
    s.append("  match q, s with")
    s.append(G.emit_tm(m))
    s.append("  end.")
    s.append("Definition cert_%s : BIRCertP := mkBIRCertP" % nm)
    s.append("  %d%%nat (%d) (%d) (%d) (%d) %s S%d"
             % (c["anchor_step"], c["k0"], c["kmin"], a, b,
                G.ST[c["tpl_state"]], c["tpl_hsym"]))
    s.append("  %s" % G.emit_blks(c["blk"]))
    s.append("  %s" % G.emit_tpl(c["tplL"]))
    s.append("  %s" % G.emit_tpl(c["tplR"]))
    s.append("  %s." % G.emit_rules(c["rules"], c["pfx"]))
    return "\n".join(s), c


def probe(outdir, certs, per):
    os.makedirs(outdir, exist_ok=True)
    nfiles = 0
    for ci in range(0, len(certs), per):
        chunk = certs[ci:ci + per]
        nn = "%02d" % nfiles
        with open(os.path.join(outdir, "Probe_%s.v" % nn), "w") as f, \
                open(os.path.join(outdir, "Probe_%s.names" % nn), "w") as g:
            f.write(PROBE_HEADER + "\n")
            for k, p in enumerate(chunk):
                nm = "p%02d_%04d" % (nfiles, k)
                body, c = tm_and_cert(p, nm)
                f.write(body + "\n")
                f.write("Eval vm_compute in irulesblkpfx_check_neverqhtr "
                        "tm_%s cert_%s %d %d.\n\n" % (nm, nm, CFUEL, FUEL))
                g.write("%s\t%s\n" % (p, c["machine"]))
        nfiles += 1
    sys.stderr.write("wrote %d probe file(s) for %d certs to %s\n"
                     % (nfiles, len(certs), outdir))


def read_verdicts(outs):
    """probe .out files -> list of booleans in Eval order."""
    vs = []
    for o in outs:
        t = open(o).read()
        vs += [x == "true" for x in re.findall(r"^\s*= (true|false)", t, re.M)]
    return vs


def stage(outdir, manifest, chunk, certs, verdicts):
    if len(verdicts) != len(certs):
        sys.exit("verdict count %d != cert count %d" % (len(verdicts), len(certs)))
    os.makedirs(outdir, exist_ok=True)
    keep = [p for p, v in zip(certs, verdicts) if v]
    flips = [p for p, v in zip(certs, verdicts) if not v]
    blocks, names, metas = [], [], []
    for idx, p in enumerate(keep):
        nm = "t3_%05d" % idx
        body, c = tm_and_cert(p, nm)
        body += ("\nLemma nqhtr_%s : NeverQuasiHaltsTr tm_%s.\n"
                 "Proof.\n  apply (irulesblkpfx_check_neverqhtr_sound tm_%s cert_%s "
                 "%d %d).\n  vm_compute. reflexivity.\nQed." % (nm, nm, nm, nm, CFUEL, FUEL))
        blocks.append(body)
        names.append(nm)
        metas.append((c["machine"], c["anchor_step"], c.get("ver", "?")))
    rows = []
    nfiles = 0
    for ci in range(0, len(blocks), chunk):
        nn = "%02d" % nfiles
        cb, cn = blocks[ci:ci + chunk], names[ci:ci + chunk]
        with open(os.path.join(outdir, "PTS_%s.v" % nn), "w") as f:
            f.write(HEADER.replace("{NN}", nn).replace("{CNT}", str(len(cb))) + "\n")
            f.write("\n\n".join(cb) + "\n\n")
            f.write("Definition pts_%s : list TM :=\n  [" % nn)
            f.write(";\n   ".join("tm_%s" % n for n in cn))
            f.write("].\n\n")
            f.write("Lemma pts_%s_nqhtr : Forall NeverQuasiHaltsTr pts_%s.\n" % (nn, nn))
            term = "(Forall_nil NeverQuasiHaltsTr)"
            for n in reversed(cn):
                term = "(Forall_cons _ nqhtr_%s %s)" % (n, term)
            f.write("Proof. exact %s. Qed.\n" % term)
        for k in range(ci, min(ci + chunk, len(blocks))):
            m, anc, ver = metas[k]
            rows.append((m, "nqhtr_%s" % names[k], "PTS_%s.v" % nn, str(anc), ver, "true"))
        nfiles += 1
    with open(manifest, "w") as f:
        f.write("machine\ttheorem\tfile\tanchor\tcert_ver\tverdict\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
        for p in flips:
            c = G.parse_cert(p)
            f.write("\t".join((c["machine"], "-", "-", str(c["anchor_step"]),
                               c.get("ver", "?"), "false")) + "\n")
    sys.stderr.write("staged %d machines into %d file(s); %d certs fail the Tr gate "
                     "(transition-quasihalters or too little fuel)\n"
                     % (len(names), nfiles, len(flips)))


def main():
    a = sys.argv[1:]
    if a and a[0] == "--probe":
        per = 50
        rest = a[1:]
        if "--per" in rest:
            i = rest.index("--per"); per = int(rest[i + 1]); del rest[i:i + 2]
        probe(rest[0], rest[1:], per)
    elif a and a[0] == "--stage":
        outdir, manifest, chunk = a[1], a[2], int(a[3])
        rest = a[4:]
        assert rest[0] == "--verdicts", "expected --verdicts OUT... -- CERT..."
        sep = rest.index("--")
        outs, certs = rest[1:sep], rest[sep + 1:]
        stage(outdir, manifest, chunk, certs, read_verdicts(outs))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
