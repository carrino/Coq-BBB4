#!/usr/bin/env python3
"""Bundle existing instruction lap proofs without changing their bodies.

Require commands are lifted out of each board's module and replaced in
place by Import commands. All other source bytes remain unchanged. This
keeps local notations isolated and avoids Require's fragile module scope.
Stage and closeout import adapters preserve the original board names.

Run this generator, then tools/closeouttr/gen_closeout_tr.py. --check
checks bundles and census stages; the closeout generator checks its own
batch import adapters. Original individual board sources stay canonical.
"""
import argparse
from pathlib import Path
import re

REPO = Path(__file__).resolve().parents[2]
BOARDS = REPO/'theories/Machines/CountersTr'
BUNDLES = BOARDS/'Bundles'
REQUIRE = re.compile(r'^From ([\w.]+) Require Import ([\w.\s]+?)\.[ \t]*$', re.M)
BOARD_REQUIRE = re.compile(
    r'^From BBB4\.Machines\.CountersTr Require (Import )?([\w \t\n]+)\.[ \t]*$', re.M)
ADAPTER = re.compile(
    r'^\(\* LAP BUNDLE IMPORT: (From BBB4\.Machines\.CountersTr Require [^*]+) \*\)\n'
    r'.*?^\(\* END LAP BUNDLE IMPORT \*\)', re.M | re.S)


def original_imports(text):
    """Recover only the import statements recorded by our adapters."""
    return ADAPTER.sub(lambda m: m[1], text)


def staged_boards(text):
    return {name for m in BOARD_REQUIRE.finditer(original_imports(text))
            for name in m[2].split() if name.startswith(('LAPT_', 'LAPQ_'))}


def groups(boards=BOARDS, chunk=100):
    if chunk < 1:
        raise ValueError('bundle size must be positive')
    result = {}
    for prefix in ['LAPT', 'LAPQ']:
        paths = sorted(Path(boards).glob(prefix+'_*.v'))
        for start in range(0, len(paths), chunk):
            name = f'Bundle{prefix}_{start//chunk:03d}'
            result[name] = paths[start:start+chunk]
    return result


def bundle_map(boards=BOARDS, chunk=100):
    return {p.stem: name for name, paths in groups(boards, chunk).items() for p in paths}


def read_bundle_map(boards=BOARDS):
    path = Path(boards)/'Bundles/boards.tsv'
    if not path.exists():
        return {}
    mapping = {}
    for line in path.read_text().splitlines():
        board, bundle = line.split('\t')
        if board in mapping or not re.fullmatch(r'LAP[QT]_\w+', board) or not re.fullmatch(r'BundleLAP[QT]_\d{3}', bundle):
            raise ValueError(f'invalid bundle inventory: {line}')
        mapping[board] = bundle
    return mapping


def render_bundle(paths):
    requires, bodies = [], []
    for path in paths:
        source = path.read_text()
        matches = list(REQUIRE.finditer(source))
        if not matches:
            raise ValueError(f'no board prerequisites: {path}')
        for match in matches:
            statement = f'From {match[1]} Require {" ".join(match[2].split())}.'
            if statement not in requires:
                requires.append(statement)
        body = REQUIRE.sub(lambda m: f'Import {m[2]}.', source)
        if re.search(r'^Require\b|^From .*Require\b', body, re.M):
            raise ValueError(f'unhandled Require in {path}')
        bodies.append(f'Module {path.stem}.\n{body}\nEnd {path.stem}.\n')
    return ('(** GENERATED by tools/censustr/gen_lap_bundles.py -- DO NOT EDIT.\n'
            '    Original board bodies, rechecked in isolated modules. *)\n' +
            '\n'.join(requires) + '\n\n' + '\n'.join(bodies))


def rewrite_imports(text, mapping):
    text = original_imports(text)
    seen_bundles = set()
    def adapt(match):
        names = match[2].split()
        if not any(name in mapping for name in names):
            return match[0]
        lines = [f'(* LAP BUNDLE IMPORT: {match[0]} *)']
        for name in names:
            if name not in mapping:
                lines.append(f'From BBB4.Machines.CountersTr Require {match[1] or ""}{name}.')
                continue
            bundle = mapping[name]
            if bundle not in seen_bundles:
                # Import the bundle's module names, not each board's contents.
                # Module aliases would duplicate native code in every consumer.
                lines.append(f'From BBB4.Machines.CountersTr.Bundles Require Import {bundle}.')
                seen_bundles.add(bundle)
            if match[1]:
                lines.append(f'Import {name}.')
        lines.append('(* END LAP BUNDLE IMPORT *)')
        return '\n'.join(lines)
    return BOARD_REQUIRE.sub(adapt, text)


def generate(boards=BOARDS, stages=REPO/'theories/CensusTr', chunk=100,
             check=False, project=REPO/'_CoqProject'):
    boards, stages = Path(boards), Path(stages)
    grouped = groups(boards, chunk)
    mapping = {p.stem: name for name, paths in grouped.items() for p in paths}
    outputs = {boards/'Bundles'/f'{name}.v': render_bundle(paths)
               for name, paths in grouped.items()}
    expected = set(outputs)
    stale = set((boards/'Bundles').glob('BundleLAP[QT]_*.v')) - expected
    if stale:
        raise ValueError('unexpected old bundles: '+', '.join(map(str, sorted(stale))))
    outputs[boards/'Bundles/boards.tsv'] = ''.join(
        f'{board}\t{bundle}\n' for board, bundle in sorted(mapping.items()))
    for path in sorted(stages.glob('ProvTr_*.v')):
        source = path.read_text()
        if staged_boards(source):
            outputs[path] = rewrite_imports(source, mapping)
    if project is not None:
        project = Path(project)
        source = project.read_text()
        have = set(source.splitlines())
        names = sorted(str(p.relative_to(REPO)) for p in expected)
        outputs[project] = source + ''.join(name+'\n' for name in names if name not in have)
    changed = [p for p, source in outputs.items() if not p.exists() or p.read_text() != source]
    if check and changed:
        raise ValueError('stale generated files: '+', '.join(map(str, changed)))
    if not check:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path])
    print(f'{len(mapping)} boards, {len(grouped)} bundles; '
          f'{"checked" if check else "wrote"} {len(outputs) if check else len(changed)} files')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--boards', type=Path, default=BOARDS)
    ap.add_argument('--stages', type=Path, default=REPO/'theories/CensusTr')
    ap.add_argument('--chunk', type=int, default=100)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--no-coqproject', action='store_true')
    args = ap.parse_args()
    generate(args.boards, args.stages, args.chunk, args.check,
             None if args.no_coqproject else REPO/'_CoqProject')


if __name__ == '__main__':
    main()
