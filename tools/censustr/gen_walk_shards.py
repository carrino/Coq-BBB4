#!/usr/bin/env python3
"""Partition a frontier-split prefix walk into parallel shard drivers.

UNTRUSTED tooling: reads `make census-tr-frontier` output
(census_probes/censustr_frontier.out), decodes the FRONT queue's
(machine, pointer) pairs, and deals the pending TNF nodes round-robin
into N generated shard drivers

    census_probes/WalkTr_Par_XX.v

each of which walks its slice to exhaustion and serializes its back
queue exactly like WalkTr_Collect.v.  The prefix's own back queue is
copied to census_probes/censustr_prefix_back.out so the final decode
is just a cat over prefix + shards.  Deferral is a per-machine
decision, so the union of back queues equals the single walk's.

A wrong shard file cannot corrupt the census: the deferred list is
collection-mode bookkeeping, re-verified by the eventual re-walk.

Usage: gen_walk_shards.py FRONTIER_OUT [--shards N] [--outdir DIR]
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from decode_enc import decode  # noqa: E402

PTR = {0: 'None', 1: '(Some StA)', 2: '(Some StB)',
       3: '(Some StC)', 4: '(Some StD)'}


def tm_lambda(name, text):
    rows = text.split('_')
    lines = [f'Definition {name} : TM := fun q s =>', '  match q, s with']
    for si, row in enumerate(rows):
        st = 'ABCD'[si]
        for xi in (0, 1):
            cell = row[3 * xi:3 * xi + 3]
            if cell == '---':
                lines.append(f'  | St{st}, S{xi} => None')
            else:
                w, d, nx = cell[0], cell[1], cell[2]
                lines.append(
                    f'  | St{st}, S{xi} => Some (mkTrans S{w} D{d} St{nx})')
    lines.append('  end.')
    return '\n'.join(lines)


HEADER = """(* GENERATED by tools/censustr/gen_walk_shards.py -- do not edit. *)
From Coq Require Import Arith List NArith.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH.
From BBB4.CensusTr Require Import RunTr.
Import ListNotations.

Set Printing Depth 100000000.
Set Printing Width 250.

"""

FOOTER = """
Time Definition walk_tr_out : (nat * nat) * list N :=
  Eval vm_compute in
    let q := Nat.iter 4096 q_suc_tr shard_q in
    (queue_sizes q, queue_encs q).

Compute (fst walk_tr_out).

Compute (snd walk_tr_out).
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('frontier_out')
    ap.add_argument('--shards', type=int, default=16)
    ap.add_argument('--outdir', default='census_probes')
    args = ap.parse_args()

    text = open(args.frontier_out).read()
    # the three Computes are typed: nat * nat, list (N * N), list N.
    mfront = re.search(r'(=.*?):\s*list \(N \* N\)', text, re.S)
    if not mfront:
        sys.exit('no `list (N * N)` block found -- is this a frontier .out?')
    pairs = [(int(a), int(b)) for a, b in
             re.findall(r'\((\d+)%N,\s*(\d+)%N\)', mfront.group(1))]
    if not pairs:
        sys.exit('frontier is empty -- FRONTIER_ITERS too big (walk done)?')
    mback = re.search(r'=(.*?):\s*list N', text[mfront.end():], re.S)
    back = re.findall(r'(\d+)%N', mback.group(1)) if mback else []

    os.makedirs(args.outdir, exist_ok=True)
    with open(os.path.join(args.outdir, 'censustr_prefix_back.out'), 'w') as f:
        f.write('\n'.join(f'{c}%N' for c in back) + '\n')

    nsh = min(args.shards, len(pairs))
    shards = [[] for _ in range(nsh)]
    for i, p in enumerate(pairs):
        shards[i % nsh].append(p)

    for si, nodes in enumerate(shards):
        parts = [HEADER]
        elems = []
        for ni, (code, ptr) in enumerate(nodes):
            name = f'ntm_{ni}'
            parts.append(tm_lambda(name, decode(code)) + '\n')
            elems.append(f'mkNode {name} {PTR[ptr]}')
        parts.append('\nDefinition shard_q : SearchQueue :=\n  ([' +
                     ';\n    '.join(elems) + '], []).\n')
        parts.append(FOOTER)
        path = os.path.join(args.outdir, f'WalkTr_Par_{si:02d}.v')
        with open(path, 'w') as f:
            f.write(''.join(parts))

    print(f'frontier: {len(pairs)} pending nodes, '
          f'{len(back)} already-deferred (prefix back)')
    print(f'wrote {nsh} shard drivers to {args.outdir}/WalkTr_Par_XX.v')


if __name__ == '__main__':
    main()
