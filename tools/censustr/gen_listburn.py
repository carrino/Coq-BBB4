#!/usr/bin/env python3
"""Shard a deferred-machine list into standalone list-burn units.

UNTRUSTED tooling: emits census_probes/listburn/ListBurn_XX.v files,
each running a REAL census decider (CensusTr/RunTr.v [decider_tr],
or [decider_tr_deep] with --deep: the same tiers and the same contract
at the same bound, with the fuel/windows the walk cannot afford)
over its slice of machines and printing one verdict tag per machine.
Burning the list directly skips all TNF/queue overhead and shards
perfectly (the tree walk has only two non-trivial subtrees), so a
16-core box sweeps the whole list in one sitting.  Verdicts:

  0 halt  1 neverqh  2 qh  3 leaf  4 deferred-lookup  5 UNKNOWN

Tag 5 machines are the survivors -- the next burn-down list.  Collect
with tools/censustr/collect_listburn.py.

Usage: gen_listburn.py LIST [--shards N] [--outdir DIR]
"""

import argparse
import os
import sys

SUB = 400  # machines per sublist definition (parser depth)

HEADER = """(* generated by tools/censustr/gen_listburn.py -- do not edit *)
From Coq Require Import Arith List NArith.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.Census Require Import TNF_QH.
From BBB4.CensusTr Require Import DecideTr RunTr.
Import ListNotations.

Set Printing Depth 100000000.
Set Printing Width 250.

Definition tag (r : QHResult) : nat :=
  match r with
  | R_Halt _ _ => 0
  | R_NeverQH => 1
  | R_QH => 2
  | R_Leaf => 3
  | R_Deferred => 4
  | R_Unknown => 5
  end.

"""


def tm_term(text):
    rows = text.split("_")
    arms = []
    for si, row in enumerate(rows):
        st = "ABCD"[si]
        for xi in (0, 1):
            cell = row[3 * xi : 3 * xi + 3]
            if cell == "---":
                arms.append(f"  | St{st}, S{xi} => None")
            else:
                w, d, nx = cell[0], cell[1], cell[2]
                arms.append(
                    f"  | St{st}, S{xi} => Some (mkTrans S{w} D{d} St{nx})"
                )
    body = "\n".join(arms)
    return f"fun q s =>\n  match q, s with\n{body}\n  end"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("list")
    ap.add_argument("--shards", type=int, default=16)
    ap.add_argument("--outdir", default="census_probes/listburn")
    ap.add_argument("--deep", action="store_true",
                    help="burn with RunTr's ESCALATED decider_tr_deep "
                         "(wider windows, 5x loop gas, 5x n-gram fuel, "
                         "8x RepWL fuel) instead of the walk decider -- "
                         "same tiers, same contract, same B_tr; the walk's "
                         "ladders are trimmed for WALK cost, which a "
                         "per-machine parallel burn does not pay")
    args = ap.parse_args()
    dec = "decider_tr_deep" if args.deep else "decider_tr"

    machines = [
        l.strip()
        for l in open(args.list)
        if l.strip() and not l.startswith("#")
    ]
    n = len(machines)
    os.makedirs(args.outdir, exist_ok=True)

    per = (n + args.shards - 1) // args.shards
    for s in range(args.shards):
        chunk = machines[s * per : (s + 1) * per]
        if not chunk:
            continue
        name = f"ListBurn_{s:02d}"
        parts = [HEADER]
        for i, m in enumerate(chunk):
            parts.append(f"Definition m_{i} : TM := {tm_term(m)}.\n")
        subs = []
        for j in range(0, len(chunk), SUB):
            refs = "; ".join(f"m_{k}" for k in range(j, min(j + SUB, len(chunk))))
            parts.append(f"Definition ms_{j // SUB} : list TM := [{refs}].\n")
            subs.append(f"ms_{j // SUB}")
        # One Eval + Compute PER SUBLIST, not one over the whole shard.
        # A shard is hours of vm_compute; a single atomic Eval loses all
        # of it to one kill (measured: a 400-machine deep burn died at
        # 244 CPU-min with no output).  Chunked, a kill costs at most
        # one sublist and the finished ones have already printed.
        for j, sub in enumerate(subs):
            parts.append(
                f"Time Definition burn_{j} : list nat :=\n"
                f"  Eval vm_compute in (map (fun tm => tag ({dec} tm)) {sub}).\n"
                f"Compute burn_{j}.\n\n"
            )
        path = os.path.join(args.outdir, name + ".v")
        with open(path, "w") as f:
            f.write("".join(parts))
        # the machine list, for the collector to zip verdicts against
        with open(os.path.join(args.outdir, name + ".machines"), "w") as f:
            f.write("\n".join(chunk) + "\n")
    print(f"{n} machines -> {args.shards} shards of <= {per} in {args.outdir}")


if __name__ == "__main__":
    main()
