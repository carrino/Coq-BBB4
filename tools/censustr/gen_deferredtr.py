#!/usr/bin/env python3
"""Generate the transition-level deferred tables (UNTRUSTED tooling).

Reads a collection-walk output -- either the decoded machine-text list
(one bbchallenge text per line, e.g. censustr_deferred_v0.txt) or the
raw `make census-tr-collect` stdout (auto-detected: the `: list N`
Compute block is decoded via decode_enc) -- and emits

    theories/CensusTr/DeferredTr_XX.v      compact machine rows
    theories/CensusTr/DeferredTr_Data.v    their concatenation, D_censusTr

mirroring tools/gen_deferred.py / theories/Census/Deferred_*.v exactly:
the Coq side gives the rows meaning through Census/Deferred_Defs.v's
[row_to_tm]; nothing here is trusted.  A wrong list only changes WHICH
machines the walk defers, and the queue-empty check fails if the list
is too small.

NOTE (v0 flow, SCOPING_INSTR.md section 5): freezing the raw ~400K-row
collection back queue is a MEASUREMENT artifact, not necessarily the
final freeze -- the intended path re-walks after the phase-3 tier ports
shrink it.  This emitter scales to either size.

Usage: gen_deferredtr.py INPUT [OUTDIR]     (OUTDIR default theories/CensusTr)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from decode_enc import decode, extract_codes  # noqa: E402


def slot_name(e):
    if e == '---':
        return 'tN'
    w, d, nx = e[0], e[1], e[2]
    return f't{w}{d}{nx}'


def machine_row(text):
    parts = text.split('_')
    assert len(parts) == 4, text
    names = []
    for p in parts:
        assert len(p) == 6, text
        names.append(slot_name(p[0:3]))
        names.append(slot_name(p[3:6]))
    return '[' + ';'.join(names) + ']'


def read_machines(path):
    text = open(path).read()
    if ': list N' in text or '%N' in text:
        return [decode(c) for c in extract_codes(text)]
    machines = []
    for line in text.splitlines():
        s = line.strip()
        if s and not s.startswith('#'):
            machines.append(s)
    return machines


ROWS_PER_FILE = 8000   # keeps each shard a fast, parse-friendly compile
SUB = 500              # rows per Definition: big literals choke the parser


def main():
    inp = sys.argv[1]
    outdir = sys.argv[2] if len(sys.argv) > 2 else 'theories/CensusTr'
    machines = read_machines(inp)
    seen = set()
    uniq = []
    for m in machines:
        if m not in seen:
            seen.add(m)
            uniq.append(m)
    uniq.sort()
    nfiles = (len(uniq) + ROWS_PER_FILE - 1) // ROWS_PER_FILE
    chunk_names = []
    for ci in range(nfiles):
        chunk = uniq[ci * ROWS_PER_FILE:(ci + 1) * ROWS_PER_FILE]
        name = f'DeferredTr_{ci:02d}'
        chunk_names.append(name)
        with open(os.path.join(outdir, name + '.v'), 'w') as f:
            f.write('(** GENERATED by tools/censustr/gen_deferredtr.py'
                    ' -- do not edit. *)\n')
            f.write('From Coq Require Import List.\n')
            f.write('From BBB4 Require Import BBB4_Statement.\n')
            f.write('From BBB4.Census Require Import Deferred_Defs.\n')
            f.write('Import ListNotations.\n')
            subs = []
            for si in range(0, len(chunk), SUB):
                sub = chunk[si:si + SUB]
                sname = f'rows_tr_{ci:02d}_{si // SUB:03d}'
                subs.append(sname)
                f.write(f'\nDefinition {sname} :'
                        ' list (list (option Trans)) := [\n')
                f.write(';\n'.join(machine_row(m) for m in sub))
                f.write('\n].\n')
            f.write(f'\nDefinition rows_tr_{ci:02d} :'
                    ' list (list (option Trans)) :=\n')
            f.write('  concat [' + ';'.join(subs) + '].\n')
    with open(os.path.join(outdir, 'DeferredTr_Data.v'), 'w') as f:
        f.write('(** GENERATED by tools/censustr/gen_deferredtr.py'
                ' -- do not edit.\n\n'
                '    The transition-level census deferred list'
                f' ({len(uniq)} machines). *)\n')
        f.write('From Coq Require Import List.\n')
        f.write('From BBB4 Require Import BBB4_Statement.\n')
        f.write('From BBB4.Census Require Import Deferred_Defs.\n')
        f.write('From BBB4.CensusTr Require Import '
                + ' '.join(chunk_names) + '.\n')
        f.write('Import ListNotations.\n\n')
        f.write('Definition deferred_tr_rows :'
                ' list (list (option Trans)) :=\n  '
                + ' ++ '.join(f'rows_tr_{ci:02d}' for ci in range(nfiles))
                + '.\n\n')
        f.write('Definition D_censusTr : list TM :='
                ' map row_to_tm deferred_tr_rows.\n')
    print(f'{len(uniq)} machines -> {nfiles} shard(s) + DeferredTr_Data.v'
          f' in {outdir}', file=sys.stderr)


if __name__ == '__main__':
    main()
