#!/usr/bin/env python3
"""Collect the QUASIHALTING-side counter boards (theories/Machines/CountersTr/
LAPQ_*.v, emitted by tools/counters/emit_lapcert.py --qh) into proven-QH
stage lists for CensusTr/RunTr.v's [provqh_tr].
Each board proves
  [qhtr_<ID> : NonHalt tm_<ID> /\ QHBoundTr 32779478 tm_<ID> /\ QuasiHaltsTr tm_<ID>]
(closer Counters/LapGlueQHTr via CensusTr/QHConveyorTr [lap_qh_stage]).
This emits
    theories/CensusTr/ProvTr_QH_NN.v      Require Import <CHUNK boards>;
                                          pqh_NN : list TM;
                                          pqh_NN_qhtr : Forall (...) pqh_NN
so [provqh_tr] can append [pqh_NN] with [Forall_app], and adds the boards
to _CoqProject (the LAPT boards are listed one per line there too).
The ProvTr_QH_NN namespace is shared with the other QH conveyors
(gen_provtr_qh.py, gen_provtr_tcqh.py): pass --start past the stages that
exist; an existing stage is never overwritten.
UNTRUSTED bookkeeping: it only names theorems the kernel already checked;
a wrong name fails to compile.
Usage: gen_provtr_lapqh.py --start N [--chunk N] [--boards DIR] [--outdir DIR]
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
HEADER = '''(** GENERATED by tools/censustr/gen_provtr_lapqh.py -- DO NOT EDIT.
    Transition-level proven-QH stage {NN}: {CNT} quiet-instruction counter
    machines boarded by lap CERTIFICATE at the instruction level
    (Machines/CountersTr/LAPQ_*.v, closer Counters/LapGlueQHTr).  Append
    [pqh_{NN}] to [provqh_tr] (CensusTr/RunTr.v). *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import TNF_QHTr.
'''
PRED = '(fun tm => NonHalt tm /\\ QHBoundTr 32779478 tm /\\ QuasiHaltsTr tm)'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--start', type=int, required=True)
    ap.add_argument('--chunk', type=int, default=200)
    ap.add_argument('--boards', default=os.path.join(REPO, 'theories', 'Machines', 'CountersTr'))
    ap.add_argument('--outdir', default=os.path.join(REPO, 'theories', 'CensusTr'))
    ap.add_argument('--no-coqproject', action='store_true')
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    # boards already imported by an existing ProvTr_QH stage are staged;
    # a later collection appends only the new ones
    staged = set()
    for st in glob.glob(os.path.join(a.outdir, 'ProvTr_QH_*.v')):
        staged |= set(re.findall(r'^From BBB4\.Machines\.CountersTr Require Import (LAPQ_\w+)\.', open(st).read(), re.M))
    boards = [b for b in sorted(glob.glob(os.path.join(a.boards, 'LAPQ_*.v')))
              if os.path.splitext(os.path.basename(b))[0] not in staged]
    if staged:
        sys.stderr.write('%d LAPQ board(s) already staged, skipped\n' % len(staged))
    if not boards:
        sys.exit('no unstaged LAPQ board in %s' % a.boards)
    rows = []
    for b in boards:
        t = open(b).read()
        ms = re.findall(r'^Theorem (qhtr_(\w+)) : NonHalt (tm_\w+) /\\ QHBoundTr 32779478 \3 /\\ QuasiHaltsTr \3\.', t, re.M)
        if not ms:
            raise SystemExit('no qhtr theorem in %s' % b)
        for th, _, tm in ms:
            rows.append((os.path.splitext(os.path.basename(b))[0], th, tm))
    n = a.start
    nfiles = 0
    for ci in range(0, len(rows), a.chunk):
        nn = '%02d' % n
        path = os.path.join(a.outdir, 'ProvTr_QH_%s.v' % nn)
        if os.path.exists(path):
            sys.exit('refusing to overwrite %s (another QH conveyor staged it): pass --start past the existing stages' % path)
        chunk = rows[ci:ci + a.chunk]
        with open(path, 'w') as f:
            f.write(HEADER.replace('{NN}', nn).replace('{CNT}', str(len(chunk))))
            seen = []
            for mod, _, _ in chunk:
                if mod not in seen:
                    seen.append(mod)
                    f.write('From BBB4.Machines.CountersTr Require Import %s.\n' % mod)
            f.write('Import ListNotations.\n\n')
            f.write('Definition pqh_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join(tm for _, _, tm in chunk))
            f.write('].\n\n')
            f.write('Lemma pqh_%s_qhtr : Forall %s pqh_%s.\n' % (nn, PRED, nn))
            term = '(Forall_nil _)'
            for _, th, _ in reversed(chunk):
                term = '(Forall_cons _ %s %s)' % (th, term)
            f.write('Proof. exact %s. Qed.\n' % term)
        n += 1
        nfiles += 1
    if not a.no_coqproject:
        cp = os.path.join(REPO, '_CoqProject')
        have = set(l.strip() for l in open(cp))
        add = ['theories/Machines/CountersTr/%s.v' % mod for mod, _, _ in rows
               if 'theories/Machines/CountersTr/%s.v' % mod not in have]
        add = sorted(set(add))
        if add:
            with open(cp, 'a') as f:
                f.write(''.join(x + '\n' for x in add))
        print('%d board path(s) added to _CoqProject' % len(add))
    print('%d boards -> %d stage file(s) (%s..) in %s' % (len(rows), nfiles, 'ProvTr_QH_%02d' % a.start, a.outdir))


if __name__ == '__main__':
    main()
