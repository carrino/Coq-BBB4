#!/usr/bin/env python3
"""Re-split a stuck walk shard into its own frontier.

UNTRUSTED tooling.  A 48-way frontier split gives each shard ONE
subtree, and subtree sizes vary by orders of magnitude -- measured
2026-08-23: 46 of 48 shards finished while two ran 5+ CPU-hours with
14 cores idle.  The fix is the same trick one level down: run the
halt-only prefix FROM the stuck node, get its own ~48-node frontier,
and shard that.

Emits one Coq driver per stuck node:

    census_probes/resplit/Resplit_NN.v

whose output has exactly the shape WalkTr_Frontier.v produces, so
tools/censustr/gen_walk_shards.py consumes it unchanged.

Because the sub-shards cover the same subtree as the shard they
replace, either source is complete on its own: run both and keep
whichever finishes first, or kill the slow original once the
sub-shards are done.  Do not concatenate both -- that double-counts
(harmless for a burn-down list, which is deduped, but it inflates
counts).

Usage:
  gen_resplit.py FRONTIER_OUT --nodes 43,47 [--pops 5] [--outdir DIR]

then, per emitted driver:
  coqc -Q theories BBB4 Resplit_43.v > resplit_43.out
  gen_walk_shards.py resplit_43.out --shards 48 --outdir census_probes/sub43
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from decode_enc import decode  # noqa: E402

PTR = {0: 'None', 1: '(Some StA)', 2: '(Some StB)',
       3: '(Some StC)', 4: '(Some StD)'}


def tm_lambda(name, text):
    rows = text.split('_')
    lines = [f'Definition {name} : TM := fun q s =>', '  match q, s with']
    for si, row in enumerate(rows):
        st = 'ABCD'[si]
        for xi in (0, 1):
            cell = row[3 * xi:3 * xi + 3]
            if cell == '---':
                lines.append(f'  | St{st}, S{xi} => None')
            else:
                w, d, nx = cell[0], cell[1], cell[2]
                lines.append(
                    f'  | St{st}, S{xi} => Some (mkTrans S{w} D{d} St{nx})')
    lines.append('  end.')
    return '\n'.join(lines)


TEMPLATE = """(* GENERATED by tools/censustr/gen_resplit.py -- do not edit.
   Sub-frontier of walk shard {idx}, whose subtree was too big to walk
   in one process.  Output shape matches WalkTr_Frontier.v, so
   gen_walk_shards.py reads it directly. *)
From Coq Require Import Arith List NArith.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH.
From BBB4.CensusTr Require Import RunTr.
Import ListNotations.

Set Printing Depth 100000000.
Set Printing Width 250.

{tmdef}

Definition start_q : SearchQueue := ([mkNode stuck_tm {ptr}], []).

Time Definition frontier_out
  : (nat * nat) * (list (N * N) * list N) :=
  Eval vm_compute in
    let q := SearchQueue_upds start_q decider_tr_fast {pops} in
    (queue_sizes q, (queue_front_encs q, queue_encs q)).

Compute (fst frontier_out).

Compute (fst (snd frontier_out)).

Compute (snd (snd frontier_out)).
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('frontier_out')
    ap.add_argument('--nodes', required=True,
                    help='comma-separated shard indices to re-split')
    ap.add_argument('--pops', type=int, default=5,
                    help='2^pops prefix pops (front saturates ~48 at 5)')
    ap.add_argument('--outdir', default='census_probes/resplit')
    args = ap.parse_args()

    text = open(args.frontier_out).read()
    m = re.search(r'(=.*?):\s*list \(N \* N\)', text, re.S)
    if not m:
        sys.exit('no `list (N * N)` block -- is this a frontier .out?')
    pairs = [(int(a), int(b)) for a, b in
             re.findall(r'\((\d+)%N,\s*(\d+)%N\)', m.group(1))]

    os.makedirs(args.outdir, exist_ok=True)
    for tok in args.nodes.split(','):
        i = int(tok)
        if i >= len(pairs):
            sys.exit(f'shard {i} out of range (frontier has {len(pairs)})')
        code, ptr = pairs[i]
        body = TEMPLATE.format(
            idx=i, pops=args.pops, ptr=PTR[ptr],
            tmdef=tm_lambda('stuck_tm', decode(code)))
        path = os.path.join(args.outdir, f'Resplit_{i:02d}.v')
        with open(path, 'w') as f:
            f.write(body)
        print(f'shard {i}: machine {decode(code)} ptr={PTR[ptr]} -> {path}')


if __name__ == '__main__':
    main()
