#!/usr/bin/env python3
"""Re-check the STATE census's inductive-rules certificates at the
instruction level and stage the ones that pass (UNTRUSTED bookkeeping).

The state boards carry, per machine, a TM definition and an irules
certificate (BIRCertP for the block-prefix engine, IRCert for the plain
engine) closed by irulesblkpfx_check_neverqh / irules_check_neverqh.
The instruction-level checkers (Checkers/IRules/MetaBlkPfxTr.v,
MetaTr.v) take the SAME certificate types, so no new search is needed:
this copies each machine's definitions verbatim out of its state board
and asks the instruction-level checker.  Measured: ~0.1-0.5 s per
machine, ~80-90% accept.

Sources (family -> board dir, names, checker):
  LCS2       theories/Machines/ListCStage2/LCS2_NN.v   tm_<id>/cert_<id>   BIRCertP 200000 300000
  IRBP       theories/Machines/IRulesBlkPfx_Batch_NN.v tmbp_<S>/certbp_<S> BIRCertP 200000 300000
  IR         theories/Machines/IRules_Batch_NN.v       tm_<S>/cert_<S>     IRCert 300000
(<S> = spec with --- written XXX; the manifests tools/irulesnqh_manifest.tsv
and tools/proven_map.tsv say which board holds which machine.)

  probe LIST OUTDIR          -> OUTDIR/ProbeIR_NN.v (Eval per machine)
  stage LIST PROBEDIR OUTDIR -> OUTDIR/ProvTr_IR_NN.v (pti_NN + Forall)
LIST: one machine spec per line (the rows to try).
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))

HEADER = """From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement CTape.
From BBB4.Checkers Require Import Cycle.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
     EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx MetaTr MetaBlkPfxTr.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
"""

STAGE_DOC = """(** GENERATED by tools/censustr/gen_provtr_irst.py -- DO NOT EDIT.

    Transition-level proven-tier stage IR {NN}: {CNT} machines whose
    STATE-census inductive-rules certificates (copied verbatim from the
    state boards) also pass the instruction-level checkers
    (MetaBlkPfxTr / MetaTr).  Append [pti_{NN}] to [prov_tr]
    (CensusTr/RunTr.v). *)
"""


def load_sources():
    """spec -> (family, board path, tm name, cert name)."""
    src = {}
    p = os.path.join(REPO, 'tools', 'irulesnqh_manifest.tsv')
    for l in open(p).read().split('\n')[1:]:
        f = l.split('\t')
        if len(f) < 3:
            continue
        nm = f[1][len('nqh_'):]
        src[f[0]] = ('LCS2', os.path.join(REPO, 'theories', 'Machines', 'ListCStage2', f[2]),
                     'tm_' + nm, 'cert_' + nm)
    p = os.path.join(REPO, 'tools', 'proven_map.tsv')
    for l in open(p).read().split('\n')[1:]:
        f = l.split('\t')
        if len(f) < 4 or f[0] in src:
            continue
        vf = f[2]
        sid = f[0].replace('---', 'XXX')
        if 'IRulesBlkPfx_Batch' in vf:
            src[f[0]] = ('IRBP', os.path.join(REPO, vf), 'tmbp_' + sid, 'certbp_' + sid)
        elif re.search(r'IRules_Batch', vf):
            src[f[0]] = ('IR', os.path.join(REPO, vf), 'tm_' + sid, 'cert_' + sid)
    return src


_cache = {}


def board_text(path):
    if path not in _cache:
        _cache[path] = open(path).read()
    return _cache[path]


def extract(path, tm, cert):
    txt = board_text(path)
    m1 = re.search(r'^Definition %s : TM :=.*?\n  end\.\n' % re.escape(tm), txt, re.S | re.M)
    m2 = re.search(r'^Definition %s : (?:BIRCertP|IRCert) :=.*?(?=\n(?:Lemma|Theorem|Definition|\(\*) )' % re.escape(cert), txt, re.S | re.M)
    if not m1 or not m2:
        return None
    return m1.group(0) + m2.group(0).rstrip() + '\n'


def check_call(fam, tm, cert):
    if fam == 'IR':
        return 'irules_check_neverqhtr %s %s 300000' % (tm, cert), \
               'irules_check_neverqhtr_sound %s %s 300000' % (tm, cert)
    return 'irulesblkpfx_check_neverqhtr %s %s 200000 300000' % (tm, cert), \
           'irulesblkpfx_check_neverqhtr_sound %s %s 200000 300000' % (tm, cert)


def items(listfile):
    src = load_sources()
    out, skipped = [], 0
    for line in open(listfile):
        sp = line.strip()
        if not sp or sp not in src:
            skipped += (1 if sp else 0)
            continue
        fam, path, tm, cert = src[sp]
        body = extract(path, tm, cert)
        if body is None:
            skipped += 1
            continue
        out.append((sp, fam, tm, cert, body))
    sys.stderr.write('gen_provtr_irst: %d machines with a state irules certificate, %d without\n'
                     % (len(out), skipped))
    return out


def probe(listfile, outdir, chunk):
    os.makedirs(outdir, exist_ok=True)
    its = items(listfile)
    n = 0
    for ci in range(0, len(its), chunk):
        nn = '%02d' % n
        with open(os.path.join(outdir, 'ProbeIR_%s.v' % nn), 'w') as f:
            f.write(HEADER + '\n')
            for sp, fam, tm, cert, body in its[ci:ci + chunk]:
                call, _ = check_call(fam, tm, cert)
                f.write('(* %s  %s *)\n%sEval vm_compute in %s.\n\n' % (sp, fam, body, call))
        n += 1
    sys.stderr.write('wrote %d probe file(s) to %s\n' % (n, outdir))


def read_verdicts(probedir):
    vs = {}
    for vf in glob.glob(os.path.join(probedir, 'ProbeIR_*.v')):
        specs = re.findall(r'^\(\* ([0-9A-Z\-]{6}(?:_[0-9A-Z\-]{6}){3})  (?:LCS2|IRBP|IR) \*\)', open(vf).read(), re.M)
        of = vf[:-2] + '.out'
        got = []
        if os.path.exists(of):
            got = [x == 'true' for x in re.findall(r'^\s*= (true|false)', open(of).read(), re.M)]
        got = got[:len(specs)] + [False] * (len(specs) - len(got))
        for sp, v in zip(specs, got):
            vs[sp] = v
    return vs


def stage(listfile, probedir, outdir, chunk, start):
    its = items(listfile)
    vs = read_verdicts(probedir)
    keep = [it for it in its if vs.get(it[0])]
    os.makedirs(outdir, exist_ok=True)
    n = start
    man = []
    for ci in range(0, len(keep), chunk):
        nn = '%02d' % n
        cb = keep[ci:ci + chunk]
        names = []
        with open(os.path.join(outdir, 'ProvTr_IR_%s.v' % nn), 'w') as f:
            f.write(STAGE_DOC.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + HEADER + '\n')
            for sp, fam, tm, cert, body in cb:
                _, lem = check_call(fam, tm, cert)
                f.write('(* %s  %s *)\n%s' % (sp, fam, body))
                f.write('Lemma nqhtr_%s : NeverQuasiHaltsTr %s.\n'
                        'Proof. apply (%s). vm_cast_no_check (eq_refl true). Qed.\n\n' % (tm, tm, lem))
                names.append(tm)
                man.append((sp, 'nqhtr_%s' % tm, 'ProvTr_IR_%s.v' % nn, fam))
            f.write('Definition pti_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join(names))
            f.write('].\n\n')
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for x in reversed(names):
                term = '(Forall_cons _ nqhtr_%s %s)' % (x, term)
            f.write('Lemma pti_%s_nqhtr : Forall NeverQuasiHaltsTr pti_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, nn, term))
        n += 1
    with open(os.path.join(outdir, 'provtr_ir_manifest.tsv'), 'w') as f:
        for r in man:
            f.write('\t'.join(r) + '\n')
    sys.stderr.write('staged %d machines into %d file(s) (of %d with certificates; %d rejected)\n'
                     % (len(keep), n - start, len(its), len(its) - len(keep)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=None)
    ap.add_argument('--start', type=int, default=0)
    a = ap.parse_args()
    if a.phase == 'probe':
        probe(a.args[0], a.args[1], a.chunk or 300)
    else:
        stage(a.args[0], a.args[1], a.args[2], a.chunk or 200, a.start)


if __name__ == '__main__':
    main()
