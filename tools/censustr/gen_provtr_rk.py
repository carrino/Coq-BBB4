#!/usr/bin/env python3
"""Rank-rung re-check of STATE-proven machines at the instruction level
(UNTRUSTED bookkeeping around the trusted checker DecideTr.rank_tier_tr).

The state census proved many machines with an n-gram rank tier at some
rung (n, t) (tools/proven_map.tsv / the LCStage and Bulk boards record
which).  The instruction-level rank tier [rank_tier_tr tm n t fuel rounds]
is the same construction with an instruction target, so the natural first
try is the SAME rung.  Measured on the 2,780 state-proven machines whose
state route was a rank rung: roughly one in five passes (the instruction
target removes fewer abstract nodes, see SCOPING_INSTR.md section 7.1y).

  probe ROWS OUTDIR          -> OUTDIR/ProbeRK_NN.v (Eval per machine)
  stage ROWS PROBEDIR OUTDIR -> OUTDIR/ProvTr_RK_NN.v (prk_NN + Forall)
ROWS: TSV with header  spec<TAB>n<TAB>t  (censustr_rank_rows_stproven.tsv).
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_walk_shards import tm_lambda  # noqa: E402

FUEL = 200000
ROUNDS = 512

HEADER = """From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import DecideTr.
Import ListNotations.
"""

STAGE_DOC = """(** GENERATED by tools/censustr/gen_provtr_rk.py -- DO NOT EDIT.

    Transition-level proven-tier stage RK {NN}: {CNT} machines that the
    STATE census proved with an n-gram rank rung (n, t) and that the
    instruction-level rank tier [rank_tier_tr] accepts at the same rung.
    Append [prk_{NN}] to [prov_tr] (CensusTr/RunTr.v). *)
"""


def rows(path):
    out = []
    for l in open(path).read().split('\n')[1:]:
        f = l.split('\t')
        if len(f) >= 3:
            out.append((f[0], int(f[1]), int(f[2])))
    return out


def probe(rowsfile, outdir, chunk):
    os.makedirs(outdir, exist_ok=True)
    rs = rows(rowsfile)
    n = 0
    for ci in range(0, len(rs), chunk):
        with open(os.path.join(outdir, 'ProbeRK_%02d.v' % n), 'w') as f:
            f.write(HEADER)
            for i, (sp, nn, t) in enumerate(rs[ci:ci + chunk]):
                f.write('(* %s  n=%d t=%d *)\n%s\nEval vm_compute in rank_tier_tr tm_%d %d %d %d %d.\n\n'
                        % (sp, nn, t, tm_lambda('tm_%d' % i, sp), i, nn, t, FUEL, ROUNDS))
        n += 1
    sys.stderr.write('wrote %d probe file(s) to %s\n' % (n, outdir))


def read_verdicts(probedir):
    vs = {}
    for vf in glob.glob(os.path.join(probedir, 'ProbeRK_*.v')):
        specs = re.findall(r'^\(\* ([0-9A-Z\-]{6}(?:_[0-9A-Z\-]{6}){3})  n=', open(vf).read(), re.M)
        of = vf[:-2] + '.out'
        got = []
        if os.path.exists(of):
            got = [x == 'true' for x in re.findall(r'^\s*= (true|false)', open(of).read(), re.M)]
        got = got[:len(specs)] + [False] * (len(specs) - len(got))
        for sp, v in zip(specs, got):
            vs[sp] = v
    return vs


def stage(rowsfile, probedir, outdir, chunk, start):
    rs = rows(rowsfile)
    vs = read_verdicts(probedir)
    keep = [r for r in rs if vs.get(r[0])]
    os.makedirs(outdir, exist_ok=True)
    n = start
    man = []
    for ci in range(0, len(keep), chunk):
        nn = '%02d' % n
        cb = keep[ci:ci + chunk]
        names = []
        with open(os.path.join(outdir, 'ProvTr_RK_%s.v' % nn), 'w') as f:
            f.write(STAGE_DOC.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + HEADER + '\n')
            for sp, rn, t in cb:
                nm = 'tm_' + sp.replace('---', 'XXX')
                f.write('(* %s  n=%d t=%d *)\n%s\n' % (sp, rn, t, tm_lambda(nm, sp)))
                f.write('Lemma nqhtr_%s : NeverQuasiHaltsTr %s.\n'
                        'Proof. apply (rank_tier_tr_sound %s %d %d %d %d). vm_cast_no_check (eq_refl true). Qed.\n\n'
                        % (nm[3:], nm, nm, rn, t, FUEL, ROUNDS))
                names.append(nm)
                man.append((sp, 'nqhtr_%s' % nm[3:], 'ProvTr_RK_%s.v' % nn, '%d,%d' % (rn, t)))
            f.write('Definition prk_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join(names))
            f.write('].\n\n')
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for x in reversed(names):
                term = '(Forall_cons _ nqhtr_%s %s)' % (x[3:], term)
            f.write('Lemma prk_%s_nqhtr : Forall NeverQuasiHaltsTr prk_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, nn, term))
        n += 1
    with open(os.path.join(outdir, 'provtr_rk_manifest.tsv'), 'w') as f:
        for r in man:
            f.write('\t'.join(r) + '\n')
    sys.stderr.write('staged %d machines into %d file(s) (of %d rows; %d rejected)\n'
                     % (len(keep), n - start, len(rs), len(rs) - len(keep)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=None)
    ap.add_argument('--start', type=int, default=0)
    a = ap.parse_args()
    if a.phase == 'probe':
        probe(a.args[0], a.args[1], a.chunk or 100)
    else:
        stage(a.args[0], a.args[1], a.args[2], a.chunk or 200, a.start)


if __name__ == '__main__':
    main()
