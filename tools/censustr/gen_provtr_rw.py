#!/usr/bin/env python3
"""Stage RepWL (Tier W) never-QH catches into the transition-level proven
tier.  UNTRUSTED tooling: every row is re-checked by the kernel through
CensusTr/RepWLTr.v's [rw_tier_tr_sound] (the parameter-closed tier: the
closure search, the per-instruction rank/lex certificate search and the
verified check all run inside one vm_compute).

  probe  ROWS.tsv OUTDIR          -> OUTDIR/ProbeRW_NN.v (Eval per row)
  stage  ROWS.tsv PROBEDIR OUTDIR -> OUTDIR/ProvTr_RW_NN.v  (ptw_NN +
         Forall NeverQuasiHaltsTr ptw_NN) for the rows whose probe printed
         true; one row per (machine, L, T, t, fuel, M); a machine is staged
         once (its first true row).

ROWS.tsv: spec L T t fuel M
Usage: gen_provtr_rw.py probe ROWS OUTDIR [--chunk 40]
       gen_provtr_rw.py stage ROWS PROBEDIR OUTDIR [--chunk 100] [--start 0]
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_walk_shards import tm_lambda  # noqa: E402

PROBE_HEADER = """(* GENERATED by tools/censustr/gen_provtr_rw.py probe -- untrusted scratch. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
"""

STAGE_HEADER = """(** GENERATED by tools/censustr/gen_provtr_rw.py -- DO NOT EDIT.

    Transition-level proven-tier stage RW {NN}: {CNT} machines closed by
    the instruction-level RepWL tier ([RepWLTr.rw_tier_tr]) at a block
    length matched to the tape period.  Append [ptw_{NN}] to [prov_tr]
    (CensusTr/RunTr.v). *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
"""


def read_rows(path):
    rows = []
    for line in open(path):
        f = line.strip().split('\t')
        if len(f) < 6:
            continue
        rows.append((f[0],) + tuple(int(x) for x in f[1:6]))
    return rows


def probe(rows, outdir, chunk):
    os.makedirs(outdir, exist_ok=True)
    n = 0
    for ci in range(0, len(rows), chunk):
        nn = '%02d' % n
        with open(os.path.join(outdir, 'ProbeRW_%s.v' % nn), 'w') as f:
            f.write(PROBE_HEADER + '\n')
            for k, (spec, L, T, t, fuel, M) in enumerate(rows[ci:ci + chunk]):
                nm = 'p%02d_%04d' % (n, k)
                f.write('(* %s L=%d T=%d *)\n' % (spec, L, T))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Eval vm_compute in rw_tier_tr tm_%s %d %d %d %d %d.\n\n'
                        % (nm, L, T, t, fuel, M))
        n += 1
    sys.stderr.write('wrote %d probe file(s) for %d rows to %s\n' % (n, len(rows), outdir))


def read_verdicts(probedir):
    vs = []
    for o in sorted(glob.glob(os.path.join(probedir, 'ProbeRW_*.out'))):
        vs += [x == 'true' for x in re.findall(r'^\s*= (true|false)', open(o).read(), re.M)]
    return vs


def stage(rows, probedir, outdir, chunk, start):
    vs = read_verdicts(probedir)
    if len(vs) != len(rows):
        sys.exit('verdict count %d != row count %d' % (len(vs), len(rows)))
    os.makedirs(outdir, exist_ok=True)
    keep, seen = [], set()
    for r, v in zip(rows, vs):
        if v and r[0] not in seen:
            keep.append(r)
            seen.add(r[0])
    n = start
    man = []
    for ci in range(0, len(keep), chunk):
        nn = '%02d' % n
        cb = keep[ci:ci + chunk]
        names = []
        with open(os.path.join(outdir, 'ProvTr_RW_%s.v' % nn), 'w') as f:
            f.write(STAGE_HEADER.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + '\n')
            for k, (spec, L, T, t, fuel, M) in enumerate(cb):
                nm = 'rw%02d_%04d' % (n, k)
                names.append(nm)
                f.write('(* %s  L=%d T=%d t=%d fuel=%d M=%d *)\n' % (spec, L, T, t, fuel, M))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Lemma nqhtr_%s : NeverQuasiHaltsTr tm_%s.\n'
                        'Proof. apply (rw_tier_tr_sound _ %d %d %d %d %d). '
                        'vm_cast_no_check (eq_refl true). Qed.\n\n'
                        % (nm, nm, L, T, t, fuel, M))
                man.append((spec, 'nqhtr_%s' % nm, 'ProvTr_RW_%s.v' % nn, str(L), str(T)))
            f.write('Definition ptw_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join('tm_%s' % x for x in names))
            f.write('].\n\n')
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for x in reversed(names):
                term = '(Forall_cons _ nqhtr_%s %s)' % (x, term)
            f.write('Lemma ptw_%s_nqhtr : Forall NeverQuasiHaltsTr ptw_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, nn, term))
        n += 1
    with open(os.path.join(outdir, 'provtr_rw_manifest.tsv'), 'w') as f:
        for r in man:
            f.write('\t'.join(r) + '\n')
    sys.stderr.write('staged %d machines into %d file(s) (%d rows true of %d)\n'
                     % (len(keep), n - start, sum(vs), len(rows)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=None)
    ap.add_argument('--start', type=int, default=0)
    a = ap.parse_args()
    if a.phase == 'probe':
        probe(read_rows(a.args[0]), a.args[1], a.chunk or 40)
    else:
        stage(read_rows(a.args[0]), a.args[1], a.args[2], a.chunk or 100, a.start)


if __name__ == '__main__':
    main()
