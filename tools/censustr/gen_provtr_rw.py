#!/usr/bin/env python3
"""Stage RepWL (Tier W) never-QH catches into the transition-level proven
tier.  UNTRUSTED tooling: every row is re-checked by the kernel through
CensusTr/RepWLTr.v's [rw_tier_tr_sound] (the parameter-closed tier: the
closure search, the per-instruction rank/lex certificate search and the
verified check all run inside one vm_compute).

  probe  ROWS.tsv OUTDIR          -> OUTDIR/ProbeRW_NN.v: ONE Eval per
         machine, a match chain over its rows in file order that stops at
         the first block length whose tier returns true (a failing L costs
         the whole fuel, so try the period before its multiples); prints
         [Some L] or [None].
  stage  ROWS.tsv PROBEDIR OUTDIR -> OUTDIR/ProvTr_RW_NN.v  (ptw_NN +
         Forall NeverQuasiHaltsTr ptw_NN) for the machines whose probe
         printed [Some L], at that L.

ROWS.tsv: spec L T t fuel M [rounds]
The optional rounds column caps the certificate search (default 300, preserving
old row files).  A smaller cap is useful for a broad first pass: exhaustion
fails closed and lets the per-machine wall clock move on to another machine.
Usage: gen_provtr_rw.py probe ROWS OUTDIR [--chunk 1]
       gen_provtr_rw.py stage ROWS PROBEDIR OUTDIR [--chunk 100] [--start 0]
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_walk_shards import tm_lambda  # noqa: E402

PROBE_HEADER = """(* GENERATED by tools/censustr/gen_provtr_rw.py probe -- untrusted scratch. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
"""

STAGE_HEADER = """(** GENERATED by tools/censustr/gen_provtr_rw.py -- DO NOT EDIT.

    Transition-level proven-tier stage RW {NN}: {CNT} machines closed by
    the instruction-level RepWL tier ([RepWLTr.rw_tier_tr]) at a block
    length matched to the tape period.  Append [ptw_{NN}] to [prov_tr]
    (CensusTr/RunTr.v). *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
"""


def read_rows(path):
    rows = []
    for line in open(path):
        f = line.strip().split('\t')
        if len(f) < 6:
            continue
        row = (f[0],) + tuple(int(x) for x in f[1:6])
        rows.append(row + (int(f[6]) if len(f) >= 7 else 300,))
    return rows


def group_rows(rows):
    """machine -> its rows, in file order (first row's T/t/fuel/M rule)."""
    order, by = [], {}
    for r in rows:
        if r[0] not in by:
            order.append(r[0])
            by[r[0]] = []
        by[r[0]].append(r)
    return [(m, by[m]) for m in order]


def chain(nm, mrows):
    """match rw_tier_tr .. L1 .. with true => Some L1 | false => match .. end"""
    txt = 'None'
    for (spec, L, T, t, fuel, M, rounds) in reversed(mrows):
        txt = ('match rw_tier_tr_rounds %d tm_%s %d %d %d %d %d with\n'
               '     | true => Some %d | false => %s end'
               % (rounds, nm, L, T, t, fuel, M, L, txt))
    return txt


def probe(rows, outdir, chunk):
    os.makedirs(outdir, exist_ok=True)
    groups = group_rows(rows)
    n = 0
    for ci in range(0, len(groups), chunk):
        nn = '%02d' % n
        with open(os.path.join(outdir, 'ProbeRW_%s.v' % nn), 'w') as f:
            f.write(PROBE_HEADER + '\n')
            for k, (spec, mrows) in enumerate(groups[ci:ci + chunk]):
                nm = 'p%02d_%04d' % (n, k)
                f.write('(* %s  L in %s *)\n' % (spec, [r[1] for r in mrows]))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Eval vm_compute in\n  (%s).\n\n' % chain(nm, mrows))
        n += 1
    sys.stderr.write('wrote %d probe file(s) for %d machines (%d rows) to %s\n'
                     % (n, len(groups), len(rows), outdir))


def read_verdicts(probedir):
    """probe outputs -> {spec: Some-L (int) or None}.

    Each probe .v carries its machines as `(* <spec>  L in [...] *)`
    comments, one per Eval, in order; the .out holds the results in the
    same order.  Keying by the spec written in the file (not by file
    order) is what makes this robust: with >100 files a lexicographic
    listing puts ProbeRW_100 before ProbeRW_11, and the first version of
    this function paired verdicts with the wrong machines -- caught by
    the kernel when the staged lemma failed to check.  A file whose coqc
    was cut short (per-file timeout, crash) has fewer results than
    machines; the missing tail is None."""
    vs = {}
    for vf in glob.glob(os.path.join(probedir, 'ProbeRW_*.v')):
        specs = re.findall(r'^\(\* ([0-9A-Z\-]{6}(?:_[0-9A-Z\-]{6}){3})  L in', open(vf).read(), re.M)
        of = vf[:-2] + '.out'
        got = []
        if os.path.exists(of):
            for m in re.finditer(r'^\s*= (Some (\d+)|None)', open(of).read(), re.M):
                got.append(int(m.group(2)) if m.group(2) else None)
        got = got[:len(specs)] + [None] * (len(specs) - len(got))
        for sp, v in zip(specs, got):
            vs[sp] = v
    return vs


def stage(rows, probedir, outdir, chunk, start):
    groups = group_rows(rows)
    vs = read_verdicts(probedir)
    missing = [spec for spec, _ in groups if spec not in vs]
    if missing:
        sys.exit('%d machines of the rows have no probe file (first: %s)'
                 % (len(missing), missing[0]))
    os.makedirs(outdir, exist_ok=True)
    keep = []
    for spec, mrows in groups:
        L = vs[spec]
        if L is None:
            continue
        row = [r for r in mrows if r[1] == L]
        if not row:
            sys.exit('probe says L=%d for %s but the rows have no such L' % (L, spec))
        keep.append(row[0])
    n = start
    man = []
    for ci in range(0, len(keep), chunk):
        nn = '%02d' % n
        cb = keep[ci:ci + chunk]
        names = []
        with open(os.path.join(outdir, 'ProvTr_RW_%s.v' % nn), 'w') as f:
            f.write(STAGE_HEADER.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + '\n')
            for k, (spec, L, T, t, fuel, M, rounds) in enumerate(cb):
                nm = 'rw%02d_%04d' % (n, k)
                names.append(nm)
                f.write('(* %s  L=%d T=%d t=%d fuel=%d M=%d rounds=%d *)\n'
                        % (spec, L, T, t, fuel, M, rounds))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Lemma nqhtr_%s : NeverQuasiHaltsTr tm_%s.\n'
                        'Proof. apply (rw_tier_tr_rounds_sound %d _ %d %d %d %d %d). '
                        'vm_cast_no_check (eq_refl true). Qed.\n\n'
                        % (nm, nm, rounds, L, T, t, fuel, M))
                man.append((spec, 'nqhtr_%s' % nm, 'ProvTr_RW_%s.v' % nn, str(L), str(T)))
            f.write('Definition ptw_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join('tm_%s' % x for x in names))
            f.write('].\n\n')
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for x in reversed(names):
                term = '(Forall_cons _ nqhtr_%s %s)' % (x, term)
            f.write('Lemma ptw_%s_nqhtr : Forall NeverQuasiHaltsTr ptw_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, nn, term))
        n += 1
    with open(os.path.join(outdir, 'provtr_rw_manifest.tsv'), 'w') as f:
        for r in man:
            f.write('\t'.join(r) + '\n')
    sys.stderr.write('staged %d machines into %d file(s) (of %d probed)\n'
                     % (len(keep), n - start, len(groups)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=None,
                    help='machines per probe file (default 1: one slow machine then stalls only its own file) / per stage file (default 100)')
    ap.add_argument('--start', type=int, default=0)
    a = ap.parse_args()
    if a.phase == 'probe':
        probe(read_rows(a.args[0]), a.args[1], a.chunk or 1)
    else:
        stage(read_rows(a.args[0]), a.args[1], a.args[2], a.chunk or 100, a.start)


if __name__ == '__main__':
    main()
