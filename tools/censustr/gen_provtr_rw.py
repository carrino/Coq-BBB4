#!/usr/bin/env python3
"""Stage RepWL (Tier W) never-QH catches into the transition-level proven
tier. UNTRUSTED tooling: every row is re-checked by the kernel. By default
CensusTr/RepWLTr.v's [rw_tier_tr_sound] runs closure search, per-instruction
rank/lex search and verification. Selected split rows instead use
Checkers/RepWLStoredTr.v's [rw_check_stored_tr_sound] to verify a supplied
closure and certificate; no search is repeated for those rows.

  probe  ROWS.tsv OUTDIR          -> OUTDIR/ProbeRW_NN.v: ONE Eval per
         machine, a match chain over its rows in file order that stops at
         the first block length whose tier returns true (a failing L costs
         the whole fuel, so try the period before its multiples); prints
         [Some L] or [None].
  stage  ROWS.tsv PROBEDIR OUTDIR -> OUTDIR/ProvTr_RW_NN.v  (ptw_NN +
         Forall NeverQuasiHaltsTr ptw_NN) for the machines whose probe
         printed [Some L], at that L.

ROWS.tsv: spec L T t fuel M
Usage: gen_provtr_rw.py probe ROWS OUTDIR [--chunk 1]
       gen_provtr_rw.py stage ROWS PROBEDIR OUTDIR [--chunk 100] [--start 0]
       gen_provtr_rw.py inventory STAGEDIR MANIFEST.tsv
       gen_provtr_rw.py split MANIFEST.tsv OUTDIR [--chunk 10] [--check]

The split phase preserves the existing stage numbers, row order, machine
definitions and proof parameters. Heavy rows get their own compilation
unit; each original stage becomes a compatibility wrapper. The manifest
is source data, not a trusted certificate or a compiled artifact.
Optional rw_certificates/RW_NN_NNNN.json files supply compact certificates;
their machine and parameters must match the manifest. The split phase
replays these into ordinary .v data under RWCerts and changes only the
corresponding checker application, preserving every wrapper and machine.
"""
import argparse
import csv
import glob
import os
from pathlib import Path
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_walk_shards import tm_lambda  # noqa: E402

PROBE_HEADER = """(* GENERATED by tools/censustr/gen_provtr_rw.py probe -- untrusted scratch. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
"""

STAGE_HEADER = """(** GENERATED by tools/censustr/gen_provtr_rw.py -- DO NOT EDIT.

    Transition-level proven-tier stage RW {NN}: {CNT} machines closed by
    the instruction-level RepWL tier ([RepWLTr.rw_tier_tr]) at a block
    length matched to the tape period.  Append [ptw_{NN}] to [prov_tr]
    (CensusTr/RunTr.v). *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
"""


def read_rows(path):
    rows = []
    for line in open(path):
        f = line.strip().split('\t')
        if len(f) < 6:
            continue
        rows.append((f[0],) + tuple(int(x) for x in f[1:6]))
    return rows


def group_rows(rows):
    """machine -> its rows, in file order (first row's T/t/fuel/M rule)."""
    order, by = [], {}
    for r in rows:
        if r[0] not in by:
            order.append(r[0])
            by[r[0]] = []
        by[r[0]].append(r)
    return [(m, by[m]) for m in order]


def chain(nm, mrows):
    """match rw_tier_tr .. L1 .. with true => Some L1 | false => match .. end"""
    txt = 'None'
    for (spec, L, T, t, fuel, M) in reversed(mrows):
        txt = ('match rw_tier_tr tm_%s %d %d %d %d %d with\n'
               '     | true => Some %d | false => %s end' % (nm, L, T, t, fuel, M, L, txt))
    return txt


def probe(rows, outdir, chunk):
    os.makedirs(outdir, exist_ok=True)
    groups = group_rows(rows)
    n = 0
    for ci in range(0, len(groups), chunk):
        nn = '%02d' % n
        with open(os.path.join(outdir, 'ProbeRW_%s.v' % nn), 'w') as f:
            f.write(PROBE_HEADER + '\n')
            for k, (spec, mrows) in enumerate(groups[ci:ci + chunk]):
                nm = 'p%02d_%04d' % (n, k)
                f.write('(* %s  L in %s *)\n' % (spec, [r[1] for r in mrows]))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Eval vm_compute in\n  (%s).\n\n' % chain(nm, mrows))
        n += 1
    sys.stderr.write('wrote %d probe file(s) for %d machines (%d rows) to %s\n'
                     % (n, len(groups), len(rows), outdir))


def read_verdicts(probedir):
    """probe outputs -> {spec: Some-L (int) or None}.

    Each probe .v carries its machines as `(* <spec>  L in [...] *)`
    comments, one per Eval, in order; the .out holds the results in the
    same order.  Keying by the spec written in the file (not by file
    order) is what makes this robust: with >100 files a lexicographic
    listing puts ProbeRW_100 before ProbeRW_11, and the first version of
    this function paired verdicts with the wrong machines -- caught by
    the kernel when the staged lemma failed to check.  A file whose coqc
    was cut short (per-file timeout, crash) has fewer results than
    machines; the missing tail is None."""
    vs = {}
    for vf in glob.glob(os.path.join(probedir, 'ProbeRW_*.v')):
        specs = re.findall(r'^\(\* ([0-9A-Z\-]{6}(?:_[0-9A-Z\-]{6}){3})  L in', open(vf).read(), re.M)
        of = vf[:-2] + '.out'
        got = []
        if os.path.exists(of):
            for m in re.finditer(r'^\s*= (Some (\d+)|None)', open(of).read(), re.M):
                got.append(int(m.group(2)) if m.group(2) else None)
        got = got[:len(specs)] + [None] * (len(specs) - len(got))
        for sp, v in zip(specs, got):
            vs[sp] = v
    return vs


def stage(rows, probedir, outdir, chunk, start):
    groups = group_rows(rows)
    vs = read_verdicts(probedir)
    missing = [spec for spec, _ in groups if spec not in vs]
    if missing:
        sys.exit('%d machines of the rows have no probe file (first: %s)'
                 % (len(missing), missing[0]))
    os.makedirs(outdir, exist_ok=True)
    keep = []
    for spec, mrows in groups:
        L = vs[spec]
        if L is None:
            continue
        row = [r for r in mrows if r[1] == L]
        if not row:
            sys.exit('probe says L=%d for %s but the rows have no such L' % (L, spec))
        keep.append(row[0])
    # balance the files by Coq's cost (the search re-runs at the row's
    # fuel = 8*nodes+64, so fuel is the proxy): largest first, each to the
    # least-loaded file.  In file order, the box's v10 stage build ran 8
    # files in minutes and then ProvTr_RW_15 alone for 3+ hours, because its
    # rows sat next to each other in the finder's output and were the big
    # closures.
    nfiles = max(1, -(-len(keep) // chunk))
    bins = [[] for _ in range(nfiles)]
    load = [0] * nfiles
    for r in sorted(keep, key=lambda r: -r[4]):
        i = min(range(nfiles), key=lambda j: (load[j], len(bins[j])))
        bins[i].append(r)
        load[i] += r[4]
    n = start
    man = []
    for cb in bins:
        nn = '%02d' % n
        names = []
        with open(os.path.join(outdir, 'ProvTr_RW_%s.v' % nn), 'w') as f:
            f.write(STAGE_HEADER.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + '\n')
            for k, (spec, L, T, t, fuel, M) in enumerate(cb):
                nm = 'rw%02d_%04d' % (n, k)
                names.append(nm)
                f.write('(* %s  L=%d T=%d t=%d fuel=%d M=%d *)\n' % (spec, L, T, t, fuel, M))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Lemma nqhtr_%s : NeverQuasiHaltsTr tm_%s.\n'
                        'Proof. apply (rw_tier_tr_sound _ %d %d %d %d %d). '
                        'vm_cast_no_check (eq_refl true). Qed.\n\n'
                        % (nm, nm, L, T, t, fuel, M))
                man.append((spec, 'nqhtr_%s' % nm, 'ProvTr_RW_%s.v' % nn, str(L), str(T)))
            f.write('Definition ptw_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join('tm_%s' % x for x in names))
            f.write('].\n\n')
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for x in reversed(names):
                term = '(Forall_cons _ nqhtr_%s %s)' % (x, term)
            f.write('Lemma ptw_%s_nqhtr : Forall NeverQuasiHaltsTr ptw_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, nn, term))
        n += 1
    sys.stderr.write('stage files balanced by fuel: max %d / min %d\n' % (max(load), min(load)))
    with open(os.path.join(outdir, 'provtr_rw_manifest.tsv'), 'w') as f:
        for r in man:
            f.write('\t'.join(r) + '\n')
    sys.stderr.write('staged %d machines into %d file(s) (of %d probed)\n'
                     % (len(keep), n - start, len(groups)))


FIELDS = ['stage', 'index', 'spec', 'L', 'T', 't', 'fuel', 'M']
CERTIFICATE_DIR = Path(__file__).resolve().parent / 'rw_certificates'
ROW_RE = re.compile(
    r'^\(\* (\S+)  L=(\d+) T=(\d+) t=(\d+) fuel=(\d+) M=(\d+) \*\)\n'
    r'(Definition tm_rw(\d+)_(\d+) : TM :=.*?\n  end\.)\n'
    r'Lemma nqhtr_rw\8_\9 : NeverQuasiHaltsTr tm_rw\8_\9\.\n'
    r'Proof\. apply \(rw_tier_tr_sound _ (\d+) (\d+) (\d+) (\d+) (\d+)\)\. '
    r'vm_cast_no_check \(eq_refl true\)\. Qed\.', re.M | re.S)


def inventory(stagedir, manifest):
    """Freeze the exact existing row order; refuse any unparsed proof."""
    rows = []
    for path in sorted(Path(stagedir).glob('ProvTr_RW_[0-9][0-9].v')):
        text = path.read_text()
        matches = list(ROW_RE.finditer(text))
        nn = int(path.stem[-2:])
        names = []
        for index, match in enumerate(matches):
            spec, *values = match.groups()[:6]
            definition, stage_name, row_index = match.groups()[6:9]
            # Comments are not authoritative: compare their machine and
            # parameters with the actual definition and theorem application.
            if int(stage_name) != nn or int(row_index) != index:
                raise ValueError(f'noncontiguous row names in {path}')
            name = f'tm_rw{nn:02d}_{index:04d}'
            if definition != tm_lambda(name, spec):
                raise ValueError(f'machine comment disagrees with {name}')
            if tuple(values) != match.groups()[9:]:
                raise ValueError(f'proof parameters disagree for {name}')
            names.append(name)
            rows.append(dict(zip(FIELDS, [nn, index, spec, *map(int, values)])))
        actual = re.search(r'Definition ptw_\d+ : list TM :=\s*\[(.*?)\]\.',
                           text, re.S)
        if not names or not actual or re.findall(r'tm_rw\d+_\d+', actual[1]) != names:
            raise ValueError(f'row list not fully accounted for in {path}')
        if len(re.findall(r'^Lemma nqhtr_', text, re.M)) != len(names):
            raise ValueError(f'unparsed proof in {path}')
    if not rows:
        raise ValueError('no original stages found')
    with open(manifest, 'w') as out:
        writer = csv.DictWriter(out, FIELDS, delimiter='\t', lineterminator='\n')
        writer.writeheader()
        writer.writerows(rows)
    print(f'inventoried {len(rows)} machines in {len(set(r["stage"] for r in rows))} stages')


def read_manifest(path):
    with open(path) as source:
        reader = csv.DictReader(source, delimiter='\t')
        if reader.fieldnames != FIELDS:
            raise ValueError('unexpected RepWL manifest columns')
        rows = [{k: v if k == 'spec' else int(v) for k, v in row.items()}
                for row in reader]
    seen = set()
    previous_stage = -1
    next_index = 0
    for r in rows:
        if r['stage'] != previous_stage:
            if r['stage'] <= previous_stage:
                raise ValueError('stages must be ordered')
            previous_stage, next_index = r['stage'], 0
        if r['index'] != next_index:
            raise ValueError('row indices must be contiguous within each stage')
        next_index += 1
        if not re.fullmatch(r'(?:[01][LR][ABCD]|---){2}(?:_(?:[01][LR][ABCD]|---){2}){3}', r['spec']):
            raise ValueError(f'invalid machine: {r["spec"]}')
        if r['spec'] in seen or any(r[k] < 0 for k in FIELDS if k != 'spec'):
            raise ValueError('duplicate machine or negative parameter')
        seen.add(r['spec'])
    if not rows:
        raise ValueError('empty manifest')
    return rows


def split_rows(rows, chunk, heavy_fuel, heavy_length):
    """Contiguous groups preserve the public lists by definitional equality."""
    if chunk < 1 or heavy_fuel < 1 or heavy_length < 1:
        raise ValueError('split thresholds must be positive')
    parts, pending = [], []
    for row in rows:
        heavy = row['fuel'] >= heavy_fuel or row['L'] >= heavy_length
        if heavy:
            if pending:
                parts.append(pending)
                pending = []
            parts.append([row])
        else:
            pending.append(row)
            if len(pending) == chunk:
                parts.append(pending)
                pending = []
    if pending:
        parts.append(pending)
    return parts


def read_stored_certificates(rows, directory=CERTIFICATE_DIR):
    import rw_stored
    by_id = {(r['stage'], r['index']): r for r in rows}
    out = {}
    for path in sorted(Path(directory).glob('RW_*.json')):
        match = re.fullmatch(r'RW_(\d{2})_(\d{4})', path.stem)
        if not match:
            raise ValueError(f'invalid certificate filename: {path}')
        key = tuple(map(int, match.groups()))
        data = rw_stored.read(path)
        if key not in by_id or any(data[k] != by_id[key][k] for k in rw_stored.PARAMS):
            raise ValueError(f'certificate machine or parameters differ: {path}')
        out[key] = data
    return out


def render_parts(rows, chunk=10, heavy_fuel=100000, heavy_length=9, certificates=None):
    import rw_stored
    certificates = certificates or {}
    files = {}
    for nn in sorted(set(r['stage'] for r in rows)):
        stage_rows = [r for r in rows if r['stage'] == nn]
        parts = split_rows(stage_rows, chunk, heavy_fuel, heavy_length)
        wrapper = [f'''(** GENERATED by tools/censustr/gen_provtr_rw.py split -- DO NOT EDIT.
    RW {nn:02d}: {len(stage_rows)} machines, {len(parts)} independent checking units.
    The original machine order and all public theorem names are preserved. *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.''']
        part_names = []
        for pi, part in enumerate(parts):
            mod = f'ProvTr_RW_{nn:02d}_P{pi:03d}'
            pn = f'ptw_{nn:02d}_p{pi:03d}'
            part_names.append((mod, pn))
            wrapper.append(f'From BBB4.CensusTr.RWParts Require {mod}.')
            body = [f'''(** GENERATED by tools/censustr/gen_provtr_rw.py split -- DO NOT EDIT.
    Independent RepWL checks for stage {nn:02d}, part {pi:03d}. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
From BBB4.CensusTr Require Import RepWLTr.
Import ListNotations.
''']
            names = []
            if any((r['stage'], r['index']) in certificates for r in part):
                body.append('From BBB4.Checkers Require Import RepWLStoredTr.')
            for r in part:
                name = f'rw{nn:02d}_{r["index"]:04d}'
                names.append(name)
                params = ' '.join(str(r[k]) for k in FIELDS[3:])
                key = (r['stage'], r['index'])
                if key in certificates:
                    cm = f'DataTr_RW_{nn:02d}_{r["index"]:04d}'
                    files[f'RWCerts/{cm}.v'] = rw_stored.render(certificates[key])
                    body.append(f'From BBB4.CensusTr.RWCerts Require {cm}.')
                    args = ' '.join(str(r[k]) for k in ['L', 'T', 't', 'M'])
                    proof = (f'rw_check_stored_tr_sound _ {args} '
                             f'{cm}.keys {cm}.ranks {cm}.cert')
                else:
                    proof = f'rw_tier_tr_sound _ {params}'
                body.extend([
                    '(* ' + r['spec'] + '  ' + ' '.join(f'{k}={r[k]}' for k in FIELDS[3:]) + ' *)',
                    tm_lambda('tm_' + name, r['spec']),
                    f'Lemma nqhtr_{name} : NeverQuasiHaltsTr tm_{name}.',
                    f'Proof. apply ({proof}). vm_cast_no_check (eq_refl true). Qed.\n'])
                wrapper.extend([
                    f'Definition tm_{name} : TM := {mod}.tm_{name}.',
                    f'Lemma nqhtr_{name} : NeverQuasiHaltsTr tm_{name}.',
                    f'Proof. exact {mod}.nqhtr_{name}. Qed.'])
            body.append(f'Definition {pn} : list TM :=\n  [' + ';\n   '.join('tm_'+n for n in names) + '].\n')
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for name in reversed(names):
                term = f'(Forall_cons _ nqhtr_{name} {term})'
            body.extend([f'Lemma {pn}_nqhtr : Forall NeverQuasiHaltsTr {pn}.',
                         f'Proof. exact {term}. Qed.\n'])
            files[f'RWParts/{mod}.v'] = '\n'.join(body)
        wrapper.extend(['Import ListNotations.\n',
            f'Definition ptw_{nn:02d} : list TM :=\n  ' +
            ' ++\n  '.join(f'{mod}.{pn}' for mod, pn in part_names) + '.\n',
            f'Lemma ptw_{nn:02d}_rows : ptw_{nn:02d} =\n  [' +
            ';\n   '.join(f'tm_rw{nn:02d}_{r["index"]:04d}' for r in stage_rows) + '].',
            'Proof. reflexivity. Qed.\n',
            f'Lemma ptw_{nn:02d}_nqhtr : Forall NeverQuasiHaltsTr ptw_{nn:02d}.',
            f'Proof. unfold ptw_{nn:02d}; repeat (apply Forall_app; split);',
            '  first [' + ' | '.join(f'exact {mod}.{pn}_nqhtr' for mod, pn in part_names) + ']. Qed.\n'])
        files[f'ProvTr_RW_{nn:02d}.v'] = '\n'.join(wrapper)
    return files


def split_stages(manifest, outdir, chunk, heavy_fuel, heavy_length, check, project):
    rows = read_manifest(manifest)
    certificates = read_stored_certificates(rows)
    files = render_parts(rows, chunk, heavy_fuel, heavy_length, certificates)
    outdir = Path(outdir)
    stale = sorted((set(outdir.glob('RWParts/ProvTr_RW_*_P*.v')) |
                    set(outdir.glob('RWCerts/DataTr_RW_*.v'))) -
                   {outdir / name for name in files})
    if stale:
        raise ValueError('unexpected old parts (refusing to silently discard): ' + ', '.join(map(str, stale)))
    for name, text in files.items():
        path = outdir / name
        if check:
            if not path.exists() or path.read_text() != text:
                raise ValueError(f'stale generated file: {path}')
        elif not path.exists() or path.read_text() != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if project:
        path = Path(project)
        old = path.read_text()
        names = [str((outdir / n).relative_to(path.resolve().parent))
                 for n in sorted(files)]
        old_lines = old.splitlines()
        missing = [n for n in names if n not in old_lines]
        if check and missing:
            raise ValueError('unregistered stages: ' + ', '.join(missing))
        if missing:
            path.write_text(old.rstrip() + '\n' + '\n'.join(missing) + '\n')
    print(f'{"checked" if check else "wrote"} {len(files)} files for {len(rows)} machines')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage', 'inventory', 'split'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=None,
                    help='maximum rows per file (probe: 1; stage: 100; split: 10)')
    ap.add_argument('--start', type=int, default=0)
    ap.add_argument('--heavy-fuel', type=int, default=100000)
    ap.add_argument('--heavy-length', type=int, default=9)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--project', help='register/check generated files in this _CoqProject')
    a = ap.parse_args()
    required = 3 if a.phase == 'stage' else 2
    if len(a.args) != required:
        ap.error(f'{a.phase} takes {required} positional arguments')
    if a.chunk is not None and a.chunk < 1:
        ap.error('--chunk must be positive')
    if a.heavy_fuel < 1 or a.heavy_length < 1:
        ap.error('heavy-row thresholds must be positive')
    if a.phase == 'probe':
        probe(read_rows(a.args[0]), a.args[1], a.chunk or 1)
    elif a.phase == 'stage':
        stage(read_rows(a.args[0]), a.args[1], a.args[2], a.chunk or 100, a.start)
    elif a.phase == 'inventory':
        inventory(a.args[0], a.args[1])
    else:
        split_stages(a.args[0], str(Path(a.args[1]).resolve()), a.chunk or 10,
                     a.heavy_fuel, a.heavy_length, a.check, a.project)


if __name__ == '__main__':
    main()
