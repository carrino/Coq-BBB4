#!/usr/bin/env python3
"""QH-side twin of gen_provtr_tcqh.py: stage translated-cycler certificates
(tc_find.py output) for QUIET-instruction machines into ProvTr_QH_NN
stages for [provqh_tr], closed by Checkers/TCyclerQHTr
[tcycler_check_qhboundtr_sound] (side R) / [_sound_L] (side L): the same
lap, the gate inverted, conclusion NonHalt /\ QHBoundTr n1 /\ QuasiHaltsTr
(SCOPING_INSTR.md 7.3a).  n1 <= B_tr = 32779478 is checked in the stage
lemma via CensusTr/QHConveyorTr [qh_bound_of].

Original docstring: Stage translated-cycler certificates (tc_find.py output) into the
transition-level proven tier.  UNTRUSTED tooling: every certificate
is re-checked by the kernel through Checkers/TCyclerTr.v's
[tcycler_check_qhboundtr_sound] (side R) / [_sound_L] (side L, the
checker runs on [mirror_tm]).

Two phases, because one failing Lemma sinks a whole stage file:

  probe  CERTS.tsv OUTDIR          -> OUTDIR/ProbeTCQH_NN.v (+ .names)
         (compile each; every `Eval vm_compute` prints true/false)
  stage  CERTS.tsv PROBEDIR OUTDIR -> OUTDIR/ProvTr_QH_NN.v
         keeps the certificates whose probe verdict was true, writes
         [pqh_NN : list TM] + [pqh_NN_nqhtr : Forall NeverQuasiHaltsTr pqh_NN]
         and OUTDIR/provtr_tcqh_manifest.tsv (machine, lemma, file).

CERTS.tsv rows: spec side n1 P W [d]   (rows ending in '-' are skipped)
Usage: gen_provtr_tcqh.py probe CERTS OUTDIR [--chunk 250]
       gen_provtr_tcqh.py stage CERTS PROBEDIR OUTDIR [--chunk 250] [--start 0]
"""
import argparse
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_walk_shards import tm_lambda  # noqa: E402

PROBE_HEADER = """(* GENERATED by tools/censustr/gen_provtr_tcqh.py probe -- untrusted scratch. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement Mirror.
From BBB4.Checkers Require Import TCyclerTr TCyclerQHTr.
From BBB4.CensusTr Require Import TNF_QHTr QHConveyorTr.
Import ListNotations.
"""

STAGE_HEADER = """(** GENERATED by tools/censustr/gen_provtr_tcqh.py -- DO NOT EDIT.

    Transition-level proven-tier stage TC {NN}: {CNT} translated
    cyclers, each certified by [tcycler_check_qhboundtr] (side L runs
    the checker on [mirror_tm]).  Append [pqh_{NN}] to [provqh_tr]
    (CensusTr/RunTr.v). *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement Mirror.
From BBB4.Checkers Require Import TCyclerTr TCyclerQHTr.
From BBB4.CensusTr Require Import TNF_QHTr QHConveyorTr.
Import ListNotations.
"""


def read_certs(path):
    certs = []
    for line in open(path):
        f = line.strip().split('\t')
        if len(f) < 5:
            continue
        spec, side, n1, P, W = f[0], f[1], int(f[2]), int(f[3]), int(f[4])
        if side not in ('L', 'R'):
            sys.exit('bad side %r in %s' % (side, line))
        certs.append((spec, side, n1, P, W))
    return certs


def target(name, side):
    return 'tm_%s' % name if side == 'R' else '(mirror_tm tm_%s)' % name


def probe(certs, outdir, chunk):
    os.makedirs(outdir, exist_ok=True)
    n = 0
    for ci in range(0, len(certs), chunk):
        nn = '%02d' % n
        with open(os.path.join(outdir, 'ProbeTCQH_%s.v' % nn), 'w') as f, \
                open(os.path.join(outdir, 'ProbeTCQH_%s.names' % nn), 'w') as g:
            f.write(PROBE_HEADER + '\n')
            for k, (spec, side, n1, P, W) in enumerate(certs[ci:ci + chunk]):
                nm = 'p%02d_%04d' % (n, k)
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Eval vm_compute in tcycler_check_qhboundtr %s %d %d %d.\n\n'
                        % (target(nm, side), n1, P, W))
                g.write('%s\n' % spec)
        n += 1
    sys.stderr.write('wrote %d probe file(s) for %d certs to %s\n'
                     % (n, len(certs), outdir))


def read_verdicts(probedir):
    vs = []
    # numeric order: past 99 files a lexicographic sort puts _100 before
    # _11 and the verdicts would pair with the wrong certificates
    def _num(path):
        m = re.search(r'_(\d+)\.out$', path)
        return int(m.group(1)) if m else -1
    for o in sorted(glob.glob(os.path.join(probedir, 'ProbeTCQH_*.out')), key=_num):
        t = open(o).read()
        vs += [x == 'true' for x in re.findall(r'^\s*= (true|false)', t, re.M)]
    return vs


def stage(certs, probedir, outdir, chunk, start):
    vs = read_verdicts(probedir)
    if len(vs) != len(certs):
        sys.exit('verdict count %d != cert count %d' % (len(vs), len(certs)))
    os.makedirs(outdir, exist_ok=True)
    keep = [c for c, v in zip(certs, vs) if v]
    drop = [c for c, v in zip(certs, vs) if not v]
    rows = []
    n = start
    for ci in range(0, len(keep), chunk):
        nn = '%02d' % n
        cb = keep[ci:ci + chunk]
        names = []
        path = os.path.join(outdir, 'ProvTr_QH_%s.v' % nn)
        if os.path.exists(path):
            sys.exit('refusing to overwrite %s (another QH conveyor staged it): pass --start N past the existing stages' % path)
        with open(path, 'w') as f:
            f.write(STAGE_HEADER.replace('{NN}', nn).replace('{CNT}', str(len(cb))) + '\n')
            for k, (spec, side, n1, P, W) in enumerate(cb):
                nm = 'tq%02d_%04d' % (n, k)
                names.append(nm)
                lem = ('tcycler_qh_stage' if side == 'R'
                       else 'tcycler_qh_stage_L')
                f.write('(* %s  side %s  n1=%d P=%d W=%d *)\n' % (spec, side, n1, P, W))
                f.write(tm_lambda('tm_' + nm, spec) + '\n')
                f.write('Lemma qhtr_%s : NonHalt tm_%s /\\ QHBoundTr 32779478 tm_%s /\\ QuasiHaltsTr tm_%s.\n'
                        'Proof. apply (%s tm_%s %d %d %d 32779478). all: vm_cast_no_check (eq_refl true). Qed.\n\n'
                        % (nm, nm, nm, nm, lem, nm, n1, P, W))
                rows.append((spec, 'qhtr_%s' % nm, 'ProvTr_QH_%s.v' % nn))
            f.write('Definition pqh_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join('tm_%s' % x for x in names))
            f.write('].\n\n')
            term = '(Forall_nil _)'
            for x in reversed(names):
                term = '(Forall_cons _ qhtr_%s %s)' % (x, term)
            f.write('Lemma pqh_%s_qhtr :\n  Forall (fun tm => NonHalt tm /\\ QHBoundTr 32779478 tm /\\ QuasiHaltsTr tm) pqh_%s.\n'
                    'Proof. exact %s. Qed.\n' % (nn, nn, term))
        n += 1
    with open(os.path.join(outdir, 'provtr_tcqh_manifest.tsv'), 'w') as f:
        for r in rows:
            f.write('\t'.join(r) + '\n')
    with open(os.path.join(outdir, 'provtr_tcqh_dropped.tsv'), 'w') as f:
        for c in drop:
            f.write('\t'.join(str(x) for x in c) + '\n')
    sys.stderr.write('staged %d certs into %d file(s) (%d probe-false dropped)\n'
                     % (len(keep), n - start, len(drop)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('phase', choices=['probe', 'stage'])
    ap.add_argument('args', nargs='+')
    ap.add_argument('--chunk', type=int, default=250)
    ap.add_argument('--start', type=int, default=0)
    a = ap.parse_args()
    if a.phase == 'probe':
        certs, outdir = read_certs(a.args[0]), a.args[1]
        probe(certs, outdir, a.chunk)
    else:
        certs, probedir, outdir = read_certs(a.args[0]), a.args[1], a.args[2]
        stage(certs, probedir, outdir, a.chunk, a.start)


if __name__ == '__main__':
    main()
