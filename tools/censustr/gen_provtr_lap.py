#!/usr/bin/env python3
"""Collect the transition-level lap boards (theories/Machines/CountersTr/
LAPT_*.v, emitted by tools/counters/emit_lapcert.py --tr) into proven-tier
stage lists for CensusTr/RunTr.v's [prov_tr].

Each board proves [nqhtr_<ID> : NeverQuasiHaltsTr tm_<ID>].  This emits

    theories/CensusTr/ProvTr_Lap_NN.v     Require Import <CHUNK boards>;
                                          ptl_NN : list TM;
                                          ptl_NN_nqhtr : Forall NeverQuasiHaltsTr ptl_NN

so [prov_tr] can append [ptl_00 ++ ptl_01 ++ ...] with [Forall_app].
UNTRUSTED bookkeeping: it only names theorems the kernel already checked;
a wrong name fails to compile.

Usage: gen_provtr_lap.py [--chunk N] [--boards DIR] [--outdir DIR]
"""
import argparse
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))

HEADER = '''(** GENERATED by tools/censustr/gen_provtr_lap.py -- DO NOT EDIT.

    Transition-level proven-tier stage {NN}: {CNT} counter machines
    boarded by lap CERTIFICATE at the instruction level
    (Machines/CountersTr/LAPT_*.v, closer Counters/LapGlueTr).  Append
    [ptl_{NN}] to [prov_tr] (CensusTr/RunTr.v). *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement.
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--chunk', type=int, default=200)
    ap.add_argument('--boards', default=os.path.join(REPO, 'theories', 'Machines', 'CountersTr'))
    ap.add_argument('--outdir', default=os.path.join(REPO, 'theories', 'CensusTr'))
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    boards = sorted(glob.glob(os.path.join(a.boards, 'LAPT*.v')))
    rows = []
    for b in boards:
        t = open(b).read()
        ms = re.findall(r'^Theorem (nqhtr_(\w+)) : NeverQuasiHaltsTr (tm_\w+)\.', t, re.M)
        if not ms:
            raise SystemExit('no nqhtr theorem in %s' % b)
        for th, _, tm in ms:
            rows.append((os.path.splitext(os.path.basename(b))[0], th, tm))
    nfiles = 0
    for ci in range(0, len(rows), a.chunk):
        nn = '%02d' % nfiles
        chunk = rows[ci:ci + a.chunk]
        with open(os.path.join(a.outdir, 'ProvTr_Lap_%s.v' % nn), 'w') as f:
            f.write(HEADER.replace('{NN}', nn).replace('{CNT}', str(len(chunk))))
            seen = []
            for mod, _, _ in chunk:
                if mod not in seen:
                    seen.append(mod)
                    f.write('From BBB4.Machines.CountersTr Require Import %s.\n' % mod)
            f.write('Import ListNotations.\n\n')
            f.write('Definition ptl_%s : list TM :=\n  [' % nn)
            f.write(';\n   '.join(tm for _, _, tm in chunk))
            f.write('].\n\n')
            f.write('Lemma ptl_%s_nqhtr : Forall NeverQuasiHaltsTr ptl_%s.\n' % (nn, nn))
            term = '(Forall_nil NeverQuasiHaltsTr)'
            for _, th, _ in reversed(chunk):
                term = '(Forall_cons _ %s %s)' % (th, term)
            f.write('Proof. exact %s. Qed.\n' % term)
        nfiles += 1
    print('%d boards -> %d stage file(s) in %s' % (len(rows), nfiles, a.outdir))


if __name__ == '__main__':
    main()
