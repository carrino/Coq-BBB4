#!/usr/bin/env python3
"""RWL8 big-block RepWL certificate emitter (wave-8 residue burn-down).

Fork of gen_repwl_certs.py's emission path, driven by the big-block sweep
tools/counters/repwl_bigblock.py (which matches block size L to a machine's
tape period, L in {5..20}, instead of the earlier L<=6 cap that wrongly
declared RepWL dead on the periodic-bouncer residue -- see
docs/MACHINE_NOTES_WAVE8.md, "the RepWL correction").

Input : a sweep TSV `machine<TAB>L<TAB>T<TAB>t<TAB>nseen` (the hits).
Output: one theories/Machines/RWL8_<NNNNN>.v per machine (failure isolation
        for the heavy closures) + tools/rwl8_manifest.tsv.

Each board is closed ONLY through the landed rw_check_neverqh_sound
(Checkers/RepWL.v) by `vm_compute; reflexivity` -- ZERO new soundness
surface.  Everything here is UNTRUSTED; the Coq kernel re-derives the
closure and re-checks every edge, so a wrong certificate fails to
TYPECHECK rather than mis-proving.  A board counts only when its file
`coqc -native-compiler no -Q theories BBB4` compiles and Print Assumptions
is functional_extensionality_dep only.

Usage:
  python3 tools/gen_rwl8_certs.py HITS.tsv [--start-idx N] [--only M1,M2]
"""

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import repwl_prover as rp
import gen_repwl_certs as gc

OUTDIR = os.path.join(ROOT, "theories", "Machines")

# Accurate provenance header (gc.HEADER credits gen_repwl_certs.py; these
# boards come from the big-block sweep instead).
HEADER = """(** Generated by tools/gen_rwl8_certs.py -- DO NOT EDIT.

    Never-quasihalting theorems for wave-8 residue machines caught by the
    BIG-BLOCK RepWL sweep (tools/counters/repwl_bigblock.py), which matches
    the abstraction block size L to a machine's tape period (L in {5..20})
    instead of the earlier L<=6 cap that wrongly declared RepWL dead on the
    periodic-bouncer residue (docs/MACHINE_NOTES_WAVE8.md, "the RepWL
    correction").  Each board is closed ONLY through the landed
    [rw_check_neverqh_sound] (Checkers/RepWL.v) by [vm_compute; reflexivity]
    -- zero new soundness surface.  Per machine: a TM definition, a
    certificate table over refined context keys (rconf_enc; untrusted data
    re-checked edge by edge by the engine), the theorem, and the [NonHalt]
    corollary.  The Coq kernel re-derives the closure and re-checks every
    edge, so a wrong certificate fails to TYPECHECK. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import RepWL.
Import ListNotations.

"""


def read_hits(path):
    hits = []
    for line in open(path):
        p = line.split()
        if not p:
            continue
        m, L, T = p[0], int(p[1]), int(p[2])
        hits.append((m, L, T))
    return hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("hits")
    ap.add_argument("--start-idx", type=int, default=1)
    ap.add_argument("--only", type=str, default="")
    args = ap.parse_args()

    hits = read_hits(args.hits)
    if args.only:
        want = set(args.only.split(","))
        hits = [h for h in hits if h[0] in want]
    hits.sort(key=lambda h: h[0])

    manifest = []
    idx = args.start_idx
    for (mtext, L, T) in hits:
        res = rp.decide(mtext, L, T, {})
        if res is None:
            print("FAIL   decide did not reproduce %s at L=%d T=%d"
                  % (mtext, L, T), flush=True)
            continue
        text, thm = gc.emit_machine(idx, mtext, L, T, res)
        fname = "RWL8_%05d.v" % idx
        open(os.path.join(OUTDIR, fname), "w").write(
            HEADER + text + "\n")
        manifest.append((mtext, thm, "theories/Machines/" + fname,
                         L, T, res["t"], res["nseen"]))
        print("OK     %-30s -> %s  L=%d T=%d t=%d contexts=%d"
              % (mtext, fname, L, T, res["t"], res["nseen"]), flush=True)
        idx += 1

    with open(os.path.join(HERE, "rwl8_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tL\tT\tt\tcontexts\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    print("emitted %d boards" % len(manifest))


if __name__ == "__main__":
    main()
