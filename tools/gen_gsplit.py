#!/usr/bin/env python3
"""Generate the per-grandchild census Qed files + the assembly theorem.

24 files theories/Census/Compute/G_<w><w2><d2><nx2>.v, each proving by
native conversion that its grandchild subtree's queue empties, plus
Census_Theorem.v assembling census_decided from them.  Compile the G_
files in parallel (make -j); each Qed is one subtree enumeration.

Usage: gen_gsplit.py OUTDIR [NITER]
"""
import sys, os

outdir = sys.argv[1]
niter = int(sys.argv[2]) if len(sys.argv) > 2 else 700
os.makedirs(outdir, exist_ok=True)

W = [('0', 'S0'), ('1', 'S1')]
D = [('L', 'DL'), ('R', 'DR')]
NX = [('A', 'StA'), ('B', 'StB'), ('C', 'StC')]

names = []
for w_t, w in W:
    for w2_t, w2 in W:
        for d_t, d in D:
            for nx_t, nx in NX:
                tag = f'{w_t}RB_{w2_t}{d_t}{nx_t}'
                names.append((tag, w, w2, d, nx))
                with open(os.path.join(outdir, f'G_{tag}.v'), 'w') as f:
                    f.write(f'''(** GENERATED by tools/gen_gsplit.py -- do not edit.
    Census subtree: A0 = {w_t}RB, B0 = {w2_t}{d_t}{nx_t}. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
Import ListNotations.

Lemma g_{tag}_empty :
  Nat.iter {niter} q_suc (q_gsub {w} {w2} {d} {nx}) = ([], []).
Proof.
  native_cast_no_check (eq_refl (@nil TNF_Node, @nil TNF_Node)).
Qed.

Lemma g_{tag}_decided :
  NodeDecided B_census D_census (node_tm (gchild {w} {w2} {d} {nx})).
Proof.
  exact (gsub_decided {w} {w2} {d} {nx} {niter} eq_refl g_{tag}_empty).
Qed.
''')

with open(os.path.join(outdir, 'Census_Theorem.v'), 'w') as f:
    f.write('''(** GENERATED by tools/gen_gsplit.py -- do not edit.

    The census theorem, assembled from the per-grandchild subtree
    computations (G_*.v) and the two single-leaf subtrees. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
''')
    for tag, *_ in names:
        f.write(f'From BBB4.Census.Compute Require Import G_{tag}.\n')
    f.write('''Import ListNotations.

Lemma sub_0RA_empty : Nat.iter 4 q_suc (q_sub S0 StA) = ([], []).
Proof. native_cast_no_check (eq_refl (@nil TNF_Node, @nil TNF_Node)). Qed.

Lemma sub_1RA_empty : Nat.iter 4 q_suc (q_sub S1 StA) = ([], []).
Proof. native_cast_no_check (eq_refl (@nil TNF_Node, @nil TNF_Node)). Qed.

''')
    for w_t, w in W:
        f.write(f'''Lemma child_{w_t}RB_decided :
  NodeDecided B_census D_census (node_tm (child {w} DR StB)).
Proof.
  apply child_from_grandchildren.
  intros w2 d2 nx2 Hok.
  destruct w2, d2, nx2; try discriminate Hok;
    first
''')
        alts = []
        for w2_t, w2 in W:
            for d_t, d in D:
                for nx_t, nx in NX:
                    alts.append(f'exact g_{w_t}RB_{w2_t}{d_t}{nx_t}_decided')
        f.write('      [ ' + '\n      | '.join(alts) + ' ].\nQed.\n\n')
    f.write('''(** The census: every 4-state 2-symbol Turing machine either has all
    its BBB scores (last visits of eventually-quiet states) below
    [B_census] = 2000, or lies in the swap/mirror/completion orbit of
    the explicit deferred list ([D_census]: the 3,713 BBB(4) holdouts
    plus the measured hard residue of the generic tiers). *)
Theorem census_decided :
  forall tm, QHBound B_census tm \\/ Deferred D_census tm.
Proof.
  apply census_from_subtrees.
  - exact (sub_decided S0 StA 4 eq_refl sub_0RA_empty).
  - exact (sub_decided S1 StA 4 eq_refl sub_1RA_empty).
  - exact child_0RB_decided.
  - exact child_1RB_decided.
Qed.

Print Assumptions census_decided.
''')
print(f'{len(names)} grandchild files + Census_Theorem.v')
