#!/usr/bin/env python3
"""Split state IRules computations while retaining the canonical board data.

Each public board keeps its original machine and certificate definitions and
theorem names. Its state theorem bodies delegate to independent small parts,
which run the original verified checker. The instruction generator continues
to read exactly the same canonical definitions from the public boards.
"""
import argparse
from pathlib import Path
import re

REPO = Path(__file__).resolve().parents[1]
MACHINES = REPO / 'theories/Machines'
CHUNK = 8
DATA_RE = re.compile(
    r'^(Definition tm_(\w+) : TM :=.*?\n  end\.\n)'
    r'\s*(Definition cert_\2 : IRCert :=.*?)(?=\nTheorem )', re.M | re.S)
PROOF_RE = re.compile(
    r'^(Theorem (ir_(\w+)_never_quasihalts) : NeverQuasiHaltsSt tm_\3\.\n)'
    r'Proof\..*?Qed\.', re.M | re.S)
HEADER = '''(** GENERATED by tools/gen_irules_state_parts.py.
    Original state certificates, checked independently in a small process. *)
From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta.
Import ListNotations.
Open Scope Z_scope.
Local Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
'''
IMPORT_ANCHOR = 'From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta.\n'
NOTE = ('(** State theorem bodies are generated by tools/gen_irules_state_parts.py.\n'
        '    Canonical machine/certificate definitions below remain the source for\n'
        '    tools/censustr/gen_irulestr_parts.py. *)\n')


def boards(machines=MACHINES):
    return {p: p.read_text() for p in sorted(machines.glob('IRules_Batch_*.v'))}


def definitions(source):
    return [(name, body + '\n' + cert.rstrip() + '\n')
            for body, name, cert in DATA_RE.findall(source)]


def render(sources=None):
    sources = boards() if sources is None else sources
    if len(sources) != 9:
        raise ValueError('expected the nine canonical state boards')
    outputs, inventory = {}, []
    for path, source in sources.items():
        rows = definitions(source)
        names = [name for name, _ in rows]
        proofs = [m[2] for m in PROOF_RE.findall(source)]
        if proofs != names:
            raise ValueError(f'certificate/proof order mismatch in {path}')
        inventory.extend(names)
        batch = path.stem.removeprefix('IRules_Batch_')
        parts, owner = [], {}
        for start in range(0, len(rows), CHUNK):
            part = f'IRulesStatePart_{batch}_{start // CHUNK:02d}'
            parts.append(part)
            body = [HEADER]
            for name, data in rows[start:start + CHUNK]:
                owner[name] = part
                body.append(data)
                body.append(
                    f'Theorem ir_{name}_never_quasihalts : NeverQuasiHaltsSt tm_{name}.\n'
                    'Proof.\n'
                    f'  apply (irules_check_neverqh_sound tm_{name} cert_{name} 300000%nat).\n'
                    '  vm_compute. reflexivity.\nQed.\n')
            outputs[path.parent / 'IRulesStateParts' / f'{part}.v'] = '\n'.join(body)
        wrapper = re.sub(
            r'^From BBB4\.Machines\.IRulesStateParts Require Import [^.]*\.\n',
            '', source, flags=re.M)
        wrapper = wrapper.replace(NOTE, '')
        if wrapper.count(IMPORT_ANCHOR) != 1:
            raise ValueError(f'expected the canonical checker imports in {path}')
        wrapper = wrapper.replace(
            IMPORT_ANCHOR, IMPORT_ANCHOR + NOTE +
            'From BBB4.Machines.IRulesStateParts Require Import ' + ' '.join(parts) + '.\n')
        wrapper = PROOF_RE.sub(
            lambda m: m[1] + f'Proof. exact {owner[m[3]]}.{m[2]}. Qed.', wrapper)
        outputs[path] = wrapper
    if len(inventory) != 250 or len(set(inventory)) != 250:
        raise ValueError('expected the 250 unique original state certificates')
    return outputs


def schedule(jobs, machines=MACHINES):
    if jobs < 1:
        raise ValueError('the IRules job limit must be positive')
    parts = sorted((machines / 'IRulesStateParts').glob('*.v'))
    names = [str(p.relative_to(machines.parents[1]).with_suffix('.vo')) for p in parts]
    return [(name, names[i - jobs]) for i, name in enumerate(names) if i >= jobs]


def generate(check=False):
    outputs = render()
    project = REPO / '_CoqProject'
    keep = [p for p in project.read_text().splitlines()
            if not p.startswith('theories/Machines/IRulesStateParts/')]
    part_paths = sorted(str(p.relative_to(REPO)) for p in outputs
                        if p.parent.name == 'IRulesStateParts')
    pos = keep.index('theories/Machines/IRules_Batch_00.v')
    outputs[project] = '\n'.join(keep[:pos] + part_paths + keep[pos:]) + '\n'
    stale = set((MACHINES / 'IRulesStateParts').glob('*.v')) - outputs.keys()
    if stale:
        raise ValueError(f'unexpected parts: {sorted(stale)}')
    changed = [p for p, source in outputs.items() if not p.exists() or p.read_text() != source]
    if check and changed:
        raise ValueError(f'stale generated files: {changed}')
    if not check:
        for path in changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[path])
    print(f'250 state certificates, {len(part_paths)} parts; '
          f'{"checked" if check else "wrote"} {len(outputs)} files')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--schedule', type=int, metavar='JOBS',
                        help='print order-only predecessor pairs for Makefile.coq.local')
    args = parser.parse_args()
    if args.schedule is not None:
        if args.schedule < 1:
            parser.error('--schedule must be positive')
        print(' '.join(f'{target}={predecessor}'
                       for target, predecessor in schedule(args.schedule)))
    else:
        generate(args.check)
