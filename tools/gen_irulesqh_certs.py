#!/usr/bin/env python3
"""Transcribe state-QH irules certificates (v3/v5/v6/v7) into staged
Coq batches for the census R_QH tier (wave 3).

Fork of tools/gen_irulesblkpfx_certs.py (same parse/emit conventions,
same BIRCertP literal), but the theorem is the census R_QH tier triple
[iqh tm = NonHalt /\ QHBound 2000 /\ QuasiHaltsSt], closed by
[irulesblkpfx_check_qh_sound] (Checkers/IRules/MetaBlkPfxQH.v) +
[vm_compute]: the certificate's forward-behavior model plus a witness
state [qz] that is prefix-visited but owns no transition in the fired
set, plus the score-window pass at B = 2000.

The witness [qz] and the B=2000 feasibility are read (UNTRUSTED) from
the certificate's [claim_trans] lines: a state is quiet iff it has a
finitely-fired (F) transition and no infinite (I) one; its last-visit
index must be < 2000 or the machine cannot satisfy QHBound 2000 and is
SKIPPED (reported).  The Coq kernel re-checks everything; a wrong pick
just fails to compile.

Files are RRStage-shaped for the batched wire follow-up
(docs/REROOT_LISTC_STAGE.md pattern): per machine [cqh_w3_NNNNN : iqh
tm_w3_NNNNN], per file [iqhstage_NN : list TM] and [iqhstage_NN_all :
Forall iqh iqhstage_NN] ([iqh] is definitionally the qhmap tier
predicate).

Usage: gen_irulesqh_certs.py OUTDIR MANIFEST.tsv CHUNKSIZE CERT [CERT ...]
       [--chunk0 N] [--idx0 N] [--append]   (stage MORE machines after a
       committed wave: first new file number, first new machine index,
       append manifest rows instead of rewriting)
"""
import sys, os, re, importlib.util

_spec = importlib.util.spec_from_file_location(
    "genbp", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "gen_irulesblkpfx_certs.py"))
G = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(G)

CFUEL = 200000
FUEL = 300000
B = 2000

HEADER = '''(** GENERATED by tools/gen_irulesqh_certs.py -- DO NOT EDIT.

    STAGED wave-3 list-C state-QH machines, chunk {NN} ({CNT} machines).
    SELF-CONTAINED and NOT imported by any census input yet: each
    machine [tm] gets [iqh tm] = [NonHalt /\\ QHBound 2000 /\\
    QuasiHaltsSt] via [irulesblkpfx_check_qh_sound]
    (Checkers/IRules/MetaBlkPfxQH.v): the Phase-2 block IRules model
    with a witness state that is prefix-visited but owns no transition
    in the meta-cycle's fired set (it goes quiet at the anchor), plus
    the score-window pass at B = 2000.  The certificates are UNTRUSTED
    search output (BBB bin/irules over the list-C residue); every
    claim is re-checked by the verified engine.  Ready to board the
    R_QH tier: append [iqhstage_{NN}] to [reroot_qh_list]
    (Census/RerootQH_Data.v) -- see docs/REROOT_LISTC_STAGE.md. *)

From Coq Require Import ZArith List Lia.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Cycle.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
     EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx MetaQH
     MetaBlkPfxQH.
From BBB4.Census Require Import TNF_QH.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).

Definition iqh (tm : TM) : Prop :=
  NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm.
'''


def quiet_state(path):
    """UNTRUSTED: (witness_state, last_visit) from claim_trans lines.
    A state is quiet iff it has >=1 F transition and 0 I transitions."""
    t = open(path).read()
    trans = {}
    for mm in re.finditer(r'^claim_trans (\w)(\d) (\w) (\d+) (\d+)', t, re.M):
        trans.setdefault(mm.group(1), []).append(
            (mm.group(3), int(mm.group(5))))
    for q in "ABCD":
        cl = trans.get(q, [])
        if any(c == 'F' for c, _ in cl) and not any(c == 'I' for c, _ in cl):
            return q, max(l for c, l in cl if c == 'F')
    return None, None


def emit_machine(path, idx):
    c = G.parse_cert(path)
    m = c["machine"]
    qz, last = quiet_state(path)
    if qz is None:
        return None, (m, "no-quiet-state")
    if last >= B:
        return None, (m, "last-visit>=B:%d" % last)
    nm = "w3_%05d" % idx
    a, b = c["meta_a"], c["meta_b"]
    s = []
    s.append("(* %s : quiet %s (last visit %d), anchor %d, ver %s *)"
             % (m, qz, last, c["anchor_step"], c.get("ver", "?")))
    s.append("Definition tm_%s : TM := fun q s =>" % nm)
    s.append("  match q, s with")
    s.append(G.emit_tm(m))
    s.append("  end.")
    s.append("Definition cert_%s : BIRCertP := mkBIRCertP" % nm)
    s.append("  %d%%nat (%d) (%d) (%d) (%d) %s S%d"
             % (c["anchor_step"], c["k0"], c["kmin"], a, b,
                G.ST[c["tpl_state"]], c["tpl_hsym"]))
    s.append("  %s" % G.emit_blks(c["blk"]))
    s.append("  %s" % G.emit_tpl(c["tplL"]))
    s.append("  %s" % G.emit_tpl(c["tplR"]))
    s.append("  %s." % G.emit_rules(c["rules"], c["pfx"]))
    s.append("Lemma cqh_%s : iqh tm_%s." % (nm, nm))
    s.append("Proof.")
    s.append("  apply (irulesblkpfx_check_qh_sound tm_%s cert_%s St%s "
             "%d %d %d)." % (nm, nm, qz, B, CFUEL, FUEL))
    s.append("  vm_compute. reflexivity.")
    s.append("Qed.")
    return ("\n".join(s), nm), (m, "ok:%s:%d" % (qz, last))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    outdir, manifest, chunk = args[0], args[1], int(args[2])
    certs = args[3:]
    def _optval(name, default):
        if name in sys.argv:
            return int(sys.argv[sys.argv.index(name) + 1])
        return default
    chunk0 = _optval("--chunk0", 0)
    idx0 = _optval("--idx0", 0)
    append = "--append" in sys.argv
    if chunk0 or idx0:
        certs = [c for c in certs if not c.isdigit()]
    os.makedirs(outdir, exist_ok=True)
    emitted = []          # (machine, nm, qz, last, anchor, ver)
    skipped = []
    idx = idx0
    blocks = []
    for p in certs:
        r, (m, status) = emit_machine(p, idx)
        if r is None:
            skipped.append((m, status))
            continue
        body, nm = r
        c = G.parse_cert(p)
        qz, last = quiet_state(p)
        emitted.append((m, nm, qz, last, c["anchor_step"],
                        c.get("ver", "?")))
        blocks.append(body)
        idx += 1
    nfiles = 0
    rows = []
    for ci in range(0, len(blocks), chunk):
        nn = "%02d" % (chunk0 + nfiles)
        chunk_blocks = blocks[ci:ci + chunk]
        chunk_names = [e[1] for e in emitted[ci:ci + chunk]]
        fn = os.path.join(outdir, "IQHStage_%s.v" % nn)
        with open(fn, "w") as f:
            f.write(HEADER.replace("{NN}", nn)
                    .replace("{CNT}", str(len(chunk_blocks))) + "\n")
            f.write("\n\n".join(chunk_blocks) + "\n\n")
            f.write("Definition iqhstage_%s : list TM :=\n  [" % nn)
            f.write(";\n   ".join("tm_%s" % n for n in chunk_names))
            f.write("].\n\n")
            f.write("Lemma iqhstage_%s_all : Forall iqh iqhstage_%s.\n"
                    % (nn, nn))
            term = "(Forall_nil iqh)"
            for n in reversed(chunk_names):
                term = "(Forall_cons _ cqh_%s %s)" % (n, term)
            f.write("Proof. exact %s. Qed.\n" % term)
        for e in emitted[ci:ci + chunk]:
            rows.append((e[0], "cqh_%s" % e[1], "IQHStage_%s.v" % nn,
                         e[2], str(e[3]), str(e[4]), e[5]))
        nfiles += 1
    with open(manifest, "a" if append else "w") as f:
        if not append:
            f.write("machine\ttheorem\tfile\tquiet_state\tlast_visit\t"
                    "anchor\tcert_ver\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    sys.stderr.write("emitted %d machines into %d files; skipped %d\n"
                     % (len(emitted), nfiles, len(skipped)))
    for m, st in skipped:
        sys.stderr.write("  skip %s: %s\n" % (m, st))


if __name__ == "__main__":
    main()
