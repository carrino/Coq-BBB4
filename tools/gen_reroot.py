#!/usr/bin/env python3
"""Generate the census RE-ROOT quasihalting tier (UNTRUSTED emitter).

Input: a TSV of boarded list-B <=3-state re-root machines, columns
  census_machine  q*  t*  core_row_coq  Sset_states  qz  qz_step  rung_L

For each row it emits a census-grade quasihalting theorem
  [NonHalt /\ QHBound 2000 /\ QuasiHaltsSt] tm
proved through Census/Reroot.v's [qh_reroot]: the re-root [TM_swap StA q* tm]
is certified NEVER-quasihalting by the census's own [rw_tier] on the concrete
core row, and [tm]'s quiet prefix state (whose re-root image is silent, via the
reachable-state closure) supplies [QuasiHaltsSt].  The Coq kernel re-checks
every step; nothing here is trusted.

Files: theories/Census/RerootQH_NN.v (chunks) + RerootQH_Data.v (assembly).
Usage: gen_reroot.py CAUGHT_TSV OUTDIR [--chunk N]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

HDR_CHUNK = """(** GENERATED by tools/gen_reroot.py -- DO NOT EDIT.

    Re-root census-grade quasihalters, chunk {nn} ({cnt} machines).
    Each list-B 0RB machine [tm] is boarded by [qh_reroot] (Census/Reroot.v):
    the re-root [TM_swap StA q* tm] is a tiny never-quasihalting core
    ([rw_tier_sound]); [tm] quasihalts via its silent prefix state. *)
From Coq Require Import List Lia.
From BBB4 Require Import BBB4_Statement.
From BBB4.Checkers Require Import RepWL.
From BBB4.Census Require Import TNF_QH Decide Deferred_Defs RepWLSearch Reroot.
Import ListNotations.

Definition rrqh (tm : TM) : Prop :=
  NonHalt tm /\ QHBound 2000 tm /\ QuasiHaltsSt tm.
"""


def gen_lemma(tag, cm, qstar, tstar, core_row, sset, qz, qzstep, L):
    slots = "; ".join(_slots_of(cm))
    live = sset.split(";")
    match_arms = " | ".join(live) + " => true" if live and live != [''] else "StA => true"
    sset_def = "fun q => match q with %s | _ => false end" % match_arms
    return f"""
Definition tm_{tag} : TM := row_to_tm [{slots}].
Definition core_{tag} : TM := row_to_tm {core_row}.
Definition S_{tag} : St -> bool := {sset_def}.
Lemma cqh_{tag} : rrqh tm_{tag}.
Proof.
  assert (Heq : TM_swap StA {qstar} tm_{tag} = core_{tag})
    by (apply tm_eqb_eq; vm_compute; reflexivity).
  assert (Htrip : NonHalt tm_{tag} /\\ QHBound {tstar} tm_{tag} /\\ QuasiHaltsSt tm_{tag}).
  {{ apply (qh_reroot tm_{tag} {qstar} {tstar} S_{tag} {qz}).
     - apply prefix_ok_sound; vm_compute; reflexivity.
     - rewrite Heq. apply (rw_tier_sound core_{tag} {L} 2 0 8192); vm_compute; reflexivity.
     - vm_compute; reflexivity.
     - rewrite Heq; vm_compute; reflexivity.
     - vm_compute; reflexivity.
     - apply (visited_prefix tm_{tag} {qz} {qzstep}); vm_compute; reflexivity. }}
  destruct Htrip as (Hnh & Hqb & Hqh).
  split; [exact Hnh | split; [ apply (qhbound_mono {tstar} 2000 tm_{tag}); [lia | exact Hqb] | exact Hqh ] ].
Qed.
"""


# --- census-string -> row_to_tm slot shorthands (bbchallenge slot order) ---
_SL = {'A': 'A', 'B': 'B', 'C': 'C', 'D': 'D'}


def _slots_of(cm):
    blocks = cm.split('_')
    out = []
    for b in blocks:
        for i in (0, 3):
            tr = b[i:i+3]
            if tr == '---':
                out.append('tN')
            else:
                out.append('t' + tr[0] + tr[1] + tr[2])
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    caught, outdir = args[0], args[1]
    chunk = 100
    if '--chunk' in sys.argv:
        chunk = int(sys.argv[sys.argv.index('--chunk') + 1])
    rows = [l.rstrip('\n').split('\t') for l in open(caught) if l.strip()]
    # stable order + dedup by census string
    seen = set()
    urows = []
    for r in rows:
        if r[0] in seen:
            continue
        seen.add(r[0])
        urows.append(r)
    urows.sort(key=lambda r: r[0])
    nchunks = (len(urows) + chunk - 1) // chunk
    chunk_names = []
    boarded = []
    for ci in range(nchunks):
        part = urows[ci*chunk:(ci+1)*chunk]
        nn = '%02d' % ci
        name = 'RerootQH_%s' % nn
        chunk_names.append(name)
        body = [HDR_CHUNK.format(nn=nn, cnt=len(part))]
        tags = []
        for k, r in enumerate(part):
            cm, qstar, tstar, core_row, sset, qz, qzstep, L = r[:8]
            tag = 'rr_%s%03d' % (nn, k)
            tags.append(tag)
            boarded.append(cm)
            body.append(gen_lemma(tag, cm, 'St'+qstar[-1] if not qstar.startswith('St') else qstar,
                                  tstar, core_row, sset,
                                  'St'+qz[-1] if not qz.startswith('St') else qz,
                                  qzstep, L))
        # list + Forall cert (nested term, O(n))
        body.append('\nDefinition %s : list TM :=\n  [%s].\n' %
                    (name.lower(), ';\n   '.join('tm_'+t for t in tags)))
        term = 'Forall_nil rrqh'
        for t in reversed(tags):
            term = 'Forall_cons _ cqh_%s (%s)' % (t, term)
        body.append('Lemma %s_all : Forall rrqh %s.\nProof. exact (%s). Qed.\n'
                    % (name.lower(), name.lower(), term))
        open(os.path.join(outdir, name + '.v'), 'w').write('\n'.join(body))
    # data assembly
    imports = ' '.join(chunk_names)
    concat = ' ++ '.join(n.lower() for n in chunk_names) if chunk_names else '[]'
    allproof = []
    for i, n in enumerate(chunk_names):
        if i < len(chunk_names) - 1:
            allproof.append('  apply Forall_app; split; [exact %s_all|].' % n.lower())
        else:
            allproof.append('  exact %s_all.' % n.lower())
    data = '''(** GENERATED by tools/gen_reroot.py -- DO NOT EDIT.

    The census re-root quasihalting tier: list-B 0RB residue machines with a
    committed census-grade quasihalting theorem, transferred from a tiny
    never-quasihalting core by [qh_reroot] (Census/Reroot.v).  Composed with
    the proven-QH tier (Run.v) as extra R_QH lookup members. *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH {imports}.
Import ListNotations.

Definition reroot_qh_list : list TM :=
  {concat}.

Lemma reroot_qh_all :
  Forall (fun tm => NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm)
         reroot_qh_list.
Proof.
  unfold reroot_qh_list.
{allproof}
Qed.
'''.format(imports=imports, concat=concat, allproof='\n'.join(allproof))
    open(os.path.join(outdir, 'RerootQH_Data.v'), 'w').write(data)
    open(os.path.join(HERE, 'reroot_boarded.txt'), 'w').write(
        '\n'.join(sorted(boarded)) + '\n')
    print('chunks:', chunk_names, 'boarded:', len(boarded))


if __name__ == '__main__':
    main()
