#!/usr/bin/env python3
"""Generate the census RE-ROOT quasihalting tier (UNTRUSTED emitter).

Input: a TSV of boarded list-B <=3-state re-root machines, columns
  census_machine  q*  t*  core_row_coq  Sset_states  qz  qz_step  rung_L

For each row it emits a census-grade quasihalting theorem
  [NonHalt /\ QHBound 2000 /\ QuasiHaltsSt] tm
proved through Census/Reroot.v's [qh_reroot]: the re-root [TM_swap StA q* tm]
is certified NEVER-quasihalting by the census's own [rw_tier] on the concrete
core row, and [tm]'s quiet prefix state (whose re-root image is silent, via the
reachable-state closure) supplies [QuasiHaltsSt].  The Coq kernel re-checks
every step; nothing here is trusted.

Files: theories/Census/RerootQH_NN.v (chunks) + RerootQH_Data.v (assembly).
Usage: gen_reroot.py CAUGHT_TSV OUTDIR [--chunk N]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

HDR_CHUNK = """(** GENERATED by tools/gen_reroot.py -- DO NOT EDIT.

    Re-root census-grade quasihalters, chunk {nn} ({cnt} machines).
    Each list-B 0RB machine [tm] is boarded by [qh_reroot] (Census/Reroot.v):
    the re-root [TM_swap StA q* tm] is a tiny never-quasihalting core
    ([rw_tier_sound]); [tm] quasihalts via its silent prefix state. *)
From Coq Require Import List Lia.
From BBB4 Require Import BBB4_Statement.
From BBB4.Checkers Require Import RepWL.
From BBB4.Census Require Import TNF_QH Decide Deferred_Defs RepWLSearch Reroot.
Import ListNotations.

Definition rrqh (tm : TM) : Prop :=
  NonHalt tm /\ QHBound 2000 tm /\ QuasiHaltsSt tm.
"""


def gen_lemma(tag, cm, qstar, tstar, core_row, sset, qz, qzstep, L):
    slots = "; ".join(_slots_of(cm))
    live = sset.split(";")
    match_arms = " | ".join(live) + " => true" if live and live != [''] else "StA => true"
    sset_def = "fun q => match q with %s | _ => false end" % match_arms
    return f"""
Definition tm_{tag} : TM := row_to_tm [{slots}].
Definition core_{tag} : TM := row_to_tm {core_row}.
Definition S_{tag} : St -> bool := {sset_def}.
Lemma cqh_{tag} : rrqh tm_{tag}.
Proof.
  assert (Heq : TM_swap StA {qstar} tm_{tag} = core_{tag})
    by (apply tm_eqb_eq; vm_compute; reflexivity).
  assert (Htrip : NonHalt tm_{tag} /\\ QHBound {tstar} tm_{tag} /\\ QuasiHaltsSt tm_{tag}).
  {{ apply (qh_reroot tm_{tag} {qstar} {tstar} S_{tag} {qz}).
     - apply prefix_ok_sound; vm_compute; reflexivity.
     - rewrite Heq. apply (rw_tier_sound core_{tag} {L} 2 0 8192); vm_compute; reflexivity.
     - vm_compute; reflexivity.
     - rewrite Heq; vm_compute; reflexivity.
     - vm_compute; reflexivity.
     - apply (visited_prefix tm_{tag} {qz} {qzstep}); vm_compute; reflexivity. }}
  destruct Htrip as (Hnh & Hqb & Hqh).
  split; [exact Hnh | split; [ apply (qhbound_mono {tstar} 2000 tm_{tag}); [lia | exact Hqb] | exact Hqh ] ].
Qed.
"""


# --- census-string -> row_to_tm slot shorthands (bbchallenge slot order) ---
_SL = {'A': 'A', 'B': 'B', 'C': 'C', 'D': 'D'}


def _slots_of(cm):
    blocks = cm.split('_')
    out = []
    for b in blocks:
        for i in (0, 3):
            tr = b[i:i+3]
            if tr == '---':
                out.append('tN')
            else:
                out.append('t' + tr[0] + tr[1] + tr[2])
    return out


# --------------------------------------------------------------------------
# STAGED mode (wave 2): additional base-checker recipes + self-contained
# theories/Machines/ output that is NOT wired into any census input.
#
# Each core's NEVER-quasihalting obligation (the second [qh_reroot] premise)
# is discharged by whichever sound census checker decides it -- not only the
# original [rw_tier].  Recipe names encode the exact checker + params, decoded
# to a [vm_compute]-closed [apply] here.  All three checkers are already-proven
# sound (RepWLSearch.rw_tier_sound / RankSearch.rank_tier_sound /
# NGram.ngram_check_neverqh_sound); this only chooses which to apply, so it
# adds NO new trust surface (the Coq kernel re-checks every core).
# --------------------------------------------------------------------------

HDR_STAGED = """(** GENERATED by tools/gen_reroot.py --staged -- DO NOT EDIT.

    STAGED re-root census-grade quasihalters, wave-2 chunk {nn} ({cnt}
    machines).  SELF-CONTAINED and NOT imported by any census input yet:
    each list-B 0RB machine [tm] gets [rrqh tm] = [NonHalt /\\ QHBound 2000
    /\\ QuasiHaltsSt] via [qh_reroot] (Census/Reroot.v), the re-root
    [TM_swap StA q* tm] being certified never-quasihalting by a per-core
    base checker ({recipe_kinds}).  Ready to board the R_QH tier: append
    [rrstage_{nn}] to [reroot_qh_list] (Census/RerootQH_Data.v) -- see
    docs/REROOT_LISTC_STAGE.md. *)
From Coq Require Import List Lia.
From BBB4 Require Import BBB4_Statement.
From BBB4.Checkers Require Import RepWL NGram.
From BBB4.Census Require Import TNF_QH Decide Deferred_Defs RepWLSearch RankSearch Reroot.
Import ListNotations.

Definition rrqh (tm : TM) : Prop :=
  NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm.
"""


def recipe_tactic(recipe, core):
    """Decode a recipe name to the [apply ...] that proves
    [NeverQuasiHaltsSt core].  Every target lemma is already sound.
       rw_L_T_fuel    -> rw_tier_sound   core L T 0 fuel
       rk_n_fuel_rnds -> rank_tier_sound core n 0 fuel rounds
       ng_n_fuel_rnds -> ngram_check_neverqh_sound core n 0 fuel rounds
    """
    p = recipe.split('_')
    kind = p[0]
    if kind == 'rw':
        L, T, fuel = p[1], p[2], p[3]
        return ('apply (rw_tier_sound %s %s %s 0 %s); vm_compute; reflexivity.'
                % (core, L, T, fuel))
    if kind == 'rk':
        n, fuel, rounds = p[1], p[2], p[3]
        return ('apply (rank_tier_sound %s %s 0 %s %s); vm_compute; reflexivity.'
                % (core, n, fuel, rounds))
    if kind == 'ng':
        n, fuel, rounds = p[1], p[2], p[3]
        return ('apply (ngram_check_neverqh_sound %s %s 0 %s %s); vm_compute; reflexivity.'
                % (core, n, fuel, rounds))
    raise SystemExit('unknown recipe: ' + recipe)


RECIPE_KIND_NAMES = {'rw': 'RepWL rw_tier', 'rk': 'NGram rank_tier',
                     'ng': 'NGram plain'}


def gen_lemma_staged(tag, cm, qstar, tstar, core_row, sset, qz, qzstep, recipe):
    slots = "; ".join(_slots_of(cm))
    live = [s for s in sset.split(";") if s]
    match_arms = " | ".join(live) + " => true" if live else "StA => true"
    sset_def = "fun q => match q with %s | _ => false end" % match_arms
    tac = recipe_tactic(recipe, 'core_%s' % tag)
    return f"""
Definition tm_{tag} : TM := row_to_tm [{slots}].
Definition core_{tag} : TM := row_to_tm {core_row}.
Definition S_{tag} : St -> bool := {sset_def}.
Lemma cqh_{tag} : rrqh tm_{tag}.
Proof.
  assert (Heq : TM_swap StA {qstar} tm_{tag} = core_{tag})
    by (apply tm_eqb_eq; vm_compute; reflexivity).
  assert (Htrip : NonHalt tm_{tag} /\\ QHBound {tstar} tm_{tag} /\\ QuasiHaltsSt tm_{tag}).
  {{ apply (qh_reroot tm_{tag} {qstar} {tstar} S_{tag} {qz}).
     - apply prefix_ok_sound; vm_compute; reflexivity.
     - rewrite Heq. {tac}
     - vm_compute; reflexivity.
     - rewrite Heq; vm_compute; reflexivity.
     - vm_compute; reflexivity.
     - apply (visited_prefix tm_{tag} {qz} {qzstep}); vm_compute; reflexivity. }}
  destruct Htrip as (Hnh & Hqb & Hqh).
  split; [exact Hnh | split; [ apply (qhbound_mono {tstar} 2000 tm_{tag}); [lia | exact Hqb] | exact Hqh ] ].
Qed.
"""


def main_staged():
    """--staged CAUGHT_TSV OUTDIR [--chunk N] [--prefix RRStage]
    CAUGHT_TSV columns: census_machine qstar tstar core_row_coq
                        Sset_states qz qz_step recipe   (qstar/qz = 'StX')."""
    argv = sys.argv[1:]
    argv.remove('--staged')
    pos = [a for a in argv if not a.startswith('--')]
    caught, outdir = pos[0], pos[1]
    chunk = 100
    if '--chunk' in argv:
        chunk = int(argv[argv.index('--chunk') + 1])
    prefix = 'RRStage'
    if '--prefix' in argv:
        prefix = argv[argv.index('--prefix') + 1]
    rows = [l.rstrip('\n').split('\t') for l in open(caught) if l.strip()]
    seen = set(); urows = []
    for r in rows:
        if r[0] in seen:
            continue
        seen.add(r[0]); urows.append(r)
    urows.sort(key=lambda r: r[0])
    os.makedirs(outdir, exist_ok=True)
    nchunks = (len(urows) + chunk - 1) // chunk
    manifest = []
    chunk_names = []
    for ci in range(nchunks):
        part = urows[ci*chunk:(ci+1)*chunk]
        nn = '%02d' % ci
        name = '%s_%s' % (prefix, nn)
        chunk_names.append(name)
        kinds = sorted({RECIPE_KIND_NAMES[r[7].split('_')[0]] for r in part})
        body = [HDR_STAGED.format(nn=nn, cnt=len(part),
                                  recipe_kinds=", ".join(kinds))]
        tags = []
        for k, r in enumerate(part):
            cm, qstar, tstar, core_row, sset, qz, qzstep, recipe = r[:8]
            tag = 's_%s%03d' % (nn, k)
            tags.append(tag)
            body.append(gen_lemma_staged(tag, cm, qstar, tstar, core_row,
                                         sset, qz, qzstep, recipe))
            manifest.append((cm, 'cqh_%s' % tag,
                             'theories/Machines/RerootStage/%s.v' % name,
                             recipe, 'R_QH'))
        listname = name.lower()
        body.append('\nDefinition %s : list TM :=\n  [%s].\n' %
                    (listname, ';\n   '.join('tm_'+t for t in tags)))
        term = 'Forall_nil rrqh'
        for t in reversed(tags):
            term = 'Forall_cons _ cqh_%s (%s)' % (t, term)
        body.append('Lemma %s_all : Forall rrqh %s.\nProof. exact (%s). Qed.\n'
                    % (listname, listname, term))
        open(os.path.join(outdir, name + '.v'), 'w').write('\n'.join(body))
    mpath = os.path.join(HERE, 'reroot_stage_manifest.tsv')
    with open(mpath, 'w') as mf:
        mf.write('machine\ttheorem\tfile\trecipe\ttier\n')
        for row in manifest:
            mf.write('\t'.join(row) + '\n')
    print('staged chunks:', chunk_names, 'machines:', len(manifest),
          'manifest:', mpath)


def main():
    if '--staged' in sys.argv:
        return main_staged()
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    caught, outdir = args[0], args[1]
    chunk = 100
    if '--chunk' in sys.argv:
        chunk = int(sys.argv[sys.argv.index('--chunk') + 1])
    rows = [l.rstrip('\n').split('\t') for l in open(caught) if l.strip()]
    # stable order + dedup by census string
    seen = set()
    urows = []
    for r in rows:
        if r[0] in seen:
            continue
        seen.add(r[0])
        urows.append(r)
    urows.sort(key=lambda r: r[0])
    nchunks = (len(urows) + chunk - 1) // chunk
    chunk_names = []
    boarded = []
    for ci in range(nchunks):
        part = urows[ci*chunk:(ci+1)*chunk]
        nn = '%02d' % ci
        name = 'RerootQH_%s' % nn
        chunk_names.append(name)
        body = [HDR_CHUNK.format(nn=nn, cnt=len(part))]
        tags = []
        for k, r in enumerate(part):
            cm, qstar, tstar, core_row, sset, qz, qzstep, L = r[:8]
            tag = 'rr_%s%03d' % (nn, k)
            tags.append(tag)
            boarded.append(cm)
            body.append(gen_lemma(tag, cm, 'St'+qstar[-1] if not qstar.startswith('St') else qstar,
                                  tstar, core_row, sset,
                                  'St'+qz[-1] if not qz.startswith('St') else qz,
                                  qzstep, L))
        # list + Forall cert (nested term, O(n))
        body.append('\nDefinition %s : list TM :=\n  [%s].\n' %
                    (name.lower(), ';\n   '.join('tm_'+t for t in tags)))
        term = 'Forall_nil rrqh'
        for t in reversed(tags):
            term = 'Forall_cons _ cqh_%s (%s)' % (t, term)
        body.append('Lemma %s_all : Forall rrqh %s.\nProof. exact (%s). Qed.\n'
                    % (name.lower(), name.lower(), term))
        open(os.path.join(outdir, name + '.v'), 'w').write('\n'.join(body))
    # data assembly
    imports = ' '.join(chunk_names)
    concat = ' ++ '.join(n.lower() for n in chunk_names) if chunk_names else '[]'
    allproof = []
    for i, n in enumerate(chunk_names):
        if i < len(chunk_names) - 1:
            allproof.append('  apply Forall_app; split; [exact %s_all|].' % n.lower())
        else:
            allproof.append('  exact %s_all.' % n.lower())
    data = '''(** GENERATED by tools/gen_reroot.py -- DO NOT EDIT.

    The census re-root quasihalting tier: list-B 0RB residue machines with a
    committed census-grade quasihalting theorem, transferred from a tiny
    never-quasihalting core by [qh_reroot] (Census/Reroot.v).  Composed with
    the proven-QH tier (Run.v) as extra R_QH lookup members. *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH {imports}.
Import ListNotations.

Definition reroot_qh_list : list TM :=
  {concat}.

Lemma reroot_qh_all :
  Forall (fun tm => NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm)
         reroot_qh_list.
Proof.
  unfold reroot_qh_list.
{allproof}
Qed.
'''.format(imports=imports, concat=concat, allproof='\n'.join(allproof))
    open(os.path.join(outdir, 'RerootQH_Data.v'), 'w').write(data)
    open(os.path.join(HERE, 'reroot_boarded.txt'), 'w').write(
        '\n'.join(sorted(boarded)) + '\n')
    print('chunks:', chunk_names, 'boarded:', len(boarded))


if __name__ == '__main__':
    main()
