#!/usr/bin/env python3
"""Bulk certificate-table generator: BBB neverqh_rank / neverqh_ngram
certs -> generated Coq theorem files.

For every machine in the BBB harness's results/certs_rank and
results/certs_neverqh (deduplicated), run the untrusted prover
(bulk_prover.decide: n-gram closure + ranking rules a/b with the full
pattern-measure vocabulary), and emit batched .v files under
theories/Machines/Bulk/, each machine getting

  - a TM definition,
  - a certificate table (encoded-key [NgRankE]/[NgPattE] components),
  - a theorem  NeverQuasiHaltsSt tm  closed by vm_compute through
    ngram_check_neverqh_lex_sound.

Everything emitted is UNTRUSTED data; the Coq checker re-derives the
closure and re-checks every edge.  A manifest TSV (machine, theorem,
file, n, t, contexts) is written next to this script.

Usage:
  python3 tools/gen_bulk_certs.py [--limit N] [--batch B] [--only M1,M2]
Env: BBB_REPO (default ../../BBB relative to this script).
"""

import argparse
import glob
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bulk_prover as bp

BBB = os.environ.get("BBB_REPO", os.path.join(ROOT, "..", "BBB"))
OUTDIR = os.path.join(ROOT, "theories", "Machines", "Bulk")

HEADER = """(** Generated by tools/gen_bulk_certs.py -- DO NOT EDIT.

    Bulk never-quasihalting theorems for the BBB harness's
    neverqh_rank / neverqh_ngram certificate machines: per machine a
    TM definition, an n-gram ranking certificate (encoded-key
    tables; untrusted data re-checked by the engine), and the
    theorem, closed by vm_compute. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import NGram.
Import ListNotations.

"""


def syms_app(l, p):
    p = 2 * p  # end-of-list marker: syms_app [] p = xO p
    for x in reversed(l):
        p = 2 * (2 * p + x) + 1
    return p


def cconf_enc(a):
    """Mirror of PosEnc.cconf_enc: st_app q (sym_app h (syms_app l
    (syms_enc r)))."""
    q, s, lw, rw = a
    p = syms_app(rw, 1)
    p = syms_app(lw, p)
    p = 2 * p + s
    return 4 * p + q


def fmt_nat(v):
    if v <= 5000:
        return str(v)
    return "(%s * 1000 + %d)" % (fmt_nat(v // 1000), v % 1000)


def coq_patt(patt):
    return "[" + "; ".join("S%d" % x for x in patt) + "]"


def emit_tm(name, mtext):
    tbl = bp.parse(mtext)
    lines = ["Definition %s : TM := fun q s =>" % name,
             "  match q, s with"]
    for qi in range(4):
        for si in range(2):
            tr = tbl[(qi, si)]
            lhs = "St%s, S%d" % (chr(65 + qi), si)
            if tr is None:
                lines.append("  | %s => None" % lhs)
            else:
                w, d, q2 = tr
                lines.append("  | %s => Some (mkTrans S%d D%s St%s)"
                             % (lhs, w, d, chr(65 + q2)))
    lines.append("  end.")
    return "\n".join(lines)


def emit_phi(phi):
    items = sorted((cconf_enc(a), v) for a, v in phi.items() if v != 0)
    return "[" + ";\n     ".join("(%d%%positive, %s)" % (e, fmt_nat(v))
                                 for e, v in items) + "]"


def emit_gate(gate):
    items = sorted(cconf_enc(a) for a in gate)
    return "[" + ";\n     ".join("%d%%positive" % e for e in items) + "]"


def emit_comp(comp):
    if comp[0] == "rank":
        return "NgRankE\n    %s" % emit_phi(comp[1])
    _, patt, reg, K, phi, gate = comp
    return "NgPattE %s Rg%s %s\n    %s\n    %s" % (
        coq_patt(patt), reg, fmt_nat(K), emit_phi(phi), emit_gate(gate))


def sanitize(mtext):
    return mtext.replace("---", "XXX")


def emit_machine(idx, mtext, n, t, comps_by_state, nseen, rounds):
    """rounds must bound the *donation-gated* Coq ng_grow iteration
    count: each non-final round adds at least one gram, and the Coq
    sets stay inside the Python fixpoint, so |lset|+|rset|+slack is
    sound (the Python round count is NOT: gated growth is slower)."""
    name = "tm_bulk_%05d" % idx
    cname = "cert_bulk_%05d" % idx
    fuel = 8 * nseen + 64
    out = []
    out.append("(** %s: n=%d t=%d contexts=%d *)" % (mtext, n, t, nseen))
    out.append(emit_tm(name, mtext))
    per_state = []
    for qi in range(4):
        comps = comps_by_state.get(qi, [])
        body = ("[" + ";\n   ".join(emit_comp(c) for c in comps) + "]"
                if comps else "[]")
        per_state.append("  | St%s =>\n  %s" % (chr(65 + qi), body))
    out.append("Definition %s (q : St) : list ngcomp :=\n  match q with\n%s\n  end."
               % (cname, "\n".join(per_state)))
    out.append("""Theorem nqh_%s : NeverQuasiHaltsSt %s.
Proof.
  apply (ngram_check_neverqh_lex_sound _ %d %s %s %s %s).
  vm_compute. reflexivity.
Qed.""" % (sanitize(mtext), name, n, fmt_nat(t), fmt_nat(fuel),
           fmt_nat(rounds), cname))
    return "\n\n".join(out), "nqh_" + sanitize(mtext)


def collect_machines():
    files = sorted(glob.glob(BBB + "/results/certs_rank/*.cert")) + \
        sorted(glob.glob(BBB + "/results/certs_neverqh/*.cert"))
    seen = set()
    uniq = []
    for f in files:
        m = os.path.basename(f)[:-5]
        if m not in seen:
            seen.add(m)
            uniq.append(f)
    return uniq


def work(path):
    mtext, n, per_state = bp.parse_cert_measures(path)
    r = bp.decide(mtext, n, per_state)
    if r is None:
        return (mtext, n, None)
    t, seen, lset, rset, comps, _rounds = r
    coq_rounds = len(lset) + len(rset) + 4
    return (mtext, n, (t, len(seen), comps, coq_rounds))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--batch", type=int, default=50)
    ap.add_argument("--only", type=str, default="")
    args = ap.parse_args()

    files = collect_machines()
    if args.only:
        want = set(args.only.split(","))
        files = [f for f in files if os.path.basename(f)[:-5] in want]
    if args.limit:
        files = files[:args.limit]

    os.makedirs(OUTDIR, exist_ok=True)
    results = []
    failures = []
    with Pool(4) as pool:
        for mtext, n, r in pool.imap(work, files, chunksize=8):
            if r is None:
                failures.append(mtext)
            else:
                results.append((mtext, n, r))
    # deterministic order by machine text
    results.sort(key=lambda x: x[0])

    manifest = []
    vfiles = []
    for b0 in range(0, len(results), args.batch):
        batch = results[b0:b0 + args.batch]
        bno = b0 // args.batch + 1
        fname = "Bulk_%03d.v" % bno
        chunks = [HEADER]
        for j, (mtext, n, (t, nseen, comps, rounds)) in enumerate(batch):
            idx = b0 + j + 1
            text, thm = emit_machine(idx, mtext, n, t, comps, nseen, rounds)
            chunks.append(text)
            manifest.append((mtext, thm, "theories/Machines/Bulk/" + fname,
                             n, t, nseen))
        open(os.path.join(OUTDIR, fname), "w").write("\n\n".join(chunks) + "\n")
        vfiles.append("theories/Machines/Bulk/" + fname)

    with open(os.path.join(HERE, "bulk_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tn\tt\tcontexts\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    with open(os.path.join(HERE, "bulk_vfiles.txt"), "w") as vf:
        vf.write("\n".join(vfiles) + "\n")
    print("emitted %d machines into %d files; %d failures"
          % (len(results), len(vfiles), len(failures)))
    for m in failures:
        print("FAILED:", m)


if __name__ == "__main__":
    main()
