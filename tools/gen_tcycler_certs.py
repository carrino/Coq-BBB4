#!/usr/bin/env python3
"""Bulk tcycler tables: BBB tcycler certificates -> Coq theorem files.

The verified checker already exists (theories/Checkers/TCycler.v);
these certificates are pure data (side, anchor_step, period_steps,
reach).  Side-R certificates use tcycler_check_neverqh_sound, side-L
the mirrored corollary.  All 40 upstream tcycler machines claim
never-QH (claim_qh F).

Machines are batched by cumulative anchor budget so vm_compute work
parallelizes across files; the 309M-step outlier gets its own file.

Usage: BBB_REPO=... python3 tools/gen_tcycler_certs.py
"""
import glob
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BBB = os.environ.get("BBB_REPO", os.path.join(ROOT, "..", "BBB"))
OUTDIR = os.path.join(ROOT, "theories", "Machines", "Bulk")
BUDGET = 15_000_000  # anchor+period steps per file

HEADER = """(** Generated by tools/gen_tcycler_certs.py -- DO NOT EDIT.

    Bulk never-quasihalting theorems for the BBB harness's tcycler
    certificate machines on the verified translated-cycler checker
    (parameters: anchor_step, period_steps, reach; side L via the
    mirrored corollary).  Anchors above 10M steps use the binary-fuel
    front end (TCyclerN) so the fuel numeral does not materialize. *)

From BBB4 Require Import BBB4_Statement CTape Mirror.
From BBB4.Checkers Require Import TCycler.

"""

HEADER_N = HEADER.replace(
    "From BBB4 Require Import",
    "From Coq Require Import NArith.\nFrom BBB4 Require Import").replace(
    "From BBB4.Checkers Require Import TCycler.",
    "From BBB4.Checkers Require Import TCycler TCyclerN.")

NAT_LIMIT = 10_000_000  # above this, use the N-fueled checker


def parse(m):
    tbl = {}
    for qi, part in enumerate(m.split('_')):
        for si in range(2):
            e = part[3*si:3*si+3]
            tbl[(qi, si)] = None if e == '---' else (int(e[0]), e[1], ord(e[2]) - 65)
    return tbl


def emit_tm(name, mtext):
    tbl = parse(mtext)
    lines = ["Definition %s : TM := fun q s =>" % name,
             "  match q, s with"]
    for qi in range(4):
        for si in range(2):
            tr = tbl[(qi, si)]
            lhs = "St%s, S%d" % (chr(65 + qi), si)
            if tr is None:
                lines.append("  | %s => None" % lhs)
            else:
                w, d, q2 = tr
                lines.append("  | %s => Some (mkTrans S%d D%s St%s)"
                             % (lhs, w, d, chr(65 + q2)))
    lines.append("  end.")
    return "\n".join(lines)


def fmt_nat(v):
    if v <= 5000:
        return str(v)
    return "(%s * 1000 + %d)" % (fmt_nat(v // 1000), v % 1000)


def collect():
    tc = {}
    for d in sorted(glob.glob(BBB + "/results/certs*")):
        for f in glob.glob(d + "/*.cert"):
            m = ty = None
            kv = {}
            for line in open(f):
                p = line.split()
                if not p:
                    continue
                if p[0] == "machine":
                    m = p[1]
                elif p[0] == "type":
                    ty = p[1]
                elif len(p) >= 2:
                    kv[p[0]] = p[1]
            if ty == "tcycler":
                assert kv.get("claim_qh") == "F", (m, kv.get("claim_qh"))
                cand = (kv["side"], int(kv["anchor_step"]),
                        int(kv["period_steps"]), int(kv["reach"]))
                # re-sweeps by later prover generations carry different
                # anchors; keep the cheapest to re-verify
                if m not in tc or cand[1] + cand[2] < tc[m][1] + tc[m][2]:
                    tc[m] = cand
    return sorted(tc.items(), key=lambda x: (x[1][1], x[0]))


def emit_machine(idx, mtext, side, anchor, period, reach):
    name = "tm_tcyc_%03d" % idx
    thm = "nqh_" + mtext.replace("---", "XXX")
    big = anchor + period > NAT_LIMIT
    if big:
        lemma = ("tcycler_check_neverqh_N_sound" if side == "R"
                 else "tcycler_check_neverqh_N_sound_L")
        a, p = "%d%%N" % anchor, "%d%%N" % period
    else:
        lemma = ("tcycler_check_neverqh_sound" if side == "R"
                 else "tcycler_check_neverqh_sound_L")
        a, p = fmt_nat(anchor), fmt_nat(period)
    return ("""(** %s: tcycler side %s, anchor %d, period %d steps, reach %d *)

%s

Theorem %s : NeverQuasiHaltsSt %s.
Proof.
  apply (%s _ %s %s %s).
  vm_compute. reflexivity.
Qed.""" % (mtext, side, anchor, period, reach,
           emit_tm(name, mtext), thm, name, lemma,
           a, p, fmt_nat(reach)), thm, big)


def main():
    rows = collect()
    os.makedirs(OUTDIR, exist_ok=True)
    batches = []
    cur, cost = [], 0
    for m, (side, anchor, period, reach) in rows:
        c = anchor + period
        if cur and (cost + c > BUDGET):
            batches.append(cur)
            cur, cost = [], 0
        cur.append((m, side, anchor, period, reach))
        cost += c
    if cur:
        batches.append(cur)

    manifest = []
    vfiles = []
    idx = 0
    for bno, batch in enumerate(batches, 1):
        fname = "TCyc_%02d.v" % bno
        chunks = [None]
        any_big = False
        for (m, side, anchor, period, reach) in batch:
            idx += 1
            text, thm, big = emit_machine(idx, m, side, anchor, period, reach)
            any_big = any_big or big
            chunks.append(text)
            manifest.append((m, thm, "theories/Machines/Bulk/" + fname,
                             side, anchor, period, reach))
        chunks[0] = HEADER_N if any_big else HEADER
        open(os.path.join(OUTDIR, fname), "w").write("\n\n".join(chunks) + "\n")
        vfiles.append("theories/Machines/Bulk/" + fname)

    with open(os.path.join(HERE, "tcyc_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tside\tanchor\tperiod\treach\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    with open(os.path.join(HERE, "tcyc_vfiles.txt"), "w") as vf:
        vf.write("\n".join(vfiles) + "\n")
    print("emitted %d machines into %d files" % (idx, len(vfiles)))


if __name__ == "__main__":
    main()
