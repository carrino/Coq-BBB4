#!/usr/bin/env python3
"""Convert BBB v1 `irules` certificates (bbbcert v1, type irules) into
Coq terms for the theories/Checkers/IRules checker.

Usage:
  gen_irules.py CERT.cert            one machine: print TM + IRCert defs
  gen_irules.py --sweep DIR OUT.v    all certs in DIR: emit a probe file
                                     that vm_computes every check

The emitted certificate is the v1 subset the Coq checker consumes:
single-symbol runs, one meta variable k, single -1 decrement rules.
Certificates outside that subset are skipped with a warning.
"""
import sys, os, glob

ST = {"A": "StA", "B": "StB", "C": "StC", "D": "StD"}
SY = {"0": "S0", "1": "S1"}


def tm_coq(machine, name):
    groups = machine.split("_")
    lines = []
    for qi, g in enumerate(groups):
        q = "ABCD"[qi]
        for si in range(2):
            t = g[3 * si:3 * si + 3]
            if t == "---":
                rhs = "None"
            else:
                rhs = "mk %s D%s %s" % (SY[t[0]], t[1], ST[t[2]])
            lines.append("  | %s, %s => %s" % (ST[q], SY[str(si)], rhs))
    return ("Definition %s : TM := fun q s =>\n  match q, s with\n%s\n  end.\n"
            % (name, "\n".join(lines)))


def parse_cert(path):
    c = {"tplL": {}, "tplR": {}, "rules": {}}
    for ln in open(path):
        p = ln.split()
        if not p:
            continue
        k = p[0]
        if k in ("anchor_step", "k0", "kmin", "meta_a", "meta_b",
                 "tpl_hsym", "nrules"):
            c[k] = int(p[1])
        elif k == "bbbcert":
            c["ver"] = p[1]
        elif k == "machine":
            c["machine"] = p[1]
        elif k == "type":
            c["type"] = p[1]
        elif k == "tpl_state":
            c["tpl_state"] = p[1]
        elif k == "tplrun":
            side, idx, sym, al, be = p[1], int(p[2]), p[3], int(p[4]), int(p[5])
            c["tplL" if side == "L" else "tplR"][idx] = (sym, al, be)
        elif k == "rule":
            ridx = int(p[1])
            c["rules"][ridx] = {"st": p[2], "hs": int(p[3]),
                                "L": {}, "R": {}}
        elif k == "rulerun":
            ridx, side, idx, sym = int(p[1]), p[2], int(p[3]), p[4]
            r = c["rules"][ridx]
            if p[5] == "C":
                run = (sym, "C", int(p[6]), None)
            else:
                run = (sym, "V", int(p[6]), int(p[7]))
            r[side][idx] = run
    if c.get("ver") != "v1" or c.get("type") != "irules":
        raise ValueError("not a v1 irules certificate")
    return c


def truns(d):
    out = []
    for i in sorted(d):
        sym, al, be = d[i]
        out.append("(%s, %d, %d)" % (SY[sym], al, be))
    return "[" + "; ".join(out) + "]"


def rruns(d):
    out = []
    for i in sorted(d):
        sym, kind, a, b = d[i]
        if kind == "C":
            out.append("(%s, RC (%d))" % (SY[sym], a))
        else:
            out.append("(%s, RV (%d) (%d))" % (SY[sym], a, b))
    return "[" + "; ".join(out) + "]"


def cert_coq(c, name):
    rules = []
    for i in sorted(c["rules"]):
        r = c["rules"][i]
        rules.append("mkRule %s %s %s %s"
                     % (ST[r["st"]], SY[str(r["hs"])],
                        rruns(r["L"]), rruns(r["R"])))
    return ("Definition %s : IRCert := mkIRCert\n"
            "  %d%%nat (%d) (%d) (%d) (%d) %s %s\n  %s\n  %s\n  [%s].\n"
            % (name, c["anchor_step"], c["k0"], c["kmin"],
               c["meta_a"], c["meta_b"],
               ST[c["tpl_state"]], SY[str(c["tpl_hsym"])],
               truns(c["tplL"]), truns(c["tplR"]),
               ";\n   ".join(rules)))


HEADER = """(* generated by tools/gen_irules.py -- do not edit *)
From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
"""


def main():
    if sys.argv[1] == "--sweep":
        certs = sorted(glob.glob(os.path.join(sys.argv[2], "*.cert")))
        with open(sys.argv[3], "w") as f:
            f.write(HEADER)
            for n, path in enumerate(certs):
                try:
                    c = parse_cert(path)
                except ValueError as e:
                    sys.stderr.write("skip %s: %s\n" % (path, e))
                    continue
                f.write(tm_coq(c["machine"], "tm_%04d" % n))
                f.write(cert_coq(c, "cert_%04d" % n))
                f.write("(* %s *)\n"
                        "Eval vm_compute in (%d,\n"
                        "  irules_check_neverqh tm_%04d cert_%04d"
                        " 300000%%nat)%%nat.\n" % (c["machine"], n, n, n))
        return
    c = parse_cert(sys.argv[1])
    print(HEADER)
    print(tm_coq(c["machine"], "tm_m"))
    print(cert_coq(c, "cert_m"))


if __name__ == "__main__":
    main()
