#!/usr/bin/env python3
"""QHBound (census-grade) theorems for wrap-decidable residue machines.

Consumes qhbound_caught.tsv (from sweep_qhbound_residue.py: machine,
quiet_state, s, n, t) and emits, per machine, the full census decision

  NonHalt tm
  /\ (forall q' s', QuietAfter tm q' s' -> S s' <= S t)   (* = QHBound (S t) *)
  /\ QuasiHaltsSt tm

via ngram_check_qhbound_sound (theories/Checkers/Wrap.v), closed by
vm_compute.  A machine with such a theorem is decided at the census
contract and can leave D_census.

Usage: gen_qhbound_wrap.py QHBOUND_TSV OUT_DIR [PER_FILE] [LIMIT]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bulk_prover as bp
import gen_residue_wrap as gw

HEADER = """(** Generated by tools/gen_qhbound_wrap.py -- DO NOT EDIT.

    Census-grade quasihalting theorems (NonHalt /\\ QHBound (S t) /\\
    QuasiHaltsSt) for wrap-decidable residue machines, via
    ngram_check_qhbound_sound (theories/Checkers/Wrap.v). *)

From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Wrap.
"""


def main():
    tsv = sys.argv[1]
    outdir = sys.argv[2]
    per_file = int(sys.argv[3]) if len(sys.argv) > 3 else 60
    limit = int(sys.argv[4]) if len(sys.argv) > 4 else None
    os.makedirs(outdir, exist_ok=True)
    rows = []
    with open(tsv) as f:
        next(f)
        for line in f:
            m, qs, s, n, t = line.rstrip("\n").split("\t")
            rows.append((m, ord(qs) - 65, int(s), int(n), int(t)))
    if limit:
        rows = rows[:limit]
    fidx = 0
    chunks = []
    emitted = 0
    manifest = []

    def flush():
        nonlocal fidx
        if chunks:
            open(os.path.join(outdir, "QHBWrap_%02d.v" % fidx), "w").write(
                HEADER + "\n\n" + "\n\n".join(chunks) + "\n")
            fidx += 1

    for m, qq, s, n, t in rows:
        sz = gw.closure_sizes(m, qq, n, t)
        if sz is None:
            continue
        nseen, nl, nr = sz
        fuel = 8 * nseen + 64
        rounds = nl + nr + 4
        emitted += 1
        qs = chr(65 + qq)
        name = "tm_qhb_%05d" % emitted
        thm = "qhb_%05d" % emitted
        chunks.append("""(** %s: quiet state %s, last visit %d; QHBound %d;
    wrapped closure n=%d t=%d (%d contexts) *)

%s

Theorem %s :
  NonHalt %s
  /\\ (forall q' s', QuietAfter %s q' s' -> S s' <= S %d)
  /\\ QuasiHaltsSt %s.
Proof.
  apply (ngram_check_qhbound_sound _ St%s %d %d %d %d %d).
  vm_compute. reflexivity.
Qed.""" % (m, qs, s, t, n, t, nseen, gw.emit_tm(name, m), thm, name, name, t,
           name, qs, s, n, t, fuel, rounds))
        manifest.append((m, thm, "QHBWrap_%02d.v" % fidx, qs, s, n, t))
        if len(chunks) >= per_file:
            flush()
            chunks.clear()
    flush()
    with open(os.path.join(outdir, "qhbwrap_manifest.tsv"), "w") as f:
        f.write("machine\ttheorem\tfile\tquiet_state\ts\tn\tt\n")
        for row in manifest:
            f.write("\t".join(str(x) for x in row) + "\n")
    print("emitted %d QHBound theorems across %d files" % (emitted, fidx))


if __name__ == "__main__":
    main()
