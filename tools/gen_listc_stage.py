#!/usr/bin/env python3
"""Emit the STAGED listC never-quasihalting tier (wave 2, UNTRUSTED emitter).

Fork of the gen_bulk_certs.py path (NGram closure + Bellman ranking via
bulk_prover.decide) pointed at the census list-C residue instead of the
BBB harness cert dirs.  For every list-C machine that the untrusted prover
decides, emit a SELF-CONTAINED

  theories/Machines/ListCStage/LCStage_NN.v

with, per machine, a TM definition + an n-gram ranking certificate
(encoded-key tables) + the theorem  NeverQuasiHaltsSt tm  closed by
vm_compute through NGram.ngram_check_neverqh_lex_sound; plus a per-file
[lcstage_NN : list TM] and [lcstage_NN_nqh : Forall NeverQuasiHaltsSt
lcstage_NN] so the follow-up can append it to [proven_list]
(Census/Proven_Data.v) -- the R_NeverQH tier -- verbatim.

NOT imported by any census input yet.  Everything here is UNTRUSTED data;
the Coq kernel re-derives the closure and re-checks every edge.

Usage:
  python3 tools/gen_listc_stage.py CAUGHT_TSV [--batch B] [--out DIR]
    CAUGHT_TSV: lines  machine<TAB>n  (n = window that decides it).
Env: BBB_REPO unused (measures come from bulk_prover's EXTRA_CANDS).
"""
import argparse
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bulk_prover as bp
import gen_bulk_certs as gbc

OUTDIR_DEFAULT = os.path.join(ROOT, "theories", "Machines", "ListCStage")

HEADER = """(** GENERATED by tools/gen_listc_stage.py -- DO NOT EDIT.

    STAGED never-quasihalting theorems for the census list-C residue
    (wave 2), chunk {nn} ({cnt} machines).  SELF-CONTAINED and NOT
    imported by any census input yet: per machine a TM definition, an
    n-gram ranking certificate (encoded-key tables; untrusted data
    re-checked by the engine), and the theorem, closed by vm_compute
    through [ngram_check_neverqh_lex_sound].  Ready to board the proven
    (R_NeverQH) tier: append [lcstage_{nn}] to [proven_list]
    (Census/Proven_Data.v) -- see docs/REROOT_LISTC_STAGE.md. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import NGram.
Import ListNotations.

"""


def work(arg):
    """(machine, n) -> (machine, n, cert-or-None) via bulk_prover.decide."""
    mtext, n = arg
    per = {qi: gbc.EXTRA_CANDS for qi in range(4)}
    r = bp.decide(mtext, n, per)
    if r is None:
        return (mtext, n, None)
    t, seen, lset, rset, comps, _rounds = r
    coq_rounds = len(lset) + len(rset) + 4
    return (mtext, n, (t, len(seen), comps, coq_rounds))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("caught_tsv")
    ap.add_argument("--batch", type=int, default=50)
    ap.add_argument("--out", default=OUTDIR_DEFAULT)
    ap.add_argument("--procs", type=int, default=4)
    ap.add_argument("--chunk0", type=int, default=0,
                    help="first chunk number (append after a committed wave)")
    ap.add_argument("--idx0", type=int, default=0,
                    help="first machine index (append mode)")
    ap.add_argument("--append", action="store_true",
                    help="append manifest rows instead of rewriting")
    args = ap.parse_args()

    pairs = []
    for line in open(args.caught_tsv):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m, n = line.split("\t")[:2]
        pairs.append((m, int(n)))
    pairs.sort()

    os.makedirs(args.out, exist_ok=True)
    results = []
    failures = []
    with Pool(args.procs) as pool:
        for mtext, n, r in pool.imap(work, pairs, chunksize=8):
            if r is None:
                failures.append(mtext)
            else:
                results.append((mtext, n, r))
    results.sort(key=lambda x: x[0])

    manifest = []
    chunk_names = []
    for b0 in range(0, len(results), args.batch):
        batch = results[b0:b0 + args.batch]
        bno = b0 // args.batch
        nn = "%02d" % (args.chunk0 + bno)
        name = "LCStage_%s" % nn
        chunk_names.append(name)
        chunks = [HEADER.format(nn=nn, cnt=len(batch))]
        thms = []
        for j, (mtext, n, (t, nseen, comps, rounds)) in enumerate(batch):
            idx = args.idx0 + b0 + j
            text, thm = gbc.emit_machine(idx, mtext, n, t, comps, nseen, rounds,
                                         name_tag="lc")
            chunks.append(text)
            thms.append((thm, "tm_lc_%05d" % idx))
            manifest.append((mtext, thm,
                             "theories/Machines/ListCStage/%s.v" % name,
                             "R_NeverQH", n, t, nseen))
        # per-file list + Forall assembly (mirrors gen_proven's proven_NN)
        listname = name.lower()
        chunks.append("Definition %s : list TM :=\n  [%s]."
                      % (listname, ";\n   ".join(c for _, c in thms)))
        proof = ["Lemma %s_nqh : Forall NeverQuasiHaltsSt %s."
                 % (listname, listname), "Proof.", "  unfold %s." % listname]
        for thm, _ in thms:
            proof.append("  apply Forall_cons; [exact %s|]." % thm)
        proof.append("  apply Forall_nil.")
        proof.append("Qed.")
        chunks.append("\n".join(proof))
        open(os.path.join(args.out, name + ".v"), "w").write(
            "\n\n".join(chunks) + "\n")

    mpath = os.path.join(HERE, "listc_stage_manifest.tsv")
    with open(mpath, "a" if args.append else "w") as mf:
        if not args.append:
            mf.write("machine\ttheorem\tfile\ttier\tn\tt\tcontexts\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    print("staged %d machines into %d files; %d prover-misses; manifest %s"
          % (len(results), len(chunk_names), len(failures), mpath))


if __name__ == "__main__":
    main()
