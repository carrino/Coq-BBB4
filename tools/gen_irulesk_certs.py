#!/usr/bin/env python3
"""Transcribe v3 multi-decrement `irules` certificates into Coq batches
for the general step-size checker (theories/Checkers/IRules/MetaK.v).

A fork of tools/gen_irules.py: same IRCert shape (single-symbol runs, one
meta variable k), but the rules may carry decrement deltas beyond -1 and
the emitted theorem is closed by [irulesk_check_neverqh_sound] (MetaK)
instead of [irules_check_neverqh_sound] (Meta).

Every machine is RE-VALIDATED through the Python model
(tools/irulesk_prover.py check_cert) before it is emitted, so a batch
only ever contains certificates the design actually replays (no silent
bad rows).  Machines that need v3 engine features beyond decrement step
size (block-level chain hops / canonical re-blocking, surfaced as a rule
that does not validate on the v1 engine) are reported and skipped.

Usage:
  gen_irulesk_certs.py CERTDIR BOARDLIST OUTDIR MANIFEST [--per N]
    CERTDIR    directory of v3 certs (results/certs_modclass)
    BOARDLIST  one machine string per line (the candidates to board)
    OUTDIR     where to write IRulesK_Batch_%02d.v
    MANIFEST   tools/irulesk_manifest.tsv to (re)write
    --per N    machines per batch file (default 8; OOM-friendly)
"""
import sys, os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import irulesk_prover as P

ST = {"A": "StA", "B": "StB", "C": "StC", "D": "StD"}
SY = {"0": "S0", "1": "S1"}
FUEL = 300000

HEADER = """(** GENERATED by tools/gen_irulesk_certs.py -- DO NOT EDIT.

    Multi-decrement (general step size) inductive-rules machines from the
    BBB harness's v3 certificate set (results/certs_modclass), batch %02d.
    Per machine: the TM, the [IRCert] literal straight from its
    certificate, the [NeverQuasiHaltsSt] theorem closed by
    [irulesk_check_neverqh_sound] (MetaK) + [vm_compute], and the
    [NonHalt] corollary.  The certificates are untrusted search output;
    every claim is re-checked by the verified general-delta IRules
    engine (theories/Checkers/IRules/RulesK.v + MetaK.v). *)

From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK MetaK.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
"""


def tm_coq(machine, name):
    lines = []
    for qi, g in enumerate(machine.split("_")):
        q = "ABCD"[qi]
        for si in range(2):
            t = g[3 * si:3 * si + 3]
            rhs = "None" if t == "---" else "mk %s D%s %s" % (SY[t[0]], t[1], ST[t[2]])
            lines.append("  | %s, %s => %s" % (ST[q], SY[str(si)], rhs))
    return ("Definition %s : TM := fun q s =>\n  match q, s with\n%s\n  end.\n"
            % (name, "\n".join(lines)))


def parse_cert(path):
    c = {"tplL": {}, "tplR": {}, "rules": {}}
    for ln in open(path):
        p = ln.split()
        if not p:
            continue
        k = p[0]
        if k in ("anchor_step", "k0", "kmin", "meta_a", "meta_b",
                 "tpl_hsym", "nrules"):
            c[k] = int(p[1])
        elif k == "bbbcert":   c["ver"] = p[1]
        elif k == "machine":   c["machine"] = p[1]
        elif k == "type":      c["type"] = p[1]
        elif k == "tpl_state": c["tpl_state"] = p[1]
        elif k == "tplrun":
            side, idx, sym, al, be = p[1], int(p[2]), p[3], int(p[4]), int(p[5])
            c["tplL" if side == "L" else "tplR"][idx] = (sym, al, be)
        elif k == "rule":
            ridx = int(p[1])
            c["rules"][ridx] = {"st": p[2], "hs": int(p[3]), "L": {}, "R": {}}
        elif k == "rulerun":
            ridx, side, idx, sym = int(p[1]), p[2], int(p[3]), p[4]
            r = c["rules"][ridx]
            if p[5] == "C":
                r[side][idx] = (sym, "C", int(p[6]), None)
            else:
                r[side][idx] = (sym, "V", int(p[6]), int(p[7]))
    if c.get("ver") != "v3" or c.get("type") != "irules":
        raise ValueError("not a v3 irules certificate")
    return c


def truns(d):
    return "[" + "; ".join("(%s, %d, %d)" % (SY[s], al, be)
                           for i in sorted(d) for (s, al, be) in [d[i]]) + "]"


def rruns(d):
    out = []
    for i in sorted(d):
        sym, kind, a, b = d[i]
        if kind == "C":
            out.append("(%s, RC (%d))" % (SY[sym], a))
        else:
            out.append("(%s, RV (%d) (%d))" % (SY[sym], a, b))
    return "[" + "; ".join(out) + "]"


def cert_coq(c, name):
    rules = ";\n   ".join(
        "mkRule %s %s %s %s" % (ST[c["rules"][i]["st"]], SY[str(c["rules"][i]["hs"])],
                                rruns(c["rules"][i]["L"]), rruns(c["rules"][i]["R"]))
        for i in sorted(c["rules"]))
    return ("Definition %s : IRCert := mkIRCert\n"
            "  %d%%nat (%d) (%d) (%d) (%d) %s %s\n  %s\n  %s\n  [%s].\n"
            % (name, c["anchor_step"], c["k0"], c["kmin"], c["meta_a"], c["meta_b"],
               ST[c["tpl_state"]], SY[str(c["tpl_hsym"])],
               truns(c["tplL"]), truns(c["tplR"]), rules))


def emit_machine(c, mach):
    tag = mach.replace("---", "XXX")   # Coq identifiers admit no '-'
    body = []
    body.append("\n(** ** %s: anchor %d, k0 %d, map k -> %d*k+%d, %d rule(s) *)\n"
                % (mach, c["anchor_step"], c["k0"], c["meta_a"], c["meta_b"],
                   len(c["rules"])))
    body.append(tm_coq(mach, "tmk_" + tag))
    body.append(cert_coq(c, "certk_" + tag))
    body.append(
        "Theorem irk_%s_never_quasihalts : NeverQuasiHaltsSt tmk_%s.\n"
        "Proof.\n"
        "  apply (irulesk_check_neverqh_sound tmk_%s certk_%s %d).\n"
        "  vm_compute. reflexivity.\n"
        "Qed.\n" % (tag, tag, tag, tag, FUEL))
    body.append(
        "Theorem irk_%s_nonhalt : NonHalt tmk_%s.\n"
        "Proof. apply never_qh_nonhalt, irk_%s_never_quasihalts. Qed.\n"
        % (tag, tag, tag))
    return "".join(body)


def main():
    certdir, boardlist, outdir, manifest = sys.argv[1:5]
    per = 8
    if "--per" in sys.argv:
        per = int(sys.argv[sys.argv.index("--per") + 1])
    machines = [m.strip() for m in open(boardlist) if m.strip()]

    boarded, skipped = [], []
    for m in machines:
        path = os.path.join(certdir, m + ".cert")
        ok, msg = P.check_cert(path, fuel=FUEL)
        if ok:
            boarded.append(m)
        else:
            skipped.append((m, msg))
            sys.stderr.write("SKIP %s: %s\n" % (m, msg))

    nbatch = (len(boarded) + per - 1) // per
    files = []
    for bi in range(nbatch):
        chunk = boarded[bi * per:(bi + 1) * per]
        fname = "IRulesK_Batch_%02d.v" % (bi + 1)
        files.append((fname, chunk))
        with open(os.path.join(outdir, fname), "w") as f:
            f.write(HEADER % (bi + 1))
            for m in chunk:
                f.write(emit_machine(parse_cert(os.path.join(certdir, m + ".cert")), m))

    with open(manifest, "w") as f:
        # header shape shared with the other manifests (check_coverage.py
        # skips exactly one header line and keys on machine = column 0)
        f.write("machine\ttheorem\tfile\tanchor\tk0\tkmin\tmeta\tnrules\tdecr_deltas\n")
        for m in boarded:
            c = parse_cert(os.path.join(certdir, m + ".cert"))
            decs = sorted({rc[2] for r in c["rules"].values() for side in ("L", "R")
                           for rc in r[side].values() if rc[1] == "V" and rc[2] <= -1})
            bi = boarded.index(m) // per + 1
            f.write("%s\tirk_%s_never_quasihalts"
                    "\ttheories/Machines/IRulesK_Batch_%02d.v"
                    "\t%d\t%d\t%d\t%d*k+%d\t%d\t%s\n"
                    % (m, m.replace("---", "XXX"), bi, c["anchor_step"], c["k0"],
                       c["kmin"], c["meta_a"], c["meta_b"], len(c["rules"]),
                       ",".join(str(x) for x in decs)))

    print("boarded %d machines -> %d batch file(s); skipped %d"
          % (len(boarded), nbatch, len(skipped)))
    for m, msg in skipped:
        print("  skipped %s: %s" % (m, msg))


if __name__ == "__main__":
    main()
