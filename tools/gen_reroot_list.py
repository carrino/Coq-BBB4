#!/usr/bin/env python3
"""Copy transparent reroot machine data while preserving kernel conversion.

The reroot boards mix row_to_tm applications and literal transition tables.
Re-encoding both as tables changes their normal forms. Copy the actual machine
and ordered list definitions, retaining row_to_tm and local helper bodies.
Run.v attaches the original certificate with `exact reroot_qh_all`; the kernel
therefore checks every machine, its representation, and the complete order.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

DEFINITION = re.compile(r'^Definition\s+(\w+)\b.*?\.(?=\s*(?:\n|$))', re.M | re.S)
IDENTIFIERS = re.compile(r'\w+(?:\s*;\s*\w+)*\s*;?\Z')


def definitions(source):
    result = {}
    for match in DEFINITION.finditer(source):
        name = match.group(1)
        if name in result:
            raise ValueError(f'duplicate definition {name}')
        result[name] = match.group(0)
    return result


def render_reroot_files(root):
    root = Path(root)
    aggregate_path = root / 'theories/Census/RerootQH_Data.v'
    aggregate_source = aggregate_path.read_text()
    aggregate = definitions(aggregate_source)['reroot_qh_list']
    rhs = aggregate.split(':=', 1)[1].removesuffix('.').strip()
    if not re.fullmatch(r'\w+(?:\s*\+\+\s*\w+)*', rhs):
        raise ValueError('reroot_qh_list must concatenate named board lists')
    list_names = re.findall(r'\w+', rhs)

    sources = {}
    for namespace, names in re.findall(
            r'From\s+(BBB4[.\w]*)\s+Require\s+Import\s+([\w\s]+)\.',
            aggregate_source):
        directory = root / 'theories' / namespace.removeprefix('BBB4').lstrip('.').replace('.', '/')
        for name in names.split():
            path = directory / f'{name}.v'
            if path.is_file():
                source = path.read_text()
                if any(re.search(r'^Definition\s+' + re.escape(n) + r'\b', source, re.M)
                       for n in list_names):
                    sources[path] = definitions(source)

    prelude = '''(** GENERATED by tools/gen_reroot_list.py -- do not edit.

    The reroot lookup tier, with the original transparent machine bodies and
    list order. In particular, row_to_tm applications remain row_to_tm
    applications. Census/Run.v reattaches reroot_qh_all by kernel conversion;
    these data carry no proof assumptions. *)
From Coq Require Import List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import Deferred_Defs.
Import ListNotations.
'''
    files = {}
    part_names = []
    aggregate_refs = {}
    audit = {'aggregate_sha256': hashlib.sha256(aggregate_path.read_bytes()).hexdigest(),
             'machine_count': 0, 'list_order': list_names, 'lists': []}
    for list_name in dict.fromkeys(list_names):
        found = [(path, defs) for path, defs in sources.items() if list_name in defs]
        if len(found) != 1:
            raise ValueError(f'{list_name}: expected one imported definition, found {len(found)}')
        path, defs = found[0]
        list_definition = defs[list_name]
        match = re.fullmatch(r'Definition\s+\w+\s*:\s*list TM\s*:=\s*\[(.*?)\]\.',
                             list_definition, re.S)
        if not match or not IDENTIFIERS.fullmatch(match.group(1).strip()):
            raise ValueError(f'{list_name}: expected a literal list of machine names')
        machines = re.findall(r'\w+', match.group(1))
        machine_definitions = []
        for machine in dict.fromkeys(machines):
            definition = defs.get(machine)
            if not definition or not re.match(r'Definition\s+\w+\s*:\s*TM\s*:=', definition):
                raise ValueError(f'{list_name}: missing transparent TM definition {machine}')
            machine_definitions.append(definition)
        module = f'RerootQH_List_{len(part_names):02d}'
        part_names.append(module)
        chunks = [prelude, f'(* Data from {path.relative_to(root)}. *)']
        # Literal IQH tables use this local constructor helper. Copy its body,
        # too, rather than changing the machine's transparent representation.
        if any(re.search(r'\bmk\b', definition) for definition in machine_definitions):
            helper = defs.get('mk')
            if not helper:
                raise ValueError(f'{path}: machine uses an undefined mk helper')
            chunks.append(helper)
        chunks.extend(machine_definitions)
        chunks.append(list_definition)
        files[f'ListParts/{module}.v'] = '\n\n'.join(chunks) + '\n'
        aggregate_refs[list_name] = f'{module}.{list_name}'
        audit['machine_count'] += len(machines) * list_names.count(list_name)
        audit['lists'].append({'part': f'ListParts/{module}.v', 'source': str(path.relative_to(root)), 'list': list_name,
                               'machines': machines,
                               'source_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                               'definition_sha256': [hashlib.sha256(x.encode()).hexdigest()
                                                     for x in machine_definitions]})
    wrapper = prelude + '\nFrom BBB4.Census.ListParts Require Import\n  ' + '\n  '.join(part_names) + '.\n\n'
    wrapper += ('Definition reroot_qh_list_data : list TM :=\n  ' +
                ' ++\n  '.join(aggregate_refs[name] for name in list_names) + '.\n')
    files['RerootQH_List.v'] = wrapper
    audit['list_count'] = len(list_names)
    return files, audit


def write_reroot_list(root, outdir, check=False):
    files, audit = render_reroot_files(root)
    outdir = Path(outdir)
    for relative, text in files.items():
        path = outdir / relative
        if check:
            if not path.exists() or path.read_text() != text:
                raise ValueError(f'{path}: regenerate with tools/gen_reroot_list.py')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    # Production regeneration also wires the physical modules into Coq's
    # project manifest. External output directories never edit the project.
    if outdir.resolve() == (Path(root) / 'theories/Census').resolve():
        project = Path(root) / '_CoqProject'
        original = project.read_text()
        lines = [line for line in original.splitlines()
                 if not line.startswith('theories/Census/ListParts/RerootQH_List_')]
        index = lines.index('theories/Census/RerootQH_List.v')
        entries = ['theories/Census/' + relative for relative in files
                   if relative.startswith('ListParts/')]
        lines[index:index] = entries
        updated = '\n'.join(lines) + '\n'
        if check and original != updated:
            raise ValueError(f'{project}: regenerate with tools/gen_reroot_list.py')
        if not check and original != updated:
            project.write_text(updated)
    return audit


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--output-dir', type=Path)
    parser.add_argument('--audit-json', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outdir = args.output_dir or args.root / 'theories/Census'
    try:
        audit = write_reroot_list(args.root, outdir, args.check)
    except ValueError as exc:
        parser.exit(1, str(exc) + '\n')
    if args.audit_json:
        args.audit_json.write_text(json.dumps(audit, indent=2) + '\n')
    print(f'{outdir / "RerootQH_List.v"}: {audit["machine_count"]} machines in {audit["list_count"]} lists')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
