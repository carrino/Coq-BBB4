#!/usr/bin/env python3
"""Point the never-QH engines at the HOLDOUTS (UNTRUSTED).

`docs/TERMINOLOGY.md` carries a standing discipline -- "point the porting
machinery at the residue; keep it AWAY from the 27" -- on the grounds that
the holdouts are what mxdys' inductive deciders could not decide, so running
a port of his method at them is re-running his failed experiment.

Wave-14 (2026-07-26) tested that and it is FALSE for a chunk of the list.
`tools/counters/sibling_scan.py` found that several unproven holdouts are
state-relabellings of machines already boarded by NGramHist, which says their
dynamics are inside our engine's reach whatever mxdys' run did; this script
then confirmed it directly.  At the CHEAPEST parameters (k=2, n=2, t=40,
fuel=20000) NGramHist boards, among others, the machine NEXT_SESSION.md had
recorded for a year as the only one with no known proof anywhere.

Why the discipline was wrong: it rests on "his deciders failed", which is a
statement about HIS method at HIS parameters.  Ours is his NGramCPS extended
to quasihalting with a lex liveness gate -- a different tool -- and the
holdout list itself is an inference, not a record (see the CAVEAT in
TERMINOLOGY.md).  Nothing about soundness changes either way: the Coq kernel
re-checks every emitted claim by [vm_compute].

Usage:
    holdout_sweep.py sweep          # which unproven holdouts close, and at what params
    holdout_sweep.py emit           # write theories/Machines/NGHHold/NGHHold_NN.v
"""
import os
import signal
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import nghist_prove as P                                    # noqa: E402

OUTDIR = os.path.join(ROOT, 'theories/Machines/NGHHold')
RESULTS = os.path.join(HERE, 'holdout_results.tsv')
PARAMS = [(2, 2, 40, 20000), (4, 2, 40, 20000), (6, 2, 60, 60000)]
PER_MACHINE_SECONDS = 90


class Timeout(Exception):
    pass


def _alarm(sig, frm):
    raise Timeout()


def targets():
    """The holdouts that are still unproven, per the closeout inventory."""
    rem = set(open(os.path.join(ROOT, 'tools/closeout/frozen_unproven.txt'))
              .read().split())
    hold = [l.strip() for l in
            open(os.path.join(ROOT, 'tools/census_holdouts_kept.txt'))
            if l.strip()]
    return [h for h in hold if h in rem]


def try_prove(m):
    signal.signal(signal.SIGALRM, _alarm)
    for (k, n, t, fuel) in PARAMS:
        signal.alarm(PER_MACHINE_SECONDS)
        try:
            r = P.prove(m, k, n, t, fuel)
        except Exception:
            r = None
        finally:
            signal.alarm(0)
        if r:
            return (k, n, t, fuel, r['nctx'])
    return None


def sweep():
    tg = targets()
    print("NGramHist over %d unproven holdouts" % len(tg), file=sys.stderr)
    out = open(RESULTS, 'w')
    hits = 0
    for m in tg:
        got = try_prove(m)
        if got:
            hits += 1
            out.write("%s\t%d\t%d\t%d\t%d\t%d\n" % ((m,) + got))
            out.flush()
            print("  HIT %s k=%d n=%d nctx=%d" % (m, got[0], got[1], got[4]),
                  flush=True)
        else:
            print("  --  %s" % m, flush=True)
    out.close()
    print("hits: %d / %d -> %s" % (hits, len(tg), RESULTS), file=sys.stderr)


HDR = '''(* UNTRUSTED-generated by tools/nghist/holdout_sweep.py; the Coq kernel
   re-checks the whole claim via vm_compute in the proof below.

   %s -- a member of tools/census_holdouts_kept.txt (mxdys' 3,713 holdout
   list intersected with D_census), boarded by the NGramHist never-QH tier
   at k=%d n=%d t=%d fuel=%d (%d contexts). *)
'''


def emit():
    os.makedirs(OUTDIR, exist_ok=True)
    rows = [l.split('\t') for l in open(RESULTS) if l.strip()]
    for i, (m, k, n, t, fuel, nctx) in enumerate(rows):
        k, n, t, fuel, nctx = int(k), int(n), int(t), int(fuel), int(nctx)
        res = P.prove(m, k, n, t, fuel)
        assert res is not None, m
        body, thm = P.emit(m, res, i)
        path = os.path.join(OUTDIR, 'NGHHold_%02d.v' % i)
        open(path, 'w').write(HDR % (m, k, n, t, fuel, nctx)
                              + P.HEADER + '\n' + body + '\n')
        print("%s\t%s\ttheories/Machines/NGHHold/NGHHold_%02d.v" % (m, thm, i))


if __name__ == '__main__':
    {'sweep': sweep, 'emit': emit}[sys.argv[1] if len(sys.argv) > 1
                                  else 'sweep']()
