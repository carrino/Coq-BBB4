#!/usr/bin/env python3
"""Generate a lexicographic (rules a/b) certificate table for the
mirrored BBB README sample machine as a Coq .v file, theorem included.

Untrusted: the emitted data is re-verified inside Coq by
ngram_check_neverqh_lex.  Usage:

    python3 tools/gen_lex_cert.py N T OUT SUFFIX FUEL

The committed large-n table is produced by

    python3 tools/gen_lex_cert.py 5 0 theories/Machines/Sample_LexCert_N5.v _n5 150000

(The committed n=2 table theories/Machines/Sample_LexCert.v predates
this script's theorem emission and additionally carries the mirrored
corollary; regenerating it reproduces its cert data verbatim.)
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
exec(open(os.path.join(HERE, "lex_prover.py")).read().split("sample=mirror")[0])

n = int(sys.argv[1]) if len(sys.argv) > 1 else 2
t = int(sys.argv[2]) if len(sys.argv) > 2 else 0
out_path = sys.argv[3] if len(sys.argv) > 3 else "theories/Machines/Sample_LexCert.v"
suffix = sys.argv[4] if len(sys.argv) > 4 else ""
fuel = int(sys.argv[5]) if len(sys.argv) > 5 else 5000
# nat literals above 5000 trip Coq's abstract-large-number warning;
# emit big round fuels as a product instead.
fuel_s = ("(%d * 1000)" % (fuel // 1000)
          if fuel > 5000 and fuel % 1000 == 0 else str(fuel))

tbl = mirror(parse("1RB1LD_1LC0LD_1RC1RA_0LB0RA"))
seen, lset, rset = build_closure(tbl, n, t)

def cq(a):
    q, s, lw, rw = a
    sym = lambda v: "S1" if v == 1 else "S0"
    return "(St%s, ([%s], %s, [%s]))" % (
        chr(65 + q), "; ".join(sym(v) for v in lw), sym(s),
        "; ".join(sym(v) for v in rw))

def emit_phi(phi):
    items = ["(%s, %d)" % (cq(a), v)
             for a, v in sorted(phi.items(), key=str) if v != 0]
    return "[" + ";\n   ".join(items) + "]"

out = []
out.append(f"""(** Generated by tools/gen_lex_cert.py from the BBB harness's rank
    procedure (rules a/b) on the n={n} n-gram closure of the mirrored
    README sample machine ({len(seen)} contexts).  Data only; the
    checker re-verifies. *)
""")
out.append("From Coq Require Import List.\n"
           "From BBB4 Require Import BBB4_Statement CTape Mirror.\n"
           "From BBB4.Machines Require Import TCycler_Examples.\n"
           "From BBB4.Checkers Require Import NGram.\n"
           "Import ListNotations.\n")
mn = ["MAll", "MLeft", "MRight"]
for qq in range(4):
    comps = procedure(tbl, seen, lset, rset, qq)
    ok, bad = lex_check(tbl, seen, lset, rset, qq, comps, len(seen) + 2)
    assert ok, (qq, bad)
    items = []
    for comp in comps:
        if comp[0] == "rank":
            items.append("NgRank\n  %s" % emit_phi(comp[1]))
        else:
            _, mid, K, phi, gate = comp
            g = "[" + ";\n   ".join(cq(a) for a in sorted(gate, key=str)) + "]"
            items.append("NgMeas %s %d\n  %s\n  %s" % (mn[mid], K, emit_phi(phi), g))
    out.append("Definition cert%s_%s : list ngcomp := [\n%s].\n"
               % (suffix, chr(65 + qq), ";\n".join(items)))
out.append(f"""Definition sample_cert{suffix} (q : St) : list ngcomp :=
  match q with
  | StA => cert{suffix}_A | StB => cert{suffix}_B
  | StC => cert{suffix}_C | StD => cert{suffix}_D
  end.

(** The BBB README sample machine, decided by the n-gram closure at
    n = {n} ({len(seen)} contexts) with ranking-rule liveness.
    Parameters: window {n}, prefix {t}, and the generated
    lexicographic certificate. *)
Theorem tm_bbb_sample_never_quasihalts_rank{suffix} :
  NeverQuasiHaltsSt (mirror_tm tm_bbb_sample).
Proof.
  apply (ngram_check_neverqh_lex_sound _ {n} {t} {fuel_s} 32 sample_cert{suffix}).
  vm_compute. reflexivity.
Qed.
""")
open(out_path, "w").write("\n".join(out))
print("emitted", out_path, ":", sum(len(x) for x in out), "chars,", len(seen), "contexts")
