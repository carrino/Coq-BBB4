#!/usr/bin/env python3
"""Emit the STAGED wave-4 Task-B3 list-C state-QH tier (R_QH, UNTRUSTED).

The high-n ngram-QUIET pass: some census list-C residue machines are actually
QUASIHALTERS mis-binned as never-QH candidates.  The wave-3 IRules sweep boarded
1,090 of them (IQHStage); this pass recovers the additional ones whose QUIET
state has a QHBound closure that closes only at the higher orders n=5..8 -- the
census R_QH route through the LANDED `Wrap.v` QHBound gate, exactly Task A's
`pqhs` shape.  It reuses `gen_provenqh_stage.py`'s growing-closure QHBound search
(`find_cert_n56` = `find_plain`/`find_lex_rich`, keeping t<=1024) with the window
ladder widened to n in {5,6,7,8}, and its RRStage-shaped `emit_lemma`.

Emits SELF-CONTAINED files (distinct from Task A's PQHS_* so provenance stays
clean):

  theories/Machines/ProvenQHStage/PQHS_LC_NN.v   -- [pqhs] list + [Forall] cert
  tools/listc_qh_manifest.tsv                     -- machine -> theorem/file/gate

NOT wired; census inputs untouched.  UNTRUSTED: the Coq kernel re-checks every
claim through `ngram_check_qhbound(_lex)_sound`.  Board R_QH like Task A --
append `pqhs_lc_NN` to `reroot_qh_list` (Census/RerootQH_Data.v).

Usage: gen_listc_qh.py POOL_TXT [PER_FILE] [JOBS] [MAX_N]
  POOL_TXT default = the pool piped in; PER_FILE default 50; MAX_N default 8.
"""
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen_provenqh_stage as gps  # noqa: E402  reuse the n>=5 search + emit

B_PQ = 2000

HDR = """(** GENERATED by tools/gen_listc_qh.py -- DO NOT EDIT.

    STAGED wave-4 Task-B3 list-C STATE-QH recovery, chunk {nn} ({cnt} machines).
    SELF-CONTAINED and NOT imported by any census input yet: each list-C machine
    [tm] (a quasihalter the wave-3 IRules sweep missed) gets [pqhs tm] =
    [NonHalt /\\ QHBound 2000 /\\ QuasiHaltsSt] via the growing-closure QHBound
    checker at n in {{5,6,7,8}} (t <= 1024) -- PLAIN [ngram_check_qhbound_sound]
    or LEX [ngram_check_qhbound_lex_sound] (theories/Checkers/Wrap.v).  Ready to
    board the R_QH tier: append [pqhs_lc_{nn}] to [reroot_qh_list]
    (Census/RerootQH_Data.v) -- see docs/WAVE4_STAGE.md. *)
From Coq Require Import List Lia ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import NGram Wrap.
From BBB4.Census Require Import TNF_QH.
Import ListNotations.

Definition pqhs (tm : TM) : Prop :=
  NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm.
"""


def main():
    txt = sys.argv[1]
    per_file = int(sys.argv[2]) if len(sys.argv) > 2 else 50
    jobs = int(sys.argv[3]) if len(sys.argv) > 3 else 2
    max_n = int(sys.argv[4]) if len(sys.argv) > 4 else 8
    # widen the window ladder to n=5..max_n (Task A used only (5,6))
    gps.CAND_N = tuple(range(5, max_n + 1))

    machines = [l.strip() for l in open(txt)
                if l.strip() and not l.startswith("#")]
    with Pool(jobs) as p:
        results = p.map(gps.find_cert_n56, machines)
    caught = [c for c in results if c is not None]
    uncaught = [m for m, c in zip(machines, results) if c is None]
    for c in caught:
        assert c['t'] < B_PQ, ("t >= B_PQ", c['m'], c['t'])

    outdir = os.path.join(ROOT, "theories/Machines/ProvenQHStage")
    os.makedirs(outdir, exist_ok=True)
    n_chunks = (len(caught) + per_file - 1) // per_file
    manifest = []
    for ci in range(n_chunks):
        chunk = caught[ci * per_file:(ci + 1) * per_file]
        nn = "%02d" % ci
        tags = ["lc%s%03d" % (nn, k) for k in range(len(chunk))]
        body = [HDR.format(nn=nn, cnt=len(chunk))]
        for tag, c in zip(tags, chunk):
            body.append(gps.emit_lemma(tag, c))
            manifest.append((c['m'], "cpq_%s" % tag,
                             "theories/Machines/ProvenQHStage/PQHS_LC_%s.v" % nn,
                             c['gate'], chr(65 + c['qq']), c['s'], c['n'], c['t'],
                             "R_QH"))
        listname = "pqhs_lc_%s" % nn
        body.append("\nDefinition %s : list TM :=\n  [%s].\n"
                    % (listname, ";\n   ".join("tm_pq_" + t for t in tags)))
        term = "Forall_nil pqhs"
        for t in reversed(tags):
            term = "Forall_cons _ cpq_%s (%s)" % (t, term)
        body.append("Lemma %s_all : Forall pqhs %s.\nProof. exact (%s). Qed.\n"
                    % (listname, listname, term))
        open(os.path.join(outdir, "PQHS_LC_%s.v" % nn), "w").write("\n".join(body))
        print("wrote PQHS_LC_%s.v: %d machines" % (nn, len(chunk)))

    with open(os.path.join(HERE, "listc_qh_manifest.tsv"), "w") as f:
        f.write("machine\ttheorem\tfile\tgate\tquiet_state\ts\tn\tt\ttier\n")
        for row in manifest:
            f.write("\t".join(str(x) for x in row) + "\n")
    with open(os.path.join(HERE, "listc_qh_uncaught.txt"), "w") as f:
        f.write("\n".join(uncaught) + ("\n" if uncaught else ""))
    print("caught %d / %d  (n=5..%d, t<=1024); uncaught %d -> listc_qh_uncaught.txt"
          % (len(caught), len(machines), max_n, len(uncaught)))


if __name__ == "__main__":
    main()
