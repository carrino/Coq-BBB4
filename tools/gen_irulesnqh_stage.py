#!/usr/bin/env python3
"""Transcribe never-QH irules certificates (v3/v5/v6/v7) from the wave-3
list-C sweep into staged Coq batches for the census proven (R_NeverQH)
tier.

The IRules share of the list-C boardable never-QH machines (SWEEP §4:
the ~1/3 the NGram-rank emitter of wave 2 missed).  Same certificate
transcription as tools/gen_irulesblkpfx_certs.py (BIRCertP literal,
verified by the LANDED [irulesblkpfx_check_neverqh_sound], MetaBlkPfx --
no new checker), but LCStage-shaped for the wire follow-up: per file
[lcs2_NN : list TM] + [lcs2_NN_nqh : Forall NeverQuasiHaltsSt lcs2_NN],
ready to append to [proven_list] (Census/Proven_Data.v) next to the
wave-2 LCStage lists.  Files theories/Machines/ListCStage2/LCS2_NN.v.

Only certs whose claim_trans lines show EVERY visited state live
(state-level never-QH: no state with F-only transitions) are emitted;
state-QH certs belong to gen_irulesqh_certs.py.

Usage: gen_irulesnqh_stage.py OUTDIR MANIFEST.tsv CHUNKSIZE CERT [CERT ...]
"""
import sys, os, re, importlib.util

_spec = importlib.util.spec_from_file_location(
    "genbp", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "gen_irulesblkpfx_certs.py"))
G = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(G)

CFUEL = 200000
FUEL = 300000

HEADER = '''(** GENERATED by tools/gen_irulesnqh_stage.py -- DO NOT EDIT.

    STAGED wave-3 list-C never-QH machines (the IRules share), chunk
    {NN} ({CNT} machines).  SELF-CONTAINED and NOT imported by any
    census input yet: each machine gets [NeverQuasiHaltsSt] via the
    LANDED [irulesblkpfx_check_neverqh_sound]
    (Checkers/IRules/MetaBlkPfx.v) + [vm_compute] -- no new checker;
    corruption coverage is the landed Phase-2 engine's.  The
    certificates are UNTRUSTED search output (BBB bin/irules over the
    list-C residue); every claim is re-checked by the verified engine.
    Ready to board the proven (R_NeverQH) tier: append [lcs2_{NN}] to
    [proven_list] (Census/Proven_Data.v) -- see
    docs/REROOT_LISTC_STAGE.md + tools/wire_wave3.py. *)

From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Cycle.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
     EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
'''


def is_state_nqh(path):
    """UNTRUSTED: every visited state live (no F-only state)."""
    t = open(path).read()
    trans = {}
    for mm in re.finditer(r'^claim_trans (\w)(\d) (\w) (\d+) (\d+)', t, re.M):
        trans.setdefault(mm.group(1), []).append(mm.group(3))
    if not trans:
        return False
    for q, cl in trans.items():
        if 'F' in cl and 'I' not in cl:
            return False
    return True


def emit_machine(path, idx):
    c = G.parse_cert(path)
    m = c["machine"]
    nm = "n3_%05d" % idx
    a, b = c["meta_a"], c["meta_b"]
    s = []
    s.append("(* %s : anchor %d, ver %s *)"
             % (m, c["anchor_step"], c.get("ver", "?")))
    s.append("Definition tm_%s : TM := fun q s =>" % nm)
    s.append("  match q, s with")
    s.append(G.emit_tm(m))
    s.append("  end.")
    s.append("Definition cert_%s : BIRCertP := mkBIRCertP" % nm)
    s.append("  %d%%nat (%d) (%d) (%d) (%d) %s S%d"
             % (c["anchor_step"], c["k0"], c["kmin"], a, b,
                G.ST[c["tpl_state"]], c["tpl_hsym"]))
    s.append("  %s" % G.emit_blks(c["blk"]))
    s.append("  %s" % G.emit_tpl(c["tplL"]))
    s.append("  %s" % G.emit_tpl(c["tplR"]))
    s.append("  %s." % G.emit_rules(c["rules"], c["pfx"]))
    s.append("Lemma nqh_%s : NeverQuasiHaltsSt tm_%s." % (nm, nm))
    s.append("Proof.")
    s.append("  apply (irulesblkpfx_check_neverqh_sound tm_%s cert_%s "
             "%d %d)." % (nm, nm, CFUEL, FUEL))
    s.append("  vm_compute. reflexivity.")
    s.append("Qed.")
    return "\n".join(s), nm, m


def main():
    outdir, manifest, chunk = sys.argv[1], sys.argv[2], int(sys.argv[3])
    certs = sys.argv[4:]
    os.makedirs(outdir, exist_ok=True)
    blocks, names, machines, meta = [], [], [], []
    idx = 0
    skipped = 0
    for p in certs:
        if not is_state_nqh(p):
            skipped += 1
            continue
        body, nm, m = emit_machine(p, idx)
        c = G.parse_cert(p)
        blocks.append(body)
        names.append(nm)
        machines.append(m)
        meta.append((c["anchor_step"], c.get("ver", "?")))
        idx += 1
    nfiles = 0
    rows = []
    for ci in range(0, len(blocks), chunk):
        nn = "%02d" % nfiles
        cb = blocks[ci:ci + chunk]
        cn = names[ci:ci + chunk]
        fn = os.path.join(outdir, "LCS2_%s.v" % nn)
        with open(fn, "w") as f:
            f.write(HEADER.replace("{NN}", nn)
                    .replace("{CNT}", str(len(cb))) + "\n")
            f.write("\n\n".join(cb) + "\n\n")
            f.write("Definition lcs2_%s : list TM :=\n  [" % nn)
            f.write(";\n   ".join("tm_%s" % n for n in cn))
            f.write("].\n\n")
            f.write("Lemma lcs2_%s_nqh : Forall NeverQuasiHaltsSt "
                    "lcs2_%s.\n" % (nn, nn))
            term = "(Forall_nil NeverQuasiHaltsSt)"
            for n in reversed(cn):
                term = "(Forall_cons _ nqh_%s %s)" % (n, term)
            f.write("Proof. exact %s. Qed.\n" % term)
        for k in range(ci, min(ci + chunk, len(blocks))):
            rows.append((machines[k], "nqh_%s" % names[k],
                         "LCS2_%s.v" % nn, str(meta[k][0]), meta[k][1]))
        nfiles += 1
    with open(manifest, "w") as f:
        f.write("machine\ttheorem\tfile\tanchor\tcert_ver\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    sys.stderr.write("emitted %d machines into %d files; "
                     "skipped %d non-state-nQH certs\n"
                     % (len(names), nfiles, skipped))


if __name__ == "__main__":
    main()
