                               (l ++ todo') with
                   | Some k => Some (S k) | None => None
                   end
               end
      end
  end.

Definition pops_of (L T : nat) (tm : TM) : nat :=
  match csteps tm 0 c0 with
  | None => 0
  | Some cc =>
      match ppops tm L T F_HI PositiveSet.empty [rw_seed L T cc] with
      | Some k => k | None => 0
      end
  end.

(* (lost, caught at F_LO, max pops seen) *)
Fixpoint diff (L T : nat) (l : list TM) (lost lo mx : nat) : nat * nat * nat :=
  match l with
  | [] => (lost, lo, mx)
  | tm :: r =>
      let hi := rw_tier tm L T 0 F_HI in
      let lw := rw_tier tm L T 0 F_LO in
      diff L T r (lost + (if andb hi (negb lw) then 1 else 0))
           (lo + (if lw then 1 else 0))
           (Nat.max mx (pops_of L T tm))
  end.

