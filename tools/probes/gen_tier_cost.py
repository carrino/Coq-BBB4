#!/usr/bin/env python3
"""Emit a vm_compute probe measuring the census decider's cost PER TIER
on real machines, so tier cost can be paired with the census-wide tier
COUNTS from tools/census_ladder.c (Amdahl, not guesswork).

The heavy-subtree attribution in docs/CENSUS_RUNTIME.md is measured on
GG_1LC_1LB, which is residue-rich by construction and therefore
overstates the ladder's share of the whole walk.  This samples each
tier from the C mirror's per-machine CSV instead.

Usage:
  ./census_ladder --holdouts tools/BBB4_holdouts_3713.txt --csv T.csv
  gen_tier_cost.py T.csv OUT.v [SEED]

Groups follow the C mirror's tier column: H (halt/expand), C (in-place
cycle), T (translated cycle), N2/N3/N4/N6 (n-gram rungs), and '-'
(residue -- in the real Coq walk these are served by the proven/
provenqh/deferred lookup tables, which decide_easy consults BEFORE any
scan, so they are the cheap tier, not an expensive one).
"""
import collections
import csv
import os
import random
import sys

DIRS = {'L': 'DL', 'R': 'DR'}

# per-group sample sizes: enough to clear timer noise without blowing
# up the n-gram groups (~0.3 s per machine there)
SIZES = {'H': 40, 'C': 40, 'T': 40, '-': 40,
         'N2': 16, 'N3': 16, 'N4': 16, 'N6': 16, 'D': 16}


def tm_def(name, m):
    lines = [f"Definition {name} : TM := fun q s =>", "  match q, s with"]
    rows = m.split('_')
    for qi, part in enumerate(rows):
        for si in range(2):
            e = part[3 * si:3 * si + 3]
            pat = f"St{chr(65 + qi)}, S{si}"
            if e == '---':
                lines.append(f"  | {pat} => None")
            else:
                w, d, n = e[0], e[1], e[2]
                lines.append(
                    f"  | {pat} => Some (mkTrans S{w} {DIRS[d]} St{n})")
    lines.append("  end.")
    return "\n".join(lines)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    csv_path, out_path = sys.argv[1], sys.argv[2]
    seed = int(sys.argv[3]) if len(sys.argv) > 3 else 20260805
    rnd = random.Random(seed)

    # reservoir-sample per tier in one streaming pass (the CSV is ~4M rows)
    seen = collections.Counter()
    keep = collections.defaultdict(list)
    with open(csv_path, newline='') as f:
        for row in csv.reader(f):
            if not row or row[0] == 'machine':
                continue
            tier = row[2]
            k = SIZES.get(tier)
            if k is None:
                continue
            seen[tier] += 1
            if len(keep[tier]) < k:
                keep[tier].append(row[0])
            else:
                j = rnd.randrange(seen[tier])
                if j < k:
                    keep[tier][j] = row[0]

    out = ["""(** GENERATED by tools/probes/gen_tier_cost.py -- do not edit.

    Per-tier cost of the real census decider on machines sampled from
    the C mirror's full-census classification.  Pair these with the
    tier counts to get the walk's actual time split (Amdahl).

    Decider and lookup maps are ProbeWalkCommon's, i.e. Run.v's
    parameters with realistic stand-in tables. *)

From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement CTape ProbeWalkCommon.
From BBB4.Census Require Import TNF_QH Decide.
Import ListNotations.

Definition decided (r : QHResult) : bool :=
  match r with R_Unknown => false | _ => true end.
"""]

    order = [t for t in ['H', 'C', 'T', 'N2', 'N3', 'N4', 'N6', '-', 'D']
             if keep.get(t)]
    for tier in order:
        tag = 'RES' if tier == '-' else tier
        names = []
        for i, m in enumerate(keep[tier]):
            nm = f"tm_{tag}_{i}"
            out.append(f"(* {m} *)")
            out.append(tm_def(nm, m))
            names.append(nm)
        out.append(f"Definition grp_{tag} : list TM :=\n  [{'; '.join(names)}].")
        out.append("")

    out.append("(* counts in the full census, for the Amdahl weighting *)")
    for tier in order:
        out.append(f"(*   tier {tier:>2}: {seen[tier]} nodes,"
                   f" {len(keep[tier])} sampled *)")
    out.append("")
    for tier in order:
        tag = 'RES' if tier == '-' else tier
        out.append(f"(* --- tier {tier} : {len(keep[tier])} machines --- *)")
        out.append(f"Time Eval vm_compute in "
                   f"(List.length (filter decided (map decider0 grp_{tag}))).")
    out.append("")

    with open(out_path, 'w') as f:
        f.write("\n".join(out) + "\n")
    tot = sum(seen[t] for t in order)
    print(f"wrote {out_path}: {len(order)} tiers, "
          f"{sum(len(keep[t]) for t in order)} machines, "
          f"{tot} census nodes covered", file=sys.stderr)
    for t in order:
        print(f"  {t:>2}: {seen[t]:>9} nodes, {len(keep[t])} sampled",
              file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
