#!/usr/bin/env python3
"""Emit the M4 sizing probe for the population that can actually pay a
diverging RepWL closure IN THE WALK.

ProbeRwDivReach measured that of the 40-machine residue sample, only 7
reach the rw tier at all under the real pipeline, all 7 are caught at
the first rung (2,2,0), and NONE of their closures diverges.  So the
sample cannot contain the walk's divergence burn, and the 89%-of-pops
figure M4 was sized from came from forcing the rw ladder onto all 40.

Structurally, a machine reaching `try_rw` (the LAST tier) and not being
caught there is R_Unknown, and the census closes -- so in the walk every
machine reaching the tier IS caught by it.  The only failing rw attempts
the walk pays are therefore the EARLIER rungs of machines caught at a
LATER one, and tools/repwl_residue_caught.tsv tabulates exactly those:

    (2,2,0)  21,727   pays no failing attempt
    (3,2,0)   2,221   pays a failing (2,2,0)
    (4,2,0)     980   pays failing (2,2,0), (3,2,0)
    (2,3,0)     583   pays failing (2,2,0), (3,2,0), (4,2,0)

3,784 of 25,511 catches (14.8%) pay anything at all.  This samples each
group and measures those failing attempts: how many diverge, and what
they cost against the winning attempt.

Usage: gen_rwdiv_probe.py OUT_V [N] [SEED]

Untrusted probe generator: output is not in _CoqProject.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TSV = os.path.join(HERE, os.pardir, "repwl_residue_caught.tsv")
DIRS = {'L': 'DL', 'R': 'DR'}


def tm_body(m):
    lines = ["fun q s =>", "  match q, s with"]
    for qi, part in enumerate(m.split('_')):
        for si in range(2):
            e = part[3 * si:3 * si + 3]
            pat = f"St{chr(65 + qi)}, S{si}"
            if e == '---':
                lines.append(f"  | {pat} => None")
            else:
                lines.append(f"  | {pat} => Some (mkTrans S{e[0]} "
                             f"{DIRS[e[1]]} St{e[2]})")
    lines.append("  end")
    return "\n".join(lines)


def main():
    out = sys.argv[1]
    n = int(sys.argv[2]) if len(sys.argv) > 2 else 30
    rng = random.Random(int(sys.argv[3]) if len(sys.argv) > 3 else 20260812)

    groups = {}
    with open(TSV) as f:
        next(f)
        for line in f:
            p = line.strip().split('\t')
            if len(p) < 5:
                continue
            groups.setdefault((p[1], p[2], p[3]), []).append(p[0])

    order = [('2', '2', '0'), ('3', '2', '0'), ('4', '2', '0'),
             ('2', '3', '0')]
    names = {('2', '2', '0'): 'G22', ('3', '2', '0'): 'G32',
             ('4', '2', '0'): 'G42', ('2', '3', '0'): 'G23'}

    L = ['''(* GENERATED by tools/probes/gen_rwdiv_probe.py -- M4 sizing, part C.

   The machines that pay a FAILING rw attempt in the walk, sampled by
   winning rung from tools/repwl_residue_caught.tsv.  A machine caught
   at rung k pays a failing attempt at every rung before k, and nothing
   else in the walk pays one -- try_rw is the last tier, so a machine
   reaching it and failing every rung would be R_Unknown, and the census
   closes.

   Census weights: (2,2,0) 21,727 catches (no failing attempt),
   (3,2,0) 2,221, (4,2,0) 980, (2,3,0) 583.

   Untrusted probe: not in _CoqProject, loads into no proof. *)

From Coq Require Import Arith Bool List ZArith PArith.
From Coq Require Import FSets.FMapPositive.
From BBB4 Require Import BBB4_Statement CTape PosEnc Closure
                         ProbeWalkCommon ProbeTierCost.
From BBB4.Checkers Require Import Cycle RepWL.
From BBB4.Census Require Import TNF_QH Decide RepWLSearch.
Import ListNotations.

Definition FC : nat := 5120.
''']

    for key in order:
        ms = groups.get(key, [])
        pick = rng.sample(ms, min(n, len(ms)))
        L.append(f"(* caught at {key}: {len(ms)} census-wide, "
                 f"{len(pick)} sampled *)")
        L.append(f"Definition {names[key]} : list TM := [")
        L.append(";\n".join("  (" + tm_body(m) + ")" for m in pick))
        L.append("].\n")

    L.append('''
Fixpoint cnt {B} (l : list B) (f : B -> bool) (acc : nat) : nat :=
  match l with [] => acc | x :: t => cnt t f (acc + (if f x then 1 else 0)) end.
Fixpoint sumf {B} (l : list B) (f : B -> nat) (acc : nat) : nat :=
  match l with [] => acc | x :: t => sumf t f (acc + f x) end.

(** [close] as [rw_tier] calls it, forced to a nat *)
Definition csz (L T : nat) (tm : TM) : nat :=
  match csteps tm 0 c0 with
  | None => 0
  | Some cc =>
      match close rconf rconf_enc (rw_succs tm L T) FC
                  [] MSetPositive.PositiveSet.empty [rw_seed L T cc] with
      | None => 1 | Some Sl => List.length Sl end
  end.

Definition divg (L T : nat) (tm : TM) : bool :=
  match csteps tm 0 c0 with
  | None => false
  | Some cc =>
      match close rconf rconf_enc (rw_succs tm L T) FC
                  [] MSetPositive.PositiveSet.empty [rw_seed L T cc] with
      | None => true | Some _ => false end
  end.

(* --- sanity: the sampled machines are caught where the sweep says --- *)
Eval vm_compute in (List.length G22, List.length G32,
                    List.length G42, List.length G23).
Eval vm_compute in (cnt G22 (fun t => rw_tier t 2 2 0 FC) 0,
                    cnt G32 (fun t => rw_tier t 3 2 0 FC) 0,
                    cnt G42 (fun t => rw_tier t 4 2 0 FC) 0,
                    cnt G23 (fun t => rw_tier t 2 3 0 FC) 0).

(* --- do the FAILING earlier attempts diverge? --------------------- *)
(* group (3,2,0): its one failing attempt is (2,2,0) *)
Eval vm_compute in cnt G32 (divg 2 2) 0.
(* group (4,2,0): failing (2,2,0) and (3,2,0) *)
Eval vm_compute in (cnt G42 (divg 2 2) 0, cnt G42 (divg 3 2) 0).
(* group (2,3,0): failing (2,2,0), (3,2,0), (4,2,0) *)
Eval vm_compute in (cnt G23 (divg 2 2) 0, cnt G23 (divg 3 2) 0,
                    cnt G23 (divg 4 2) 0).
(* control: the 85% majority pays no failing attempt at all *)
Eval vm_compute in cnt G22 (divg 2 2) 0.

(* warm-up, not a measurement *)
Time Eval vm_compute in sumf (firstn 1 G22) (csz 2 2) 0.

(* --- what the failing attempts COST, per group -------------------- *)
Time Eval vm_compute in sumf G32 (csz 2 2) 0.
Time Eval vm_compute in (sumf G42 (csz 2 2) 0, sumf G42 (csz 3 2) 0).
Time Eval vm_compute in (sumf G23 (csz 2 2) 0, sumf G23 (csz 3 2) 0,
                         sumf G23 (csz 4 2) 0).

(* --- against the WINNING attempt of each group -------------------- *)
Time Eval vm_compute in sumf G22 (csz 2 2) 0.
Time Eval vm_compute in sumf G32 (csz 3 2) 0.
Time Eval vm_compute in sumf G42 (csz 4 2) 0.
Time Eval vm_compute in sumf G23 (csz 2 3) 0.

(* --- and the whole rw ladder, as the walk pays it, per group ------ *)
Definition rwladder (tm : TM) : bool :=
  anyb (fun '(L, T, t) => rw_tier tm L T t FC)
       [(2,2,0); (3,2,0); (4,2,0); (2,3,0)].
Time Eval vm_compute in cnt G22 rwladder 0.
Time Eval vm_compute in cnt G32 rwladder 0.
Time Eval vm_compute in cnt G42 rwladder 0.
Time Eval vm_compute in cnt G23 rwladder 0.
''')

    with open(out, 'w') as f:
        f.write("\n".join(L))
    print(f"wrote {out}")


if __name__ == '__main__':
    main()
