#!/bin/sh
# Emit one catch-diff probe per RepWL rung.  Split per rung so the four
# runs go on four cores; rung (3,2,0) is ~20x the cost of (2,2,0), so it
# takes a prefix of the sample (see NTAKE below) instead of all of it.
#
#   ./census_ladder --holdouts tools/BBB4_holdouts_3713.txt --csv T.csv
#   TIER_SCALE=15 TIER_ONLY=C,T,N6,- \
#     tools/probes/gen_tier_cost.py T.csv tools/probes/ProbeTierBig.v
#   tools/probes/gen_rwdiff.sh
set -e
out=$(dirname "$0")
i=0
for rung in "2 2 600" "3 2 200" "4 2 600" "2 3 600"; do
  set -- $rung
  L=$1; T=$2; N=$3; i=$((i+1))
  cat > "$out/ProbeRwDiff_$i.v" <<EOF
(* GENERATED by tools/probes/gen_rwdiff.sh -- do not edit.
   Catch-diff, rung ($L,$T,0), first $N of ProbeTierBig's residue sample.
   Prints (disagreements, catches): the first component must be 0. *)
From Coq Require Import Arith Bool List.
From BBB4 Require Import BBB4_Statement CTape ProbeWalkCommon ProbeTierBig.
From BBB4.Census Require Import TNF_QH Decide RepWLSearch.
Import ListNotations.

Definition F8k : nat := 8192.

Fixpoint dg (l : list TM) (d c : nat) : nat * nat :=
  match l with
  | [] => (d, c)
  | tm :: t =>
      let n := rw_tier tm $L $T 0 F8k in
      let o := rw_tier_ref tm $L $T 0 F8k in
      dg t (d + (if Bool.eqb n o then 0 else 1)) (c + (if n then 1 else 0))
  end.

Definition sample : list TM := Eval vm_compute in firstn $N grp_RES.
Eval vm_compute in List.length sample.
Time Eval vm_compute in dg sample 0 0.
EOF
done
echo "wrote $out/ProbeRwDiff_1.v .. ProbeRwDiff_4.v"
