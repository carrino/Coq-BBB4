#!/usr/bin/env python3
"""Generate the rw_fuel catch-diff probe (untrusted).

Lowering `close` fuel is MONOTONE: with less fuel the worklist has
strictly fewer chances to empty, so `close` can only turn Some into
None -- a catch can be LOST, never GAINED.  The gate is therefore
one-sided: every machine currently caught must still be caught.

tools/repwl_residue_caught.tsv is the CENSUS-WIDE kept-catch table
(machine, L, T, t, nseen) for the four rungs the walk runs, so the
machines at risk are exactly the ones with the largest closures --
they are known by name, not sampled.  This emits the top `--top` of
them per rung (largest nseen first), which is a far tighter gate than
a random sample of the residue.

  python3 tools/probes/gen_rwfuel_diff.py --top 60 > tools/probes/ProbeRwFuelDiff.v
"""
import argparse
import collections
import csv

DIRS = {'L': 'DL', 'R': 'DR'}


def tm_def(name, m):
    lines = [f"Definition {name} : TM := fun q s =>", "  match q, s with"]
    for qi, part in enumerate(m.split('_')):
        for si in range(2):
            e = part[3 * si:3 * si + 3]
            pat = f"St{chr(65 + qi)}, S{si}"
            if e == '---':
                lines.append(f"  | {pat} => None")
            else:
                w, d, n = e[0], e[1], e[2]
                lines.append(f"  | {pat} => Some (mkTrans S{w} {DIRS[d]} St{n})")
    lines.append("  end.")
    return "\n".join(lines)


ap = argparse.ArgumentParser()
ap.add_argument("--top", type=int, default=60)
ap.add_argument("--tsv", default="tools/repwl_residue_caught.tsv")
a = ap.parse_args()

rows = list(csv.DictReader(open(a.tsv), delimiter="\t"))
by = collections.defaultdict(list)
for r in rows:
    by[(int(r["L"]), int(r["T"]), int(r["t"]))].append((int(r["nseen"]), r["machine"]))

out, groups, tot = [], [], 0
for rung in sorted(by):
    sel = sorted(by[rung], reverse=True)[:a.top]
    L, T, t = rung
    tag = f"{L}{T}{t}"
    names = []
    for i, (nseen, m) in enumerate(sel):
        nm = f"tm_{tag}_{i}"
        out.append(f"(* {m}  nseen={nseen} *)\n{tm_def(nm, m)}")
        names.append(nm)
    groups.append((rung, tag, names, sel[0][0]))
    tot += len(names)

print(f"""(* GENERATED by tools/probes/gen_rwfuel_diff.py -- do not edit.

   rw_fuel catch-diff, {tot} machines: the largest-closure kept catches
   at each walked rung, taken from the CENSUS-WIDE table
   tools/repwl_residue_caught.tsv (all 25,511 catches), not sampled.

   Lowering fuel is monotone -- it can only LOSE catches -- and the
   machines that can lose one are exactly those whose closure is
   nearest the cap.  Each row prints (lost, caught_at_low, pops_max):
   the first component MUST be 0.

   Untrusted probe: not in _CoqProject, loads into no proof. *)

From Coq Require Import Arith Bool List PArith.
From BBB4 Require Import BBB4_Statement CTape PosEnc Closure.
From BBB4.Checkers Require Import Cycle RepWL.
From BBB4.Census Require Import TNF_QH RepWLSearch.
Import ListNotations.

Definition F_HI : nat := 8192.   (* rw_fuel_census today *)
Definition F_LO : nat := 4608.   (* the candidate *)

(* Closure.close, instrumented to report the pops it actually used *)
Fixpoint ppops (tm : TM) (L T fuel : nat) (sp : PositiveSet.t)
    (todo : list rconf) : option nat :=
  match fuel with
  | 0 => None
  | S f =>
      match todo with
      | [] => Some 0
      | b :: todo' =>
          if pset_mem rconf rconf_enc b sp
          then match ppops tm L T f sp todo' with
               | Some k => Some (S k) | None => None end
          else match rw_succs tm L T b with
               | None => None
               | Some l =>
                   match ppops tm L T f (pset_add rconf rconf_enc b sp)
                               (l ++ todo') with
                   | Some k => Some (S k) | None => None
                   end
               end
      end
  end.

Definition pops_of (L T : nat) (tm : TM) : nat :=
  match csteps tm 0 c0 with
  | None => 0
  | Some cc =>
      match ppops tm L T F_HI PositiveSet.empty [rw_seed L T cc] with
      | Some k => k | None => 0
      end
  end.

(* (lost, caught at F_LO, max pops seen) *)
Fixpoint diff (L T : nat) (l : list TM) (lost lo mx : nat) : nat * nat * nat :=
  match l with
  | [] => (lost, lo, mx)
  | tm :: r =>
      let hi := rw_tier tm L T 0 F_HI in
      let lw := rw_tier tm L T 0 F_LO in
      diff L T r (lost + (if andb hi (negb lw) then 1 else 0))
           (lo + (if lw then 1 else 0))
           (Nat.max mx (pops_of L T tm))
  end.
""")
print("\n".join(out))
for (L, T, t), tag, names, mx in groups:
    print(f"\n(* rung ({L},{T},{t}) -- {len(names)} largest closures, max nseen {mx} *)")
    print(f"Definition g{tag} : list TM := [{'; '.join(names)}].")
    print(f"Time Eval vm_compute in diff {L} {T} g{tag} 0 0 0.")
