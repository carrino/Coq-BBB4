#!/usr/bin/env python3
"""Generate ProbeLookup.v: the walk probe's stand-in lookup table.

Union of the proven / provenqh / holdout machine lists from tools/,
emitted in Deferred_Defs row format so the probe's pmap behaves
cost-wise like the real walk's lookup tiers.  Untrusted scaffolding;
see tools/probes/README.md.  Run from the repo root:

    python3 tools/probes/gen_probe_lookup.py > tools/probes/ProbeLookup.v
"""
import re, sys, os

SOURCES = ['proven_map.tsv', 'provenqh_map.tsv', 'proven_dropped.txt',
           'provenqh_dropped.txt', 'proven_listc_dropped.txt',
           'reroot_boarded.txt', 'iqh_boarded.txt', 'BBB4_holdouts_3713.txt']
PAT = re.compile(r'([01-][RL-][A-D-]){2}(_([01-][RL-][A-D-]){2}){3}')

def row(m):
    toks = []
    for part in m.split('_'):
        for tr in (part[:3], part[3:]):
            toks.append('tN' if tr == '---' else f't{tr}')
    return '[' + ';'.join(toks) + ']'

machines = set()
base = os.path.join(os.path.dirname(__file__), '..')
for name in SOURCES:
    try:
        for line in open(os.path.join(base, name)):
            f = line.strip().split('\t')[0].strip()
            if PAT.fullmatch(f):
                machines.add(f)
    except FileNotFoundError:
        print(f'missing source: {name}', file=sys.stderr)

rows = [row(m) for m in sorted(machines)]
print(f'(* GENERATED by gen_probe_lookup.py ({len(rows)} machines) -- do not edit. *)')
print('From Coq Require Import List.')
print('From BBB4 Require Import BBB4_Statement.')
print('From BBB4.Census Require Import Deferred_Defs.')
print('Import ListNotations.')
names = []
CH = 400
for i in range(0, len(rows), CH):
    n = f'plk_{i//CH:03d}'
    names.append(n)
    print(f'Definition {n} : list (list (option Trans)) := [')
    print(';\n'.join(rows[i:i+CH]) + '].')
print('Definition probe_lookup : list TM := map row_to_tm (' +
      ' ++ '.join(names) + ').')
