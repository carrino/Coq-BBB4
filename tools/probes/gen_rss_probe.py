#!/usr/bin/env python3
"""Emit peak-RSS ATTRIBUTION probes for the census walk.

docs/CENSUS_RUNTIME.md's "<1 h goal is now a MEMORY problem" section
turns the goal into one number -- per-unit peak RSS <= 3.75 GB, so
WALK_JOBS = min(cores, (RAM - 2 GB)/RSS) reaches 8 on 8 cores / 32 GB.
Nothing had ever measured WHERE a walk unit's RSS goes.  This emits one
probe per (workload, fuel) configuration so each can be run in its OWN
`coqc` process under `/usr/bin/time -v`: peak RSS is a whole-process
high-water mark, so configurations must not share a process.

Workloads (all use ProbeWalkCommon's decider parameters, i.e. Run.v's,
with the generated stand-in lookup tables):

  load   nothing at all -- the floor: Coq + the .vo of the dependency
         closure, with no evaluation.  Subtract this from everything.
  tab    forces the three lookup maps (proven / deferred / hints) with
         vm_compute but decides nothing -- the floor PLUS the tables.
  bulk   the decider over ProbeTierCost's C and T groups (80 machines):
         the cheap scan tiers, no deep ladder.
  res    the decider over ProbeTierCost's residue group (40 machines):
         the machines that fall through every scan into the rank /
         wrapped-QHBound / RepWL ladders.  This is where ng_fuel and
         rw_fuel are actually spent.
  walk   ProbeWalk_K1: 8192 pop-slots of the heavy GG_1LC_1LB subtree,
         i.e. a bounded real walk of a real unit's subtree.
  unit   the REAL walk unit: Run.v's own decider, the real proven /
         provenqh / deferred maps, rooted at Run_Split2's q_ggsub --
         literally what theories/Census/Compute/GG_1LC_1LB.v walks,
         cut to `--iter' q_suc rounds (the unit itself runs 700).
         `--iter 0' walks nothing and measures the FLOOR: what the
         engine pays to load, compile and link the census environment
         before any machine is decided.

Usage:
  gen_rss_probe.py WORKLOAD OUT.v [--ng N] [--rw N] [--rounds N]
                                  [--iter N] [--gas A,B] [--native]

Example (the attribution A/B):
  for ng in 200000 20000 2000; do
    python3 tools/probes/gen_rss_probe.py res /tmp/R_$ng.v --ng $ng
    /usr/bin/time -v coqc -Q theories BBB4 -Q tools/probes BBB4 /tmp/R_$ng.v
  done

Example (the NATIVE decomposition -- needs the census opam switch, and
answers what vm_compute cannot: how the walk unit's 6.8 GB splits
between the engine's fixed cost and the walk itself):
  for it in 0 1 4 16; do
    python3 tools/probes/gen_rss_probe.py unit /tmp/U_$it.v --iter $it --native
    OCAMLRUNPARAM=o=40,O=60 /usr/bin/time -v \\
      coqc -Q theories BBB4 -Q tools/probes BBB4 /tmp/U_$it.v
  done
The `--iter 0' row is the floor; if it is already most of 6.8 GB, no
decider-side parameter can reach the memory target and the lever is the
engine (GC settings, unit granularity), not the pipeline.
"""
import argparse
import sys

HEAD = """(** GENERATED by tools/probes/gen_rss_probe.py -- do not edit.
    Peak-RSS attribution probe: workload {workload}, ng_fuel {ng},
    ng_rounds {rounds}, rw_fuel {rw}, gas ({hg},{lg}), engine {engine}.
    Run in its OWN process under /usr/bin/time -v. *)

From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data.
From BBB4 Require Import ProbeWalkCommon.
Import ListNotations.
"""

UNIT_HEAD = """(** GENERATED by tools/probes/gen_rss_probe.py -- do not edit.
    Peak-RSS attribution probe: the REAL walk unit's computation
    (Run.v's decider and lookup maps, Run_Split2's q_ggsub root),
    {iter} of the 700 q_suc rounds GG_1LC_1LB runs, engine {engine}.
    `--iter 0' measures the engine's fixed cost, decides nothing.
    Run in its OWN process under /usr/bin/time -v. *)

From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data
                                Run Run_Split Run_Split2.
Import ListNotations.

Time Eval {engine} in
  (let q := Nat.iter {iter} q_suc (q_ggsub S1 DL StB) in
   (length (fst q), length (snd q))).
"""

DECIDER = """
Definition decider_v : TM -> QHResult :=
  decide_easy Bc {hg} {lg} {ng} {rounds} ngr rkr qhr rwr {rw}
              pmap0 emap dmap0 hmap0.
"""

BODIES = {
    'load': """
(* floor: no evaluation at all *)
Time Eval {engine} in (1 + 1).
""",
    'tab': """
(* the lookup tables, forced, and nothing else *)
Definition tm_triv : TM := fun _ _ => None.
Time Eval {engine} in
  (deferred_lookup dmap0 tm_triv, proven_lookup pmap0 tm_triv).
""",
    'bulk': """
From BBB4 Require Import ProbeTierCost.
Time Eval {engine} in
  (List.length (filter decided (map decider_v (grp_C ++ grp_T)))).
""",
    'res': """
From BBB4 Require Import ProbeTierCost.
Time Eval {engine} in
  (List.length (filter decided (map decider_v grp_RES))).
""",
    'walk': """
Definition qsuc_v (q : SearchQueue) : SearchQueue :=
  SearchQueue_upds q decider_v 13.
Time Eval {engine} in
  (let q := Nat.iter {iter} qsuc_v q_probe in
   (length (fst q), length (snd q))).
""",
}


def main():
    ap = argparse.ArgumentParser(add_help=False)
    ap.add_argument('workload', choices=sorted(BODIES) + ['unit'])
    ap.add_argument('out')
    ap.add_argument('--ng', type=int, default=200000)
    ap.add_argument('--rw', type=int, default=5120)
    ap.add_argument('--rounds', type=int, default=512)
    ap.add_argument('--iter', type=int, default=1)
    ap.add_argument('--gas', default='130,512')
    ap.add_argument('--native', action='store_true',
                    help='native_compute (census opam switch); apt Coq has '
                         'no native compiler and silently falls back to the VM')
    a = ap.parse_args()
    hg, lg = (int(x) for x in a.gas.split(','))

    fmt = dict(workload=a.workload, ng=a.ng, rw=a.rw, rounds=a.rounds,
               hg=hg, lg=lg, iter=a.iter,
               engine='native_compute' if a.native else 'vm_compute')
    if a.workload == 'unit':
        out = UNIT_HEAD.format(**fmt)
    else:
        out = HEAD.format(**fmt)
        if a.workload not in ('load', 'tab'):
            out += DECIDER.format(**fmt)
        out += BODIES[a.workload].format(**fmt)
    with open(a.out, 'w') as f:
        f.write(out)
    print(f"wrote {a.out}: {a.workload} ng={a.ng} rounds={a.rounds} "
          f"rw={a.rw} gas=({hg},{lg}) iter={a.iter} engine={fmt['engine']}",
          file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
