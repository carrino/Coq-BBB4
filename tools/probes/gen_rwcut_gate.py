#!/usr/bin/env python3
"""The EXHAUSTIVE gate for M4's node-size cut.

The cut aborts a RepWL closure as soon as a popped node carries more
than M run-length items.  It is MONOTONE -- it can only turn a [Some]
into a [None] -- so it can lose a catch and can never gain one, and a
lost catch in this census is not a coverage regression but R_Unknown,
i.e. the walk does not close.

That monotonicity plus the fact that every kept catch is TABULATED is
what makes the gate exhaustive rather than sampled: for each of the
25,511 rows of tools/repwl_residue_caught.tsv, recompute the max node
size over THAT row's winning closure and check none exceeds M.  Nothing
else can lose a catch -- a failing earlier rung aborting early returns
no catch either way, and rungs are independent attempts.

Machines are emitted through [row_to_tm] (Census/Deferred_Defs.v) so
each is one line instead of an eleven-line match; the gate measures a
maximum, not a time, so the slightly slower lookup costs nothing that
matters.

Usage: gen_rwcut_gate.py OUTDIR [CHUNK]

Untrusted probe generator: output is not in _CoqProject.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TSV = os.path.join(HERE, os.pardir, "repwl_residue_caught.tsv")

HEAD = '''(* GENERATED by tools/probes/gen_rwcut_gate.py -- M4's exhaustive gate,
   chunk %d of %d (rows %d..%d of tools/repwl_residue_caught.tsv).

   Prints (rows, max node size over the winning closures, how many
   exceed 24, how many exceed 32).  The gate passes iff the third
   component is 0 for every chunk.

   Untrusted probe: not in _CoqProject, loads into no proof. *)

From Coq Require Import Arith Bool List ZArith PArith.
From Coq Require Import FSets.FMapPositive.
From BBB4 Require Import BBB4_Statement CTape PosEnc Closure.
From BBB4.Checkers Require Import Cycle RepWL.
From BBB4.Census Require Import TNF_QH Decide Deferred_Defs RepWLSearch.
Import ListNotations.

Definition FC : nat := 5120.

Definition asz (a : rconf) : nat :=
  match a with
  | (_, (l, ls, _, rs, r)) =>
      List.length l + List.length r + List.length ls + List.length rs
  end.

Fixpoint mclose (tm : TM) (L T fuel mx : nat) (sp : PositiveSet.t)
    (todo : list rconf) : nat :=
  match fuel with
  | 0 => mx
  | S f =>
      match todo with
      | [] => mx
      | a :: todo' =>
          if pset_mem rconf rconf_enc a sp then mclose tm L T f mx sp todo'
          else match rw_succs tm L T a with
               | None => Nat.max mx (asz a)
               | Some l =>
                   mclose tm L T f (Nat.max mx (asz a))
                     (pset_add rconf rconf_enc a sp) (l ++ todo')
               end
      end
  end.

Definition runmx (p : TM * nat * nat) : nat :=
  match p with
  | (tm, L, T) =>
      match csteps tm 0 c0 with
      | None => 0
      | Some cc => mclose tm L T FC 0 PositiveSet.empty [rw_seed L T cc]
      end
  end.

Fixpoint maxf {B} (l : list B) (f : B -> nat) (acc : nat) : nat :=
  match l with [] => acc | x :: t => maxf t f (Nat.max acc (f x)) end.
Fixpoint cnt {B} (l : list B) (f : B -> bool) (acc : nat) : nat :=
  match l with [] => acc | x :: t => cnt t f (acc + (if f x then 1 else 0)) end.

'''


def row(m):
    """machine string -> the eight row_to_tm slots, bbchallenge order"""
    out = []
    for part in m.split('_'):
        for si in range(2):
            e = part[3 * si:3 * si + 3]
            out.append('tN' if e == '---' else f"t{e[0]}{e[1]}{e[2]}")
    return "; ".join(out)


def main():
    outdir = sys.argv[1]
    chunk = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
    os.makedirs(outdir, exist_ok=True)

    rows = []
    with open(TSV) as f:
        next(f)
        for line in f:
            p = line.strip().split('\t')
            if len(p) >= 4:
                rows.append((p[0], p[1], p[2]))

    n = (len(rows) + chunk - 1) // chunk
    names = []
    for i in range(n):
        part = rows[i * chunk:(i + 1) * chunk]
        name = f"PRwGate_{i:02d}"
        names.append(name)
        with open(os.path.join(outdir, name + ".v"), 'w') as f:
            f.write(HEAD % (i + 1, n, i * chunk, i * chunk + len(part) - 1))
            f.write("Definition rows : list (TM * nat * nat) := [\n")
            f.write(";\n".join(
                f"  (row_to_tm [{row(m)}], {L}, {T})" for m, L, T in part))
            f.write("].\n\n")
            f.write("Eval vm_compute in (List.length rows,\n"
                    "                    maxf rows runmx 0,\n"
                    "                    cnt rows (fun p => 24 <? runmx p) 0,\n"
                    "                    cnt rows (fun p => 32 <? runmx p) 0).\n")
    print(f"wrote {n} chunks of <= {chunk} into {outdir}")
    print(" ".join(names))


if __name__ == '__main__':
    main()
