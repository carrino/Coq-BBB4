#!/usr/bin/env python3
"""UNTRUSTED generator: one Coq counter-alphabet module per inferred family.

`alphabet_infer.py` reads a counter's word family off the tape as three fixed
words (A, B, C) with

    E xH = C        E (xO q) = A ++ E q        E (xI q) = B ++ E q

and that is ALL an ENCDATA row needs.  This turns such a triple into
`theories/Counters/Alph_<tag>.v` -- a fixpoint plus the two decomposition
lemmas, in exactly the form `Checkers/LapDecider.v`'s glue consumes -- and
into the matching row for `emit_lapcert.ENCDATA`.

The proofs are the same induction for every alphabet (it is the same theorem
with different letters), which is the whole point: `Ip`, `Jp`, `Kp`, `Dp`,
`Mp` and `Bp` were six hand-written files and six tape readings for what is
one parameterised argument.

Everything here is untrusted -- a wrong (A, B, C) makes the generated file
FAIL TO COMPILE, since the lemmas are proved, not asserted.
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
OUTDIR = os.path.join(REPO, 'theories', 'Counters')


def tag(A, B, C):
    d = lambda w: ''.join(str(x) for x in w)          # noqa: E731
    return 'Alph_%s_%s_%s' % (d(A), d(B), d(C))


def clist(w):
    return '[' + '; '.join('S%d' % x for x in w) + ']'


TEMPLATE = r'''(** * @TAG@: an INFERRED counter word alphabet.

    Generated by tools/counters/gen_alphabet.py from a family read off the
    tape by tools/counters/alphabet_infer.py.  Every counter alphabet in this
    development ([ILCounter.Ip], [JpCounter.Jp], [KpCounter.Kp],
    [DpCounter.Dp], [MpCounter.Mp], [BpCounter.Bp]) has the shape

      E xH = C        E (xO q) = A ++ E q        E (xI q) = B ++ E q

    and the two decomposition lemmas below are the SAME induction for every
    choice of A, B and C.  Here

      A = @A@        B = @B@        C = @C@

    verified against the machine's own tape for @NW@ consecutive anchor words
    before this file was generated.  The generator is untrusted: a wrong
    triple does not typecheck, because the lemmas are proved rather than
    assumed.

    Axiom footprint: none (closed under the global context). *)

From Coq Require Import Arith Lia Bool List PArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Counters Require Import WTape MonoCounter.
Import ListNotations.

Fixpoint Ap_@TAG@ (p : positive) : list Sym :=
  match p with
  | xH => @C@
  | xO q => @A@ ++ Ap_@TAG@ q
  | xI q => @B@ ++ Ap_@TAG@ q
  end.

(** Interior increment: [j] trailing set bits clear and the first clear bit
    sets, so a run of [B] becomes a run of [A] and the stop digit swaps. *)
Lemma cview_some_@TAG@ : forall p j q, cview p = (j, Some q) ->
  Ap_@TAG@ p = rep @B@ j ++ @A@ ++ Ap_@TAG@ q /\
  Ap_@TAG@ (Pos.succ p) = rep @A@ j ++ @B@ ++ Ap_@TAG@ q.
Proof.
  induction p; intros j q H; simpl in H.
  - destruct (cview p) as [j' r] eqn:E. inversion H; subst j r.
    destruct (IHp j' q eq_refl) as (H1 & H2).
    split; simpl; [rewrite H1 | rewrite H2]; reflexivity.
  - inversion H; subst j q. split; reflexivity.
  - discriminate.
Qed.

(** Overflow, [p = 2^(j+1) - 1]: the whole word is a run of [B] over the
    terminator, and the increment turns it into a longer run of [A]. *)
Lemma cview_none_@TAG@ : forall p j, cview p = (S j, None) ->
  Ap_@TAG@ p = rep @B@ j ++ @C@ /\
  Ap_@TAG@ (Pos.succ p) = rep @A@ (S j) ++ @C@.
Proof.
  induction p; intros j H; simpl in H.
  - destruct (cview p) as [j' r] eqn:E. inversion H; subst j' r.
    destruct j as [|j].
    + (* cview p = (0, None) is impossible *)
      exfalso. destruct p; simpl in E.
      * destruct (cview p) as [jj rr]; discriminate.
      * discriminate.
      * discriminate.
    + destruct (IHp j eq_refl) as (H1 & H2).
      split; simpl; [rewrite H1 | rewrite H2]; reflexivity.
  - discriminate.
  - inversion H; subst j. split; reflexivity.
Qed.
'''


def render(A, B, C, nwords):
    t = tag(A, B, C)
    out = TEMPLATE
    for k, v in (('@TAG@', t), ('@A@', clist(A)), ('@B@', clist(B)),
                 ('@C@', clist(C)), ('@NW@', str(nwords))):
        out = out.replace(k, v)
    return out


def row(A, B, C):
    """The emit_lapcert.ENCDATA row this alphabet induces."""
    t = tag(A, B, C)
    return ("    '%s': dict(uS=%r, sS=%r, uD=%r, sD=%r,\n"
            "               obS=0, soS=%r, soD=%r,\n"
            "               mod='%s', some='cview_some_%s',"
            " none='cview_none_%s'),\n"
            % (t, tuple(B), tuple(A), tuple(A), tuple(B),
               tuple(C), tuple(C), t, t, t))


def coqc(path):
    r = subprocess.run(['coqc', '-native-compiler', 'no', '-Q', 'theories',
                        'BBB4', path], cwd=REPO, capture_output=True, text=True)
    return r.returncode == 0, (r.stderr or r.stdout)[-800:]


def build(A, B, C, nwords=0, compile_it=True):
    t = tag(A, B, C)
    path = os.path.join(OUTDIR, t + '.v')
    open(path, 'w').write(render(A, B, C, nwords))
    if not compile_it:
        return t, True, ''
    ok, log = coqc(os.path.relpath(path, REPO))
    if not ok:
        os.remove(path)
    return t, ok, log


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--abc', required=True,
                    help='A,B,C as digit strings, e.g. 00,10,1')
    ap.add_argument('--nwords', type=int, default=0)
    ap.add_argument('--row', action='store_true')
    a = ap.parse_args()
    A, B, C = [[int(c) for c in part] for part in a.abc.split(',')]
    t, ok, log = build(A, B, C, a.nwords)
    print('%s : %s' % (t, 'OK' if ok else 'FAILED'))
    if not ok:
        print(log)
        sys.exit(1)
    if a.row:
        sys.stdout.write(row(A, B, C))


if __name__ == '__main__':
    main()
