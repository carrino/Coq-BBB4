#!/usr/bin/env python3
"""Wrap-QH theorems for census RESIDUE machines -> Coq.

Consumes the caught.tsv produced by sweep_wrap_residue.py (machine,
quiet_state, s, n, t) and emits, per machine, a theorem

  NonHalt tm /\ QuietAfter tm q s /\ QuasiHaltsSt tm

via ngram_check_quiet_sound (theories/Checkers/Wrap.v) -- the SAME
verified checker the upstream wrapctl/wrapfar holdouts use.  Each
machine is thereby a Coq-checked quasihalter (closed by vm_compute),
which removes it from the never-QH search space; folding these into the
census deferred list additionally needs the QHBound-over-all-quiet-
states tier (see NEXT_SESSION.md).

The closure sizes (for the fuel / rounds vm_compute parameters) are
recomputed here from the same untrusted search.

Usage: gen_residue_wrap.py CAUGHT_TSV OUT_DIR [PER_FILE] [LIMIT]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bulk_prover as bp
import sweep_wrap_residue as sw

HEADER = """(** Generated by tools/gen_residue_wrap.py -- DO NOT EDIT.

    Quasihalting theorems for census-residue machines that are
    prefix-quiet quasihalters, via the halt-redirect n-gram closure
    (theories/Checkers/Wrap.v, ngram_check_quiet_sound). *)

From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Wrap.
"""


def emit_tm(name, mtext):
    tbl = bp.parse(mtext)
    lines = ["Definition %s : TM := fun q s =>" % name, "  match q, s with"]
    for qi in range(4):
        for si in range(2):
            tr = tbl[(qi, si)]
            lhs = "St%s, S%d" % (chr(65 + qi), si)
            if tr is None:
                lines.append("  | %s => None" % lhs)
            else:
                w, d, q2 = tr
                lines.append("  | %s => Some (mkTrans S%d D%s St%s)"
                             % (lhs, w, d, chr(65 + q2)))
    lines.append("  end.")
    return "\n".join(lines)


def closure_sizes(mtext, qq, n, t):
    """Re-run the wrapped closure to size fuel/rounds; returns
    (|seen|, |lset|, |rset|) or None."""
    tbl = bp.parse(mtext)
    tape = {}
    pos = 0
    q = 0
    for _ in range(t):
        tr = tbl[(q, tape.get(pos, 0))]
        w, d, nq = tr
        tape[pos] = w
        pos += 1 if d == "R" else -1
        q = nq
    tw = dict(tbl)
    tw[(qq, 0)] = None
    tw[(qq, 1)] = None
    minp = min([pos] + list(tape))
    maxp = max([pos] + list(tape))
    Lf = lambda i: tape.get(pos - 1 - i, 0)
    Rf = lambda i: tape.get(pos + 1 + i, 0)
    win = lambda f, d: tuple(f(d + i) for i in range(n))
    depth = max(pos - minp, maxp - pos) + n + 2
    lset = {win(Lf, d) for d in range(1, depth)}
    rset = {win(Rf, d) for d in range(1, depth)}
    a0 = (q, tape.get(pos, 0), win(Lf, 0), win(Rf, 0))
    for _ in range(400):
        seen = set()
        todo = [a0]
        while todo:
            a = todo.pop()
            if a in seen:
                continue
            seen.add(a)
            q1, s1, lw, rw = a
            tr = tw[(q1, s1)]
            if tr is None:
                continue
            w, d, q2 = tr
            if d == "R":
                for x in (0, 1):
                    rw2 = rw[1:] + (x,)
                    if rw2 in rset:
                        todo.append((q2, rw[0], (w,) + lw[:-1], rw2))
            else:
                for x in (0, 1):
                    lw2 = lw[1:] + (x,)
                    if lw2 in lset:
                        todo.append((q2, lw[0], lw2, (w,) + rw[:-1]))
        newl = {a[2] for a in seen if tw[(a[0], a[1])] and tw[(a[0], a[1])][1] == "R"}
        newr = {a[3] for a in seen if tw[(a[0], a[1])] and tw[(a[0], a[1])][1] == "L"}
        if newl <= lset and newr <= rset:
            return len(seen), len(lset), len(rset)
        lset |= newl
        rset |= newr
    return None


def main():
    caught = sys.argv[1]
    outdir = sys.argv[2]
    per_file = int(sys.argv[3]) if len(sys.argv) > 3 else 60
    limit = int(sys.argv[4]) if len(sys.argv) > 4 else None
    os.makedirs(outdir, exist_ok=True)
    rows = []
    with open(caught) as f:
        next(f)
        for line in f:
            m, qs, s, n, t = line.rstrip("\n").split("\t")
            rows.append((m, ord(qs) - 65, int(s), int(n), int(t)))
    if limit:
        rows = rows[:limit]
    fidx = 0
    chunks = None
    emitted = 0
    manifest = []

    def flush():
        nonlocal chunks, fidx
        if chunks:
            fn = "RWrap_%02d.v" % fidx
            open(os.path.join(outdir, fn), "w").write(
                HEADER + "\n\n" + "\n\n".join(chunks) + "\n")
            fidx += 1
        chunks = []

    chunks = []
    for i, (m, qq, s, n, t) in enumerate(rows):
        sz = closure_sizes(m, qq, n, t)
        if sz is None:
            continue
        nseen, nl, nr = sz
        fuel = 8 * nseen + 64
        rounds = nl + nr + 4
        gi = emitted + 1
        name = "tm_rw_%05d" % gi
        thm = "qh_rw_%05d" % gi
        qs = chr(65 + qq)
        chunks.append("""(** %s: quiet state %s, last visit index %d;
    wrapped closure n=%d t=%d (%d contexts) *)

%s

Theorem %s :
  NonHalt %s /\\ QuietAfter %s St%s %d /\\ QuasiHaltsSt %s.
Proof.
  apply (ngram_check_quiet_sound _ St%s %d %d %d %d %d).
  vm_compute. reflexivity.
Qed.""" % (m, qs, s, n, t, nseen, emit_tm(name, m), thm, name, name, qs, s,
           name, qs, s, n, t, fuel, rounds))
        manifest.append((m, thm, "RWrap_%02d.v" % fidx, qs, s, n, t, nseen))
        emitted += 1
        if len(chunks) >= per_file:
            flush()
            chunks = []
    flush()
    with open(os.path.join(outdir, "rwrap_manifest.tsv"), "w") as f:
        f.write("machine\ttheorem\tfile\tquiet_state\ts\tn\tt\tcontexts\n")
        for row in manifest:
            f.write("\t".join(str(x) for x in row) + "\n")
    print("emitted %d theorems across %d files" % (emitted, fidx))


if __name__ == "__main__":
    main()
