#!/usr/bin/env python3
"""Split a heavy census grandchild subtree once more (great-grandchild
level), the Run_Split2 pattern generalized.

Each heavy grandchild G_<A0>_<B0> owns a native_compute walk that the
verified-tier pipeline made too slow (>2.5h) to finish inside the
remote container's preemption window.  We expand the grandchild's
FIRST undefined transition into its 12 or 16 admissible fills (exactly
node_expand_spec, the same argument Run_Split/Run_Split2 use), so the
one heavy walk becomes 12-16 sub-walks of a few minutes each.

Per heavy grandchild (w, w2, d2, nx2) it emits:
  Run_Split_<tag>.v   -- tm_g, ggchild_<tag>, q_ggsub_<tag>, the WF
                         lemma, ggsub_decided_<tag>, and the cover
                         lemma gchild_from_ggchildren_<tag>
  GGH_<tag>_<fill>.v   -- one native queue walk per fill
  G_<A0>_<B0>.v        -- REPLACEMENT proving the same g_<tag>_decided
                         lemma via the cover + the per-fill facts

Nothing here is trusted: every walk is a native_compute Qed and the
cover lemmas ride node_expand_spec.

Usage: gen_gsplit_heavy.py OUTDIR [NITER]
"""
import os
import sys

SYM = {0: 'S0', 1: 'S1'}
DIRC = {'L': 'DL', 'R': 'DR'}
STC = {0: 'StA', 1: 'StB', 2: 'StC', 3: 'StD'}

# the 7 heavy grandchildren: (A0-tag, B0-tag) -> (w, w2, d2, nx2)
#   A0 = <w>RB ; B0 = <w2><d2><nx2>
HEAVY = [
    ('1RB', '0LC', 1, 0, 'L', 2),
    ('1RB', '0RC', 1, 0, 'R', 2),
    ('1RB', '1LA', 1, 1, 'L', 0),
    ('1RB', '1LB', 1, 1, 'L', 1),
    ('1RB', '1RC', 1, 1, 'R', 2),
    ('0RB', '1LC', 0, 1, 'L', 2),
    ('0RB', '1RC', 0, 1, 'R', 2),
]


def simulate(w, w2, d2, nx2):
    """Return (k, steps, q_u, s_u): the machine (A0=<w>RB, B0=<w2><d2>
    <nx2>) runs k steps, then state q_u reads undefined symbol s_u.
    steps is [(write, dir_char)] per taken step."""
    tbl = {(0, 0): (w, 'R', 1), (1, 0): (w2, d2, nx2)}
    tape = {}
    pos = 0
    st = 0
    steps = []
    for k in range(200):
        h = tape.get(pos, 0)
        tr = tbl.get((st, h))
        if tr is None:
            return k, steps, st, h
        ww, dd, nn = tr
        tape[pos] = ww
        pos += 1 if dd == 'R' else -1
        steps.append((ww, dd))
        st = nn
    raise RuntimeError("no hole in 200 steps")


def tape_expr(steps):
    e = "(mkTape blank_side S0 blank_side)"
    for (ww, dd) in steps:
        e = f"(tape_move {DIRC[dd]} {SYM[ww]} {e})"
    return e


def fills(n):
    """node_expand order: write outer (S0,S1), dir mid (DL,DR), target
    inner (A,B,C[,D])."""
    targets = [0, 1, 2, 3] if n == 16 else [0, 1, 2]
    out = []
    for w3 in (0, 1):
        for d3 in ('L', 'R'):
            for nx3 in targets:
                out.append((SYM[w3], DIRC[d3], STC[nx3]))
    return out


def fill_tag(w3, d3, nx3):
    return f"{w3[1]}{d3[1]}{nx3[2]}"


def gen_one(outdir, atag, btag, w, w2, d2, nx2, niter):
    tag = f"{atag}_{btag}"
    k, steps, q_u, s_u = simulate(w, w2, d2, nx2)
    gptr = 'StD' if nx2 == 2 else 'StC'      # grandchild node pointer
    nfill = 16 if nx2 == 2 else 12
    qu = STC[q_u]
    su = SYM[s_u]
    wS, w2S, d2S, nx2S = SYM[w], SYM[w2], DIRC[d2], STC[nx2]
    tape = tape_expr(steps)

    # which defined transition targets q_u (for ~UnusedState)
    if q_u == nx2:
        used_p, used_s, used_tr = 'StB', 'S0', f"mkTrans {w2S} {d2S} {nx2S}"
    elif q_u == 1:
        used_p, used_s, used_tr = 'StA', 'S0', f"mkTrans {wS} DR StB"
    else:
        raise RuntimeError(f"{tag}: q_u={qu} not a defined target")

    fl = fills(nfill)
    # In (a::b::...::nil) is right-nested: x=a \/ (x=b \/ ... \/ False),
    # so the destruct pattern nests: [<-|[<-|...[<-|[]]...]]
    ncases = '[<-|' * nfill + '[]' + ']' * nfill
    firstbr = '\n      '.join(
        f"{'[' if i == 0 else '|'} exact (Hg {a} {b} {c} eq_refl)"
        for i, (a, b, c) in enumerate(fl)) + " ]"

    # ---- Run_Split_<tag>.v ----
    mod = f"""(** GENERATED by tools/gen_gsplit_heavy.py -- do not edit.
    Great-grandchild split of the heavy grandchild A0={atag}, B0={btag}
    (its first hole is {qu} reading {su} at step {k}; pointer {gptr},
    {nfill} fills). *)
From Coq Require Import Arith Lia Bool List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
Import ListNotations.

Set Default Goal Selector "!".

Definition tm_g_{tag} : TM :=
  TM_upd' (tm_child {wS}) StB S0 (Some (mkTrans {w2S} {d2S} {nx2S})).

Definition ggchild_{tag} (w3 : Sym) (d3 : Dir) (nx3 : St) : TNF_Node :=
  mkNode (TM_upd' tm_g_{tag} {qu} {su} (Some (mkTrans w3 d3 nx3)))
         (ptr_after (Some {gptr}) nx3).

Definition q_ggsub_{tag} (w3 : Sym) (d3 : Dir) (nx3 : St) : SearchQueue :=
  ([ggchild_{tag} w3 d3 nx3], []).

Lemma tm_g_{tag}_used : ~ UnusedState tm_g_{tag} {qu}.
Proof.
  intros (Hin & _ & _).
  refine (Hin {used_p} {used_s} ({used_tr}) _ eq_refl).
  reflexivity.
Qed.

Lemma ggchild_{tag}_WF : forall w3 d3 nx3,
  trans_ok (Some {gptr}) (mkTrans w3 d3 nx3) = true ->
  Node_WF (ggchild_{tag} w3 d3 nx3).
Proof.
  intros w3 d3 nx3 Hok.
  unfold Node_WF, ggchild_{tag}; simpl.
  rewrite TM_upd'_spec.
  apply (UnusedState_ptr_upd tm_g_{tag} {qu} {su} (mkTrans w3 d3 nx3)
           (Some {gptr})).
  - reflexivity.
  - exact tm_g_{tag}_used.
  - exact (gchild_WF {wS} {w2S} {d2S} {nx2S} eq_refl).
  - exact Hok.
Qed.

Lemma ggsub_decided_{tag} : forall w3 d3 nx3 n,
  trans_ok (Some {gptr}) (mkTrans w3 d3 nx3) = true ->
  Nat.iter n q_suc (q_ggsub_{tag} w3 d3 nx3) = ([], []) ->
  NodeDecided B_census D_census (node_tm (ggchild_{tag} w3 d3 nx3)).
Proof.
  intros w3 d3 nx3 n Hok Hempty.
  assert (HWF : SearchQueue_WF B_census D_census
                  (Nat.iter n q_suc (q_ggsub_{tag} w3 d3 nx3))
                  (ggchild_{tag} w3 d3 nx3)).
  {{ clear Hempty. induction n.
    - apply SearchQueue_init_spec. apply ggchild_{tag}_WF. exact Hok.
    - simpl. apply SearchQueue_upds_spec; [exact IHn | exact decider_WF]. }}
  rewrite Hempty in HWF.
  exact (SearchQueue_empty_decided B_census D_census _ HWF).
Qed.

Lemma gchild_from_ggchildren_{tag} :
  (forall w3 d3 nx3,
     trans_ok (Some {gptr}) (mkTrans w3 d3 nx3) = true ->
     NodeDecided B_census D_census (node_tm (ggchild_{tag} w3 d3 nx3))) ->
  NodeDecided B_census D_census (node_tm (gchild {wS} {w2S} {d2S} {nx2S})).
Proof.
  intros Hg.
  assert (Hstep : stepn tm_g_{tag} {k} InitES =
                  Some ({qu}, {tape})).
  {{ reflexivity. }}
  assert (Hhole : tm_g_{tag} {qu} (t_head {tape}) = None) by reflexivity.
  assert (HB : {k + 1} <= B_census) by (unfold B_census; lia).
  pose proof (node_expand_spec B_census D_census tm_g_{tag} (Some {gptr}) {k}
                {qu} {tape}
                Hstep Hhole HB (gchild_WF {wS} {w2S} {d2S} {nx2S} eq_refl))
    as [_ Hexp].
  change (NodeDecided B_census D_census tm_g_{tag}).
  apply Hexp.
  intros x' Hin.
  cbn [node_expand node_tm node_ptr filter trans_ok all_trans map
       t_next t_head tape_move St_to_nat Nat.leb In] in Hin.
  destruct Hin as {ncases};
    cbn [node_tm];
    first
      {firstbr}.
Qed.
"""
    open(os.path.join(outdir, f"Run_Split_{tag}.v"), 'w').write(mod)

    # ---- per-fill walk files ----
    for (w3, d3, nx3) in fl:
        ft = fill_tag(w3, d3, nx3)
        wf = f"""(** GENERATED by tools/gen_gsplit_heavy.py -- do not edit.
    Census subtree: A0={atag}, B0={btag}, {qu}{su[1]} = {ft}. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
From BBB4.Census Require Import Run_Split_{tag}.
Import ListNotations.

Lemma ggh_{tag}_{ft}_empty :
  Nat.iter {niter} q_suc (q_ggsub_{tag} {w3} {d3} {nx3}) = ([], []).
Proof.
  native_cast_no_check (eq_refl (@nil TNF_Node, @nil TNF_Node)).
Qed.

Lemma ggh_{tag}_{ft}_decided :
  NodeDecided B_census D_census (node_tm (ggchild_{tag} {w3} {d3} {nx3})).
Proof.
  exact (ggsub_decided_{tag} {w3} {d3} {nx3} {niter} eq_refl
           ggh_{tag}_{ft}_empty).
Qed.
"""
        open(os.path.join(outdir, f"GGH_{tag}_{ft}.v"), 'w').write(wf)

    # ---- replacement G_<tag>.v ----
    imports = '\n'.join(
        f"From BBB4.Census.Compute Require Import GGH_{tag}_{fill_tag(*f)}."
        for f in fl)
    dcases = fl if nfill == 16 else fl  # destruct produces all 16 nx3
    # destruct w3,d3,nx3 yields 16 cases (nx3 over A,B,C,D); for a
    # 12-fill node the StD cases are discharged by Hok=false, so the
    # decided lemma still destructs into 16 and the trans_ok gate kills
    # the 4 StD branches -- but node_expand already filtered them, so
    # gchild_from_ggchildren_<tag> only feeds admissible fills.  We
    # match the fill list exactly via the cover lemma's Hg calls.
    exacts = '\n      '.join(
        f"{'[' if i == 0 else '|'} exact ggh_{tag}_{fill_tag(*f)}_decided"
        for i, f in enumerate(fl)) + " ]"
    if nfill == 16:
        destruct = "destruct w3, d3, nx3;\n    first\n      " + exacts + "."
    else:
        # 12 fills: nx3 in {A,B,C}; Hok rules out StD.  destruct nx3
        # gives 4 branches; the StD one has Hok : trans_ok (Some StC)
        # (mkTrans _ _ StD) = true = false -> discriminate.
        exacts12 = []
        idx = 0
        for w3 in ('S0', 'S1'):
            for d3 in ('DL', 'DR'):
                for nx3 in ('StA', 'StB', 'StC', 'StD'):
                    if nx3 == 'StD':
                        exacts12.append("discriminate Hok")
                    else:
                        exacts12.append(
                            f"exact ggh_{tag}_{fill_tag(w3, d3, nx3)}_decided")
                        idx += 1
        body = '\n      '.join(
            f"{'[' if i == 0 else '|'} {e}" for i, e in enumerate(exacts12)) \
            + " ]"
        destruct = "destruct w3, d3, nx3;\n    first\n      " + body + "."

    g = f"""(** GENERATED by tools/gen_gsplit_heavy.py -- do not edit.
    Census subtree A0={atag}, B0={btag} -- assembled from the {nfill}
    great-grandchild walks (GGH_{tag}_*.v) via Run_Split_{tag}, proving
    the same g_{tag}_decided lemma as the monolithic version. *)
From Coq Require Import Arith List.
From BBB4 Require Import BBB4_Statement.
From BBB4.Census Require Import TNF_QH Decide Deferred_Data Run Run_Split.
From BBB4.Census Require Import Run_Split_{tag}.
{imports}
Import ListNotations.

Lemma g_{tag}_decided :
  NodeDecided B_census D_census (node_tm (gchild {wS} {w2S} {d2S} {nx2S})).
Proof.
  apply gchild_from_ggchildren_{tag}.
  intros w3 d3 nx3 Hok.
  {destruct}
Qed.
"""
    open(os.path.join(outdir, f"G_{tag}.v"), 'w').write(g)
    return tag, k, qu, su, nfill


def main():
    outdir = sys.argv[1]
    niter = int(sys.argv[2]) if len(sys.argv) > 2 else 700
    os.makedirs(outdir, exist_ok=True)
    for (atag, btag, w, w2, d2, nx2) in HEAVY:
        tag, k, qu, su, nfill = gen_one(outdir, atag, btag, w, w2, d2, nx2,
                                        niter)
        print(f"{tag}: hole {qu}/{su} at step {k}, {nfill} fills")


if __name__ == "__main__":
    main()
