#!/usr/bin/env python3
"""Fuel certificate-table generator: BBB neverqh_fuel certs ->
generated Coq theorem files (fork of gen_bulk_certs.py).

For every machine in the BBB harness's results/certs_fuel, search for
parameters that make the Coq fuel checker pass: per visited state q,
EITHER the lex procedure (rules (a)/(b), bulk_prover.procedure with
the cert's rank_q measures + defaults + a window-bounded exhaustive
pool) discharges q, OR the runner rule (c2) does -- which in the Coq
in-window instance (Checkers/Fuel.v) means EVERY closure node outside
q moves right and holds a nonblank in its right window.  Left-runners
go through the mirrored machine and the [mirror_never_qh] transfer.

Emitted per machine:
  - a TM definition (always the ORIGINAL machine),
  - a certificate table ([NgRankE]/[NgPattE] components over the
    orientation actually checked; runner states get []),
  - Theorem  NeverQuasiHaltsSt tm  via ngram_check_neverqh_fuel_sound
    (prefixed by  apply mirror_never_qh.  for left-runners),
  - Corollary  NonHalt tm  via never_qh_nonhalt.

Everything emitted is UNTRUSTED data; the Coq checker re-derives the
closure and re-checks every state gate.  This script also
differential-validates out of Coq: the per-state gate it enforces
(bulk_prover.lex_check || runner_ok below, plus the cvisits warmup
gate) is a faithful mirror of Closure.v's state_live_ok.

Machines it cannot place are DEFERRED with an exact reason into
tools/fuel_deferred.tsv -- no silent caps.  The classifier peels the
q-avoiding graph with rules (a)/(b) to a fixpoint and inspects the
stuck cyclic SCCs (the rule-(c2) targets):

  - offwindow-fuel: a uniform-direction stuck SCC whose nodes lack a
    nonblank in the movement-side WINDOW -- dischargeable only with
    the FuelClass.v beyond-window classes (cconf * fclass * fclass);
  - mixed-scc: a stuck SCC whose nodes move both ways at this window
    -- the class-refined contexts must split it (as verify.c's
    id = base*9 + clL*3 + clR contexts do) before any runner rule
    applies;
  - needs-per-scc-gate: whole-closure runner_ok fails even though
    every stuck SCC is a uniform fueled runner -- the engine's
    per-state disjunct cannot see it (verify.c applies (c2) per SCC
    inside the peeling loop).

Note the in-window runner disjunct is NEARLY SUBSUMED by lex: a
right-moving abstract cycle whose windows always hold fuel consumes
a right-window nonblank every lap (cells leave the right window only
through the head), so the 1/R measure drains and rule (b) kills the
SCC.  The runner rule only genuinely adds power when the fuel sits
BEYOND the window -- which is exactly the unwired FuelClass path, and
why the upstream neverqh_fuel holdouts do not land on this checker.

Usage:
  python3 tools/gen_fuel_certs.py [--batch B] [--only M1,M2]
                                  [--dry-run] [--n-extra K]
Env: BBB_REPO (default ../BBB relative to the repo root).
"""

import argparse
import glob
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bulk_prover as bp
import gen_bulk_certs as gb

BBB = os.environ.get("BBB_REPO", os.path.join(ROOT, "..", "BBB"))
OUTDIR = os.path.join(ROOT, "theories", "Machines")

HEADER = """(** Generated by tools/gen_fuel_certs.py -- DO NOT EDIT.

    Never-quasihalting theorems for the BBB harness's neverqh_fuel
    certificate machines: per machine a TM definition, an n-gram
    certificate table (lex components for the rank-covered states,
    [] for the states discharged by the runner rule (c2); untrusted
    data re-checked by the engine), the theorem closed by vm_compute
    through [ngram_check_neverqh_fuel_sound] (left-runners via the
    [mirror_never_qh] transfer), and the [NonHalt] corollary. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape Mirror.
From BBB4.Checkers Require Import NGram Fuel.
Import ListNotations.

"""

T_CANDS = (0, 64, 256, 1024, 4096, 16384, 65536, 262144, 500000)


def mirror_mtext(m):
    """Swap L/R in every transition of the standard machine text."""
    parts = []
    for part in m.split("_"):
        out = ""
        for si in range(2):
            e = part[3 * si:3 * si + 3]
            if e == "---":
                out += e
            else:
                out += e[0] + {"L": "R", "R": "L"}[e[1]] + e[2]
        parts.append(out)
    return "_".join(parts)


def mirror_meas(ms):
    """Transport measure candidates to the mirrored machine: sided
    regions swap, patterns (written in tape order) reverse."""
    swap = {"A": "A", "L": "R", "R": "L"}
    return [(tuple(reversed(patt)), swap[reg]) for patt, reg in ms]


def moves_right(tbl, a):
    """Mirror of Fuel.v fnode_moves_right."""
    tr = tbl[(a[0], a[1])]
    return tr is not None and tr[1] == "R"


def rfuel_ge1(a):
    """Mirror of Fuel.v fnode_rfuel_ge1: nonblank in the right window."""
    return any(x != 0 for x in a[3])


def runner_ok(tbl, seen, qq):
    """Mirror of Closure.v runner_ok: every node outside state qq
    moves right and holds right-window fuel."""
    return all(a[0] == qq or (moves_right(tbl, a) and rfuel_ge1(a))
               for a in seen)


def warmup_states(tbl, t):
    """States occupied at steps 0..t-1 from the blank tape (the Coq
    cvisits gate); assumes the machine does not halt before t (the
    closure build already simulated t steps)."""
    tape = {}
    pos = 0
    q = 0
    out = set()
    for _ in range(t):
        out.add(q)
        tr = tbl[(q, tape.get(pos, 0))]
        w, d, nq = tr
        tape[pos] = w
        pos += 1 if d == "R" else -1
        q = nq
    return out


def all_patts(maxlen):
    """All nonblank-containing 0/1 patterns of length <= maxlen, in a
    deterministic (length, value) order."""
    out = []
    for ln in range(1, maxlen + 1):
        for v in range(2 ** ln):
            patt = tuple((v >> (ln - 1 - i)) & 1 for i in range(ln))
            if 1 in patt:
                out.append(patt)
    return out


def exhaustive_cands(n):
    """The full window-coverage-legal measure pool (pm_ok limits:
    len-1 <= n for 'A', len <= n for 'L'/'R'), capped to patterns of
    length <= 4 to keep the search bounded (only n=6 is truncated,
    and that machine's window already exceeds every sided pattern we
    could use)."""
    out = [(p, "A") for p in all_patts(min(n + 1, 4))]
    out += [(p, r) for p in all_patts(min(n, 4)) for r in ("L", "R")]
    return out


def try_lex(tbl, n, seen, lset, rset, qq, cands):
    """Run the lex procedure and re-check its output (the same gate
    the Coq engine's lex_ok computes); None on failure."""
    cands = [m for m in dict.fromkeys(cands) if bp.meas_ok(m[0], m[1], n)]
    comps = bp.procedure(tbl, n, seen, lset, rset, qq, cands)
    if comps is None:
        return None
    ok, _bad = bp.lex_check(tbl, n, seen, lset, rset, qq, comps)
    return comps if ok else None


def stuck_residue(tbl, n, seen, lset, rset, qq, cands):
    """bulk_prover.procedure's peeling loop (rules (a)/(b)), but on
    getting stuck return the residual cyclic SCCs -- the rule-(c2)
    targets -- as (component nodes, intra alive edges) pairs."""
    cands = [m for m in dict.fromkeys(cands) if bp.meas_ok(m[0], m[1], n)]
    nodes = [a for a in seen if a[0] != qq]
    Kc = len(nodes) + 2
    alive = {}
    for a in nodes:
        for b in bp.succs(tbl, lset, rset, seen, a):
            if b[0] != qq:
                alive[(a, b)] = True
    for _ in range(200):
        adjmap = {}
        for (u, v) in alive:
            adjmap.setdefault(u, []).append(v)
        comp_list = bp.sccs(nodes, lambda v: adjmap.get(v, []))
        cyclic = [c for c in comp_list
                  if len(c) > 1 or c[0] in adjmap.get(c[0], [])]
        if not cyclic:
            return []
        progress = False
        for c in cyclic:
            cs = set(c)
            intra = [(u, v) for (u, v) in alive if u in cs and v in cs]
            done = False
            for (patt, reg) in cands:
                ds = {e: bp.pdelta(tbl, n, patt, reg, e[0]) for e in intra}
                if (all(d <= 0 for d in ds.values())
                        and any(d < 0 for d in ds.values())):
                    for e in intra:
                        if ds[e] < 0:
                            del alive[e]
                    progress = True
                    done = True
                    break
            if done:
                continue
            for (patt, reg) in cands:
                W = [(u, v, Kc * bp.pdelta(tbl, n, patt, reg, u) + 1)
                     for (u, v) in intra]
                if bp.bellman_potentials(list(cs), W) is not None:
                    for e in intra:
                        del alive[e]
                    progress = True
                    break
        if not progress:
            out = []
            for c in cyclic:
                cs = set(c)
                intra = [(u, v) for (u, v) in alive if u in cs and v in cs]
                out.append((c, intra))
            return out
    return []


def classify_sccs(tbl, residue):
    """Tags for the stuck SCCs of one state's q-avoiding graph."""
    tags = set()
    parts = []
    for c, intra in residue:
        srcs = sorted({u for (u, _v) in intra})
        dirs = {tbl[(a[0], a[1])][1] for a in srcs}
        if dirs == {"R"}:
            fueled = all(rfuel_ge1(a) for a in srcs)
            d = "R"
        elif dirs == {"L"}:
            fueled = all(any(x != 0 for x in a[2]) for a in srcs)
            d = "L"
        else:
            fueled = False
            d = "RL"
        if d == "RL":
            tags.add("mixed-scc")
        elif not fueled:
            tags.add("offwindow-fuel")
        else:
            tags.add("needs-per-scc-gate")
        parts.append("scc[sz=%d dir=%s winfuel=%s states=%s]"
                     % (len(c), d, "y" if fueled else "n",
                        "".join(sorted({chr(65 + a[0]) for a in c}))))
    return tags, " ".join(parts)


def diagnose(mtext, n, per_state):
    """Deferral diagnosis on the original orientation at the first t
    whose closure builds: per lex-undischargeable state, the stuck
    cyclic SCCs after rules-(a)/(b) peeling and their (c2) shape."""
    tbl = bp.parse(mtext)
    for t in T_CANDS:
        r = bp.build_closure(tbl, n, t)
        if r is None:
            continue
        seen, lset, rset, _a0, _rounds = r
        states = sorted({a[0] for a in seen} | warmup_states(tbl, t))
        tags = set()
        details = []
        for qq in states:
            comps = try_lex(tbl, n, seen, lset, rset, qq,
                            per_state.get(qq, []) + bp.DEFAULT_MEASURES)
            if comps is None:
                comps = try_lex(tbl, n, seen, lset, rset, qq,
                                exhaustive_cands(n))
            if comps is not None:
                continue
            res = stuck_residue(tbl, n, seen, lset, rset, qq,
                                exhaustive_cands(n))
            st_tags, st_desc = classify_sccs(tbl, res)
            tags |= st_tags
            details.append("q=%s: %s" % (chr(65 + qq), st_desc))
        return t, len(seen), sorted(tags), "; ".join(details)
    return None, 0, ["no-closure"], ""


def fuel_decide(mtext, n0, per_state, n_extra=2):
    """Search both orientations, the window ladder n0..n0+n_extra and
    the t ladder for parameters the Coq fuel checker accepts.
    Returns (result dict, None) or (None, short diag string)."""
    first_fail = None
    for n in range(n0, n0 + n_extra + 1):
        for mirrored in (False, True):
            text = mirror_mtext(mtext) if mirrored else mtext
            tbl = bp.parse(text)
            meas = {qi: (mirror_meas(ms) if mirrored else list(ms))
                    for qi, ms in per_state.items()}
            for t in T_CANDS:
                r = bp.build_closure(tbl, n, t)
                if r is None:
                    continue
                seen, lset, rset, _a0, _rounds = r
                states = sorted({a[0] for a in seen} | warmup_states(tbl, t))
                comps_by_state = {}
                modes = {}
                ok = True
                for qq in states:
                    comps = try_lex(tbl, n, seen, lset, rset, qq,
                                    meas.get(qq, []) + bp.DEFAULT_MEASURES)
                    if comps is not None:
                        comps_by_state[qq] = comps
                        modes[qq] = "lex"
                        continue
                    if runner_ok(tbl, seen, qq):
                        comps_by_state[qq] = []
                        modes[qq] = "runner"
                        continue
                    comps = try_lex(tbl, n, seen, lset, rset, qq,
                                    exhaustive_cands(n))
                    if comps is not None:
                        comps_by_state[qq] = comps
                        modes[qq] = "lex+"
                        continue
                    if first_fail is None:
                        first_fail = ("orient=%s n=%d t=%d q=%s"
                                      % ("L" if mirrored else "R", n, t,
                                         chr(65 + qq)))
                    ok = False
                    break
                if ok:
                    return {"mirrored": mirrored, "n": n, "t": t,
                            "nseen": len(seen), "comps": comps_by_state,
                            "modes": modes,
                            "rounds": len(lset) + len(rset) + 4}, None
    return None, first_fail or "no closure at any t"


def collect_machines():
    return sorted(glob.glob(BBB + "/results/certs_fuel/*.cert"))


def work(arg):
    path, n_extra = arg
    mtext, n, per_state = bp.parse_cert_measures(path)
    res, fail = fuel_decide(mtext, n, per_state, n_extra=n_extra)
    if res is not None:
        return (mtext, n, res, None)
    dt, dnseen, tags, detail = diagnose(mtext, n, per_state)
    diag = ("first-fail=%s; at n=%d t=%s contexts=%d: %s"
            % (fail, n, dt, dnseen, detail))
    return (mtext, n, None, ("+".join(tags), diag))


def emit_machine(idx, mtext, res):
    """One machine's block: TM (original orientation), cert table,
    fuel theorem (+ mirror transfer when the runner goes left),
    NonHalt corollary."""
    name = "tm_fuel_%05d" % idx
    cname = "cert_fuel_%05d" % idx
    n = res["n"]
    t = res["t"]
    nseen = res["nseen"]
    fuel = 8 * nseen + 64
    modes = ",".join("%s=%s" % (chr(65 + q), m)
                     for q, m in sorted(res["modes"].items()))
    thm = "nqh_" + gb.sanitize(mtext)
    nh = "nonhalt_" + gb.sanitize(mtext)
    out = []
    out.append("(** %s: n=%d t=%d contexts=%d orient=%s %s *)"
               % (mtext, n, t, nseen, "L(mirror)" if res["mirrored"] else "R",
                  modes))
    out.append(gb.emit_tm(name, mtext))
    per_state = []
    for qi in range(4):
        comps = res["comps"].get(qi, [])
        body = ("[" + ";\n   ".join(gb.emit_comp(c) for c in comps) + "]"
                if comps else "[]")
        per_state.append("  | St%s =>\n  %s" % (chr(65 + qi), body))
    out.append("Definition %s (q : St) : list ngcomp :=\n"
               "  match q with\n%s\n  end." % (cname, "\n".join(per_state)))
    mirror_line = "\n  apply mirror_never_qh." if res["mirrored"] else ""
    out.append("""Theorem %s : NeverQuasiHaltsSt %s.
Proof.%s
  apply (ngram_check_neverqh_fuel_sound _ %d %s %s %s %s).
  vm_compute. reflexivity.
Qed.""" % (thm, name, mirror_line, n, gb.fmt_nat(t), gb.fmt_nat(fuel),
           gb.fmt_nat(res["rounds"]), cname))
    out.append("Corollary %s : NonHalt %s.\n"
               "Proof. exact (never_qh_nonhalt _ %s). Qed." % (nh, name, thm))
    return "\n\n".join(out), thm


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=int, default=25)
    ap.add_argument("--only", type=str, default="")
    ap.add_argument("--n-extra", type=int, default=2,
                    help="also try windows n0+1 .. n0+K")
    ap.add_argument("--dry-run", action="store_true",
                    help="search + validate only; write no .v files")
    args = ap.parse_args()

    files = collect_machines()
    if args.only:
        want = set(args.only.split(","))
        files = [f for f in files if os.path.basename(f)[:-5] in want]

    results = []
    deferred = []
    with Pool(4) as pool:
        for mtext, n, res, diag in pool.imap(
                work, [(f, args.n_extra) for f in files], chunksize=1):
            if res is None:
                deferred.append((mtext, n) + diag)
                print("DEFER %s: %s" % (mtext, diag[0]))
            else:
                results.append((mtext, res))
                print("OK    %s n=%d t=%d contexts=%d orient=%s %s"
                      % (mtext, res["n"], res["t"], res["nseen"],
                         "L" if res["mirrored"] else "R",
                         ",".join("%s=%s" % (chr(65 + q), m)
                                  for q, m in sorted(res["modes"].items()))))
    results.sort(key=lambda x: x[0])
    deferred.sort(key=lambda x: x[0])

    with open(os.path.join(HERE, "fuel_deferred.tsv"), "w") as df:
        df.write("machine\tngram_n\ttags\tdetail\n")
        for mtext, n, tags, diag in deferred:
            df.write("%s\t%d\t%s\t%s\n" % (mtext, n, tags, diag))

    print("landed %d / %d (deferred %d)"
          % (len(results), len(results) + len(deferred), len(deferred)))
    if args.dry_run:
        return

    manifest = []
    vfiles = []
    for b0 in range(0, len(results), args.batch):
        batch = results[b0:b0 + args.batch]
        bno = b0 // args.batch + 1
        fname = "Fuel_Batch_%02d.v" % bno
        chunks = [HEADER]
        for j, (mtext, res) in enumerate(batch):
            idx = b0 + j + 1
            text, thm = emit_machine(idx, mtext, res)
            chunks.append(text)
            manifest.append((mtext, thm, "theories/Machines/" + fname,
                             res["n"], res["t"], res["nseen"],
                             "mirror" if res["mirrored"] else "direct"))
        open(os.path.join(OUTDIR, fname), "w").write(
            "\n\n".join(chunks) + "\n")
        vfiles.append("theories/Machines/" + fname)

    with open(os.path.join(HERE, "fuel_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tn\tt\tcontexts\torient\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    with open(os.path.join(HERE, "fuel_vfiles.txt"), "w") as vf:
        vf.write("\n".join(vfiles) + "\n")
    print("emitted %d machines into %d files" % (len(results), len(vfiles)))


if __name__ == "__main__":
    main()
