#!/usr/bin/env python3
"""Emit the census proven-machines tier: Proven_00.v .. Proven_07.v and
Proven_Data.v, from a proven_map.tsv audited by tools/audit_lever_a.py.

Each Proven_XX.v Require-Imports only the Machines/* batch modules whose
theorems its machines use, lists those machines' TM constants, and proves
[Forall NeverQuasiHaltsSt proven_XX] by chaining the committed
[NeverQuasiHaltsSt <tm>] theorems (opaque exacts; no vm_compute).  The rows
of proven_map.tsv are already sorted by (file, theorem), so consecutive
500-row slices cluster the batch imports (mirrors the audit's chunking).

Proven_Data.v concatenates the eight chunk lists and assembles
[proven_all : Forall NeverQuasiHaltsSt proven_list] with Forall_app.

Everything under tools/ is UNTRUSTED: the generated Coq is re-checked by
the kernel; soundness rests only on the [exact <thm>] type-checks and the
[Forall NeverQuasiHaltsSt] statements, never on this script.

Usage: gen_proven.py [PROVEN_MAP_TSV] [OUT_DIR]
  defaults: measure_A/proven_map.tsv  ->  theories/Census/
"""
import os
import re
import sys

ROOT = "/home/user/Coq-BBB4"
DEFAULT_MAP = ("/tmp/claude-0/-home-user/2b01b1ad-6519-5466-986f-cbc04a643004"
               "/scratchpad/measure_A/proven_map.tsv")
CHUNK = 500
N_CHUNKS = 8

THM_RE = re.compile(
    r'\b(?:Theorem|Lemma)\s+(\w+)\s*:\s*NeverQuasiHaltsSt\s+(\w+)\s*\.')


def module_of(vfile):
    """theories/Machines/Bulk/Bulk_001.v -> BBB4.Machines.Bulk.Bulk_001"""
    assert vfile.startswith("theories/") and vfile.endswith(".v"), vfile
    return "BBB4." + vfile[len("theories/"):-len(".v")].replace("/", ".")


def parse_thm_const(vfile, cache):
    """vfile -> {theorem_name: tm_constant} for its NeverQuasiHaltsSt thms."""
    if vfile in cache:
        return cache[vfile]
    txt = open(os.path.join(ROOT, vfile)).read()
    m = {name: const for name, const in THM_RE.findall(txt)}
    cache[vfile] = m
    return m


def load_rows(path):
    rows = []
    with open(path) as f:
        next(f)  # header: machine kind vfile theorem
        for line in f:
            line = line.rstrip("\n")
            if not line:
                continue
            machine, kind, vfile, theorem = line.split("\t")
            rows.append((machine, kind, vfile, theorem))
    return rows


def emit_chunk(idx, rows, cache):
    """Return the source of Proven_<idx:02d>.v for the given rows."""
    tag = "%02d" % idx
    # resolve (module, const, theorem) per row; collect imports in first-seen order
    resolved = []
    modules = []
    seen = set()
    for machine, kind, vfile, theorem in rows:
        const = parse_thm_const(vfile, cache).get(theorem)
        if const is None:
            raise SystemExit("unresolved theorem %s in %s" % (theorem, vfile))
        mod = module_of(vfile)
        if mod not in seen:
            seen.add(mod)
            modules.append(mod)
        resolved.append((machine, const, theorem))

    L = []
    L.append("(** GENERATED by tools/gen_proven.py -- do not edit.")
    L.append("")
    L.append("    Proven never-quasihalting machines, census chunk %s" % tag)
    L.append("    (%d machines; imports %d batch modules).  The [exact]s below")
    L[-1] = L[-1] % (len(resolved), len(modules))
    L.append("    reference the committed [NeverQuasiHaltsSt <tm>] theorems;")
    L.append("    no vm_compute runs when this file is checked. *)")
    L.append("From Coq Require Import List.")
    L.append("From BBB4 Require Import BBB4_Statement.")
    for mod in modules:
        L.append("Require Import %s." % mod)
    L.append("Import ListNotations.")
    L.append("")
    # the machine list
    L.append("Definition proven_%s : list TM :=" % tag)
    body = ";\n   ".join(const for _, const, _ in resolved)
    L.append("  [%s]." % body)
    L.append("")
    # the Forall proof
    L.append("Lemma proven_%s_nqh : Forall NeverQuasiHaltsSt proven_%s."
             % (tag, tag))
    L.append("Proof.")
    L.append("  unfold proven_%s." % tag)
    for _, _, theorem in resolved:
        L.append("  apply Forall_cons; [exact %s|]." % theorem)
    L.append("  apply Forall_nil.")
    L.append("Qed.")
    L.append("")
    return "\n".join(L)


def emit_data(n_chunks):
    tags = ["%02d" % i for i in range(n_chunks)]
    L = []
    L.append("(** GENERATED by tools/gen_proven.py -- do not edit.")
    L.append("")
    L.append("    The census proven-machines tier: BBB(4) holdouts with a")
    L.append("    committed in-Coq [NeverQuasiHaltsSt] theorem, assembled into")
    L.append("    one list with its [Forall] certificate.  Require-Imports only")
    L.append("    the eight chunk modules (interface load; no recomputation). *)")
    L.append("From Coq Require Import List.")
    L.append("From BBB4 Require Import BBB4_Statement.")
    L.append("From BBB4.Census Require Import %s."
             % " ".join("Proven_" + t for t in tags))
    L.append("Import ListNotations.")
    L.append("")
    L.append("Definition proven_list : list TM :=")
    L.append("  " + " ++ ".join("proven_" + t for t in tags) + ".")
    L.append("")
    L.append("Lemma proven_all : Forall NeverQuasiHaltsSt proven_list.")
    L.append("Proof.")
    L.append("  unfold proven_list.")
    for t in tags[:-1]:
        L.append("  apply Forall_app; split; [exact proven_%s_nqh|]." % t)
    L.append("  exact proven_%s_nqh." % tags[-1])
    L.append("Qed.")
    L.append("")
    return "\n".join(L)


def main():
    map_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_MAP
    out_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
        ROOT, "theories/Census")
    rows = load_rows(map_path)
    n_chunks = (len(rows) + CHUNK - 1) // CHUNK
    if n_chunks != N_CHUNKS:
        print("WARNING: expected %d chunks, got %d (rows=%d)"
              % (N_CHUNKS, n_chunks, len(rows)), file=sys.stderr)
    cache = {}
    for i in range(n_chunks):
        chunk = rows[i * CHUNK:(i + 1) * CHUNK]
        src = emit_chunk(i, chunk, cache)
        path = os.path.join(out_dir, "Proven_%02d.v" % i)
        open(path, "w").write(src)
        mods = len({r[2] for r in chunk})
        print("wrote %s: %d machines, %d imports" % (path, len(chunk), mods))
    data = emit_data(n_chunks)
    open(os.path.join(out_dir, "Proven_Data.v"), "w").write(data)
    print("wrote %s/Proven_Data.v: %d chunks, %d machines"
          % (out_dir, n_chunks, len(rows)))


if __name__ == "__main__":
    main()
