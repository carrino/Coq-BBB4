#!/usr/bin/env python3
"""Generate the census deferred-list tables (UNTRUSTED tooling).

Reads the BBB(4) holdout list and the census ladder's residue file and
emits theories/Census/Deferred_XX.v (compact machine rows) plus
theories/Census/Deferred_Data.v (their concatenation).  The Coq side
gives these rows meaning through Census/Deferred_Defs.v's [row_to_tm];
nothing here is trusted -- a wrong list only changes WHICH machines the
census defers (and the queue-empty check fails if the list is too
small).

Usage: gen_deferred.py HOLDOUTS RESIDUE OUTDIR
"""
import sys, os

def slot_name(e):
    if e == '---':
        return 'tN'
    w, d, nx = e[0], e[1], e[2]
    return f't{w}{d}{nx}'

def machine_row(text):
    parts = text.split('_')
    assert len(parts) == 4, text
    names = []
    for p in parts:
        assert len(p) == 6, text
        names.append(slot_name(p[0:3]))
        names.append(slot_name(p[3:6]))
    return '[' + ';'.join(names) + ']'

def main():
    holdouts, residue, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
    machines = []
    seen = set()
    for path in (holdouts, residue):
        with open(path) as f:
            for line in f:
                m = line.strip()
                if m and m not in seen:
                    seen.add(m)
                    machines.append(m)
    machines.sort()
    nchunks = 8
    sub = 500          # rows per Definition: big literals choke the parser
    per = (len(machines) + nchunks - 1) // nchunks
    chunk_names = []
    for ci in range(nchunks):
        chunk = machines[ci*per:(ci+1)*per]
        if not chunk:
            break
        name = f'Deferred_{ci:02d}'
        chunk_names.append(name)
        with open(os.path.join(outdir, name + '.v'), 'w') as f:
            f.write('(** GENERATED by tools/gen_deferred.py -- do not edit. *)\n')
            f.write('From Coq Require Import List.\n')
            f.write('From BBB4 Require Import BBB4_Statement.\n')
            f.write('From BBB4.Census Require Import Deferred_Defs.\n')
            f.write('Import ListNotations.\n\n')
            subnames = []
            for si in range(0, len(chunk), sub):
                sn = f'rows_{ci:02d}_{si//sub:03d}'
                subnames.append(sn)
                f.write(f'Definition {sn} : list (list (option Trans)) := [\n')
                f.write(';\n'.join(machine_row(m) for m in chunk[si:si+sub]))
                f.write('\n].\n')
            f.write(f'\nDefinition rows_{ci:02d} : list (list (option Trans)) :=\n  concat [' +
                    ';'.join(subnames) + '].\n')
    with open(os.path.join(outdir, 'Deferred_Data.v'), 'w') as f:
        f.write('(** GENERATED by tools/gen_deferred.py -- do not edit.\n\n')
        f.write(f'    The census deferred list: the {3713} BBB(4) holdouts\n')
        f.write('    plus the measured hard residue of the generic tiers\n')
        f.write(f'    ({len(machines)} machines total). *)\n')
        f.write('From Coq Require Import List.\n')
        f.write('From BBB4 Require Import BBB4_Statement.\n')
        f.write('From BBB4.Census Require Import Deferred_Defs '
                + ' '.join(chunk_names) + '.\n')
        f.write('Import ListNotations.\n\n')
        f.write('Definition deferred_rows : list (list (option Trans)) :=\n  '
                + ' ++ '.join(f'rows_{i:02d}' for i in range(len(chunk_names)))
                + '.\n\n')
        f.write('Definition D_census : list TM := map row_to_tm deferred_rows.\n')
    print(f'{len(machines)} machines -> {len(chunk_names)} chunks')

if __name__ == '__main__':
    main()
