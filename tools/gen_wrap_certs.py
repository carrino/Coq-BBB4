#!/usr/bin/env python3
"""Wrap-QH tables: BBB wrapctl/wrapfar certificates -> Coq theorems.

For each upstream quiet-state QH machine, find (n, t) such that the
n-gram closure of the halt-redirected machine from the real machine's
step-t configuration is halt-free (bulk_prover-style untrusted
search), and emit a theorem

  NonHalt tm /\ QuietAfter tm q s /\ QuasiHaltsSt tm

via ngram_check_quiet_sound (s = claim_score - 1: the cert's score is
the last-fire step, QuietAfter's index is the configuration index).

Usage: BBB_REPO=... python3 tools/gen_wrap_certs.py
"""
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bulk_prover as bp

BBB = os.environ.get("BBB_REPO", os.path.join(ROOT, "..", "BBB"))
OUTDIR = os.path.join(ROOT, "theories", "Machines", "Bulk")

HEADER = """(** Generated by tools/gen_wrap_certs.py -- DO NOT EDIT.

    Quiet-state quasihalting theorems (exact last-visit index) for
    the BBB harness's wrapctl/wrapfar certificate machines, via the
    halt-redirect construction on the n-gram closure
    (theories/Checkers/Wrap.v). *)

From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Wrap.

"""


def collect():
    """QH machines whose certs are wrap-type (quiet_state present)."""
    info = {}
    for d in sorted(glob.glob(BBB + "/results/certs*")):
        for f in glob.glob(d + "/*.cert"):
            m = ty = None
            kv = {}
            for line in open(f):
                p = line.split()
                if not p:
                    continue
                if p[0] == "machine":
                    m = p[1]
                elif p[0] == "type":
                    ty = p[1]
                elif len(p) >= 2:
                    kv[p[0]] = p[1]
            if ty in ("wrapctl", "wrapfar", "wrapngram") and "quiet_state" in kv:
                if kv.get("claim_qh") == "T" and m not in info:
                    info[m] = (kv["quiet_state"], int(kv["claim_score"]))
    return sorted(info.items())


def wrapped_closure(mtext, qq, n, t):
    """Halt-free n-gram closure of the wrapped machine from the real
    machine's step-t config; returns (|seen|, |lset|, |rset|) or None."""
    tbl = bp.parse(mtext)
    tape = {}
    pos = 0
    q = 0
    for _ in range(t):
        tr = tbl[(q, tape.get(pos, 0))]
        if tr is None:
            return None
        w, d, nq = tr
        tape[pos] = w
        pos += 1 if d == 'R' else -1
        q = nq
    if q == qq:
        return None
    tblw = dict(tbl)
    for sy in range(2):
        tblw[(qq, sy)] = None
    minp = min([pos] + list(tape))
    maxp = max([pos] + list(tape))
    Lf = lambda i: tape.get(pos - 1 - i, 0)
    Rf = lambda i: tape.get(pos + 1 + i, 0)
    win = lambda f, d: tuple(f(d + i) for i in range(n))
    depth = max(pos - minp, maxp - pos) + n + 2
    lset = {win(Lf, d) for d in range(1, depth)}
    rset = {win(Rf, d) for d in range(1, depth)}
    a0 = (q, tape.get(pos, 0), win(Lf, 0), win(Rf, 0))
    for _ in range(400):
        seen = set()
        todo = [a0]
        while todo:
            a = todo.pop()
            if a in seen:
                continue
            seen.add(a)
            if len(seen) > 150000:
                return None
            q1, s1, lw, rw = a
            tr = tblw[(q1, s1)]
            if tr is None:
                continue
            w, d, q2 = tr
            if d == 'R':
                for x in (0, 1):
                    rw2 = rw[1:] + (x,)
                    if rw2 in rset:
                        todo.append((q2, rw[0], (w,) + lw[:-1], rw2))
            else:
                for x in (0, 1):
                    lw2 = lw[1:] + (x,)
                    if lw2 in lset:
                        todo.append((q2, lw[0], lw2, (w,) + rw[:-1]))
        newl = {a[2] for a in seen
                if tblw[(a[0], a[1])] and tblw[(a[0], a[1])][1] == 'R'}
        newr = {a[3] for a in seen
                if tblw[(a[0], a[1])] and tblw[(a[0], a[1])][1] == 'L'}
        if newl <= lset and newr <= rset:
            if any(tblw[(a[0], a[1])] is None for a in seen):
                return None
            return len(seen), len(lset), len(rset)
        lset |= newl
        rset |= newr
    return None


def emit_tm(name, mtext):
    tbl = bp.parse(mtext)
    lines = ["Definition %s : TM := fun q s =>" % name,
             "  match q, s with"]
    for qi in range(4):
        for si in range(2):
            tr = tbl[(qi, si)]
            lhs = "St%s, S%d" % (chr(65 + qi), si)
            if tr is None:
                lines.append("  | %s => None" % lhs)
            else:
                w, d, q2 = tr
                lines.append("  | %s => Some (mkTrans S%d D%s St%s)"
                             % (lhs, w, d, chr(65 + q2)))
    lines.append("  end.")
    return "\n".join(lines)


def main():
    rows = collect()
    print(len(rows), "wrap QH machines")
    chunks = [HEADER]
    manifest = []
    fname = "Wrap_01.v"
    for idx, (m, (qs, score)) in enumerate(rows, 1):
        qq = ord(qs) - 65
        s = score - 1
        got = None
        for n in (2, 3, 4, 5, 6):
            for t in (s + 1, s + 16, 256, 4096, 65536, 500000):
                r = wrapped_closure(m, qq, n, t)
                if r:
                    got = (n, t) + r
                    break
            if got:
                break
        if got is None:
            print("FAILED:", m)
            continue
        n, t, nseen, nl, nr = got
        fuel = 8 * nseen + 64
        rounds = nl + nr + 4
        name = "tm_wrap_%03d" % idx
        thm = "qh_" + m.replace("---", "XXX")
        chunks.append("""(** %s: quiet state %s, last visit index %d (score %d);
    wrapped closure n=%d t=%d (%d contexts) *)

%s

Theorem %s :
  NonHalt %s /\\ QuietAfter %s St%s %d /\\ QuasiHaltsSt %s.
Proof.
  apply (ngram_check_quiet_sound _ St%s %d %d %d %d %d).
  vm_compute. reflexivity.
Qed.""" % (m, qs, s, score, n, t, nseen,
           emit_tm(name, m), thm, name, name, qs, s, name,
           qs, s, n, t, fuel, rounds))
        manifest.append((m, thm, "theories/Machines/Bulk/" + fname,
                         qs, score, n, t, nseen))
    os.makedirs(OUTDIR, exist_ok=True)
    open(os.path.join(OUTDIR, fname), "w").write("\n\n".join(chunks) + "\n")
    with open(os.path.join(HERE, "wrap_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tquiet_state\tscore\tn\tt\tcontexts\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    print("emitted %d machines into %s" % (len(manifest), fname))


if __name__ == "__main__":
    main()
