#!/usr/bin/env python3
"""Drift certificate-table generator: BBB neverqh_drift certs ->
generated Coq theorem files (fork of gen_fuel_certs.py).

For every machine in the BBB harness's results/certs_drift, search
for parameters the Coq drift checker accepts
([ngram_check_neverqh_driftw_sound], Checkers/Drift.v): per visited
state q, the lex procedure (rules (a)/(b)) peels the class-refined
q-avoiding graph and every stuck cyclic SCC is discharged by the
two-sided drift kill (c3) -- fuel at the toward-moving nodes plus
Bellman-Ford potentials certifying net-positive-toward cycles
(tools/drift_prover.py, the untrusted mirror of the checker).  No
machine-level mirror: right- and left-drifting SCCs land in separate
per-state gates, which is load-bearing for two of the 17 (a single
state with SCCs drifting opposite ways).

Emitted per machine:
  - a TM definition,
  - a certificate table mapping each state to
    (lex components, R gate, R potentials, L gate, L potentials, W)
    over REFINED context keys (fcconf_enc; untrusted data re-checked
    node by node and edge by edge by the engine),
  - Theorem  NeverQuasiHaltsSt tm  via ngram_check_neverqh_driftw_sound,
  - Corollary  NonHalt tm  via never_qh_nonhalt.

Machines it cannot place are DEFERRED with an exact reason into
tools/drift_deferred.tsv -- no silent caps.

Usage:
  python3 tools/gen_drift_certs.py [--batch B] [--only M1,M2]
                                   [--dry-run] [--n-extra K]
Env: BBB_REPO (default ../BBB relative to the repo root).
"""

import argparse
import glob
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bulk_prover as bp
import gen_bulk_certs as gb
import gen_fuel_certs as gf
import drift_prover as dp

BBB = os.environ.get("BBB_REPO", os.path.join(ROOT, "..", "BBB"))
OUTDIR = os.path.join(ROOT, "theories", "Machines")

HEADER = """(** Generated by tools/gen_drift_certs.py -- DO NOT EDIT.

    Never-quasihalting theorems for the BBB harness's neverqh_drift
    certificate machines, through the two-sided per-SCC drift checker
    [ngram_check_neverqh_driftw_sound] (Checkers/Drift.v, rule (c3))
    on the class-refined contexts of Checkers/FuelWide.v.  Per
    machine: a TM definition, a certificate table mapping each state
    to (lex components, R gate, R potentials, L gate, L potentials,
    W) over refined context keys (fcconf_enc; untrusted data
    re-checked node by node and edge by edge by the engine), the
    theorem closed by vm_compute, and the [NonHalt] corollary. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import NGram Drift.
Import ListNotations.

"""


def collect_machines():
    return sorted(glob.glob(BBB + "/results/certs_drift/*.cert"))


def work(arg):
    path, n_extra = arg
    mtext, n, per_state = bp.parse_cert_measures(path)
    res, fail = dp.dw_decide(mtext, n, per_state, n_extra=n_extra)
    if res is not None:
        return (mtext, n, res, None)
    return (mtext, n, None, ("no-params", "first-fail=%s" % fail))


def emit_machine(idx, mtext, res):
    """One machine's block: TM, refined-key certificate table (per
    state: lex components + the two drift gates with potentials and
    the scale W), the driftw theorem, and the NonHalt corollary."""
    name = "tm_drift_%05d" % idx
    cname = "cert_drift_%05d" % idx
    n = res["n"]
    t = res["t"]
    nseen = res["nseen"]
    fuel = 8 * nseen + 64
    modes = ",".join("%s=%s" % (chr(65 + q), m)
                     for q, m in sorted(res["modes"].items()))
    thm = "nqh_" + gb.sanitize(mtext)
    nh = "nonhalt_" + gb.sanitize(mtext)
    out = []
    out.append("(** %s: n=%d t=%d contexts=%d %s *)"
               % (mtext, n, t, nseen, modes))
    out.append(gb.emit_tm(name, mtext))
    per_state = []
    for qi in range(4):
        comps, gR, phiR, gL, phiL, W = res["per_q"].get(
            qi, ([], set(), {}, set(), {}, 1))
        cbody = ("[" + ";\n   ".join(gf.emit_fcomp(c) for c in comps) + "]"
                 if comps else "[]")
        per_state.append(
            "  | St%s =>\n  (%s,\n   %s,\n   %s,\n   %s,\n   %s,\n   %s)"
            % (chr(65 + qi), cbody, gf.emit_fkeys(gR), gf.emit_fphi(phiR),
               gf.emit_fkeys(gL), gf.emit_fphi(phiL), gb.fmt_nat(W)))
    out.append("Definition %s (q : St) : dw_cert :=\n"
               "  match q with\n%s\n  end." % (cname, "\n".join(per_state)))
    out.append("""Theorem %s : NeverQuasiHaltsSt %s.
Proof.
  apply (ngram_check_neverqh_driftw_sound _ %d %s %s %s %s).
  vm_compute. reflexivity.
Qed.""" % (thm, name, n, gb.fmt_nat(t), gb.fmt_nat(fuel),
           gb.fmt_nat(res["rounds"]), cname))
    out.append("Corollary %s : NonHalt %s.\n"
               "Proof. exact (never_qh_nonhalt _ %s). Qed." % (nh, name, thm))
    return "\n\n".join(out), thm


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=int, default=25)
    ap.add_argument("--only", type=str, default="")
    ap.add_argument("--n-extra", type=int, default=1,
                    help="also try windows n0+1 .. n0+K")
    ap.add_argument("--dry-run", action="store_true",
                    help="search + validate only; write no .v files")
    args = ap.parse_args()

    files = collect_machines()
    if args.only:
        want = set(args.only.split(","))
        files = [f for f in files if os.path.basename(f)[:-5] in want]

    results = []
    deferred = []
    with Pool(4) as pool:
        for mtext, n, res, diag in pool.imap(
                work, [(f, args.n_extra) for f in files], chunksize=1):
            if res is None:
                deferred.append((mtext, n) + diag)
                print("DEFER %s: %s" % (mtext, diag[1]))
            else:
                results.append((mtext, res))
                print("OK    %s n=%d t=%d contexts=%d %s"
                      % (mtext, res["n"], res["t"], res["nseen"],
                         ",".join("%s=%s" % (chr(65 + q), m)
                                  for q, m in sorted(res["modes"].items()))))
    results.sort(key=lambda x: x[0])
    deferred.sort(key=lambda x: x[0])

    with open(os.path.join(HERE, "drift_deferred.tsv"), "w") as df:
        df.write("machine\tngram_n\ttags\tdetail\n")
        for mtext, n, tags, diag in deferred:
            df.write("%s\t%d\t%s\t%s\n" % (mtext, n, tags, diag))

    print("landed %d / %d (deferred %d)"
          % (len(results), len(results) + len(deferred), len(deferred)))
    if args.dry_run:
        return

    manifest = []
    vfiles = []
    for b0 in range(0, len(results), args.batch):
        batch = results[b0:b0 + args.batch]
        bno = b0 // args.batch + 1
        fname = "Drift_Batch_%02d.v" % bno
        chunks = [HEADER]
        for j, (mtext, res) in enumerate(batch):
            idx = b0 + j + 1
            text, thm = emit_machine(idx, mtext, res)
            chunks.append(text)
            gates = ";".join(
                "%s=%s" % (chr(65 + q), m)
                for q, m in sorted(res["modes"].items()) if m != "lex")
            manifest.append((mtext, thm, "theories/Machines/" + fname,
                             res["n"], res["t"], res["nseen"],
                             gates or "lex-only"))
        open(os.path.join(OUTDIR, fname), "w").write(
            "\n\n".join(chunks) + "\n")
        vfiles.append("theories/Machines/" + fname)

    with open(os.path.join(HERE, "drift_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tn\tt\tcontexts\tgates\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    with open(os.path.join(HERE, "drift_vfiles.txt"), "w") as vf:
        vf.write("\n".join(vfiles) + "\n")
    print("emitted %d machines into %d files" % (len(results), len(vfiles)))


if __name__ == "__main__":
    main()
