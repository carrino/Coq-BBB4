#!/usr/bin/env python3
"""census_cache.py -- the committed-census .vo cache guard (BUILD HYGIENE ONLY).

The census (`make census`) is a ~7h native_compute walk.  Its .vo outputs are
committed on this branch so a fresh container never re-walks.  This script is
the honesty valve: it hashes the census's .v INPUTS (the transitive dependency
closure of the census target) so that editing any of those inputs is detected
and forces a re-walk on stable hardware, while an unedited tree just reuses the
committed .vo.

  --check   Recompute the input hash, compare to the committed CENSUS_VO_HASH,
            and verify every committed census .vo is present.  Exit 0 +
            "CENSUS CACHE: MATCH" iff both hold; otherwise exit 1 with a loud
            re-walk banner.  (Container setup precondition.)
  --touch   Touch the committed census .vo (+ .glob if present) in dependency
            order so `make`-style timestamp checks see them as newest and skip
            the walk.  Run only AFTER --check passes.
  --update  Recompute and rewrite CENSUS_VO_HASH.  Run only after a GREEN
            re-walk on stable hardware (`make census-verify`), then commit the
            new .vo + hash.

IMPORTANT -- TRUST BOUNDARY.  Nothing here carries proof weight.  The Coq
kernel is what certifies the census (`census_decided`, Print Assumptions =
functional_extensionality_dep only).  This guard cannot make a false census
true; it can only tell you the committed .vo were built from a DIFFERENT tree
than the one on disk, in which case the .vo must be regenerated by a real walk.
Everything under tools/ is UNTRUSTED.

The hash covers ONLY the .v source inputs (their sorted (path, content) list).
It deliberately does NOT hash the .vo bytes -- .vo are arch/version specific,
whereas the .v inputs are what a re-walk consumes.  .vo *presence* is checked
separately.

Coq's coqdep computes the dependency closure; it lives in the opam switch
`census` (OPAMROOT=/root/.opam).  Run under `eval $(opam env --switch=census)`.
"""

import hashlib
import os
import shutil
import subprocess
import sys

# --- repo layout -----------------------------------------------------------

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEORIES = os.path.join(REPO_ROOT, "theories")
HASH_FILE = os.path.join(REPO_ROOT, "CENSUS_VO_HASH")

# The census target's .v inputs whose transitive closure we hash: the assembled
# theorem, all Run_Split* base-split units, and every Compute/*.v walk unit.
CENSUS_TARGET_GLOBS = [
    ("theories/Census", "Run_Split*.v"),
    ("theories/Census/Compute", "*.v"),  # includes Census_Theorem.v + all walk units
]

REWALK_BANNER = (
    "CENSUS INPUTS EDITED -- the committed census .vo no longer certify this "
    "tree; re-walk required on STABLE hardware (make census-verify)"
)


# --- coqdep discovery / invocation -----------------------------------------

def find_coqdep():
    """Locate coqdep: PATH first, then the census opam switch."""
    exe = shutil.which("coqdep")
    if exe:
        return exe
    for cand in (
        "/root/.opam/census/bin/coqdep",
        os.path.join(os.environ.get("OPAMROOT", "/root/.opam"), "census", "bin", "coqdep"),
    ):
        if os.path.isfile(cand) and os.access(cand, os.X_OK):
            return cand
    return None


def all_theory_v_files():
    """Every .v under theories/, repo-relative with forward slashes, sorted."""
    out = []
    for dirpath, _dirs, files in os.walk(THEORIES):
        for f in files:
            if f.endswith(".v"):
                rel = os.path.relpath(os.path.join(dirpath, f), REPO_ROOT)
                out.append(rel.replace(os.sep, "/"))
    return sorted(out)


def run_coqdep():
    """Run `coqdep -Q theories BBB4 <all theories .v>`; return stdout text.

    Relies on the ambient environment (an active `census` opam switch) to
    resolve Coq's stdlib.  Raises RuntimeError with coqdep's stderr on failure.
    """
    coqdep = find_coqdep()
    if not coqdep:
        raise RuntimeError(
            "coqdep not found; activate the census switch:\n"
            "  export OPAMROOT=/root/.opam; eval $(opam env --switch=census)"
        )
    vfiles = all_theory_v_files()
    cmd = [coqdep, "-Q", "theories", "BBB4"] + vfiles
    proc = subprocess.run(
        cmd, cwd=REPO_ROOT, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True,
    )
    if not proc.stdout.strip():
        raise RuntimeError(
            "coqdep produced no dependency output (Coq stdlib not resolvable?).\n"
            "Ensure the census switch is active:\n"
            "  export OPAMROOT=/root/.opam; eval $(opam env --switch=census)\n"
            "coqdep stderr:\n" + proc.stderr
        )
    return proc.stdout


# --- dependency closure ----------------------------------------------------

def _stem(token):
    """Strip a coq artifact extension to its module stem, or None if not a .vo."""
    # We build the module graph from *.vo targets/deps only.  coqdep also emits
    # .glob/.vio/.v.beautified/.required_vo/.v tokens; only true '.vo' count.
    if token.endswith(".vo"):
        return os.path.normpath(token)[:-3].replace(os.sep, "/")
    return None


def parse_coqdep(text):
    """Parse coqdep make-rules into {module_stem: set(dep_module_stem)}."""
    deps = {}
    for line in text.splitlines():
        if ":" not in line:
            continue
        lhs, rhs = line.split(":", 1)
        # The rule's module = the .vo target on the LHS (ignore .glob/.vio/etc).
        tgt = None
        for tok in lhs.split():
            s = _stem(tok)
            if s is not None:
                tgt = s
                break
        if tgt is None:
            continue  # e.g. the separate .vio rule line -- skip
        dep_set = deps.setdefault(tgt, set())
        for tok in rhs.split():
            s = _stem(tok)
            if s is not None and s != tgt:
                dep_set.add(s)
    return deps


def census_target_stems():
    """Module stems of the census target .v inputs."""
    import glob
    stems = set()
    for subdir, pat in CENSUS_TARGET_GLOBS:
        for p in glob.glob(os.path.join(REPO_ROOT, subdir, pat)):
            rel = os.path.relpath(p, REPO_ROOT).replace(os.sep, "/")
            stems.add(rel[:-2])  # drop trailing '.v'
    return stems


def closure_v_files():
    """Return the sorted list of repo-relative .v files in the census input
    closure (transitive over coqdep's dependency graph)."""
    deps = parse_coqdep(run_coqdep())
    frontier = census_target_stems()
    seen = set()
    while frontier:
        stem = frontier.pop()
        if stem in seen:
            continue
        seen.add(stem)
        for d in deps.get(stem, ()):  # stdlib deps are not emitted, so we stay in-tree
            if d not in seen:
                frontier.add(d)
    vfiles = []
    for stem in seen:
        vpath = stem + ".v"
        if os.path.isfile(os.path.join(REPO_ROOT, vpath)):
            vfiles.append(vpath)
    return sorted(vfiles)


def compute_hash():
    """Stable sha256 over the sorted (path, content) list of the closure."""
    vfiles = closure_v_files()
    h = hashlib.sha256()
    for path in vfiles:  # already sorted, repo-relative, forward-slash
        with open(os.path.join(REPO_ROOT, path), "rb") as fh:
            data = fh.read()
        pb = path.encode("utf-8")
        # length-prefixed framing => injective, order-stable
        h.update(len(pb).to_bytes(8, "big"))
        h.update(pb)
        h.update(len(data).to_bytes(8, "big"))
        h.update(data)
    return h.hexdigest(), vfiles


# --- committed census .vo set ----------------------------------------------

def committed_census_vo():
    """The committed census .vo paths, from `git ls-files '*.vo'`."""
    proc = subprocess.run(
        ["git", "ls-files", "*.vo"], cwd=REPO_ROOT,
        stdout=subprocess.PIPE, text=True, check=True,
    )
    return sorted(p for p in proc.stdout.splitlines() if p.strip())


def _touch_order(vo_files):
    """Order the census .vo in dependency order for touching (earliest dep
    first, so later units end up newest): base Run_Split(.vo/2) -> heavy
    Run_Split_* grandchild splits -> GG/GGH great-grandchild walks -> G_*
    grandchild assemblies -> Census_Theorem."""
    def rank(p):
        b = os.path.basename(p)
        if b in ("Run_Split.vo", "Run_Split2.vo"):
            return 0
        if b.startswith("Run_Split_"):
            return 1
        if b.startswith("GG_") or b.startswith("GGH_"):
            return 2
        if b.startswith("G_"):
            return 3
        if b == "Census_Theorem.vo":
            return 4
        return 5  # any unexpected census .vo touched last
    return sorted(vo_files, key=lambda p: (rank(p), p))


# --- read/parse the committed hash file ------------------------------------

def read_committed_hash():
    """Return the committed hex digest, or None if the file is absent/empty.
    Ignores '#' comment lines and blanks; takes the single 64-hex token."""
    if not os.path.isfile(HASH_FILE):
        return None
    with open(HASH_FILE) as fh:
        for line in fh:
            tok = line.strip()
            if not tok or tok.startswith("#"):
                continue
            return tok
    return None


def write_hash_file(digest, closure_size):
    with open(HASH_FILE, "w") as fh:
        fh.write("# CENSUS_VO_HASH -- sha256 of the census .v INPUT closure.\n")
        fh.write("# Build-hygiene guard only (UNTRUSTED, no proof weight); see\n")
        fh.write("# tools/census_cache.py.  Regenerate with: census_cache.py --update\n")
        fh.write("# after a GREEN re-walk on stable hardware (make census-verify).\n")
        fh.write("# closure: %d .v input files.\n" % closure_size)
        fh.write(digest + "\n")


# --- modes -----------------------------------------------------------------

def mode_check():
    committed = read_committed_hash()
    try:
        current, vfiles = compute_hash()
    except RuntimeError as e:
        sys.stderr.write(str(e) + "\n")
        return 1

    vo_expected = committed_census_vo()
    missing = [p for p in vo_expected if not os.path.isfile(os.path.join(REPO_ROOT, p))]

    problems = []
    if committed is None:
        problems.append("no committed CENSUS_VO_HASH file (run --update after a green walk)")
    elif current != committed:
        problems.append("census input hash mismatch")
        problems.append("  committed: %s" % committed)
        problems.append("  current:   %s" % current)
    if missing:
        problems.append("%d committed census .vo missing from the tree:" % len(missing))
        for p in missing[:10]:
            problems.append("    " + p)
        if len(missing) > 10:
            problems.append("    ... and %d more" % (len(missing) - 10))

    if not problems:
        print("CENSUS CACHE: MATCH")
        print("  closure: %d .v input files; %d committed census .vo present" %
              (len(vfiles), len(vo_expected)))
        print("  hash: %s" % current)
        return 0

    line = "!" * 72
    print(line)
    print(REWALK_BANNER)
    print(line)
    for p in problems:
        print(p)
    return 1


def mode_touch():
    vo_expected = committed_census_vo()
    n = 0
    for vo in _touch_order(vo_expected):
        vpath = os.path.join(REPO_ROOT, vo)
        if os.path.isfile(vpath):
            os.utime(vpath, None)  # touch to now; dep order => later units newest
            n += 1
            glob_path = vpath[:-3] + ".glob"
            if os.path.isfile(glob_path):
                os.utime(glob_path, None)
    print("census cache: touched %d committed census .vo (+.glob if present) "
          "in dependency order" % n)
    return 0


def mode_update():
    try:
        digest, vfiles = compute_hash()
    except RuntimeError as e:
        sys.stderr.write(str(e) + "\n")
        return 1
    write_hash_file(digest, len(vfiles))
    print("wrote %s" % os.path.relpath(HASH_FILE, REPO_ROOT))
    print("  closure: %d .v input files" % len(vfiles))
    print("  hash: %s" % digest)
    return 0


def main(argv):
    modes = {"--check": mode_check, "--touch": mode_touch, "--update": mode_update}
    if len(argv) != 1 or argv[0] not in modes:
        sys.stderr.write(
            "usage: census_cache.py (--check | --touch | --update)\n"
            "  --check   compare tree against committed CENSUS_VO_HASH + .vo presence\n"
            "  --touch   touch committed census .vo newest (after --check passes)\n"
            "  --update  rewrite CENSUS_VO_HASH (after a green re-walk)\n"
        )
        return 2
    return modes[argv[0]]()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
