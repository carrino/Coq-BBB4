#!/usr/bin/env python3
"""Emit block-list batches using positive binary-frontier returns."""
import argparse
import json
from pathlib import Path
from period3_batch import ROOT, row


def render(nn, rec):
    mapping, = rec['maps']
    p = mapping['p']
    assert rec['mirrored'] and rec['t'] == 0
    assert rec['failed'] == [[p[1], 0]]
    flip = str(not mapping['flip']).lower()
    perm = ' | '.join(f'St{chr(65+q)}=>St{chr(65+x)}' for q,x in enumerate(p))
    syms = lambda xs: '['+';'.join('S'+str(x) for x in xs)+']'
    return fr'''(** GENERATED by tools/closeouttr/blocklists_return_batch.py. *)
From Coq Require Import Arith List ZArith.
From BBB4 Require Import BBB4_Statement BBBT4_Statement CTape Mirror.
From BBB4.Census Require Import Deferred_Defs.
From BBB4.CensusTr Require Import TNF_QHTr.
From BBB4.CloseoutTr Require Import CloseoutKitTr.
From BBB4.Checkers Require Import NGram FuelMixTr FuelMixPartialTr.
From BBB4.Counters Require Import CConjugateTr FiniteReturnTr FuelB0ReturnTr.
Import ListNotations.
Definition cert_AST_{nn}_0000 : Instr -> list fmxcomp * list positive :=
{rec['cert']}.
(* spec {rec['spec']} *)
Definition r_AST_{nn}_0000 : list(option Trans) := {row(rec['spec'])}.
Local Definition tm := mirror_tm(row_to_tm r_AST_{nn}_0000).
Local Definition src := row_to_tm {row('1RB1RC_0LC0RA_1RA1LD_1LA0LC')}.
Local Definition p(q:St):St := match q with {perm} end.
Local Definition skip(t:Instr):bool := instr_eqb t (St{chr(65+p[1])},S0).
Local Lemma recurrent : forall N,exists j,N<=j /\ FiresAt tm (St{chr(65+p[1])},S0)j.
Proof.
 apply(conjugate_return_recurrent src tm p {flip} StB S0 {rec['boot']} {syms(rec['L'])} {syms(rec['R'])}).
 - intros[] [];reflexivity.
 - rewrite <-lift_c0. apply csteps_lift. vm_compute;reflexivity.
 - apply bf_B0_return;reflexivity.
Qed.
Lemma cv_AST_{nn}_0000 : coversTr(row_to_tm r_AST_{nn}_0000).
Proof.
 apply coversTr_nqh,neverqhtr_mirror.
 apply(ngram_check_neverqh_fuelmixtr_except_sound tm {rec['n']} 0 {rec['fuel']} {rec['rounds']} skip cert_AST_{nn}_0000).
 - intros[[] []] H N;try discriminate. apply recurrent.
 - vm_compute;reflexivity.
Qed.
Definition cbtrows_AST_{nn} : list(list(option Trans)) := [r_AST_{nn}_0000].
Lemma cbt_AST_{nn}_covers : Forall coversTr(map row_to_tm cbtrows_AST_{nn}).
Proof. constructor;[exact cv_AST_{nn}_0000|constructor]. Qed.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    records = json.loads(Path(__file__).with_name('blocklists_return_ast.json').read_text())
    assert len(records) == 2
    for nn, rec in zip((117,118), records):
        path = ROOT / f'theories/CloseoutTr/CBT_AST_{nn}.v'
        text = render(nn, rec)
        if args.check:
            assert path.read_text() == text, path
        else:
            path.write_text(text)
        print(('checked' if args.check else 'wrote'), path.relative_to(ROOT))


if __name__ == '__main__':
    main()
