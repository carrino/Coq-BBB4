#!/usr/bin/env python3
"""Assemble the transition-level closeout (UNTRUSTED generator).

Reads the frozen deferred list (censustr_deferred_v10.txt, the rows of
CensusTr/DeferredTr_*.v) and every batch theories/CloseoutTr/CBT_*.v (their
`(* spec ... *)` comments), then writes

  theories/CloseoutTr/RemainingTr.v   remaining_tr_rows: deferred minus boarded
  theories/CloseoutTr/CloseoutTr.v    proven_tr_rows, the reflective split,
                                      closeout_tr_partial
  closeouttr_remaining.txt            the remaining specs, one per line
  closeouttr_boarded.tsv              spec -> batch, for bookkeeping

and lists every CloseoutTr file in _CoqProject.  Re-run it after adding or
merging batches: the files it writes are the only ones two workstreams
share, and regenerating them is the whole merge-conflict story.

    python3 tools/closeouttr/gen_closeout_tr.py [--check]

--check exits non-zero if any generated file would change (CI use).
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from cbt import CT, spec_row  # noqa: E402

DEFERRED = os.path.join(REPO, 'censustr_deferred_v10.txt')
SPEC_RE = re.compile(r'^\(\* spec (\S+) \*\)$', re.M)
BATCH_RE = re.compile(r'^CBT_([A-Z][A-Z0-9]{0,7})_(\d\d)\.v$')
SUB = 500   # rows per Definition in RemainingTr.v: big literals choke the parser


def read_list(path):
    out = []
    for line in open(path):
        s = line.strip()
        if s and not s.startswith('#'):
            out.append(s)
    return out


def batches():
    out = []
    for p in sorted(glob.glob(os.path.join(CT, 'CBT_*.v'))):
        b = os.path.basename(p)
        m = BATCH_RE.match(b)
        if not m:
            sys.exit('bad batch file name %s (want CBT_<TAG>_<NN>.v)' % b)
        specs = SPEC_RE.findall(open(p).read())
        if not specs:
            sys.exit('%s carries no (* spec ... *) rows' % b)
        out.append((b[:-2], '%s_%s' % (m.group(1), m.group(2)), specs))
    return out


def remaining_v(rows):
    lines = ['(** GENERATED by tools/closeouttr/gen_closeout_tr.py -- do not edit.',
             '',
             '    The transition-level residue: the %d rows of the frozen v10' % len(rows),
             '    deferred list no closeout batch has boarded yet. *)',
             'From Coq Require Import List.',
             'From BBB4 Require Import BBB4_Statement.',
             'From BBB4.Census Require Import Deferred_Defs.',
             'Import ListNotations.', '']
    subs = []
    for i in range(0, max(len(rows), 1), SUB):
        nm = 'remaining_tr_%03d' % (i // SUB)
        subs.append(nm)
        chunk = rows[i:i + SUB]
        lines.append('Definition %s : list (list (option Trans)) := [' % nm)
        lines.append(';\n'.join(spec_row(s) for s in chunk))
        lines.append('].')
        lines.append('')
    lines.append('Definition remaining_tr_rows : list (list (option Trans)) :=')
    lines.append('  ' + ' ++ '.join(subs) + '.')
    return '\n'.join(lines) + '\n'


def closeout_v(bs, n_def, n_rem):
    mods = ' '.join(m for m, _, _ in bs)
    n_pro = sum(len(s) for _, _, s in bs)
    out = ['(** GENERATED by tools/closeouttr/gen_closeout_tr.py -- do not edit.',
           '',
           '    The transition-level closeout.  [proven_tr_rows] concatenates the',
           '    %d batch tables (%d rows, each with a kernel-checked [coversTr]' % (len(bs), n_pro),
           '    proof); [remaining_tr_rows] (RemainingTr.v) lists the %d rows' % n_rem,
           '    still open.  The reflective check [closeout_tr_rows_split] states',
           '    every one of the %d frozen v10 rows is in one of the two tables;' % n_def,
           '    [deferred_split_tr] then gives',
           '',
           '      [closeout_tr_partial : Deferred D_censusTr tm ->',
           '                             QHBoundTr B_close tm \\/ Deferred D_remaining_tr tm].',
           '',
           '    No census walk is involved and no census .vo is loaded; the',
           '    chain through [census_tr] is CloseoutFinalTr.v (box only). *)',
           'From Coq Require Import Bool List.',
           'From BBB4 Require Import BBB4_Statement BBBT4_Statement.',
           'From BBB4.Census Require Import TNF_QH Deferred_Defs.',
           'From BBB4.CensusTr Require Import TNF_QHTr DeferredTr_Data.',
           'From BBB4.Closeout Require Import CloseoutKit.',
           'From BBB4.CloseoutTr Require Import CloseoutKitTr RemainingTr%s.' % ((' ' + mods) if mods else ''),
           'Import ListNotations.', '']
    if bs:
        out.append('Definition proven_tr_rows : list (list (option Trans)) :=')
        out.append('  ' + ' ++ '.join('cbtrows_%s' % b for _, b, _ in bs) + '.')
        out.append('')
        out.append('Lemma proven_tr_rows_covers : Forall coversTr (map row_to_tm proven_tr_rows).')
        out.append('Proof.')
        out.append('  unfold proven_tr_rows.')
        out.append('  repeat rewrite map_app.')
        out.append('  repeat (apply Forall_app; split);')
        out.append('    first [ ' + '\n          | '.join('exact cbt_%s_covers' % b for _, b, _ in bs) + ' ].')
        out.append('Qed.')
    else:
        out.append('Definition proven_tr_rows : list (list (option Trans)) := [].')
        out.append('')
        out.append('Lemma proven_tr_rows_covers : Forall coversTr (map row_to_tm proven_tr_rows).')
        out.append('Proof. exact (Forall_nil _). Qed.')
    out += ['',
            'Definition D_remaining_tr : list TM := map row_to_tm remaining_tr_rows.',
            '',
            'Lemma closeout_tr_rows_split :',
            '  split_ok deferred_tr_rows proven_tr_rows remaining_tr_rows = true.',
            'Proof. vm_cast_no_check (eq_refl true). Qed.',
            '',
            'Theorem closeout_tr_partial : forall tm,',
            '  Deferred D_censusTr tm -> QHBoundTr B_close tm \\/ Deferred D_remaining_tr tm.',
            'Proof.',
            '  exact (deferred_split_tr deferred_tr_rows proven_tr_rows remaining_tr_rows',
            '           closeout_tr_rows_split proven_tr_rows_covers).',
            'Qed.']
    return '\n'.join(out) + '\n'


KIT = ['theories/CloseoutTr/CloseoutKitTr.v']
TAIL = ['theories/CloseoutTr/RemainingTr.v', 'theories/CloseoutTr/CloseoutTr.v']


def coqproject(bs):
    path = os.path.join(REPO, '_CoqProject')
    lines = open(path).read().splitlines()
    keep = [l for l in lines if not l.startswith('theories/CloseoutTr/')]
    ours = KIT + ['theories/CloseoutTr/%s.v' % m for m, _, _ in bs] + TAIL
    return '\n'.join(keep + ours) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    deferred = read_list(DEFERRED)
    dset = set(deferred)
    bs = batches()
    boarded = {}
    for m, b, specs in bs:
        for s in specs:
            if s not in dset:
                sys.exit('%s boards %s, which is not a v10 deferred row' % (m, s))
            boarded.setdefault(s, m)
    remaining = [s for s in deferred if s not in boarded]
    files = {
        os.path.join(CT, 'RemainingTr.v'): remaining_v(remaining),
        os.path.join(CT, 'CloseoutTr.v'): closeout_v(bs, len(deferred), len(remaining)),
        os.path.join(REPO, 'closeouttr_remaining.txt'): ''.join(s + '\n' for s in remaining),
        os.path.join(REPO, 'closeouttr_boarded.tsv'): ''.join('%s\t%s\n' % (s, boarded[s]) for s in deferred if s in boarded),
        os.path.join(REPO, '_CoqProject'): coqproject(bs),
    }
    stale = [p for p, txt in files.items()
             if not os.path.exists(p) or open(p).read() != txt]
    if a.check:
        if stale:
            print('CLOSEOUTTR: STALE (%s); run python3 tools/closeouttr/gen_closeout_tr.py'
                  % ', '.join(os.path.relpath(p, REPO) for p in stale))
            sys.exit(1)
        print('CLOSEOUTTR: OK (%d batches, %d boarded, %d remaining of %d)'
              % (len(bs), len(boarded), len(remaining), len(deferred)))
        return
    for p in stale:
        with open(p, 'w') as f:
            f.write(files[p])
    print('%d batches, %d rows boarded, %d of %d remaining; wrote %d file(s)'
          % (len(bs), len(boarded), len(remaining), len(deferred), len(stale)))


if __name__ == '__main__':
    main()
