#!/usr/bin/env python3
"""Write transition-level closeout batch files (UNTRUSTED generator).

A batch file theories/CloseoutTr/CBT_<TAG>_<NN>.v proves, for each of its
rows r, [coversTr (row_to_tm r)] (CloseoutKitTr.v), and exports

    Definition cbtrows_<TAG>_<NN> : list (list (option Trans)) := [...].
    Lemma cbt_<TAG>_<NN>_covers :
      Forall coversTr (map row_to_tm cbtrows_<TAG>_<NN>).

Every row is preceded by a `(* spec <bbchallenge text> *)` comment: that
is how gen_closeout_tr.py learns which deferred rows a batch settles, so a
hand-written batch must carry the same comments.  The kernel re-checks all
of it: a wrong comment makes the reflective split in CloseoutTr.v fail.

TAG names the workstream (RW, QH, NG, HY, ...), so parallel sessions never
write the same file.  Library use:

    from cbt import write_batch
    write_batch('RW', 0, ['From BBB4.CensusTr Require Import RepWLTr.'],
                [(spec, 'apply coversTr_nqh, (rw_tier_tr_sound _ 6 2 256 11048 30). '
                        'vm_cast_no_check (eq_refl true).'), ...],
                blurb='never-QH bouncers by RepWL (rw_tier_tr)')
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
CT = os.path.join(REPO, 'theories', 'CloseoutTr')

TAG_RE = re.compile(r'^[A-Z][A-Z0-9]{0,7}$')


def slot_name(e):
    if e == '---':
        return 'tN'
    return 't%s%s%s' % (e[0], e[1], e[2])


def spec_row(spec):
    """bbchallenge text -> the Coq row literal Deferred_Defs.row_to_tm reads"""
    parts = spec.split('_')
    assert len(parts) == 4 and all(len(p) == 6 for p in parts), spec
    names = []
    for p in parts:
        names.append(slot_name(p[0:3]))
        names.append(slot_name(p[3:6]))
    return '[' + ';'.join(names) + ']'


def batch_path(tag, nn):
    return os.path.join(CT, 'CBT_%s_%02d.v' % (tag, nn))


def next_free(tag):
    n = 0
    while os.path.exists(batch_path(tag, n)):
        n += 1
    return n


def write_batch(tag, nn, requires, entries, blurb, overwrite=False):
    """entries: [(spec, proof)] where proof is the tactic text proving
    [coversTr (row_to_tm r)] (without Proof./Qed.)"""
    assert TAG_RE.match(tag), 'TAG must be 1-8 of [A-Z0-9], starting with a letter: %r' % tag
    path = batch_path(tag, nn)
    if os.path.exists(path) and not overwrite:
        raise SystemExit('refusing to overwrite %s' % path)
    base = '%s_%02d' % (tag, nn)
    os.makedirs(CT, exist_ok=True)
    with open(path, 'w') as f:
        f.write('(** GENERATED by tools/closeouttr -- DO NOT EDIT.\n\n'
                '    Transition-level closeout batch %s: %d deferred rows, %s.\n'
                '    Collected by tools/closeouttr/gen_closeout_tr.py. *)\n'
                % (base, len(entries), blurb))
        f.write('From Coq Require Import Arith List ZArith.\n'
                'From BBB4 Require Import BBB4_Statement BBBT4_Statement.\n'
                'From BBB4.Census Require Import Deferred_Defs.\n'
                'From BBB4.CloseoutTr Require Import CloseoutKitTr.\n')
        for r in requires:
            f.write(r.rstrip() + '\n')
        f.write('Import ListNotations.\n\n')
        names = []
        for k, (spec, proof) in enumerate(entries):
            nm = '%s_%04d' % (base, k)
            names.append(nm)
            f.write('(* spec %s *)\n' % spec)
            f.write('Definition r_%s : list (option Trans) := %s.\n' % (nm, spec_row(spec)))
            f.write('Lemma cv_%s : coversTr (row_to_tm r_%s).\nProof. %s Qed.\n\n' % (nm, nm, proof.strip()))
        f.write('Definition cbtrows_%s : list (list (option Trans)) :=\n  [' % base)
        f.write(';\n   '.join('r_%s' % x for x in names))
        f.write('].\n\nLemma cbt_%s_covers : Forall coversTr (map row_to_tm cbtrows_%s).\n' % (base, base))
        term = '(Forall_nil _)'
        for x in reversed(names):
            term = '(Forall_cons _ cv_%s %s)' % (x, term)
        f.write('Proof. exact %s. Qed.\n' % term)
    return path
