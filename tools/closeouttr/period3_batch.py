#!/usr/bin/env python3
"""Emit six period-three carry batches; --check verifies byte-for-byte output.

The certificates use the landed partial FuelMixTr checker. The two manual
instructions are justified by the generic finite-word termination proofs.
The source/target conjugacy is checked here and independently in each proof.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = Path(__file__).with_name('period3_ast.json')
BATCHES = [98, 99, 101, 107, 108, 109]


def table(spec):
    return [(int(block[i]), block[i + 1], ord(block[i + 2]) - ord('A'))
            for block in spec.split('_') for i in (0, 3)]


def row(spec):
    return '[' + ';'.join('t' + block[i:i + 3]
                         for block in spec.split('_') for i in (0, 3)) + ']'


def render(nn, rec, records):
    mapping, = rec['maps']
    p, flip = mapping['p'], mapping['flip']
    source = records[mapping['source']]['spec']
    src, dst = table(source), table(rec['spec'])
    assert sorted(p) == list(range(4))
    for q in range(4):
        for s in range(2):
            w, direction, target = src[2 * q + s]
            if flip:
                direction = 'L' if direction == 'R' else 'R'
            assert dst[2 * p[q] + s] == (w, direction, p[target])
    assert sorted(rec['failed']) == sorted([[p[1], 0], [p[3], 0]])
    assert rec['mirrored'] and rec['t'] == 0
    b, d = (chr(65 + p[i]) for i in (1, 3))
    skip = ' || '.join(f'instr_eqb t (St{chr(65 + q)},S{s})'
                      for q, s in rec['failed'])
    permutation = ' | '.join(f'St{chr(65 + q)} => St{chr(65 + x)}'
                             for q, x in enumerate(p))
    proof_prefix = f'''(** GENERATED by tools/closeouttr/period3_batch.py.

    Transition-level closeout batch AST_{nn}: finite-word carry termination
    and partial FuelMixTr recurrence certificates. *)
From Coq Require Import Arith List ZArith.
From BBB4 Require Import BBB4_Statement BBBT4_Statement CTape Mirror.
From BBB4.Census Require Import Deferred_Defs.
From BBB4.CloseoutTr Require Import CloseoutKitTr.
From BBB4.Checkers Require Import NGram FuelMixTr FuelMixPartialTr.
From BBB4.Counters Require Import CConjugateTr FiniteInstrTr Period3FiniteTr.
From BBB4.CensusTr Require Import TNF_QHTr.
Import ListNotations.

Definition cert_AST_{nn}_0000 : Instr -> list fmxcomp * list positive :=
{rec['cert']}.

(* spec {rec['spec']} *)
Definition r_AST_{nn}_0000 : list (option Trans) := {row(rec['spec'])}.
Definition source_AST_{nn} : list (option Trans) := {row(source)}.
Definition perm_AST_{nn} (q:St):St := match q with {permutation} end.
Definition skip_AST_{nn} (t:Instr):bool := {skip}.

Lemma cv_AST_{nn}_0000 : coversTr(row_to_tm r_AST_{nn}_0000).
Proof.
 assert(Htable:forall q s,row_to_tm r_AST_{nn}_0000 (perm_AST_{nn} q) s =
  option_map(tconj perm_AST_{nn} {str(flip).lower()})(row_to_tm source_AST_{nn} q s))
  by(intros[] [];reflexivity).
 assert(Honto:forall q,exists q0,perm_AST_{nn} q0=q).
 {{ intros[];first[exists StA;reflexivity|exists StB;reflexivity|
                  exists StC;reflexivity|exists StD;reflexivity]. }}
 assert(HB:finite_instr_hit(row_to_tm r_AST_{nn}_0000)(St{b},S0)).
 {{ apply(finite_instr_conjugate (row_to_tm source_AST_{nn}) _ perm_AST_{nn}
   {str(flip).lower()} (StB,S0) Htable Honto).
   intro c. apply p3_B0_finite;reflexivity. }}
 assert(HD:finite_instr_hit(row_to_tm r_AST_{nn}_0000)(St{d},S0)).
 {{ apply(finite_instr_conjugate (row_to_tm source_AST_{nn}) _ perm_AST_{nn}
   {str(flip).lower()} (StD,S0) Htable Honto).
   intro c. apply(p3_D0_finite _ S{mapping['source']});reflexivity. }}
 assert(Htotal:forall q s,exists tr,row_to_tm r_AST_{nn}_0000 q s=Some tr)
  by(intros[] [];eexists;reflexivity).
 pose proof(finite_instr_recurrent _ _ Htotal HB)as RB.
 pose proof(finite_instr_recurrent _ _ Htotal HD)as RD.
 apply coversTr_nqh,neverqhtr_mirror.
 apply(ngram_check_neverqh_fuelmixtr_except_sound _ {rec['n']} 0 {rec['fuel']} {rec['rounds']}
  skip_AST_{nn} cert_AST_{nn}_0000).
 - intros[[] []] H N;try discriminate;
   first[destruct(RB N)as(j&Hj&Hf);exists j;split;[exact Hj|apply mirror_fires;exact Hf]
        |destruct(RD N)as(j&Hj&Hf);exists j;split;[exact Hj|apply mirror_fires;exact Hf]].
 - vm_compute. reflexivity.
Qed.

Definition cbtrows_AST_{nn} : list (list (option Trans)) := [r_AST_{nn}_0000].
Lemma cbt_AST_{nn}_covers : Forall coversTr(map row_to_tm cbtrows_AST_{nn}).
Proof. exact(Forall_cons _ cv_AST_{nn}_0000 (Forall_nil _)). Qed.
'''
    return proof_prefix


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    records = json.loads(DATA.read_text())
    assert len(records) == len(BATCHES)
    for nn, rec in zip(BATCHES, records):
        path = ROOT / f'theories/CloseoutTr/CBT_AST_{nn}.v'
        text = render(nn, rec, records)
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'stale: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
        print(('checked' if args.check else 'wrote'), path.relative_to(ROOT))


if __name__ == '__main__':
    main()
