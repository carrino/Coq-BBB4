#!/usr/bin/env python3
"""RepWL certificate-table generator: BBB neverqh_rwlrank certs ->
generated Coq theorem files through rw_check_neverqh_sound
(Checkers/RepWL.v).  Fork of gen_fuel_certs.py's emission shape;
the search/validation lives in repwl_prover.py (the exact Python
mirror of the Coq checker).

Usage:
  python3 tools/gen_repwl_certs.py [--batch B] [--only M1,M2] [--dry-run]
Env: BBB_REPO (default ../BBB relative to the repo root).
"""

import argparse
import glob
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import repwl_prover as rp
import gen_bulk_certs as gb

BBB = os.environ.get("BBB_REPO", os.path.join(ROOT, "..", "BBB"))
OUTDIR = os.path.join(ROOT, "theories", "Machines")

HEADER = """(** Generated by tools/gen_repwl_certs.py -- DO NOT EDIT.

    Never-quasihalting theorems for the BBB harness's neverqh_rwlrank
    certificate machines, through the repeated-word-list checker
    [rw_check_neverqh_sound] (Checkers/RepWL.v).  Per machine: a TM
    definition, a certificate table mapping each state to its
    lexicographic components over REFINED context keys (rconf_enc;
    untrusted data re-checked edge by edge by the engine), the
    theorem closed by vm_compute, and the [NonHalt] corollary. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import RepWL.
Import ListNotations.

"""

MEAS_CTOR = {'N/A': 'RwNA', 'N/L': 'RwNL', 'N/R': 'RwNR',
             '0/l': 'RwZL', '0/r': 'RwZR'}


def emit_phi(phi):
    items = sorted((rp.rconf_enc(a), v) for a, v in phi.items() if v != 0)
    if not items:
        return "[]"
    return "[" + ";\n     ".join("(%d%%positive, %s)" % (e, gb.fmt_nat(v))
                                 for e, v in items) + "]"


def emit_gate(gate):
    items = sorted(rp.rconf_enc(a) for a in gate)
    if not items:
        return "[]"
    return "[" + ";\n     ".join("%d%%positive" % e for e in items) + "]"


def emit_comp(comp):
    if comp[0] == "rank":
        return "RwRankE\n    %s" % emit_phi(comp[1])
    _, m, K, phi, gate = comp
    return "RwMeasE %s %s\n    %s\n    %s" % (
        MEAS_CTOR[m], gb.fmt_nat(K), emit_phi(phi), emit_gate(gate))


def emit_machine(idx, mtext, L, T, res):
    name = "tm_rwl_%05d" % idx
    cname = "cert_rwl_%05d" % idx
    t = res["t"]
    nseen = res["nseen"]
    fuel = 8 * nseen + 64
    thm = "nqh_" + gb.sanitize(mtext)
    nh = "nonhalt_" + gb.sanitize(mtext)
    out = []
    out.append("(** %s: L=%d T=%d t=%d contexts=%d *)"
               % (mtext, L, T, t, nseen))
    out.append(gb.emit_tm(name, mtext))
    per_state = []
    for qi in range(4):
        comps = res["comps"].get(qi, [])
        body = ("[" + ";\n   ".join(emit_comp(c) for c in comps) + "]"
                if comps else "[]")
        per_state.append("  | St%s =>\n  %s" % (chr(65 + qi), body))
    out.append("Definition %s (q : St) : list rwcomp :=\n"
               "  match q with\n%s\n  end." % (cname, "\n".join(per_state)))
    out.append("""Theorem %s : NeverQuasiHaltsSt %s.
Proof.
  apply (rw_check_neverqh_sound _ %d %d %s %s %s).
  vm_compute. reflexivity.
Qed.""" % (thm, name, L, T, gb.fmt_nat(t), gb.fmt_nat(fuel), cname))
    out.append("Corollary %s : NonHalt %s.\n"
               "Proof. exact (never_qh_nonhalt _ %s). Qed." % (nh, name, thm))
    return "\n\n".join(out), thm


def work(path):
    mtext, L, T, per_state = rp.parse_cert(path)
    res = rp.decide(mtext, L, T, per_state)
    return (mtext, L, T, res)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", type=int, default=27)
    ap.add_argument("--only", type=str, default="")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    files = sorted(glob.glob(BBB + "/results/certs_rwlrank/*.cert"))
    if args.only:
        want = set(args.only.split(","))
        files = [f for f in files if os.path.basename(f)[:-5] in want]

    results = []
    failures = []
    with Pool(4) as pool:
        for mtext, L, T, res in pool.imap(work, files, chunksize=1):
            if res is None:
                failures.append(mtext)
                print("FAIL  %s" % mtext, flush=True)
            else:
                results.append((mtext, L, T, res))
                print("OK    %s L=%d T=%d t=%d nseen=%d"
                      % (mtext, L, T, res["t"], res["nseen"]), flush=True)
    results.sort(key=lambda x: x[0])
    print("landed %d / %d" % (len(results), len(results) + len(failures)))
    for m in failures:
        print("FAILED:", m)
    if args.dry_run:
        return

    manifest = []
    vfiles = []
    for b0 in range(0, len(results), args.batch):
        batch = results[b0:b0 + args.batch]
        bno = b0 // args.batch + 1
        fname = "RepWL_Batch_%02d.v" % bno
        chunks = [HEADER]
        for j, (mtext, L, T, res) in enumerate(batch):
            idx = b0 + j + 1
            text, thm = emit_machine(idx, mtext, L, T, res)
            chunks.append(text)
            manifest.append((mtext, thm, "theories/Machines/" + fname,
                             L, T, res["t"], res["nseen"]))
        open(os.path.join(OUTDIR, fname), "w").write(
            "\n\n".join(chunks) + "\n")
        vfiles.append("theories/Machines/" + fname)

    with open(os.path.join(HERE, "repwl_manifest.tsv"), "w") as mf:
        mf.write("machine\ttheorem\tfile\tL\tT\tt\tcontexts\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    print("emitted %d machines into %d files" % (len(results), len(vfiles)))


if __name__ == "__main__":
    main()
