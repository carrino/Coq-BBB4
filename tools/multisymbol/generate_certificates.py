#!/usr/bin/env python3
"""Untrusted producer of proof trees; Coq's verify checks every leaf and branch.

The survey emits a preorder tree. A halt row has 2*n*m children, one
per defined transition; the undefined choice is checked at that node.
JSON stages name their input/residue files and a Coq certificate expression.
Only a subsequent kernel-checked census check establishes an upper bound.
"""
import argparse
import csv
import json
from pathlib import Path


def generate(rows_path, stages_path, ns, ms, known_path=None):
    def machines(path):
        return {s.replace("_", "") for s in Path(path).read_text().splitlines() if s}

    witnesses = {}
    known = ({row["machine"].replace("_", ""): row["index"]
              for row in json.loads(Path(known_path).read_text())} if known_path else {})
    def leaf(expression):
        return f"(KLeaf {expression})" if known_path else expression
    for stage in json.loads(Path(stages_path).read_text()):
        before = machines(stage["input"])
        after = machines(stage["residue"])
        if not after <= before:
            raise ValueError("stage residue is not a subset of its input")
        for machine in before - after:
            witnesses.setdefault(machine, stage["certificate"])
    rows = iter(csv.DictReader(Path(rows_path).open(), delimiter="\t"))
    missing = []

    def visit():
        row = next(rows)
        if row["kind"] == "halt":
            children = [visit() for _ in range(2 * ns * ms)]
            branch = "KBranch" if known_path else "Branch"
            return f'({branch} {row["anchor"]} [{' ; '.join(children)}])'
        if row["kind"] in {"cycle", "translated"}:
            mirrored = "true" if int(row["shift"]) < 0 else "false"
            return leaf(f'(Cycle {mirrored} {row["anchor"]} {row["period"]} {row["reach"]})')
        key = row["machine"].replace("_", "")
        if key not in witnesses:
            if key in known:
                return f'(KKnown {known[key]})'
            missing.append(row["machine"])
            return "Invalid"
        return leaf(f'({witnesses[key]})')

    cert = visit()
    if next(rows, None) is not None:
        raise ValueError("extra rows after the certificate tree")
    if missing:
        raise ValueError(f"{len(missing)} unresolved leaves, first: {missing[0]}")
    return cert


def main():
    p = argparse.ArgumentParser()
    p.add_argument("rows")
    p.add_argument("stages")
    p.add_argument("output")
    p.add_argument("--states", type=int, required=True)
    p.add_argument("--symbols", type=int, required=True)
    p.add_argument("--state-bound", type=int, required=True)
    p.add_argument("--instruction-bound", type=int, required=True)
    p.add_argument("--mode", choices=["both", "state"], default="both")
    p.add_argument("--known", help="JSON machine/index registry, proved in KnownNM.v")
    p.add_argument("--residue", action="store_true",
                   help="emit an explicitly conditional theorem using RemainingNM.v")
    a = p.parse_args()
    ns, ms, bs, bi = a.states, a.symbols, a.state_bound, a.instruction_bound
    if a.known and a.mode != "both":
        p.error("--known currently supports --mode both")
    if a.residue and not a.known:
        p.error("--residue requires a proved conditional --known registry")
    cert = generate(a.rows, a.stages, ns, ms, a.known)
    tag = f"{ns}{ms}"
    if a.mode == "state":
        tag += "_state"
        modules = "StateCensus"
        check = f"verify_state {ns} {ms} {bs}"
        claim = f"QHBound {bs} tm"
        complete = f"state_census_complete {ns} {ms} {bs}"
    else:
        modules = ""
        check = f"verify {ns} {ms} {bs} {bi}"
        claim = f"Bounds {bs} {bi} tm"
        complete = f"census_complete {ns} {ms} {bs} {bi}"
    cert_type = "Cert"
    extra_proof = ""
    if a.known:
        modules = f"KnownCensus Known{tag}"
        cert_type = "KCert"
        check = f"verify_known {ns} {ms} {bs} {bi} known{tag}"
        complete = f"known_census_complete {ns} {ms} {bs} {bi} known{tag}"
        extra_proof = f"  - exact known{tag}_sound.\n"
    theorem_name = f"bbb{tag}_upper"
    premise = ""
    intro = ""
    if a.residue:
        modules += f" StatementTr Remaining{tag}"
        theorem_name += "_conditional"
        premise = f"Forall (QHBoundTr {bi}) remaining{tag} -> "
        intro = "  intro residue_bounds.\n"
        extra_proof = f"  - exact (known{tag}_sound residue_bounds).\n"
    Path(a.output).write_text(f"""(* Generated by tools/multisymbol/generate_certificates.py; fully rechecked. *)
From Coq Require Import List.
From SmallBB Require Import Statement Size Bounds Census {modules}.
Import ListNotations.
Definition certificate{tag} : {cert_type} := {cert}.
Lemma census{tag}_checked : {check} {ns*ms+1} empty certificate{tag} = true.
Proof. native_compute. reflexivity. Qed.
Theorem {theorem_name} : {premise}forall tm, Admissible {ns} {ms} tm -> {claim}.
Proof.
{intro}  eapply ({complete}).
{extra_proof.rstrip()}
  - unfold supported; auto.
  - exact census{tag}_checked.
Qed.
""")


if __name__ == "__main__":
    main()
