#!/usr/bin/env python3
"""Emit the STAGED wave-4 listC never-QH tier via the FUEL/DRIFT checkers.

Wave-4 Task B: over the 3,557 still-unboarded census list-C residue machines
(listC target 6,247 minus the wave-2/3 irulesqh/irulesnqh/listc-stage boards),
run the BBB sweep

  bin/quietngram --neverqh --rank --fuel   (then --drift over the remainder)
                 --max-n 8 --t 5e6 --cert-dir BBB/results/certs_wave4/<mode>

and board its catches through the LANDED Coq fuel/drift checkers -- no new
trust surface.  This adapter reads the produced certs, re-derives the
Coq-checker params (gen_fuel_certs.fw_decide / drift_prover.dw_decide, the
untrusted mirrors of the engines), and emits SELF-CONTAINED, LCStage-shaped
files in a NEW dir:

  theories/Machines/ListCStage3/LCS3_<mode>_NN.v

each with, per machine, a TM + a class-refined certificate table + the
theorem  NeverQuasiHaltsSt tm  closed by vm_compute through
[ngram_check_neverqh_fuelw_sound] (FuelWide.v) / [..._driftw_sound]
(Drift.v), plus a per-file [lcstage3_<mode>_NN : list TM] and
[Forall NeverQuasiHaltsSt] so the wire follow-up can append it to
[proven_list] (Census/Proven_Data.v) -- the R_NeverQH tier -- verbatim.

NOT wired; no census input touched (docs/WAVE4_STAGE.md).  Everything here is
UNTRUSTED: the Coq kernel re-derives the closure and re-checks every edge.

Usage:
  gen_listc_stage3.py --mode fuel|drift --cert-dir DIR
                      [--batch B] [--procs P] [--n-extra K]
                      [--chunk0 N] [--idx0 N] [--append]
"""
import argparse
import glob
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bulk_prover as bp        # noqa: E402  parse_cert_measures
import gen_fuel_certs as gf     # noqa: E402  fw_decide + emit_machine
import gen_drift_certs as gd    # noqa: E402  emit_machine (drift)
import drift_prover as dp       # noqa: E402  dw_decide

OUTDIR = os.path.join(ROOT, "theories", "Machines", "ListCStage3")

HEADER = {
    'fuel': """(** GENERATED by tools/gen_listc_stage3.py --mode fuel -- DO NOT EDIT.

    STAGED wave-4 listC never-quasihalting theorems via the FUEL checker,
    chunk {nn} ({cnt} machines).  SELF-CONTAINED and NOT imported by any
    census input yet: per machine a TM definition, a class-refined fuel
    certificate (encoded-key tables; untrusted data re-checked node by node
    by the engine), and the theorem closed by vm_compute through
    [ngram_check_neverqh_fuelw_sound] (Checkers/FuelWide.v).  Ready to board
    the proven (R_NeverQH) tier: append [lcstage3_fuel_{nn}] to [proven_list]
    (Census/Proven_Data.v) -- see docs/WAVE4_STAGE.md. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape Mirror.
From BBB4.Checkers Require Import NGram FuelWide.
Import ListNotations.

""",
    'drift': """(** GENERATED by tools/gen_listc_stage3.py --mode drift -- DO NOT EDIT.

    STAGED wave-4 listC never-quasihalting theorems via the two-sided DRIFT
    checker, chunk {nn} ({cnt} machines).  SELF-CONTAINED and NOT imported by
    any census input yet: per machine a TM definition, a class-refined drift
    certificate (untrusted data re-checked edge by edge by the engine), and
    the theorem closed by vm_compute through
    [ngram_check_neverqh_driftw_sound] (Checkers/Drift.v).  Ready to board the
    proven (R_NeverQH) tier: append [lcstage3_drift_{nn}] to [proven_list]
    (Census/Proven_Data.v) -- see docs/WAVE4_STAGE.md. *)

From Coq Require Import List ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import NGram Drift.
Import ListNotations.

""",
}


def _work(arg):
    path, mode, n_extra = arg
    mtext, n, per_state = bp.parse_cert_measures(path)
    if mode == 'fuel':
        res, _fail = gf.fw_decide(mtext, n, per_state, n_extra=n_extra)
    else:
        res, _fail = dp.dw_decide(mtext, n, per_state, n_extra=n_extra)
    return (mtext, res)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=["fuel", "drift"], required=True)
    ap.add_argument("--cert-dir", required=True)
    ap.add_argument("--batch", type=int, default=50)
    ap.add_argument("--procs", type=int, default=2)
    ap.add_argument("--n-extra", type=int, default=1)
    ap.add_argument("--chunk0", type=int, default=0)
    ap.add_argument("--idx0", type=int, default=0)
    ap.add_argument("--append", action="store_true")
    args = ap.parse_args()

    files = sorted(glob.glob(os.path.join(args.cert_dir, "*.cert")))
    emit_machine = gf.emit_machine if args.mode == "fuel" else gd.emit_machine

    results, misses = [], []
    with Pool(args.procs) as pool:
        for mtext, res in pool.imap(
                _work, [(f, args.mode, args.n_extra) for f in files],
                chunksize=1):
            if res is None:
                misses.append(mtext)
            else:
                results.append((mtext, res))
    results.sort(key=lambda x: x[0])

    os.makedirs(OUTDIR, exist_ok=True)
    manifest, chunk_names = [], []
    for b0 in range(0, len(results), args.batch):
        batch = results[b0:b0 + args.batch]
        bno = b0 // args.batch
        nn = "%02d" % (args.chunk0 + bno)
        name = "LCS3_%s_%s" % (args.mode, nn)
        chunk_names.append(name)
        chunks = [HEADER[args.mode].format(nn=nn, cnt=len(batch))]
        entries = []
        for j, (mtext, res) in enumerate(batch):
            idx = args.idx0 + b0 + j
            text, thm = emit_machine(idx, mtext, res)
            chunks.append(text)
            tmname = "tm_%s_%05d" % (args.mode, idx)
            entries.append((thm, tmname))
            manifest.append((mtext, thm,
                             "theories/Machines/ListCStage3/%s.v" % name,
                             "R_NeverQH", args.mode, res["n"], res["t"],
                             res["nseen"]))
        listname = name.lower()
        chunks.append("Definition %s : list TM :=\n  [%s]."
                      % (listname, ";\n   ".join(t for _, t in entries)))
        proof = ["Lemma %s_nqh : Forall NeverQuasiHaltsSt %s."
                 % (listname, listname), "Proof.", "  unfold %s." % listname]
        for thm, _ in entries:
            proof.append("  apply Forall_cons; [exact %s|]." % thm)
        proof += ["  apply Forall_nil.", "Qed."]
        chunks.append("\n".join(proof))
        open(os.path.join(OUTDIR, name + ".v"), "w").write(
            "\n\n".join(chunks) + "\n")

    mpath = os.path.join(HERE, "listc_stage3_manifest.tsv")
    with open(mpath, "a" if args.append else "w") as mf:
        if not args.append:
            mf.write("machine\ttheorem\tfile\ttier\tmethod\tn\tt\tcontexts\n")
        for row in manifest:
            mf.write("\t".join(str(x) for x in row) + "\n")
    print("[%s] staged %d machines into %d files; %d prover-misses; manifest %s"
          % (args.mode, len(results), len(chunk_names), len(misses), mpath))


if __name__ == "__main__":
    main()
