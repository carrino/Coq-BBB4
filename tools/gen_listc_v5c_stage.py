#!/usr/bin/env python3
"""Transcribe the v5-gap list-C never-QH irules certificates into staged
Coq batches, boarded through the v5c engine extension (block-hop closure
+ multi-run cell-stream end-match): theories/Checkers/IRules/BlkClosure.v
+ StreamEq2.v + MetaBlkPfxV5c.v.

These are the 8 remaining BBB-verified never-QH scalar machines whose
meta cycle the landed v5/v5b checkers cannot close: with the block table
closed under block-hop outputs the UNCHANGED engine
([EngineKS.beng_stepS]) tracks the C verifier's [iv_step] through the
whole cycle, reaching a configuration CELL-equal to the shifted template
whose two sides each carry TWO variable-count runs.  [cseq2] (strip the
common runs, then the proven one-pump [cseq]) recognises that, so
[irulesblkpfx_check_neverqh_v5c_sound] boards them -- no new axiom
(Print Assumptions = functional_extensionality_dep only).

Same LCStage-shaped emission as gen_listc_v5b_stage.py: per file
[lcv5c_NN : list TM] + [lcv5c_NN_nqh : Forall NeverQuasiHaltsSt lcv5c_NN],
files theories/Machines/ListCV5Stage/LCV5C_NN.v, manifest
tools/listc_v5c_manifest.tsv.  Self-contained and NOT wired into any
census input.

Usage: gen_listc_v5c_stage.py OUTDIR MANIFEST.tsv CHUNKSIZE CERT [CERT ...]
"""
import sys, os, importlib.util

_spec = importlib.util.spec_from_file_location(
    "genbp", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "gen_irulesblkpfx_certs.py"))
G = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(G)

CFUEL = 200000
# The v5c meta cycles are short (~137 iterations for the measured donor),
# so a modest fuel closes every board in ~1s -- no need for the 300000
# the v5/v5b boards used (whose cycles ran longer).
FUEL = 3000

HEADER = '''(** GENERATED by tools/gen_listc_v5c_stage.py -- DO NOT EDIT.

    STAGED v5-gap list-C never-QH machines, chunk {NN} ({CNT} machines).
    SELF-CONTAINED and NOT imported by any census input yet: each
    machine gets [NeverQuasiHaltsSt] via
    [irulesblkpfx_check_neverqh_v5c_sound]
    (Checkers/IRules/MetaBlkPfxV5c.v) + [vm_compute].  The v5c checker
    differs from the landed v5b checker only by (a) closing the block
    table under block-hop outputs (BlkClosure.blk_closure, untrusted,
    re-verified by bhop_result) and (b) a multi-run cell-stream
    end-match (StreamEq2.cseq2); the engine (EngineKS.beng_stepS) is
    UNCHANGED.  Corruption coverage is theories/Tests/IRulesV5c_Corruption.v.
    The certificates are UNTRUSTED search output (BBB bin/irules over the
    v5 gap); every claim is re-checked by the verified engine.  Ready to
    board the proven (R_NeverQH) tier: append [lcv5c_{NN}] to
    [proven_list] (Census/Proven_Data.v) -- a future box session wires +
    regens. *)

From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Cycle.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
     EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx StreamEq
     MetaBlkPfxV5 Reblock MetaBlkPfxV5b BlkClosure StreamEq2 MetaBlkPfxV5c.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
'''


def emit_machine(path, idx):
    c = G.parse_cert(path)
    m = c["machine"]
    nm = "v5c_%05d" % idx
    a, b = c["meta_a"], c["meta_b"]
    s = []
    s.append("(* %s : anchor %d, ver %s *)"
             % (m, c["anchor_step"], c.get("ver", "?")))
    s.append("Definition tm_%s : TM := fun q s =>" % nm)
    s.append("  match q, s with")
    s.append(G.emit_tm(m))
    s.append("  end.")
    s.append("Definition cert_%s : BIRCertP := mkBIRCertP" % nm)
    s.append("  %d%%nat (%d) (%d) (%d) (%d) %s S%d"
             % (c["anchor_step"], c["k0"], c["kmin"], a, b,
                G.ST[c["tpl_state"]], c["tpl_hsym"]))
    s.append("  %s" % G.emit_blks(c["blk"]))
    s.append("  %s" % G.emit_tpl(c["tplL"]))
    s.append("  %s" % G.emit_tpl(c["tplR"]))
    s.append("  %s." % G.emit_rules(c["rules"], c["pfx"]))
    s.append("Lemma nqh_%s : NeverQuasiHaltsSt tm_%s." % (nm, nm))
    s.append("Proof.")
    s.append("  apply (irulesblkpfx_check_neverqh_v5c_sound tm_%s cert_%s "
             "%d %d)." % (nm, nm, CFUEL, FUEL))
    s.append("  vm_compute. reflexivity.")
    s.append("Qed.")
    return "\n".join(s), nm, m


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    outdir, manifest, chunk = args[0], args[1], int(args[2])
    certs = args[3:]
    os.makedirs(outdir, exist_ok=True)
    blocks, names, machines, meta = [], [], [], []
    idx = 0
    for p in certs:
        body, nm, m = emit_machine(p, idx)
        c = G.parse_cert(p)
        blocks.append(body)
        names.append(nm)
        machines.append(m)
        meta.append((c["anchor_step"], c.get("ver", "?")))
        idx += 1
    nfiles = 0
    rows = []
    for ci in range(0, len(blocks), chunk):
        nn = "%02d" % nfiles
        cb = blocks[ci:ci + chunk]
        cn = names[ci:ci + chunk]
        fn = os.path.join(outdir, "LCV5C_%s.v" % nn)
        with open(fn, "w") as f:
            f.write(HEADER.replace("{NN}", nn)
                    .replace("{CNT}", str(len(cb))) + "\n")
            f.write("\n\n".join(cb) + "\n\n")
            f.write("Definition lcv5c_%s : list TM :=\n  [" % nn)
            f.write(";\n   ".join("tm_%s" % n for n in cn))
            f.write("].\n\n")
            f.write("Lemma lcv5c_%s_nqh : Forall NeverQuasiHaltsSt "
                    "lcv5c_%s.\n" % (nn, nn))
            term = "(Forall_nil NeverQuasiHaltsSt)"
            for n in reversed(cn):
                term = "(Forall_cons _ nqh_%s %s)" % (n, term)
            f.write("Proof. exact %s. Qed.\n" % term)
        for k in range(ci, min(ci + chunk, len(blocks))):
            rows.append((machines[k], "nqh_%s" % names[k],
                         "LCV5C_%s.v" % nn, str(meta[k][0]), meta[k][1]))
        nfiles += 1
    with open(manifest, "w") as f:
        f.write("machine\ttheorem\tfile\tanchor\tcert_ver\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    sys.stderr.write("emitted %d machines into %d files\n"
                     % (len(names), nfiles))


if __name__ == "__main__":
    main()
