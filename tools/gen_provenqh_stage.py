#!/usr/bin/env python3
"""Emit the STAGED wave-4 proven-QH recovery tier at n=5/6 (UNTRUSTED).

Wave-4 Task A: the 1,475 list-B machines in tools/provenqh_uncaught.txt
resisted the census QHBound gates at n<=4, t<=1024.  This emitter re-runs
the SAME gen_provenqh.py growing-closure machinery
(find_plain / find_lex_rich, theories/Checkers/Wrap.v
ngram_check_qhbound(_lex)_sound) at the higher closure orders n in {5,6},
KEEPING t <= 1024 (B_census = 2000 caps the S t -> 2000 lift; t=4096 is
unsound).  No new checker, no new trust surface.

Unlike gen_provenqh.py -- which writes the COMMITTED census inputs
theories/Census/ProvenQH_*.v (FROZEN while the census re-cert runs) -- this
emits SELF-CONTAINED, RRStage-shaped stage files that touch no census input:

  theories/Machines/ProvenQHStage/PQHS_NN.v   -- [pqhs] list + [Forall] cert
  tools/provenqh_stage_manifest.tsv           -- machine -> theorem/file/gate
  tools/provenqh_stage_uncaught.txt           -- the still-uncaught remainder

Each file defines
  Definition pqhs (tm : TM) : Prop := NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm.
and, per machine, [Lemma cpq_<tag> : pqhs tm_pq_<tag>] closed by the sound
QHBound checker (the middle conjunct proved unfolded at S t, then lifted to
QHBound 2000 by qhbound_mono since t < 2000), plus one nested [Forall_cons]
term over the chunk -- exactly the RerootStage/RRStage_*.v shape.  Ready to
board the R_QH tier (append [pqhstage_NN] to reroot_qh_list) -- see
docs/WAVE4_STAGE.md.  Everything under tools/ is UNTRUSTED: the Coq kernel
re-checks every emitted claim.

Usage: gen_provenqh_stage.py [UNCAUGHT_TXT] [PER_FILE] [JOBS]
  UNCAUGHT_TXT default tools/provenqh_uncaught.txt; PER_FILE default 100.
"""
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import gen_provenqh as gp     # noqa: E402  the growing-closure QHBound finders
import gen_bulk_certs as gb   # noqa: E402  emit_tm / emit_comp

B_PQ = 2000                   # census score bound; every emitted t stays < B_PQ
CAND_N = (5, 6)               # the wave-4 lever: closure orders past n<=4
CAND_T = (64, 256, 1024)      # KEEP t <= 1024 (sound S t -> 2000 lift)


def find_cert_n56(m):
    """gen_provenqh.find_cert but forced to the higher n in {5,6} (t<=1024).
    PLAIN acyclicity gate first, then the rich-vocabulary LEX gate."""
    try:
        r = gp.find_plain(m, cand_n=CAND_N, cand_t=CAND_T)
        if r is not None:
            qq, s, n, t, seen, lset, rset = r
            return dict(gate='plain', m=m, qq=qq, s=s, n=n, t=t,
                        fuel=8 * len(seen) + 64, rounds=len(lset) + len(rset) + 4)
        lr = gp.find_lex_rich(m, cand_n=CAND_N, cand_t=CAND_T)
        if lr is not None:
            qq, s, n, t, seen, lset, rset, comps = lr
            return dict(gate='lex', m=m, qq=qq, s=s, n=n, t=t,
                        fuel=8 * len(seen) + 64, rounds=len(lset) + len(rset) + 4,
                        comps_by_state=comps)
    except Exception:  # noqa: BLE001  untrusted search; a crash just = uncaught
        return None
    return None


HDR = """(** GENERATED by tools/gen_provenqh_stage.py -- DO NOT EDIT.

    STAGED wave-4 proven-QH recovery, chunk {nn} ({cnt} machines).
    SELF-CONTAINED and NOT imported by any census input yet: each list-B
    machine [tm] (uncaught by the n<=4 QHBound gates) gets [pqhs tm] =
    [NonHalt /\\ QHBound 2000 /\\ QuasiHaltsSt] via the growing-closure
    QHBound checker at n in {{5,6}} (t <= 1024) -- PLAIN
    [ngram_check_qhbound_sound] or LEX [ngram_check_qhbound_lex_sound]
    (theories/Checkers/Wrap.v).  The sound lemma proves the middle
    conjunct unfolded at [S t]; [qhbound_mono] lifts it to [QHBound 2000]
    ([t < 2000]).  Ready to board the R_QH tier: append [pqhstage_{nn}]
    to [reroot_qh_list] (Census/RerootQH_Data.v) -- see
    docs/WAVE4_STAGE.md. *)
From Coq Require Import List Lia ZArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import NGram Wrap.
From BBB4.Census Require Import TNF_QH.
Import ListNotations.

Definition pqhs (tm : TM) : Prop :=
  NonHalt tm /\\ QHBound 2000 tm /\\ QuasiHaltsSt tm.
"""


def emit_lemma(tag, c):
    m, qq, s, n, t = c['m'], c['qq'], c['s'], c['n'], c['t']
    fuel, rounds = c['fuel'], c['rounds']
    qs = chr(65 + qq)
    name = "tm_pq_%s" % tag
    tmdef = gb.emit_tm(name, m)
    if c['gate'] == 'plain':
        certdef = ""
        apply_line = ("apply (ngram_check_qhbound_sound _ St%s %d %d %d %d %d)."
                      % (qs, s, n, t, fuel, rounds))
    else:
        cname = "cert_pq_%s" % tag
        comps = c['comps_by_state']
        per_state = []
        for qi in range(4):
            cs = comps.get(qi, [])
            body = ("[" + ";\n   ".join(gb.emit_comp(x) for x in cs) + "]") \
                if cs else "[]"
            per_state.append("  | St%s =>\n  %s" % (chr(65 + qi), body))
        certdef = ("Definition %s (q : St) : list ngcomp :=\n  match q with\n%s\n  end.\n\n"
                   % (cname, "\n".join(per_state)))
        apply_line = ("apply (ngram_check_qhbound_lex_sound _ St%s %d %d %d %d %d %s)."
                      % (qs, s, n, t, fuel, rounds, cname))
    return """
(** {m}: quiet {qs} s={s}; {G} QHBound {t} (n={n} t={t}) *)

{tmdef}
{certdef}Lemma cpq_{tag} : pqhs tm_pq_{tag}.
Proof.
  assert (H : NonHalt tm_pq_{tag}
    /\\ (forall q' s', QuietAfter tm_pq_{tag} q' s' -> S s' <= S {t})
    /\\ QuasiHaltsSt tm_pq_{tag}).
  {{ {apply_line}
     vm_compute. reflexivity. }}
  destruct H as (Hnh & Hqb & Hqh).
  split; [exact Hnh | split;
    [ apply (qhbound_mono (S {t}) 2000 tm_pq_{tag}); [lia | exact Hqb] | exact Hqh ] ].
Qed.
""".format(m=m, qs=qs, s=s, G=c['gate'].upper(), t=t, n=n,
           tmdef=tmdef, certdef=certdef, tag=tag, apply_line=apply_line)


def main():
    txt = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "provenqh_uncaught.txt")
    per_file = int(sys.argv[2]) if len(sys.argv) > 2 else 100
    jobs = int(sys.argv[3]) if len(sys.argv) > 3 else 2

    machines = []
    with open(txt) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                machines.append(line)

    with Pool(jobs) as p:
        results = p.map(find_cert_n56, machines)
    caught = [c for c in results if c is not None]
    uncaught = [m for m, c in zip(machines, results) if c is None]
    for c in caught:
        assert c['t'] < B_PQ, ("t >= B_PQ", c['m'], c['t'])

    outdir = os.path.join(ROOT, "theories/Machines/ProvenQHStage")
    os.makedirs(outdir, exist_ok=True)
    n_chunks = (len(caught) + per_file - 1) // per_file
    manifest = []
    for ci in range(n_chunks):
        chunk = caught[ci * per_file:(ci + 1) * per_file]
        nn = "%02d" % ci
        tags = ["%s%03d" % (nn, k) for k in range(len(chunk))]
        body = [HDR.format(nn=nn, cnt=len(chunk))]
        for tag, c in zip(tags, chunk):
            body.append(emit_lemma(tag, c))
            manifest.append((c['m'], "cpq_%s" % tag,
                             "theories/Machines/ProvenQHStage/PQHS_%s.v" % nn,
                             c['gate'], chr(65 + c['qq']), c['s'], c['n'], c['t'],
                             "R_QH"))
        listname = "pqhstage_%s" % nn
        body.append("\nDefinition %s : list TM :=\n  [%s].\n"
                    % (listname, ";\n   ".join("tm_pq_" + t for t in tags)))
        term = "Forall_nil pqhs"
        for t in reversed(tags):
            term = "Forall_cons _ cpq_%s (%s)" % (t, term)
        body.append("Lemma %s_all : Forall pqhs %s.\nProof. exact (%s). Qed.\n"
                    % (listname, listname, term))
        open(os.path.join(outdir, "PQHS_%s.v" % nn), "w").write("\n".join(body))
        print("wrote PQHS_%s.v: %d machines" % (nn, len(chunk)))

    with open(os.path.join(HERE, "provenqh_stage_manifest.tsv"), "w") as f:
        f.write("machine\ttheorem\tfile\tgate\tquiet_state\ts\tn\tt\ttier\n")
        for row in manifest:
            f.write("\t".join(str(x) for x in row) + "\n")
    with open(os.path.join(HERE, "provenqh_stage_uncaught.txt"), "w") as f:
        f.write("\n".join(uncaught) + ("\n" if uncaught else ""))
    print("caught %d / %d  (n=5/6, t<=1024); uncaught %d -> tools/provenqh_stage_uncaught.txt"
          % (len(caught), len(machines), len(uncaught)))


if __name__ == "__main__":
    main()
