#!/usr/bin/env python3
"""Transcribe the v5-gap list-C never-QH irules certificates into staged
Coq batches, boarded through the v5 end-match engine extension
(theories/Checkers/IRules/MetaBlkPfxV5.v + StreamEq.v).

These are the BBB-verified never-QH machines whose meta-cycle closes on a
configuration CELL-equal to the shifted template but with a run
decomposition the landed [irulesblkpfx_check_neverqh] refuses (its
[bend_eqb] only re-encodes constant-count blocks).  The v5 checker's
[bend_eqb2 = bend_eqb || cseq] recognises the symbolic-cell-stream
equality (StreamEq.cseq_sound), so
[irulesblkpfx_check_neverqh_v5b_sound] boards them -- no new axiom
(Print Assumptions = functional_extensionality_dep only).

Same LCStage-shaped emission as gen_irulesnqh_stage.py: per file
[lcv5b_NN : list TM] + [lcv5b_NN_nqh : Forall NeverQuasiHaltsSt lcv5b_NN],
files theories/Machines/ListCV5Stage/LCV5B_NN.v, manifest
tools/listc_v5_manifest.tsv.  Self-contained and NOT wired into any
census input.

Usage: gen_listc_v5b_stage.py OUTDIR MANIFEST.tsv CHUNKSIZE CERT [CERT ...]
"""
import sys, os, importlib.util

_spec = importlib.util.spec_from_file_location(
    "genbp", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                          "gen_irulesblkpfx_certs.py"))
G = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(G)

CFUEL = 200000
FUEL = 300000

HEADER = '''(** GENERATED by tools/gen_listc_v5b_stage.py -- DO NOT EDIT.

    STAGED v5-gap list-C never-QH machines, chunk {NN} ({CNT} machines).
    SELF-CONTAINED and NOT imported by any census input yet: each
    machine gets [NeverQuasiHaltsSt] via
    [irulesblkpfx_check_neverqh_v5b_sound]
    (Checkers/IRules/MetaBlkPfxV5.v) + [vm_compute].  The v5 checker's
    only difference from the landed [irulesblkpfx_check_neverqh] is the
    symbolic-cell-stream end-match ([StreamEq.bend_eqb2]); corruption
    coverage is theories/Tests/IRulesV5_Corruption.v.  The certificates
    are UNTRUSTED search output (BBB bin/irules over the v5 gap); every
    claim is re-checked by the verified engine.  Ready to board the
    proven (R_NeverQH) tier: append [lcv5b_{NN}] to [proven_list]
    (Census/Proven_Data.v) -- a future box session wires + regens. *)

From Coq Require Import ZArith List.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Checkers Require Import Cycle.
From BBB4.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
     EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx StreamEq
     MetaBlkPfxV5 Reblock MetaBlkPfxV5b.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w : Sym) (d : Dir) (n : St) : option Trans :=
  Some (mkTrans w d n).
'''


def emit_machine(path, idx):
    c = G.parse_cert(path)
    m = c["machine"]
    nm = "v5b_%05d" % idx
    a, b = c["meta_a"], c["meta_b"]
    s = []
    s.append("(* %s : anchor %d, ver %s *)"
             % (m, c["anchor_step"], c.get("ver", "?")))
    s.append("Definition tm_%s : TM := fun q s =>" % nm)
    s.append("  match q, s with")
    s.append(G.emit_tm(m))
    s.append("  end.")
    s.append("Definition cert_%s : BIRCertP := mkBIRCertP" % nm)
    s.append("  %d%%nat (%d) (%d) (%d) (%d) %s S%d"
             % (c["anchor_step"], c["k0"], c["kmin"], a, b,
                G.ST[c["tpl_state"]], c["tpl_hsym"]))
    s.append("  %s" % G.emit_blks(c["blk"]))
    s.append("  %s" % G.emit_tpl(c["tplL"]))
    s.append("  %s" % G.emit_tpl(c["tplR"]))
    s.append("  %s." % G.emit_rules(c["rules"], c["pfx"]))
    s.append("Lemma nqh_%s : NeverQuasiHaltsSt tm_%s." % (nm, nm))
    s.append("Proof.")
    s.append("  apply (irulesblkpfx_check_neverqh_v5b_sound tm_%s cert_%s "
             "%d %d)." % (nm, nm, CFUEL, FUEL))
    s.append("  vm_compute. reflexivity.")
    s.append("Qed.")
    return "\n".join(s), nm, m


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    outdir, manifest, chunk = args[0], args[1], int(args[2])
    certs = args[3:]
    os.makedirs(outdir, exist_ok=True)
    blocks, names, machines, meta = [], [], [], []
    idx = 0
    for p in certs:
        body, nm, m = emit_machine(p, idx)
        c = G.parse_cert(p)
        blocks.append(body)
        names.append(nm)
        machines.append(m)
        meta.append((c["anchor_step"], c.get("ver", "?")))
        idx += 1
    nfiles = 0
    rows = []
    for ci in range(0, len(blocks), chunk):
        nn = "%02d" % nfiles
        cb = blocks[ci:ci + chunk]
        cn = names[ci:ci + chunk]
        fn = os.path.join(outdir, "LCV5B_%s.v" % nn)
        with open(fn, "w") as f:
            f.write(HEADER.replace("{NN}", nn)
                    .replace("{CNT}", str(len(cb))) + "\n")
            f.write("\n\n".join(cb) + "\n\n")
            f.write("Definition lcv5b_%s : list TM :=\n  [" % nn)
            f.write(";\n   ".join("tm_%s" % n for n in cn))
            f.write("].\n\n")
            f.write("Lemma lcv5b_%s_nqh : Forall NeverQuasiHaltsSt "
                    "lcv5b_%s.\n" % (nn, nn))
            term = "(Forall_nil NeverQuasiHaltsSt)"
            for n in reversed(cn):
                term = "(Forall_cons _ nqh_%s %s)" % (n, term)
            f.write("Proof. exact %s. Qed.\n" % term)
        for k in range(ci, min(ci + chunk, len(blocks))):
            rows.append((machines[k], "nqh_%s" % names[k],
                         "LCV5B_%s.v" % nn, str(meta[k][0]), meta[k][1]))
        nfiles += 1
    with open(manifest, "w") as f:
        f.write("machine\ttheorem\tfile\tanchor\tcert_ver\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    sys.stderr.write("emitted %d machines into %d files\n"
                     % (len(names), nfiles))


if __name__ == "__main__":
    main()
