#!/usr/bin/env python3
"""Generate the winning-rung hint table (Census/Hints_*.v) from a
tools/census_ladder.c CSV run.

Hint semantics (Census/Decide.v hint_lookup / decide_easy):
  0     -> the n-gram ladder is measured futile: try the rank tier
           first, full ladder as fallback
  S k   -> start the n-gram ladder at rung S k (skipn k ng_rungs),
           full ladder as fallback
CSV tier -> hint: N3 -> 2, N4 -> 3, N6 -> 4, '-' (residue) -> 0.
N2 (rung-1 catches: nothing to skip), C/T/H/D rows are omitted.

Keys are tm_enc positives (see tools/dec_tm_enc.py for the encoding).
Hints are ADVISORY: a wrong entry costs one extra ladder attempt and
falls back to the full ladder, so this table carries no proof weight.

Usage:
  gen_hints.py CSV OUTDIR [--prefix Hints] [--chunk 12000]
               [--filter REGEX]
"""
import csv, re, sys, os

TIER_HINT = {'N3': 2, 'N4': 3, 'N6': 4, '-': 0}

def enc_slot(t):
    if t == '---':
        return 0
    w = int(t[0]); d = 1 if t[1] == 'R' else 0; st = ord(t[2]) - 65
    return 1 + w + 2 * d + 4 * st

def tm_enc(m):
    acc = 0
    for part in m.split('_'):
        for tr in (part[:3], part[3:]):
            acc = 17 * acc + enc_slot(tr)
    return acc + 1  # N.succ_pos

def main():
    args = sys.argv[1:]
    csv_path, outdir = args[0], args[1]
    prefix, chunk, filt = 'Hints', 12000, None
    i = 2
    while i < len(args):
        if args[i] == '--prefix': prefix = args[i+1]; i += 2
        elif args[i] == '--chunk': chunk = int(args[i+1]); i += 2
        elif args[i] == '--filter': filt = re.compile(args[i+1]); i += 2
        else: raise SystemExit(f'unknown arg {args[i]}')

    rows = []
    with open(csv_path) as f:
        for rec in csv.reader(f):
            if len(rec) < 3 or rec[0] == 'machine':
                continue
            hint = TIER_HINT.get(rec[2])
            if hint is None:
                continue
            if filt and not filt.match(rec[0]):
                continue
            rows.append((tm_enc(rec[0]), hint))
    rows.sort()
    os.makedirs(outdir, exist_ok=True)
    names = []
    for ci in range(0, len(rows), chunk):
        n = f'{prefix.lower()}_{ci//chunk:02d}'
        names.append(n)
        with open(os.path.join(outdir, f'{prefix}_{ci//chunk:02d}.v'), 'w') as f:
            f.write(f'(* GENERATED by tools/gen_hints.py -- do not edit. *)\n')
            f.write('From Coq Require Import List PArith.\n')
            f.write('Import ListNotations.\n')
            f.write(f'Definition {n} : list (positive * nat) := [\n')
            f.write(';\n'.join(f'({k}%positive,{v})' for k, v in rows[ci:ci+chunk]))
            f.write('].\n')
    with open(os.path.join(outdir, f'{prefix}_Data.v'), 'w') as f:
        f.write(f'(* GENERATED by tools/gen_hints.py ({len(rows)} hints) -- do not edit. *)\n')
        f.write('From Coq Require Import List PArith.\n')
        for j, n in enumerate(names):
            f.write(f'From BBB4.Census Require Import {prefix}_{j:02d}.\n')
        f.write('Import ListNotations.\n')
        f.write(f'Definition {prefix.lower()}_rows : list (positive * nat) :=\n  ')
        f.write(' ++ '.join(names) + '.\n')
    print(f'{len(rows)} hints -> {len(names)} chunks in {outdir}', file=sys.stderr)

if __name__ == '__main__':
    main()
