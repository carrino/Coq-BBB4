"""Replay the exact champion board without evaluating its score as unary nat.

Only a new theory and generated one-row inventory wrapper are compiled. Existing
dependencies must already be built. Complete-closure kernel validation uses the
unchanged V3 exact-artifact receipt checker, or an explicitly requested recursive
audit. The frozen small-bound campaign is never mutated or recomputed.
"""
import argparse
import csv
import json
import os
from pathlib import Path
import resource
import re
import subprocess
import time

from kernel_audit_cache_v3 import audit, digest, fresh_paths

ROOT = Path(__file__).resolve().parents[1]
CHAMPION = '1LB2RA1LA1RB_0RB2LB3LB1RA'
SCORE = 205770076433044242247860
PACKED = 2788885433
NAMESPACE = 'BBB24NextChampion'
DESCRIPTOR = ROOT/'research/next-champion-board.json'
INVENTORY = ROOT/'research/next-champion-inventory.json'
THEORY = ROOT/'theories/ChampionCensusNext.v'


def unpack(value):
    if type(value) is not int or not 0 <= value < 17**8:
        raise ValueError('Invalid packed machine')
    cells = []
    for _ in range(8):
        value, cell = divmod(value, 17)
        cells.append('---' if cell == 16 else
                     f'{cell//4}{"R" if cell&2 else "L"}{"B" if cell&1 else "A"}')
    return ''.join(cells[:4])+'_'+''.join(cells[4:])


def rel(path):
    return os.path.relpath(path, ROOT)


def artifact(path):
    return dict(path=rel(path), sha256=digest(path))


def validate_inputs():
    data = json.loads(DESCRIPTOR.read_text())
    inventory = json.loads(INVENTORY.read_text())
    if data['schema'] != 1 or data['kind'] != 'standalone-exact-champion-board':
        raise ValueError('Unsupported descriptor')
    if len(data['boards']) != 1:
        raise ValueError('Expected one exact champion board')
    board = data['boards'][0]
    expected = dict(id='ChampionCensusNext', scope='both',
                    module='BBB24.ChampionCensusNext', board='champion_census_board',
                    sound='champion_census_board_sound', small_sound='champion_census_board_sound',
                    was_pending='champion_census_board_pending', rows=1,
                    state_bound=SCORE, instruction_bound=SCORE,
                    state_bound_term='scoreN', instruction_bound_term='scoreN',
                    load_paths=[], inventories=[dict(path=rel(INVENTORY), format='packed17', order='input')])
    if board != expected:
        raise ValueError('Descriptor changed; explicitly review the exact board interface')
    if inventory != dict(schema=1, rows=[PACKED]) or unpack(PACKED) != CHAMPION:
        raise ValueError('Exact champion inventory changed')
    return board


def render(board):
    return f'''(** GENERATED by check_champion_census_next.py. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement StatementTr Spec Bounds Census Bootstrap
  Closeout BoardManifest ChampionCensusNext.
Import ListNotations.
Definition recorded_scoreN : N := {board['state_bound']}%N.
Lemma recorded_score_exact : recorded_scoreN = scoreN.
Proof. reflexivity. Qed.
Local Opaque scoreN previousN.
Definition rows : list N := [{PACKED}%N].
Definition board := champion_census_board.
Lemma inventory_checked : manifest_check rows board = true.
Proof. vm_compute. reflexivity. Qed.
Theorem inventory_exact : manifest_board rows = board.
Proof. apply manifest_check_sound. exact inventory_checked. Qed.
Theorem sound : BoardSound scoreN scoreN board.
Proof. exact champion_census_board_sound. Qed.
Theorem recorded_bounds : BoardSound recorded_scoreN recorded_scoreN board.
Proof. rewrite recorded_score_exact. exact sound. Qed.
Theorem was_pending : forall family, In family board -> bootstrap_pending family.
Proof. exact champion_census_board_pending. Qed.
Theorem exact_completions : forall complete,
  TM_le canonical_champion complete -> NonHalt complete /\\
  (QHBound score complete /\\ AttainsSt complete score) /\\
  (QHBoundTr score complete /\\ AttainsTr complete score).
Proof. exact canonical_champion_completion_exact. Qed.
Print Assumptions inventory_exact.
Print Assumptions sound.
Print Assumptions was_pending.
Print Assumptions exact_completions.
'''


def comparisons():
    """Read-only cohort comparisons; no subtraction from frozen reports."""
    final = json.loads((ROOT/'research/campaign-final-summary.json').read_text())
    result = {}
    for scope in ('both', 'state'):
        recorded = final['initial_search_cohort'][scope]
        path = ROOT/recorded['unproved_path']
        if not path.is_file():
            result[scope] = dict(available=False)
            continue
        rows = path.read_text().splitlines()
        if digest(path) != recorded['unproved_sha256'] or len(rows) != recorded['unproved']:
            raise ValueError('Historical residual differs from its frozen audited summary')
        result[scope] = dict(available=True, artifact=artifact(path), rows=len(rows),
                             champion_present=CHAMPION in rows)
    queue = ROOT/'build/campaign-next/queued.tsv'
    if queue.is_file():
        scheduling = json.loads((ROOT/'research/campaign-next-summary.json').read_text())
        if digest(queue) != scheduling['outputs']['queued.tsv']['sha256']:
            raise ValueError('Candidate queue differs from its frozen scheduling summary')
        with queue.open(newline='') as f:
            rows = list(csv.DictReader(f, delimiter='\t'))
        result['candidate_queue'] = dict(artifact=artifact(queue), rows=len(rows),
                                        champion_present=any(CHAMPION in row.values() for row in rows))
    result['historical_summary'] = artifact(ROOT/'research/campaign-final-summary.json')
    result['historical_board_count'] = len(final['source_rows'])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, default=ROOT/'build/next-champion')
    parser.add_argument('--report', type=Path, default=ROOT/'research/next-champion-summary.json')
    parser.add_argument('--audit-cache', type=Path, action='append', default=[])
    parser.add_argument('--recursive', action='store_true', help='Freshly audit all dependencies (may be expensive)')
    parser.add_argument('--timeout', type=int, default=900)
    parser.add_argument('--memory-mib', type=int, default=1024)
    args = parser.parse_args()
    if not args.recursive and not args.audit_cache:
        parser.error('Supply exact-artifact --audit-cache receipts, or explicitly request --recursive')
    if args.memory_mib <= 0 or args.timeout <= 0:
        parser.error('Resource bounds must be positive')
    limit = args.memory_mib * 1024 * 1024
    resource.setrlimit(resource.RLIMIT_AS, (limit, limit))
    os.environ.setdefault('OCAMLRUNPARAM', 's=1M,i=1M,o=50,O=100')
    started = time.monotonic()
    board = validate_inputs()
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    source = output/'Inventory.v'
    source.write_text(render(board))
    protected = [ROOT/'research/campaign-final-input.json',
                 ROOT/'research/campaign-final-summary.json',
                 ROOT/'research/campaign-next-summary.json',
                 ROOT/'tools/check_campaign.py', ROOT/'tools/check_campaign_v2.py']
    inputs = [DESCRIPTOR, INVENTORY, THEORY, Path(__file__).resolve(),
              ROOT/'tools/kernel_audit_cache_v3.py', *protected]
    before = {rel(path): digest(path) for path in inputs}
    loadpaths = [(ROOT/'theories', 'BBB24'), (ROOT.parent/'small/theories', 'SmallBB'),
                 (output, NAMESPACE)]
    flags = [item for path, name in loadpaths for item in ('-Q', str(path), name)]
    runs = []
    assumptions = set()
    for target in (THEORY, source):
        _, log = fresh_paths(output, target.stem+'-compile')
        command = ['coqc', '-native-compiler', 'no', *flags, str(target)]
        t = time.monotonic()
        with log.open('w') as f:
            subprocess.run(command, stdout=f, stderr=subprocess.STDOUT,
                           check=True, timeout=args.timeout)
        assumptions.update(re.findall(r'^([\w.]+)\n\s+:', log.read_text(), re.M))
        runs.append(dict(command=command, log=artifact(log),
                         elapsed_seconds=round(time.monotonic()-t, 3)))
    if {name.rsplit('.', 1)[-1] for name in assumptions} != {'functional_extensionality_dep'}:
        raise ValueError('Unexpected theorem assumptions: '+repr(sorted(assumptions)))
    receipt, log = fresh_paths(output, 'kernel-audit')
    checked = audit([NAMESPACE+'.Inventory'], [source], loadpaths, receipt, log,
                    cache=args.audit_cache, recursive=args.recursive, timeout=args.timeout)
    after = {rel(path): digest(path) for path in inputs}
    if before != after:
        raise ValueError('Input or frozen campaign artifact changed during replay')
    report = dict(schema=1, result='passed', scope='standalone-exact-both-board',
                  machine=CHAMPION, source_machine='1RB2LA1RA1LB_0LB2RB3RB1LA',
                  transport='left/right reflection', rows=1,
                  state_bound=SCORE, instruction_bound=SCORE,
                  state_attained=True, instruction_attained=True,
                  all_completions=True, nonhalting=True, formal_pending_membership=True,
                  descriptor=artifact(DESCRIPTOR), inventory=artifact(INVENTORY),
                  theory=artifact(THEORY), generated_source=artifact(source),
                  theorem_module='BBB24.ChampionCensusNext',
                  wrapper_module=NAMESPACE+'.Inventory',
                  inputs=before, compilation=runs,
                  audit=dict(receipt=artifact(receipt), log=artifact(log), kind=checked['kind'],
                             checked_modules=checked['checked_modules'],
                             reused_modules=checked['reused_modules'],
                             dependency_count=len(checked['snapshot']['graph']),
                             elapsed_seconds=checked['elapsed_seconds']),
                  comparisons=comparisons(), historical_counts_changed=False,
                  resource_limits=dict(workers=1, memory_mib=args.memory_mib,
                                       command_timeout_seconds=args.timeout),
                  elapsed_seconds=round(time.monotonic()-started, 3),
                  assumptions=sorted(assumptions),
                  limitations='Standalone formal closeout; not incorporated into the frozen 113-board campaign. No global upper bound.')
    args.report.parent.mkdir(parents=True, exist_ok=True)
    temporary = args.report.with_suffix(args.report.suffix+'.tmp')
    temporary.write_text(json.dumps(report, indent=2, sort_keys=True)+'\n')
    temporary.replace(args.report)
    print(json.dumps(dict(result='passed', report=str(args.report), machine=CHAMPION,
                          rows=1, state_bound=SCORE, instruction_bound=SCORE,
                          audit_kind=checked['kind'])))


if __name__ == '__main__':
    main()
