"""Join the two remaining B3 partial roots using a marker family and exceptions.

The fourteen recurrent B3 choices use RightMarkerFamily; 0LB and 3LB use
independently checked affine/cycle proofs. The undefined choice remains explicit.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import time
from check_state_branches import ROOT,REPO,sha
from check_affine_wave import source_hashes
from check_late_cycles import cert_text
from generate_pipeline_examples import codes

BUILD=ROOT/'build/state-b3-branches'
INPUT=ROOT/'research/state-b3-branches-input.json'

def generate(data):
 cycles=['  (['+';'.join(map(str,codes(r['cycle_child'])))+'], '+cert_text(r['cycle'])+')' for r in data['rows']]
 roots=['  (machine_of_codes ['+';'.join(map(str,codes(r['machine'])))+'], '+str(r['anchor'])+')' for r in data['rows']]
 transitions=['mkTrans S'+str(v//4)+' '+('DR' if v//2%2 else 'DL')+' '+('StB' if v%2 else 'StA') for v in range(16) if v not in [1,13]]
 return r'''(** Generated by check_state_b3_joins.py. Original roots: STATE ONLY. *)
From Coq Require Import Arith List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout Pipeline
  StateOnlyCloseout StateBranchJoin CycleBatch RightMarkerFamily.
From BBB24AffineChildren.B3Parents Require Import Children.
Import ListNotations.
Definition cycle_rows : CycleRows := [
'''+ ';\n'.join(cycles)+r'''
].
Lemma cycles_checked : cycle_batch_check 4096%N 4096%N cycle_rows = true.
Proof. vm_compute; reflexivity. Qed.
Lemma cycles_state_sound : StateBoardSound (N.to_nat 4096%N) (cycle_board cycle_rows).
Proof.
  intros family Hin tm Hle.
  exact (proj1 (cycle_board_sound _ _ _ cycles_checked family Hin tm Hle)).
Qed.
Definition marker_transitions := ['''+';'.join(transitions)+r'''].
Lemma marker_transitions_checked : forallb mrf_check marker_transitions = true.
Proof. vm_compute; reflexivity. Qed.
Definition marker_board := flat_map (fun b2 => map (mrf_tm b2) marker_transitions) [S2;S3].
Lemma marker_state_sound : StateBoardSound (N.to_nat 4096%N) marker_board.
Proof.
  apply state_board_zero_weaken. intros family Hin tm Hle.
  apply in_flat_map in Hin as (b2 & _ & Hin).
  apply in_map_iff in Hin as (b3 & <- & Hin).
  pose proof marker_transitions_checked as H.
  apply forallb_forall with (x:=b3) in H; [|exact Hin].
  exact (mrf_completion_state b2 b3 H tm Hle).
Qed.
Definition child_boards : list (list TM) := [cycle_board cycle_rows;
  BBB24AffineChildren.B3Parents.Children.board; marker_board].
Definition child_board := concat child_boards.
Lemma child_board_state_sound : StateBoardSound (N.to_nat 4096%N) child_board.
Proof.
  apply state_boards_sound.
  apply Forall_cons; [exact cycles_state_sound|].
  apply Forall_cons; [exact BBB24AffineChildren.B3Parents.Children.state_small_sound|].
  apply Forall_cons; [exact marker_state_sound|].
  apply Forall_nil.
Qed.
Definition root_rows : list (TM*nat) := [
'''+ ';\n'.join(roots)+r'''
].
Lemma joined_checked : forallb (fun row =>
  state_branch_lookup_check 4096%N child_board (fst row) (snd row)) root_rows = true.
Proof. vm_compute; reflexivity. Qed.
Definition branch_state_board := map fst root_rows.
Lemma branch_state_board_small_sound : StateBoardSound (N.to_nat 4096%N) branch_state_board.
Proof.
  intros family Hin tm Hle.
  apply in_map_iff in Hin as ([root anchor] & <- & Hin).
  pose proof joined_checked as H.
  apply forallb_forall with (x:=(root,anchor)) in H; [|exact Hin].
  exact (state_branch_lookup_check_sound _ _ _ _ child_board_state_sound H tm Hle).
Qed.
Lemma branch_state_board_sound : StateBoardSound score branch_state_board.
Proof.
  eapply (state_board_N_weaken 4096%N scoreN).
  - vm_compute; discriminate.
  - exact branch_state_board_small_sound.
Qed.
Lemma pending_checked : forallb (pending_check 9 empty bootstrap) branch_state_board = true.
Proof. vm_compute; reflexivity. Qed.
Lemma branch_state_board_was_pending : forall family,
  In family branch_state_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound. pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_b3_branch_pending := remaining bootstrap_pending branch_state_board.
Theorem bootstrap_b3_branch_coverage : forall tm,
  QHBound score tm \/ bootstrap_b3_branch_pending tm.
Proof. exact (state_closeout_coverage _ _ _ bootstrap_state_coverage branch_state_board_sound). Qed.
Theorem b3_branch_families_discharged : forall family,
  In family branch_state_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ QHBound score tm /\ ~ bootstrap_b3_branch_pending tm.
Proof. exact (state_board_discharge _ _ branch_state_board_was_pending branch_state_board_sound). Qed.
Print Assumptions b3_branch_families_discharged.
'''

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--prepare',action='store_true')
 p.add_argument('--timeout',type=int,default=3600);a=p.parse_args();data=json.loads(INPUT.read_text());rows=data['rows']
 expected={'1LB2RA0RA2LA_3RB1RA3LA---','1LB2RA0RA2LA_3RB1RA2LA---'}
 if {r['machine'] for r in rows}!=expected or len(rows)!=2:raise ValueError('Unexpected roots')
 for row in rows:
  table=codes(row['machine']);table[7]=13
  if tuple(table)!=tuple(codes(row['cycle_child'])):raise ValueError('Wrong cycle exception')
  if not 0<=row['anchor']<4096:raise ValueError('Invalid anchor')
 BUILD.mkdir(parents=True,exist_ok=True);source=BUILD/'B3Parents.v';source.write_text(generate(data))
 members=BUILD/'machines.txt';members.write_text('\n'.join(r['machine'] for r in rows)+'\n')
 flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(ROOT/'build/affine-children'),'BBB24AffineChildren',
        '-Q',str(BUILD),'BBB24StateB3Branches'];module='BBB24StateB3Branches.B3Parents'
 commands=[(['coqc','-w','-abstract-large-number','-native-compiler','no',*flags,str(source)],'compile.log')]
 if not a.prepare:commands.append((['coqchk','-silent','-bytecode-compiler','yes',*flags,module],'coqchk.log'))
 start=time.monotonic()
 for cmd,log in commands:
  with (BUILD/log).open('w') as out:subprocess.run(['nice','-n','10',*cmd],cwd=REPO,stdout=out,stderr=subprocess.STDOUT,check=True,timeout=a.timeout)
 sources=source_hashes();todo=['StateBranchJoin','RightMarkerFamily','CycleBatch'];seen=set()
 while todo:
  name=todo.pop()
  if name in seen:continue
  seen.add(name);path=ROOT/'theories'/Path(*name.split('.')).with_suffix('.v');sources[str(path.relative_to(REPO))]=sha(path)
  for prefix,names in re.findall(r'From\s+(BBB24[\w.]*)\s+Require\s+(?:Import|Export)\s+([\w\s]+)\.',path.read_text()):
   todo.extend('.'.join(prefix.split('.')[1:]+[module]) for module in names.split())
 for tool in ['check_state_b3_joins.py','check_affine_children.py','check_late_cycles.py','check_state_branches.py']:
  sources['four/tools/'+tool]=sha(ROOT/'tools'/tool)
 sources['four/build/affine-children/B3Parents/Children.v']=sha(ROOT/'build/affine-children/B3Parents/Children.v')
 descriptor=dict(kind='state_only',module=module,board=module+'.branch_state_board',state_sound=module+'.branch_state_board_sound',
  state_small_sound=module+'.branch_state_board_small_sound',was_pending=module+'.branch_state_board_was_pending',
  state_discharge=module+'.b3_branch_families_discharged',state_coverage=module+'.bootstrap_b3_branch_coverage',state_bound=4096,
  members=str(members.relative_to(ROOT)),flags=['-Q','four/theories','BBB24','-Q','four/build/affine-children','BBB24AffineChildren',
    '-Q','four/build/state-b3-branches','BBB24StateB3Branches'])
 report=dict(status='queued_for_combined_audit' if a.prepare else 'recursive_coqchk_passed',scope='state_only',families=2,partial=2,concrete=0,
  defined_children=32,halting_choices=2,state_bound=4096,instruction_bound=None,state_census_linked=None if a.prepare else 2,descriptor=descriptor,
  input_sha256=sha(INPUT),affine_input_sha256=sha(ROOT/'research/state-b3-affine-children-input.json'),
  member_ids_sha256=sha(members),generated_source_sha256=sha(source),source_sha256=sources,
  proof_object_sha256={str(x.relative_to(ROOT)):sha(x) for x in [ROOT/'theories/RightMarkerFamily.vo',source.with_suffix('.vo')]},
  accounting='Two original partial families. Each has sixteen defined choices and a separate halting choice. No root NonHalt or instruction claim.',
  validation='Compiled cycle/affine exceptions, generic marker recurrence, branch prefixes and exact pending membership; '+('queued for combined recursive audit.' if a.prepare else 'recursive coqchk passed.'))
 dest=ROOT/'research'/('state-b3-branches-queued.json' if a.prepare else 'state-b3-branches-checked.json');text=json.dumps(report,indent=2)+'\n'
 if dest.exists() and dest.read_text()!=text:raise ValueError('Frozen B3 branch report differs')
 dest.write_text(text);print(json.dumps(dict(status=report['status'],families=2,seconds=round(time.monotonic()-start,2))))
if __name__=='__main__':main()
