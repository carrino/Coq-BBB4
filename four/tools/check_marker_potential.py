"""Compile the additional weighted-capacity marker class and link it to the state census.

Only the276 new-beyond-v2 rows are selected; selection is untrusted. Every table/mask pair
passes mp_batch_check, and the original family is checked in bootstrap_pending.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import time
from check_state_branches import ROOT,REPO,sha
from generate_pipeline_examples import codes
from marker_state_potential_profile import invariant_conditions

BUILD=ROOT/'build/marker-potential'
INPUT=ROOT/'research/state-marker-potential-profile.json'

def generate(rows):
 entries=['  (mkMPRow '+str(sum(v*17**i for i,v in enumerate(codes(r['machine']))))+'%N '+str(r['marker_mask'])+'%N '+' '.join(str(w)+'%N' for w in r['weights'][1:])+')' for r in rows]
 return r'''(** Generated by check_marker_potential.py. STATE ONLY. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Census Bootstrap Closeout
  StateOnlyCloseout MarkerPotential.
Import ListNotations.
Definition rows : list MPRow := [
'''+ ';\n'.join(entries)+r'''
].
Lemma checked : mp_batch_check rows = true.
Proof. vm_compute; reflexivity. Qed.
Definition marker_board := mp_board rows.
Lemma marker_board_zero_sound : StateBoardSound 0 marker_board.
Proof. exact (mp_batch_state_sound rows checked). Qed.
Lemma marker_board_sound : StateBoardSound score marker_board.
Proof. apply state_board_zero_weaken. exact marker_board_zero_sound. Qed.
Lemma marker_board_nonhalt : forall family, In family marker_board -> NonHalt family.
Proof. exact (mp_batch_nonhalt rows checked). Qed.
Lemma pending_checked : forallb (pending_check 9 empty bootstrap) marker_board = true.
Proof. vm_compute; reflexivity. Qed.
Lemma marker_board_was_pending : forall family,
  In family marker_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound. pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_marker_pending := remaining bootstrap_pending marker_board.
Theorem bootstrap_marker_state_coverage : forall tm,
  QHBound score tm \/ bootstrap_marker_pending tm.
Proof. exact (state_closeout_coverage _ _ _ bootstrap_state_coverage marker_board_sound). Qed.
Theorem marker_families_state_discharged : forall family,
  In family marker_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ QHBound score tm /\ ~ bootstrap_marker_pending tm.
Proof. exact (state_board_discharge _ _ marker_board_was_pending marker_board_sound). Qed.
Print Assumptions marker_families_state_discharged.
'''

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--prepare',action='store_true')
 p.add_argument('--timeout',type=int,default=3600);a=p.parse_args();data=json.loads(INPUT.read_text());rows=[row for row in data['rows'] if not row['covered_by_v2']]
 machines=[r['machine'] for r in rows]
 if not rows or len(machines)!=len(set(machines)):raise ValueError('Empty or duplicated input')
 for row in rows:
  table=codes(row['machine']);weights=row['weights']
  if len(weights)!=4 or weights[0]!=0 or any(type(w) is not int or not 0<=w<=3 for w in weights):raise ValueError('Invalid weight witness')
  if not invariant_conditions(table,row['marker_mask']):raise ValueError('Measured invariant check differs')
  if not all(v%2==0 or weights[v//4]-weights[s] <= (1 if v//2%2 else -1) for s,v in enumerate(table[4:])):raise ValueError('Invalid capacity inequality')
 BUILD.mkdir(parents=True,exist_ok=True);source=BUILD/'PotentialBoard.v';source.write_text(generate(rows))
 members=BUILD/'machines.txt';members.write_text('\n'.join(machines)+'\n')
 flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(BUILD),'BBB24MarkerPotential'];module='BBB24MarkerPotential.PotentialBoard'
 commands=[(['coqc','-native-compiler','no',*flags,str(source)],'compile.log')]
 if not a.prepare:commands.append((['coqchk','-silent','-bytecode-compiler','yes',*flags,module],'coqchk.log'))
 start=time.monotonic()
 for cmd,log in commands:
  with (BUILD/log).open('w') as out:subprocess.run(['nice','-n','10',*cmd],cwd=REPO,stdout=out,stderr=subprocess.STDOUT,check=True,timeout=a.timeout)
 sources={};todo=['MarkerPotential','StateOnlyCloseout'];seen=set()
 while todo:
  name=todo.pop()
  if name in seen:continue
  seen.add(name);path=ROOT/'theories'/Path(*name.split('.')).with_suffix('.v');sources[str(path.relative_to(REPO))]=sha(path)
  for prefix,names in re.findall(r'From\s+(BBB24[\w.]*)\s+Require\s+(?:Import|Export)\s+([\w\s]+)\.',path.read_text()):
   todo.extend('.'.join(prefix.split('.')[1:]+[module]) for module in names.split())
 for tool in ['check_marker_potential.py','marker_state_potential_profile.py','generate_pipeline_examples.py','check_state_branches.py']:
  sources['four/tools/'+tool]=sha(ROOT/'tools'/tool)
 descriptor=dict(kind='state_only',module=module,board=module+'.marker_board',state_sound=module+'.marker_board_sound',
  state_small_sound=module+'.marker_board_zero_sound',nonhalt=module+'.marker_board_nonhalt',was_pending=module+'.marker_board_was_pending',
  state_discharge=module+'.marker_families_state_discharged',state_coverage=module+'.bootstrap_marker_state_coverage',state_bound=0,
  members=str(members.relative_to(ROOT)),flags=['-Q','four/theories','BBB24','-Q','four/build/marker-potential','BBB24MarkerPotential'])
 report=dict(status='queued_for_combined_audit' if a.prepare else 'recursive_coqchk_passed',scope='state_only',families=len(rows),
  partial=0,concrete=len(rows),state_bound=0,instruction_bound=None,state_census_linked=None if a.prepare else len(rows),descriptor=descriptor,
  input_sha256=sha(INPUT),member_ids_sha256=sha(members),generated_source_sha256=sha(source),source_sha256=sources,
  proof_object_sha256={str(x.relative_to(ROOT)):sha(x) for x in [ROOT/'theories/MarkerPotential.vo',source.with_suffix('.vo')]},
  accounting='Original families and all completions. The marker theorem asserts state recurrence only; no instruction claim.',
  validation='Compiled generic marker/ranking checks and exact original pending membership; '+('queued for combined recursive audit.' if a.prepare else 'recursive coqchk passed.'))
 dest=ROOT/'research'/('marker-potential-queued.json' if a.prepare else 'marker-potential-checked.json');text=json.dumps(report,indent=2)+'\n'
 if dest.exists() and dest.read_text()!=text:raise ValueError('Frozen marker-potential report differs')
 dest.write_text(text);print(json.dumps(dict(status=report['status'],families=len(rows),seconds=round(time.monotonic()-start,2))))
if __name__=='__main__':main()
