"""Kernel-check state-only alphabet quotients and their census membership.

The resulting board proves only state bounds. It never supplies a both-bound
BoardSound theorem, because the quotient merges instruction identities.
"""
import argparse
import json
from pathlib import Path
import subprocess
import time

from check_alphabet23 import sha, source_tree_digest, SOURCES
from alphabet_quotients import compatible, survives
from generate_pipeline_examples import codes

ROOT=Path(__file__).resolve().parents[1]
REPO=ROOT.parent
BUILD=ROOT/'build/state-alphabet-quotient'
INPUT=ROOT/'research/state-alphabet-quotient-search.json'
REPORT=ROOT/'research/state-alphabet-quotient-checked.json'


def generate(rows):
    entries=['  (['+';'.join(map(str,codes(r['machine'])))+'], ['+
             ';'.join(map(str,r['partition']))+'])' for r in rows]
    return r'''(** Generated by check_state_quotients.py. STATE ONLY. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Census Bootstrap Closeout
  StateOnlyCloseout AlphabetQuotientState.
Import ListNotations.
Definition rows : StateQuotientRows := [
'''+ ';\n'.join(entries)+r'''
].
Lemma checked : state_quotient_batch_check rows = true.
Proof. vm_compute. reflexivity. Qed.
Definition quotient_board := state_quotient_board rows.
Lemma quotient_board_small_sound : StateBoardSound 59 quotient_board.
Proof. exact (state_quotient_board_small_sound rows checked). Qed.
Lemma quotient_board_sound : StateBoardSound score quotient_board.
Proof. exact (state_quotient_board_sound rows checked). Qed.
Lemma quotient_board_nonhalt : forall family, In family quotient_board -> NonHalt family.
Proof. exact (state_quotient_board_nonhalt rows checked). Qed.
Lemma pending_checked : forallb (pending_check 9 empty bootstrap) quotient_board = true.
Proof. vm_compute. reflexivity. Qed.
Lemma quotient_board_was_pending : forall family,
  In family quotient_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound.
  pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_quotient_pending := remaining bootstrap_pending quotient_board.
Theorem bootstrap_quotient_state_coverage : forall tm,
  QHBound score tm \/ bootstrap_quotient_pending tm.
Proof.
  exact (state_closeout_coverage _ _ _ bootstrap_state_coverage quotient_board_sound).
Qed.
Theorem quotient_families_state_discharged : forall family,
  In family quotient_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ QHBound score tm /\ ~ bootstrap_quotient_pending tm.
Proof. exact (state_board_discharge _ _ quotient_board_was_pending quotient_board_sound). Qed.
Print Assumptions quotient_families_state_discharged.
'''


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepare',action='store_true')
    parser.add_argument('--refresh',action='store_true')
    parser.add_argument('--timeout',type=int,default=3600)
    args=parser.parse_args()
    data=json.loads(INPUT.read_text());rows=data['rows'];machines=[r['machine'] for r in rows]
    if not rows or len(machines)!=len(set(machines)):
        raise ValueError('Empty or repeated quotient family')
    for row in rows:
        partition=row['partition'];table=codes(row['machine'])
        if len(partition)!=4 or partition[0]!=0 or any(type(x) is not int or not 0<=x<3 for x in partition):
            raise ValueError('Invalid quotient partition')
        if not compatible(table,partition) or not survives(table):
            raise ValueError('Quotient candidate does not satisfy the measured conditions')
    BUILD.mkdir(parents=True,exist_ok=True)
    source=BUILD/'QuotientBoard.v';source.write_text(generate(rows))
    members=BUILD/'machines.txt';members.write_text('\n'.join(machines)+'\n')
    flags=['-Q',str(REPO/'small/theories'),'SmallBB',
           '-Q',str(ROOT/'theories'),'BBB24','-Q',str(BUILD),'BBB24StateQuotient']
    namespace='BBB24StateQuotient.QuotientBoard'
    commands=[
        (['coqc','-native-compiler','no',*flags,str(ROOT/'theories/AlphabetQuotientState.v')],'transport.log'),
        (['coqc','-native-compiler','no',*flags,str(source)],'compile.log'),
    ]
    if not args.prepare:
        commands.append((['coqchk','-silent','-bytecode-compiler','yes',*flags,namespace],'coqchk.log'))
    start=time.monotonic()
    for command,log in commands:
        with (BUILD/log).open('w') as output:
            subprocess.run(['nice','-n','10',*command],cwd=REPO,stdout=output,stderr=subprocess.STDOUT,
                           check=True,timeout=args.timeout)
    report=dict(status='queued_for_combined_audit' if args.prepare else 'recursive_coqchk_passed',
        scope='state_only',families=len(rows),concrete=sum('---' not in m for m in machines),
        partial=sum('---' in m for m in machines),state_census_linked=None if args.prepare else len(rows),state_bound=59,
        instruction_bound=None,
        descriptor=dict(kind='state_only',module=namespace,board=namespace+'.quotient_board',
            state_sound=namespace+'.quotient_board_sound',state_small_sound=namespace+'.quotient_board_small_sound',
            nonhalt=namespace+'.quotient_board_nonhalt',was_pending=namespace+'.quotient_board_was_pending',
            state_discharge=namespace+'.quotient_families_state_discharged',
            state_coverage=namespace+'.bootstrap_quotient_state_coverage',state_bound=59,
            members=str(members.relative_to(ROOT)),
            flags=['-Q','small/theories','SmallBB','-Q','four/theories','BBB24',
                   '-Q','four/build/state-alphabet-quotient','BBB24StateQuotient']),
        input_sha256=sha(INPUT),member_ids_sha256=sha(members),generated_source_sha256=sha(source),
        source_sha256={p:sha(REPO/p) for p in SOURCES+[
            'four/theories/AlphabetMask.v','four/theories/AlphabetQuotientState.v',
            'four/theories/StateOnlyCloseout.v','four/tools/alphabet_quotients.py',
            'four/tools/check_state_quotients.py']},
        small_theories_source_tree_sha256=source_tree_digest(REPO/'small/theories'),
        proof_object_sha256={str(p.relative_to(ROOT)):sha(p) for p in
            [ROOT/'theories/AlphabetQuotientState.vo',BUILD/'QuotientBoard.vo']},
        validation=('Compiled quotient coherence,67-step survival and actual bootstrap membership checks; awaiting named combined recursive audit.' if args.prepare else
            'Compiled quotient coherence,67-step survival and actual bootstrap membership checks; recursive coqchk.'),
        accounting='Original completion families. Alphabet classes merge instructions; only the state residual is refined.')
    text=json.dumps(report,indent=2)+'\n'
    destination=ROOT/'research/state-alphabet-quotient-queued.json' if args.prepare else REPORT
    if args.refresh or not destination.exists():destination.write_text(text)
    elif destination.read_text()!=text:raise ValueError('State quotient evidence changed')
    print(json.dumps({'state_compiled_families':len(rows),'status':report['status'],
        'descriptor_report':str(destination.relative_to(ROOT)), 'seconds':round(time.monotonic()-start,2)}))


if __name__=='__main__':main()
