"""Close families whose six reachable entries use a closed three-symbol alphabet.

The checker transfers the already proved BBB(2,3) upper bounds (59,67).
--select INPUT freezes the selected rows; rerunning without it reproduces the
proof bundle and recursive kernel audit. Counts refer to original families.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import time

from generate_pipeline_examples import codes

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
BUILD = ROOT / 'build/alphabet23'
BUNDLE = ROOT / 'research/alphabet23-families.json'
REPORT = ROOT / 'research/alphabet23-checked.json'
SOURCES = [
    'four/tools/check_alphabet23.py', 'four/tools/generate_pipeline_examples.py',
    'four/theories/AlphabetReduction.v', 'four/theories/Alphabet23.v',
    'four/theories/Statement.v', 'four/theories/StatementTr.v',
    'four/theories/Spec.v', 'four/theories/Bounds.v', 'four/theories/Census.v',
    'four/theories/Bootstrap.v', 'four/theories/Closeout.v',
    'four/theories/CertifiedBoard.v', 'four/theories/Pipeline.v',
]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_tree_digest(directory):
    entries = [f'{p.relative_to(REPO)}\0{sha(p)}\n'
               for p in sorted(directory.rglob('*.v'))]
    return hashlib.sha256(''.join(entries).encode()).hexdigest()


def closed(machine, omitted):
    table = codes(machine)
    return all(table[4*q+a] < 16 and table[4*q+a]//4 != omitted
               for q in range(2) for a in range(4) if a != omitted)


def select(source):
    machines = source.read_text().splitlines()
    if len(machines) != len(set(machines)):
        raise ValueError('Repeated original input family')
    rows = []
    for machine in machines:
        codes(machine)
        for omitted in (3, 2):
            if closed(machine, omitted):
                rows.append({'machine': machine, 'unused_symbol': omitted})
                break
    return dict(input_families=len(machines), input_sha256=sha(source), rows=rows)


def generate(rows):
    entries = ['  ([' + ';'.join(map(str, codes(r['machine']))) + '], ' +
               str(r['unused_symbol'] == 2).lower() + ')' for r in rows]
    return r'''(** Generated by check_alphabet23.py. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout
  CertifiedBoard Pipeline AlphabetReduction Alphabet23.
Import ListNotations.
Definition rows : AlphabetRows := [
''' + ';\n'.join(entries) + r'''
].
Lemma checked : alphabet_batch_check rows = true.
Proof. vm_compute. reflexivity. Qed.
Definition closed_alphabet_board := alphabet_board rows.
Lemma closed_alphabet_board_small_sound : BoardSound 59 67 closed_alphabet_board.
Proof. exact (alphabet_board_small_sound rows checked). Qed.
Lemma closed_alphabet_board_sound : BoardSound scoreN scoreN closed_alphabet_board.
Proof. exact (alphabet_board_sound rows checked). Qed.
Lemma closed_alphabet_board_nonhalt : forall family,
  In family closed_alphabet_board -> NonHalt family.
Proof. exact (alphabet_board_nonhalt rows checked). Qed.
Lemma pending_checked :
  forallb (pending_check 9 empty bootstrap) closed_alphabet_board = true.
Proof. vm_compute. reflexivity. Qed.
Lemma closed_alphabet_board_was_pending : forall family,
  In family closed_alphabet_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound.
  pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_alphabet_pending := remaining bootstrap_pending closed_alphabet_board.
Theorem bootstrap_alphabet_coverage : forall tm,
  Bounds scoreN scoreN tm \/ bootstrap_alphabet_pending tm.
Proof. exact (closeout_coverage _ _ _ _ bootstrap_coverage closed_alphabet_board_sound). Qed.
Theorem alphabet_families_discharged : forall family,
  In family closed_alphabet_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ Bounds scoreN scoreN tm /\ ~ bootstrap_alphabet_pending tm.
Proof.
  exact (board_families_discharged _ _ _ _ _
    closed_alphabet_board_was_pending closed_alphabet_board_sound).
Qed.
Print Assumptions alphabet_families_discharged.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--select', type=Path)
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--timeout', type=int, default=3600)
    args = parser.parse_args()
    if args.select:
        BUNDLE.write_text(json.dumps(select(args.select), separators=(',', ':')) + '\n')
    data = json.loads(BUNDLE.read_text())
    rows = data['rows']
    machines = [r['machine'] for r in rows]
    if not rows or len(machines) != len(set(machines)):
        raise ValueError('Empty or repeated proof family')
    for row in rows:
        if row['unused_symbol'] not in (2, 3) or not closed(row['machine'], row['unused_symbol']):
            raise ValueError('Invalid claimed closed alphabet')
    BUILD.mkdir(parents=True, exist_ok=True)
    source = BUILD / 'AlphabetBoard.v'
    source.write_text(generate(rows))
    members = BUILD / 'machines.txt'
    members.write_text('\n'.join(machines) + '\n')
    flags = ['-Q', str(REPO/'small/theories'), 'SmallBB',
             '-Q', str(ROOT/'theories'), 'BBB24', '-Q', str(BUILD), 'BBB24Alphabet']
    namespace = 'BBB24Alphabet.AlphabetBoard'
    start = time.monotonic()
    commands = [
        (['coqc', '-native-compiler', 'no', *flags, str(ROOT/'theories/AlphabetReduction.v')], 'transport.log'),
        (['coqc', '-native-compiler', 'no', *flags, str(ROOT/'theories/Alphabet23.v')], 'theorem.log'),
        (['coqc', '-native-compiler', 'no', *flags, str(source)], 'compile.log'),
        (['coqchk', '-silent', '-bytecode-compiler', 'yes', *flags, namespace], 'coqchk.log'),
    ]
    for command, log in commands:
        with (BUILD/log).open('w') as output:
            subprocess.run(['nice', '-n', '10', *command], cwd=REPO, stdout=output, stderr=subprocess.STDOUT,
                           check=True, timeout=args.timeout)
    report = dict(
        families=len(rows), concrete=sum('---' not in m for m in machines),
        partial=sum('---' in m for m in machines), census_linked=len(rows),
        state_bound=59, instruction_bound=67,
        descriptor=dict(module=namespace,
            board=namespace+'.closed_alphabet_board',
            sound=namespace+'.closed_alphabet_board_sound',
            small_sound=namespace+'.closed_alphabet_board_small_sound',
            nonhalt=namespace+'.closed_alphabet_board_nonhalt',
            was_pending=namespace+'.closed_alphabet_board_was_pending',
            discharge=namespace+'.alphabet_families_discharged',
            coverage=namespace+'.bootstrap_alphabet_coverage',
            state_bound=59, instruction_bound=67,
            members=str(members.relative_to(ROOT)),
            flags=['-Q','small/theories','SmallBB','-Q','four/theories','BBB24',
                   '-Q','four/build/alphabet23','BBB24Alphabet']),
        loadpath_convention='Descriptor flags are relative to the repository root; subprocess paths are resolved from the running checkout.',
        bundle_sha256=sha(BUNDLE), member_ids_sha256=sha(members),
        generated_source_sha256=sha(source),
        source_sha256={p:sha(REPO/p) for p in SOURCES},
        small_theories_source_tree_sha256=source_tree_digest(REPO/'small/theories'),
        validation='Compiled transport and board; recursive coqchk includes SmallBB.Value23 and all dependencies.',
        accounting='Original input families, with every completion of unused-symbol entries covered. No raw-table or bootstrap-leaf cardinality claim.')
    serialized = json.dumps(report, indent=2)+'\n'
    if args.select or args.refresh or not REPORT.exists():
        REPORT.write_text(serialized)
    elif REPORT.read_text() != serialized:
        raise ValueError('Checked alphabet evidence changed')
    print(json.dumps({'checked_families':len(rows), 'seconds':round(time.monotonic()-start,2)}))


if __name__ == '__main__':
    main()
