"""Portably replay a frozen direct repeated-word board without changing research.

The default full replay populates four/build/next-rw with the exact frozen
BBB24NextRW sources and freshly compiled objects. It requires the core BBB24
library to be built. --check-only verifies inputs, inventory and regenerated
source bytes without writing or invoking Coq. --output-dir permits an isolated
physical build directory while retaining the frozen logical namespace.

Only direct rw_check reports are supported. Historical objects, receipts and
search logs are unnecessary: fresh recursive coqchk is mandatory. New timings,
logs and audit receipts are written under build/next-rw-replay only. Research
files and historical receipts are never written, temporarily replaced or restored.
"""
import argparse
import base64
from collections import Counter
import hashlib
import json
from pathlib import Path
import resource
import subprocess
import tempfile
import time
import zlib

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REPORT = ROOT / 'research/next-rw-batch32v1-report.json'
INPUT = 'research/next-rw-input.json'
NAMESPACE = 'BBB24NextRW'
OUTPUT = 'build/next-rw'
MEMORY_BYTES = 3 * 1024**3
FROZEN_TOOLS = {'tools/' + name for name in (
    'check_next_rw.py', 'check_closure_wave.py', 'generate_pipeline_examples.py',
    'check_state_repwl_batch.py', 'check_shadow_links.py', 'kernel_audit_cache.py',
    'next_rw_certificate.v', 'next_rw_producer.ml')}


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def text_digest(source):
    return hashlib.sha256(source.encode()).hexdigest()


def project_path(root, name):
    path = root / name
    if Path(name).is_absolute() or '..' in Path(name).parts:
        raise ValueError('Noncanonical project path: ' + name)
    return path


def checked_pins(root, pins):
    for name, expected in pins.items():
        path = project_path(root, name)
        if not path.is_file() or digest(path) != expected:
            raise ValueError('Frozen input/source pin differs: ' + name)


def unpack_json(path):
    data = json.loads(path.read_text())
    if data.get('encoding') == 'zlib-base64':
        raw = zlib.decompress(base64.b64decode(data['data'], validate=True))
        if hashlib.sha256(raw).hexdigest() != data['uncompressed_sha256']:
            raise ValueError('Compressed input hash mismatch')
        data = json.loads(raw)
    return data


def prepare_document(frozen, root=ROOT):
    """Read and validate frozen data; return generated bytes without any writes."""
    if frozen.get('method') != 'direct rw_check':
        raise ValueError('Unsupported replay method: only direct rw_check reports are supported')
    descriptor = frozen['board_descriptor']
    module = descriptor['module']
    if not module.startswith(NAMESPACE + '.') or module.count('.') != 1:
        raise ValueError('Unsupported frozen logical namespace')
    aggregate_name = module.split('.')[1]
    if not aggregate_name.isascii() or not aggregate_name.isidentifier():
        raise ValueError('Invalid aggregate module name')
    if (descriptor['load_paths'] != [{'path': OUTPUT, 'namespace': NAMESPACE}]
        or descriptor['scope'] != 'both'
        or descriptor['state_bound'] != 4096 or descriptor['instruction_bound'] != 4096
        or any(descriptor[name] != name for name in
               ('board', 'sound', 'small_sound', 'was_pending'))
        or frozen['inventory_theorem'] != module + '.inventory_exact'
        or frozen['discharge_theorem'] != module + '.discharged'):
        raise ValueError('Frozen board descriptor or theorem scope differs')
    inventories = descriptor['inventories']
    if (len(inventories) != 1 or inventories[0]['format'] != 'columns'
        or inventories[0].get('order', 'input') != 'input'):
        raise ValueError('Unsupported exact inventory encoding/order')
    inventory_name = inventories[0]['path']
    if not inventory_name.startswith('research/next-rw-'):
        raise ValueError('Unexpected frozen inventory path')
    inputs = {INPUT: frozen['queue_input_sha256'],
              inventory_name: frozen['board_input_sha256']}
    checked_pins(root, inputs)
    queue = unpack_json(project_path(root, INPUT))
    inventory = unpack_json(project_path(root, inventory_name))
    provenance = queue['source_sha256']
    summary_name = 'research/campaign-next-summary.json'
    checked_pins(root, {summary_name: provenance[summary_name]})
    summary = json.loads(project_path(root, summary_name).read_text())
    # queued.tsv is an ignored historical scheduling log. Its recorded identity
    # is checked against the pinned summary, but replay never requires its bytes.
    queue_log = summary['outputs']['queued.tsv']
    if provenance.get(queue_log['path']) != queue_log['sha256']:
        raise ValueError('Frozen scheduling-log provenance differs')
    tracked_provenance = {name: value for name, value in provenance.items()
                          if name != queue_log['path']}
    checked_pins(root, tracked_provenance)
    generated_pins = frozen['generated_sha256']
    static_pins = {name: value for name, value in frozen['source_sha256'].items()
                   if name not in generated_pins}
    if not FROZEN_TOOLS <= static_pins.keys():
        raise ValueError('Frozen source pins omit a replay implementation dependency')
    if any(name.startswith('build/') for name in static_pins):
        raise ValueError('Unsupported generated dependency outside the direct board')
    checked_pins(root, static_pins)
    # Import frozen generators only after their implementation pins have passed.
    import check_closure_wave as generator
    from check_state_repwl_batch import pack

    if inventory['columns'] != generator.FIELDS:
        raise ValueError('Frozen inventory columns differ')
    raw_rows = inventory['rows']
    if any(not isinstance(row, list) or len(row) != len(generator.FIELDS) for row in raw_rows):
        raise ValueError('Malformed frozen inventory row')
    rows = [dict(zip(generator.FIELDS, row)) for row in raw_rows]
    pool = {row['machine']: row for row in queue['rows']}
    count = len(rows)
    if (not count or len(pool) != len(queue['rows']) or len(pool) != queue['selected_rows']
        or len({row['machine'] for row in rows}) != count
        or count != descriptor['rows'] or count != frozen['checked_families']):
        raise ValueError('Frozen accepted inventory/count differs')
    for row in rows:
        generator.validate_row(row)
        if (row['mode'] != 'rw' or row['bound'] != 4096
            or row['machine'] not in pool
            or row != {key: pool[row['machine']][key] for key in generator.FIELDS}):
            raise ValueError('Accepted row differs from the frozen compact queue')
    attempts = frozen['attempts']
    if (any(row['status'] not in {'compiled', 'coq_failure', 'coq_timeout'} for row in attempts)
        or len(attempts) != frozen['attempted_rows']
        or dict(Counter(row['status'] for row in attempts)) != frozen['attempt_counts']
        or [row['machine'] for row in attempts if row['status'] == 'compiled']
           != [row['machine'] for row in rows]
        or [row['machine'] for row in attempts]
           != [row['machine'] for row in queue['rows'][:len(attempts)]]):
        raise ValueError('Frozen accepted inventory differs from the attempt ledger')
    if (sum(pool[row['machine']]['state_already_checked'] == 'no' for row in rows)
        != frozen['new_state_families']
        or frozen['remaining_rw_obligations'] != len(pool) - count
        or frozen['unattempted_rows'] != len(pool) - len(attempts)):
        raise ValueError('Frozen residual accounting differs')
    modules = ['DirectRow' + hashlib.sha256(row['machine'].encode()).hexdigest()[:16]
               for row in rows]
    if len(set(modules)) != count:
        raise ValueError('Generated module name collision')
    sources = {OUTPUT + '/' + name + '.v': generator.shard_source([row])
               for name, row in zip(modules, rows)}
    aggregate = generator.aggregate_source(modules, NAMESPACE, 4096, count)
    packed = '[' + ';'.join(str(pack(row['machine'])) + '%N' for row in rows) + ']'
    aggregate += ('\nFrom BBB24 Require Import BoardManifest.\nDefinition inventory : list N := '
                  + packed + '.\nLemma inventory_checked : manifest_check inventory board = true.\n'
                  'Proof. vm_compute. reflexivity. Qed.\nTheorem inventory_exact : '
                  'manifest_board inventory = board.\nProof. apply manifest_check_sound. '
                  'exact inventory_checked. Qed.\nPrint Assumptions inventory_exact.\n')
    sources[OUTPUT + '/' + aggregate_name + '.v'] = aggregate
    if set(sources) != set(generated_pins):
        raise ValueError('Frozen generated-source inventory differs')
    for name, source in sources.items():
        if (text_digest(source) != generated_pins[name]
            or generated_pins[name] != frozen['source_sha256'].get(name)):
            raise ValueError('Regenerated frozen source pin differs: ' + name)
    return {'frozen': frozen, 'root': root, 'sources': sources, 'module': module,
            'output': root / OUTPUT, 'count': count,
            'protected': {**inputs, **tracked_provenance, **static_pins}}


def prepare(reference_path):
    reference_path = reference_path.resolve()
    plan = prepare_document(json.loads(reference_path.read_text()))
    plan.update(reference=reference_path, reference_sha256=digest(reference_path))
    return plan


def limit_child():
    resource.setrlimit(resource.RLIMIT_AS, (MEMORY_BYTES, MEMORY_BYTES))


def replay(plan, output, timeout, audit_timeout):
    """Compile and recursively audit; never call the historical report writer."""
    output = output.resolve()
    output.relative_to((ROOT / 'build').resolve())
    mapped = [(output / Path(name).name, source) for name, source in plan['sources'].items()]
    for path, source in mapped:
        if path.exists() and path.read_text() != source:
            raise ValueError('Existing generated source differs: ' + str(path))
    output.mkdir(parents=True, exist_ok=True)
    runtime_root = ROOT / 'build/next-rw-replay'
    runtime_root.mkdir(parents=True, exist_ok=True)
    run_dir = Path(tempfile.mkdtemp(prefix=plan['module'].split('.')[-1] + '-', dir=runtime_root))
    evidence = {'status': 'running', 'frozen_report': str(plan['reference']),
                'frozen_report_sha256': plan['reference_sha256'],
                'adapter_sha256': digest(Path(__file__)), 'output': str(output),
                'module': plan['module'], 'accepted_rows': plan['count'],
                'historical_object_bytes_compared': False,
                'resources': {'workers': 1, 'address_space_bytes': MEMORY_BYTES,
                              'compile_timeout_seconds': timeout,
                              'audit_timeout_seconds': audit_timeout}, 'compilation': []}
    flags = ['-Q', str(ROOT / 'theories'), 'BBB24', '-Q', str(output), NAMESPACE]
    try:
        for path, source in mapped:
            if not path.exists():
                path.write_text(source)
            command = ['coqc', '-w', '-abstract-large-number', '-native-compiler', 'no',
                       *flags, str(path)]
            log = run_dir / (path.stem + '.log')
            entry = {'module': path.stem, 'command': command, 'status': 'running'}
            evidence['compilation'].append(entry)
            start = time.monotonic()
            try:
                with log.open('w') as stream:
                    subprocess.run(command, cwd=ROOT.parent, stdout=stream,
                                   stderr=subprocess.STDOUT, check=True,
                                   timeout=timeout, preexec_fn=limit_child)
                entry['status'] = 'compiled'
            except subprocess.TimeoutExpired:
                entry['status'] = 'timeout'
                raise
            except subprocess.CalledProcessError:
                entry['status'] = 'failed'
                raise
            finally:
                entry['seconds'] = round(time.monotonic() - start, 3)
                entry['log_sha256'] = digest(log)
            print('Freshly compiled ' + path.stem, flush=True)
        from kernel_audit_cache import audit
        aggregate_path = mapped[-1][0]
        receipt, audit_log = run_dir / 'kernel-audit.json', run_dir / 'kernel-audit.log'
        previous_limit = resource.getrlimit(resource.RLIMIT_AS)
        resource.setrlimit(resource.RLIMIT_AS, (MEMORY_BYTES, previous_limit[1]))
        try:
            audit([plan['module']], [aggregate_path],
                  [(ROOT / 'theories', 'BBB24'), (output, NAMESPACE)],
                  receipt, audit_log, recursive=True, timeout=audit_timeout)
        finally:
            resource.setrlimit(resource.RLIMIT_AS, previous_limit)
        checked_pins(ROOT, plan['protected'])
        if digest(plan['reference']) != plan['reference_sha256']:
            raise ValueError('Frozen report changed during replay')
        if digest(Path(__file__)) != evidence['adapter_sha256']:
            raise ValueError('Replay adapter changed during replay')
        for path, source in mapped:
            if digest(path) != text_digest(source):
                raise ValueError('Generated source changed during replay')
        evidence.update(status='passed', published_evidence_unchanged=True,
                        exact_inventory_and_pending_membership_audited=True,
                        audit_receipt=str(receipt), audit_receipt_sha256=digest(receipt),
                        audit_log_sha256=digest(audit_log),
                        object_sha256={str(path.with_suffix('.vo')): digest(path.with_suffix('.vo'))
                                       for path, _ in mapped})
    except Exception as error:
        evidence.update(status='failed', error_type=type(error).__name__, error=str(error))
        raise
    finally:
        (run_dir / 'runtime.json').write_text(json.dumps(evidence, indent=2, sort_keys=True) + '\n')
        print('Runtime evidence: ' + str(run_dir / 'runtime.json'), flush=True)
    print(f'{plan["count"]} families freshly audited; frozen research evidence unchanged.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report', type=Path, default=DEFAULT_REPORT)
    parser.add_argument('--check-only', '--preflight', action='store_true',
                        help='Read-only validation; do not compile or audit')
    parser.add_argument('--output-dir', type=Path,
                        help='Optional physical build directory; logical namespace remains BBB24NextRW')
    parser.add_argument('--timeout', type=int)
    parser.add_argument('--audit-timeout', type=int)
    args = parser.parse_args()
    plan = prepare(args.report)
    if args.check_only:
        print(f'Validated frozen inputs, exact {plan["count"]}-ID inventory and '
              f'{len(plan["sources"])} regenerated sources; no files written and no Coq run.')
        return
    timeout = args.timeout if args.timeout is not None else plan['frozen']['budgets']['coq_seconds_per_row']
    audit_timeout = (args.audit_timeout if args.audit_timeout is not None
                     else plan['frozen']['budgets']['audit_seconds'])
    if timeout <= 0 or audit_timeout <= 0:
        raise ValueError('Replay timeouts must be positive')
    replay(plan, args.output_dir or plan['output'], timeout, audit_timeout)


if __name__ == '__main__':
    main()
