"""Transcribe the advanced closure pilot into a kernel-checked census board."""
import argparse
import hashlib
import json
from pathlib import Path

from generate_pipeline_examples import codes

ROOT = Path(__file__).resolve().parents[1]


def generate(data):
    rows = data['rows']
    if not rows or len({r['machine'] for r in rows}) != len(rows):
        raise ValueError('Empty or duplicate pilot inventory')
    fields = ('machine', 'stage', 'mode', 'bound', 'size', 'anchor', 'fuel', 'extra', 'history')
    candidate_tsv = '\t'.join(fields) + '\n' + ''.join(
        '\t'.join(str(row[key]) for key in fields) + '\n' for row in rows)
    if hashlib.sha256(candidate_tsv.encode()).hexdigest() != data['candidate_tsv_sha256']:
        raise ValueError('Pilot inputs differ from the recorded candidate inventory')
    entries = []
    for row in rows:
        if row['bound'] != 4096:
            raise ValueError('This proof batch uses bound 4096')
        for field in ('size', 'anchor', 'fuel', 'extra', 'history'):
            if type(row[field]) is not int or row[field] < 0:
                raise ValueError(f'Invalid parameter: {field}')
        n, t, fuel, extra, k = (row[x] for x in ('size', 'anchor', 'fuel', 'extra', 'history'))
        if row['mode'] == 'finite':
            cert = f'Finite {n} {t} {fuel} {extra}'
        elif row['mode'] == 'hist':
            cert = f'History {k} {n} {t} {fuel} {extra}'
        elif row['mode'] == 'rw':
            cert = f'ExistingStage (RepeatedWord {n} {extra} {t} {fuel})'
        else:
            raise ValueError('Unknown checker mode')
        table = ';'.join(map(str, codes(row['machine'])))
        entries.append(f'  (* {row["machine"]} *)\n  ([{table}], {cert})')
    body = ';\n'.join(entries)
    return f'''(** GENERATED by four/tools/generate_advanced_examples.py.
    Both-bound replay of every advanced-pilot success. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout
  CertifiedBoard Pipeline PipelineExamples AdvancedPipeline.
Import ListNotations.

Definition advanced_rows : AdvancedBatch := [
{body}
].
Lemma advanced_rows_checked : advanced_batch_check 4096%N 4096%N advanced_rows = true.
Proof. vm_compute. reflexivity. Qed.
Example advanced_row_count : length advanced_rows = {len(rows)}.
Proof. reflexivity. Qed.

Definition advanced_pilot_board := advanced_board advanced_rows.
Lemma advanced_pilot_small_sound : BoardSound 4096%N 4096%N advanced_pilot_board.
Proof. apply advanced_board_sound; exact advanced_rows_checked. Qed.
Lemma advanced_pilot_nonhalt : forall family,
  In family advanced_pilot_board -> NonHalt family.
Proof. apply (advanced_board_nonhalt 4096%N 4096%N); exact advanced_rows_checked. Qed.
Lemma advanced_pilot_sound : BoardSound scoreN scoreN advanced_pilot_board.
Proof.
  intros family Hin tm Hle.
  eapply (bounds_weaken 4096%N 4096%N scoreN scoreN tm).
  - vm_compute. discriminate.
  - vm_compute. discriminate.
  - exact (advanced_pilot_small_sound family Hin tm Hle).
Qed.

Lemma advanced_pilot_pending_checked :
  forallb (pending_check 9 empty bootstrap) advanced_pilot_board = true.
Proof. vm_compute. reflexivity. Qed.
Lemma advanced_pilot_was_pending : forall family,
  In family advanced_pilot_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound.
  pose proof advanced_pilot_pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.

Definition bootstrap_advanced_pending := remaining bootstrap_pipeline_pending advanced_pilot_board.
Theorem bootstrap_advanced_coverage : forall tm,
  Bounds scoreN scoreN tm \\/ bootstrap_advanced_pending tm.
Proof.
  exact (closeout_coverage _ _ _ _ bootstrap_pipeline_coverage advanced_pilot_sound).
Qed.
Theorem advanced_families_discharged : forall family,
  In family advanced_pilot_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\\ Bounds scoreN scoreN tm /\\ ~ bootstrap_advanced_pending tm.
Proof.
  exact (board_families_discharged _ _ _ _ _
    advanced_pilot_was_pending advanced_pilot_sound).
Qed.

Print Assumptions advanced_families_discharged.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads((ROOT/'research/advanced-examples.json').read_text()))
    path = ROOT/'theories/AdvancedExamples.v'
    if args.check:
        if path.read_text() != output:
            raise SystemExit('Advanced examples differ; regenerate and audit them')
    else:
        path.write_text(output)
    print('Advanced examples reproduced; Coq checking is required.')


if __name__ == '__main__':
    main()
