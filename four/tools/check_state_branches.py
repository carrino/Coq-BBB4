"""Check state-only discharges for five reached partial-table branches.

Each root retains its halting completion; its sixteen defined children are
checked by OneStateReach. The root board does not assert NonHalt or an
instruction bound. --prepare queues the compiled board for a combined audit.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import time
from generate_pipeline_examples import codes

ROOT=Path(__file__).resolve().parents[1]
REPO=ROOT.parent
BUILD=ROOT/'build/state-branches'
INPUT=ROOT/'research/state-branch-families.json'
SOURCES=['four/theories/StateBranchCloseout.v','four/theories/StateOnlyCloseout.v',
 'four/theories/OneStateReach.v','four/theories/BranchCloseout.v','four/theories/Pipeline.v',
 'four/theories/Census.v','four/theories/Closeout.v','four/theories/Bootstrap.v',
 'four/theories/Bounds.v','four/theories/Spec.v','four/theories/Statement.v',
 'four/theories/CTape.v','four/theories/Mirror.v','four/theories/TotalCompletion.v',
 'four/tools/check_state_branches.py','four/tools/generate_pipeline_examples.py']

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def generate(rows):
 entries=['  (['+';'.join(map(str,codes(r['machine'])))+'], '+str(r['anchor'])+')' for r in rows]
 return r'''(** Generated by check_state_branches.py. STATE ONLY; roots may halt. *)
From Coq Require Import Arith List NArith Lia.
From BBB24 Require Import Statement Spec Census Bootstrap Closeout
  StateOnlyCloseout StateBranchCloseout.
Import ListNotations.
Definition rows : StateBranchRows := [
'''+ ';\n'.join(entries)+r'''
].
Lemma checked : state_branch_batch_check 8192 rows = true.
Proof. vm_compute; reflexivity. Qed.
Definition branch_state_board := state_branch_board rows.
Lemma branch_state_board_small_sound : StateBoardSound 8192 branch_state_board.
Proof. exact (state_branch_board_sound _ _ checked). Qed.
Lemma branch_state_board_sound : StateBoardSound score branch_state_board.
Proof.
  intros family Hin tm Hle q s Hquiet.
  pose proof (branch_state_board_small_sound family Hin tm Hle q s Hquiet) as Hsmall.
  assert (Hbig : (8192 <= scoreN)%N) by (vm_compute; discriminate).
  assert (Hnat : N.to_nat 8192 <= N.to_nat scoreN).
  { apply Nat.compare_le_iff. rewrite <- N2Nat.inj_compare. exact Hbig. }
  exact (Nat.le_trans _ _ _ Hsmall Hnat).
Qed.
Lemma pending_checked : forallb (pending_check 9 empty bootstrap) branch_state_board = true.
Proof. vm_compute; reflexivity. Qed.
Lemma branch_state_board_was_pending : forall family,
  In family branch_state_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound. pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_branch_state_pending := remaining bootstrap_pending branch_state_board.
Theorem bootstrap_branch_state_coverage : forall tm,
  QHBound score tm \/ bootstrap_branch_state_pending tm.
Proof. exact (state_closeout_coverage _ _ _ bootstrap_state_coverage branch_state_board_sound). Qed.
Theorem branch_families_state_discharged : forall family,
  In family branch_state_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ QHBound score tm /\ ~ bootstrap_branch_state_pending tm.
Proof. exact (state_board_discharge _ _ branch_state_board_was_pending branch_state_board_sound). Qed.
Print Assumptions branch_families_state_discharged.
'''

def main():
 p=argparse.ArgumentParser(description=__doc__)
 p.add_argument('--prepare',action='store_true');p.add_argument('--refresh',action='store_true')
 p.add_argument('--timeout',type=int,default=3600);a=p.parse_args()
 data=json.loads(INPUT.read_text());rows=data['rows'];machines=[r['machine'] for r in rows]
 if not rows or len(machines)!=len(set(machines)):raise ValueError('Empty or duplicated input')
 for row in rows:
  if row['machine'].count('---')!=1 or type(row['anchor']) is not int or not 0<=row['anchor']<8192:
   raise ValueError('Expected one reached undefined slot and bounded anchor')
  codes(row['machine'])
 BUILD.mkdir(parents=True,exist_ok=True)
 source=BUILD/'StateBranches.v';source.write_text(generate(rows))
 members=BUILD/'machines.txt';members.write_text('\n'.join(machines)+'\n')
 flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(BUILD),'BBB24StateBranches']
 module='BBB24StateBranches.StateBranches'
 commands=[(['coqc','-native-compiler','no',*flags,str(ROOT/'theories/StateBranchCloseout.v')],'bridge.log'),
           (['coqc','-w','-abstract-large-number','-native-compiler','no',*flags,str(source)],'compile.log')]
 if not a.prepare:commands.append((['coqchk','-silent','-bytecode-compiler','yes',*flags,module],'coqchk.log'))
 start=time.monotonic()
 for command,log in commands:
  with (BUILD/log).open('w') as out:
   subprocess.run(['nice','-n','10',*command],cwd=REPO,stdout=out,stderr=subprocess.STDOUT,check=True,timeout=a.timeout)
 descriptor=dict(kind='state_only',module=module,board=module+'.branch_state_board',
  state_sound=module+'.branch_state_board_sound',state_small_sound=module+'.branch_state_board_small_sound',
  was_pending=module+'.branch_state_board_was_pending',state_discharge=module+'.branch_families_state_discharged',
  state_coverage=module+'.bootstrap_branch_state_coverage',state_bound=8192,
  members=str(members.relative_to(ROOT)),flags=['-Q','four/theories','BBB24','-Q','four/build/state-branches','BBB24StateBranches'])
 report=dict(status='queued_for_combined_audit' if a.prepare else 'recursive_coqchk_passed',scope='state_only',
  families=len(rows),partial=len(rows),concrete=0,defined_children=16*len(rows),halting_choices=len(rows),
  state_bound=8192,instruction_bound=None,state_census_linked=None if a.prepare else len(rows),
  descriptor=descriptor,input_sha256=sha(INPUT),member_ids_sha256=sha(members),generated_source_sha256=sha(source),
  source_sha256={x:sha(REPO/x) for x in SOURCES},
  proof_object_sha256={str(x.relative_to(ROOT)):sha(x) for x in [ROOT/'theories/StateBranchCloseout.vo',BUILD/'StateBranches.vo']},
  accounting='Original partial families, not child counts. Each None branch halts within8192; all16 defined branches have state recurrence. No root NonHalt or instruction claim.',
  validation='Compiled exact prefix, all16 defined child recurrence checks and original bootstrap membership; '+('queued for combined recursive audit.' if a.prepare else 'recursive coqchk passed.'))
 dest=ROOT/'research'/('state-branches-queued.json' if a.prepare else 'state-branches-checked.json')
 text=json.dumps(report,indent=2)+'\n'
 if not dest.exists() or a.refresh:dest.write_text(text)
 elif dest.read_text()!=text:raise ValueError('Frozen report differs')
 print(json.dumps(dict(status=report['status'],families=len(rows),seconds=round(time.monotonic()-start,2))))
if __name__=='__main__':main()
