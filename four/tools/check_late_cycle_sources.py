"""Export a non-halting source board from an audited late-cycle batch.

Root-cycle rows support symmetry/shadow transport. A closed branching family
does not imply NonHalt for its original partial table and is excluded here.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import time

ROOT=Path(__file__).resolve().parents[1]
BUILD=ROOT/'build/late-cycle-proofs'


def sha(path): return hashlib.sha256(path.read_bytes()).hexdigest()


def generate(stage, modules, bound):
    def proof(theorem):
        return '\n'.join(f'  apply Forall_cons; [exact ({theorem} _ _ _ {m}.checked)|].'
                         for m in modules)+'\n  apply Forall_nil.'
    return f'''(** Generated by check_late_cycle_sources.py. Branching roots excluded. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Closeout CycleBatch CycleNonHalt.
From BBB24LateCycles.{stage} Require Import All {' '.join(modules)}.
Import ListNotations.
Definition cycle_source_boards : list (list TM) := [
  {';'.join('cycle_only_board '+m+'.rows' for m in modules)}].
Definition cycle_source_board := concat cycle_source_boards.
Lemma cycle_source_board_small_sound : BoardSound {bound}%N {bound}%N cycle_source_board.
Proof. apply All.concat_sound.
{proof('cycle_only_board_sound')}
Qed.
Lemma cycle_source_board_nonhalt : forall family,
  In family cycle_source_board -> Statement.NonHalt family.
Proof. apply concat_property.
{proof('cycle_only_board_nonhalt')}
Qed.
Lemma cycle_source_board_sound : BoardSound scoreN scoreN cycle_source_board.
Proof.
  intros family Hin tm Hle. eapply (bounds_weaken {bound}%N {bound}%N scoreN scoreN tm).
  - vm_compute. discriminate.
  - vm_compute. discriminate.
  - exact (cycle_source_board_small_sound family Hin tm Hle).
Qed.
Print Assumptions cycle_source_board_nonhalt.
'''


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage',required=True)
    parser.add_argument('--refresh',action='store_true')
    parser.add_argument('--timeout',type=int,default=3600)
    args=parser.parse_args()
    if not re.fullmatch('[a-z][a-z0-9_]*',args.stage): raise ValueError('Invalid stage')
    base_report=ROOT/f'research/late-cycles-{args.stage}-checked.json'
    report=json.loads(base_report.read_text())
    bundle=ROOT/f'research/late-cycles-{args.stage}.json'
    if sha(bundle)!=report['bundle_sha256']: raise ValueError('Audited bundle changed')
    for path,expected in report['source_sha256'].items():
        if sha(ROOT/path)!=expected: raise ValueError(f'Audited source changed: {path}')
    for path,expected in report['generated_source_sha256'].items():
        if sha(BUILD/path)!=expected: raise ValueError(f'Generated source changed: {path}')
    rows=json.loads(bundle.read_text())['rows']
    modules=sorted(Path(p).stem for p in report['generated_source_sha256'] if Path(p).stem!='All')
    output=BUILD/args.stage; source=output/'NonHalt.v'
    source.write_text(generate(args.stage,modules,report['state_bound']))
    flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(BUILD),'BBB24LateCycles']
    namespace=f'BBB24LateCycles.{args.stage}.NonHalt'
    start=time.monotonic()
    for command,log in [
        (['coqc','-native-compiler','no',*flags,str(source)],output/'nonhalt-compile.log'),
        (['coqchk','-silent','-bytecode-compiler','yes',*flags,namespace],output/'nonhalt-coqchk.log')]:
        with log.open('w') as f:
            subprocess.run(command,cwd=ROOT.parent,stdout=f,stderr=subprocess.STDOUT,check=True,timeout=args.timeout)
    members=[machine for machine,cert in rows if cert[0]=='C']
    excluded=[machine for machine,cert in rows if cert[0]!='C']
    text='\n'.join(members)+'\n'
    (output/'nonhalt-machines.txt').write_text(text)
    evidence=dict(families=len(members),concrete=sum('---' not in m for m in members),
        partial=sum('---' in m for m in members),excluded_branch_families=excluded,
        state_bound=report['state_bound'],instruction_bound=report['instruction_bound'],
        board=namespace+'.cycle_source_board',nonhalt=namespace+'.cycle_source_board_nonhalt',
        small_sound=namespace+'.cycle_source_board_small_sound',sound=namespace+'.cycle_source_board_sound',
        member_order='Audited input order, retaining root-C certificates only; this is the exact board index order.',
        member_ids_sha256=hashlib.sha256(text.encode()).hexdigest(),
        base_report_sha256=sha(base_report),generated_source_sha256=sha(source),
        source_sha256={p:sha(ROOT/p) for p in ['theories/CycleNonHalt.v','tools/check_late_cycle_sources.py']},
        validation='Compiled source-board projection and recursive coqchk; no NonHalt claim for excluded branching families.')
    path=ROOT/f'research/late-cycles-{args.stage}-sources.json'
    serialized=json.dumps(evidence,indent=2)+'\n'
    if args.refresh or not path.exists(): path.write_text(serialized)
    elif path.read_text()!=serialized: raise ValueError('Source-board evidence differs; audit with --refresh')
    print(json.dumps({'nonhalting_source_families':len(members),'excluded_branch_families':len(excluded),
                      'seconds':round(time.monotonic()-start,2)}))


if __name__=='__main__': main()
