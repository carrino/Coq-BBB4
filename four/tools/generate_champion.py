"""Untrusted certificate generator for the BBB(2,4) champion.

The emitted command list is checked by BBB24.Replay, whose soundness theorem
reduces it to ordinary Turing-machine steps. Python output is never trusted.
Run with --check to compare with the committed certificate.
"""
from collections import Counter, deque
import json

TRANS=(((1,1,1),(2,0,0),(1,1,0),(1,0,1)),
       ((0,0,1),(2,1,1),(3,1,1),(1,0,0)))

class Replay:
    def __init__(self):
        # Finite blocks, furthest from the head first; absent tail is blank.
        # Head reads last block on side d (0 left, 1 right).
        self.tape=[[],[]]; self.d=1; self.q=0; self.steps=0
        self.ops=Counter(); self.recent=deque(maxlen=10); self.trace=[]; self.before=[]
    def top(self,d):
        return self.tape[d][-1] if self.tape[d] else [0,None]
    def push(self,d,s,n):
        if not n:return
        if self.tape[d] and self.tape[d][-1][0]==s:
            self.tape[d][-1][1]+=n
        elif s or self.tape[d]: self.tape[d].append([s,n])
    def take(self,d,n):
        if self.tape[d]:
            assert self.tape[d][-1][1]>=n
            self.tape[d][-1][1]-=n
            if not self.tape[d][-1][1]: self.tape[d].pop()
    def step(self,macros=True,chains=True):
        l,r=self.top(0),self.top(1)
        if macros and self.d==0 and l[0]==3 and l[1]>=3:
            k=(l[1]-1)//2
            self.take(0,2*k); self.push(1,1,2*k); self.steps+=2*k
            self.ops['pair3']+=1; self.trace.append(f'Pair3 {k}'); return True
        if macros and self.d==0 and self.q==0 and l[0]==2 and r[0]==2:
            L,R=l[1],r[1]
            if L>=3 and len(self.tape[1])==1:
                k=(L-1)//2
                self.take(0,2*k); self.tape[1][-1][1]+=3*k
                self.steps+=6*k*k+(4*R+8)*k
                self.ops['grow2']+=1; self.trace.append(f'Grow2 {k}'); return True
            if L>=2 and len(self.tape[1])==2 and self.tape[1][0][0]==1 and self.tape[1][0][1]>=2:
                k=min(L-1,self.tape[1][0][1]-1)
                self.take(0,k); self.tape[1][-1][1]+=2*k; self.tape[1][0][1]-=k
                self.steps+=2*k*k+(2*R+1)*k
                self.ops['consume1']+=1; self.trace.append(f'Consume1 {k}'); return True
        s,n=self.top(self.d)
        w,d,q=TRANS[self.q][s]
        self.recent.append({'index':self.steps,'instruction':chr(65+self.q)+str(s)})
        if chains and d==self.d and q==self.q:
            if n is None: return False
            self.take(self.d,n); self.push(1-d,w,n); self.steps+=n
            self.ops['chain']+=1; self.trace.append(f'Chain {n}'); return True
        self.take(self.d,1); self.push(1-d,w,1)
        self.d=d; self.q=q; self.steps+=1; self.ops['atomic']+=1; self.trace.append('Basic')
        return True



def generate():
    import copy
    r=Replay()
    for _ in range(100000):
        before=copy.deepcopy((r.q,r.d,r.tape,r.steps))
        if not r.step(): break
        r.before=before
    else: raise RuntimeError('Operation budget exceeded')
    q,d,tape,t=r.before
    assert r.steps==205770076433044242247860 and t==r.steps-1
    assert q==0 and d==0 and tape[0]==[[3,1]]
    assert r.trace[-1]=='Basic'
    prefix=r.trace[:-1]
    def side(xs):
        return '['+'; '.join(f'(S{s}, {n})' for s,n in reversed(xs))+']'
    chunks=['; '.join(prefix[i:i+8]) for i in range(0,len(prefix),8)]
    commands=';\n  '.join(chunks)
    output=f"""(** Generated by four/tools/generate_champion.py. Every command is rechecked.
    The prefix stops just before the final A3 execution. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec RLE Replay.
Import ListNotations.
Local Open Scope N_scope.
Definition initial := RC StA DR [] [].
Definition previous := RC StA DL {side(tape[0])} {side(tape[1])}.
Definition certificate : list Op := [
  {{commands}}].

Lemma certificate_checked : replay certificate initial = Some (previousN, previous).
Proof. vm_compute. reflexivity. Qed.
""".replace('{commands}',commands)
    return output, {'operations':len(r.trace),'prefix_operations':len(prefix),'steps':r.steps,'rules':dict(r.ops)}

if __name__=='__main__':
    import argparse
    from pathlib import Path
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'theories'/'Certificate.v')
    args=parser.parse_args()
    text,stats=generate()
    if args.check:
        if args.output.read_text()!=text: raise SystemExit('Certificate differs; regenerate it.')
    else: args.output.write_text(text)
    print(json.dumps(stats,sort_keys=True))
