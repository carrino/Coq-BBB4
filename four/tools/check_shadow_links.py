"""Kernel-check all frozen blank-prefix shadow links, without assuming core bounds.

Run `make -C four` first, with Coq on PATH. The compact TSV is sufficient after
build/ cleanup. `--refresh` recreates it from the exploratory mapping when that
mapping is present, then publishes the report only after coqc and coqchk pass.
Generated proof shards remain ignored. These are conditional transports, not
10,572 new bounded families; check_family_transport.py reuses proved cores.
"""
import argparse
import csv
import hashlib
import io
import json
import subprocess
import time
from pathlib import Path

import group_families as grouping
from generate_pipeline_examples import codes

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT/'build/shadow-links'
INPUT = ROOT/'research/shadow-links.tsv'
REPORT = ROOT/'research/shadow-links-summary.json'
SHARD_SIZE = 256
EXPECTED_ROWS = 10572


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def serialize(rows):
    out = io.StringIO()
    writer = csv.DictWriter(out, ['machine', 'core', 'permutation', 'mirrored'],
                            delimiter='\t', lineterminator='\n')
    writer.writeheader(); writer.writerows(rows)
    return out.getvalue()


def infer_links():
    source = ROOT/'build/grouping/shadow-candidates.tsv'
    if not source.exists():
        with INPUT.open() as f:
            return list(csv.DictReader(f, delimiter='\t'))
    result = []
    with source.open() as f:
        for row in csv.DictReader(f, delimiter='\t'):
            if row['prefix_steps'] != '1':
                raise ValueError('This transport checks exactly one blank step')
            matches = [(p, mirrored) for p in grouping.PERMS for mirrored in (False, True)
                       if grouping.render(grouping.rename(grouping.parse(row['machine']), p,
                             mirror=mirrored, swap=True)) == row['transformed']]
            if not matches:
                raise ValueError(f'No symbol/reflection witness for {row["machine"]}')
            p, mirrored = matches[0]
            result.append(dict(machine=row['machine'], core=row['partner'],
                               permutation='P'+''.join(map(str, p[1:])),
                               mirrored=str(mirrored).lower()))
    return result


def check_shape(rows):
    if len(rows) != EXPECTED_ROWS or len({r['machine'] for r in rows}) != len(rows):
        raise ValueError('Expected exactly 10,572 distinct shadow families')
    if rows != sorted(rows, key=lambda r: r['machine']):
        raise ValueError('Shadow inventory must be sorted')
    perms = {'P'+''.join(map(str, p[1:])) for p in grouping.PERMS}
    for row in rows:
        codes(row['machine']); codes(row['core'])
        if row['permutation'] not in perms or row['mirrored'] not in {'true', 'false'}:
            raise ValueError('Invalid permutation/reflection witness')


def table(machine):
    return '['+';'.join(map(str, codes(machine)))+']'


def header():
    return '''(** GENERATED by four/tools/check_shadow_links.py. Conditional links only. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout
  Symmetry Shadow Pipeline FamilyTransport.
Import ListNotations.
'''


def generate(rows):
    BUILD.mkdir(parents=True, exist_ok=True)
    paths = []
    for offset in range(0, len(rows), SHARD_SIZE):
        chunk = rows[offset:offset+SHARD_SIZE]
        path = BUILD/f'ShadowLinks{offset//SHARD_SIZE:03}.v'
        body = ';\n'.join('  shadow_link '+table(r['machine'])+' '+table(r['core'])+
                         f' {r["permutation"]} {r["mirrored"]}' for r in chunk)
        path.write_text(header()+f'''
Definition rows : list ShadowLink := [
{body}
].
Lemma rows_checked : forallb shadow_link_check rows=true.
Proof. vm_compute. reflexivity. Qed.
Example row_count : length rows={len(chunk)}.
Proof. reflexivity. Qed.
Theorem conditional_transports : forall row, In row rows ->
  forall bs bi, NonHalt (link_core row) -> Bounds bs bi (link_core row) ->
  forall complete, TM_le (link_shadow row) complete ->
  NonHalt complete /\\ Bounds (N.succ bs) (N.succ bi) complete.
Proof. exact (shadow_links_conditional rows rows_checked). Qed.
Lemma rows_pending_checked :
  forallb (fun row => pending_check 9 empty bootstrap (link_shadow row)) rows=true.
Proof. vm_compute. reflexivity. Qed.
Theorem shadows_pending : forall row, In row rows -> bootstrap_pending (link_shadow row).
Proof.
  intros row Hin. apply pending_check_sound.
  pose proof rows_pending_checked as H.
  apply forallb_forall with (x:=row) in H; assumption.
Qed.
Print Assumptions conditional_transports.
''')
        paths.append(path)
    return paths


def command(args, log, timeout):
    with log.open('w') as out:
        subprocess.run(args, cwd=ROOT.parent, stdout=out, stderr=subprocess.STDOUT,
                       check=True, timeout=timeout)


def dependency_hashes(roots, loadpath):
    """Pin the transitive local Coq sources, including ignored generated proofs."""
    seen, pending = set(), {p.resolve() for p in roots}
    while pending:
        batch = sorted(pending-seen)
        if not batch:
            break
        seen.update(batch)
        output = subprocess.check_output(['coqdep', *loadpath, *map(str, batch)],
                                         cwd=ROOT.parent, text=True)
        pending = set()
        for line in output.splitlines():
            if ': ' not in line or not line.split()[0].endswith('.vo'):
                continue
            for token in line.split(': ', 1)[1].split():
                if token.endswith('.vo'):
                    path = Path(token).with_suffix('.v')
                    if not path.is_absolute():
                        path = ROOT.parent/path
                    if not path.is_file():
                        raise ValueError(f'Missing local proof dependency: {path}')
                    pending.add(path.resolve())
    return {str(p.relative_to(ROOT)): sha(p) for p in sorted(seen)}


def source_hashes():
    paths = [Path(__file__).resolve(), ROOT/'tools/group_families.py',
             ROOT/'tools/generate_pipeline_examples.py']
    local = dependency_hashes([ROOT/'theories/FamilyTransport.v'],
                              ['-Q', str(ROOT/'theories'), 'BBB24'])
    return dict(local, **{str(p.relative_to(ROOT)): sha(p) for p in paths})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--timeout', type=int, default=300)
    args = parser.parse_args()
    if args.refresh:
        rows = infer_links()
    else:
        with INPUT.open() as f:
            rows = list(csv.DictReader(f, delimiter='\t'))
    check_shape(rows)
    text = serialize(rows)
    pinned = source_hashes()
    if not args.refresh:
        expected = json.loads(REPORT.read_text())
        if expected['input_sha256'] != hashlib.sha256(text.encode()).hexdigest() or expected['source_sha256'] != pinned:
            raise ValueError('Recorded input/proof hashes changed; refresh and recheck')
    paths = generate(rows)
    start = time.monotonic()
    loadpath = ['-Q', str(ROOT/'theories'), 'BBB24', '-Q', str(BUILD), 'BBB24ShadowLinks']
    for path in paths:
        command(['coqc', '-native-compiler', 'no', *loadpath, str(path)], path.with_suffix('.log'), args.timeout)
        print(f'Checked {path.stem}', flush=True)
    command(['coqchk', '-silent', '-bytecode-compiler', 'yes', *loadpath,
             *[f'BBB24ShadowLinks.{p.stem}' for p in paths]], BUILD/'coqchk.log', args.timeout*len(paths))
    if pinned != source_hashes():
        raise ValueError('Proof inputs changed during the audit')
    report = dict(
        scope='All 10,572 frozen one-blank-step links; conditional transports only, no new core bounds',
        input_sha256=hashlib.sha256(text.encode()).hexdigest(),
        counts=dict(conditional_links=len(rows), distinct_cores=len({r['core'] for r in rows}),
                    bootstrap_pending_families=len(rows), newly_bounded_families=0),
        state_bound_transport='core bound + 1', instruction_bound_transport='core bound + 1',
        validation='coqc vm_compute checks and recursive coqchk; all completions covered conditionally',
        proof_namespace='BBB24ShadowLinks',
        source_sha256=pinned, shard_sha256={p.name: sha(p) for p in paths})
    rendered = json.dumps(report, indent=2)+'\n'
    if args.refresh:
        INPUT.write_text(text); REPORT.write_text(rendered)
    elif INPUT.read_text() != text or REPORT.read_text() != rendered:
        raise ValueError('Checked outputs differ from the frozen report')
    print(json.dumps(dict(counts=report['counts'], checking_seconds=round(time.monotonic()-start, 2))))


if __name__ == '__main__':
    main()
