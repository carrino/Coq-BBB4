"""Generate a compact certificate DAG from the untrusted multisymbol survey.

Coq rechecks every resolved leaf and every branch. Unresolved leaves remain
explicit partial-table families; the resulting theorem is a coverage theorem,
not a global upper bound. The checked bootstrap uses a eight-step horizon.
"""
import argparse
import csv
import json
import subprocess
from pathlib import Path


def generate(rows, fuel):
    rows = iter(rows)
    nodes = []
    ids = {}
    cursor = 0

    def intern(node):
        if node not in ids:
            ids[node] = len(nodes)
            nodes.append(node)
        return ids[node]

    def read():
        nonlocal cursor
        row = next(rows)
        cursor += 1
        kind = row['kind']
        if kind == 'unresolved':
            return intern(('deferred',))
        if kind in ('cycle', 'translated'):
            return intern(('cycle', int(row['shift']) < 0, int(row['anchor']),
                           int(row['period']), int(row['reach'])))
        if kind == 'halt':
            return intern(('branch', int(row['anchor']), tuple(read() for _ in range(16))))
        raise ValueError(f'Unknown survey result: {kind}')

    root = read()
    assert next(rows, None) is None, 'Survey is not one complete depth-first census'
    definitions = []
    for i, node in enumerate(nodes):
        if node[0] == 'deferred':
            body = 'Deferred'
        elif node[0] == 'cycle':
            _, mirror, t, p, w = node
            body = f'Cycle {str(mirror).lower()} {t} {p} {w}'
        else:
            _, n, children = node
            body = f'Branch {n} [' + '; '.join(f'node_{c}' for c in children) + ']'
        definitions.append(f'Definition node_{i} : Cert := {body}.')
    header = f'''(** Generated by four/tools/generate_census.py, horizon {fuel}.
    Identical subtrees are shared. Deferred leaves are not treated as solved. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census.
Import ListNotations.
'''
    tail = fr'''
Definition bootstrap := node_{root}.
Lemma bootstrap_checked : verify scoreN scoreN 9 empty bootstrap = true.
Proof. vm_compute. reflexivity. Qed.
Definition bootstrap_pending tm := Pending (residue 9 empty bootstrap) tm.
Theorem bootstrap_coverage : forall tm,
  Bounds scoreN scoreN tm \/ bootstrap_pending tm.
Proof. exact (census_coverage scoreN scoreN 9 bootstrap bootstrap_checked). Qed.
'''
    return header + '\n'.join(definitions) + '\n' + tail, len(nodes), cursor


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fuel', type=int, default=8)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not 1 <= args.fuel <= 8:
        parser.error('Bootstrap horizon must be between 1 and 8')
    root = Path(__file__).resolve().parents[1]
    build = root / 'build'
    build.mkdir(exist_ok=True)
    exe = build / 'survey'
    subprocess.run(['g++', '-O3', '-std=c++17', str(root.parent/'tools/multisymbol/survey.cpp'), '-o', str(exe)], check=True)
    prefix = build / f'census-{args.fuel}'
    result = subprocess.run([str(exe), str(prefix), '4', str(args.fuel), str(args.fuel), '2'], check=True, capture_output=True, text=True, timeout=300)
    stats = json.loads(result.stdout)
    with prefix.with_suffix('.certificates.tsv').open() as f:
        source, unique, node_count = generate(csv.DictReader(f, delimiter='\t'), args.fuel)
    assert node_count == stats['nodes']
    resolved = stats['covered'] - stats['weighted'].get('unresolved', 0)
    pending = stats['weighted'].get('unresolved', 0)
    source += f'''
Lemma bootstrap_counts : counts 8 bootstrap = ({resolved}, {pending})%N.
Proof. vm_compute. reflexivity. Qed.
Lemma bootstrap_total :
  (fst (counts 8 bootstrap) + snd (counts 8 bootstrap))%N = table_count 8.
Proof. rewrite bootstrap_counts. reflexivity. Qed.
Print Assumptions bootstrap_coverage.
'''
    output = root / 'theories' / 'Bootstrap.v'
    if args.check:
        if output.read_text() != source:
            raise SystemExit('Bootstrap differs; regenerate it.')
    else:
        output.write_text(source)
    print(json.dumps({'fuel':args.fuel,'tree_nodes':node_count,'unique_nodes':unique,
                     'resolved_weight':resolved,'pending_weight':pending,
                     'total_weight':stats['covered'],'deferred_families':stats['leaves']['unresolved']}, sort_keys=True))


if __name__ == '__main__':
    main()
