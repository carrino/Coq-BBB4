"""Join one partial root using cycle, finite-state, affine and marker proofs.

The sixteen total children are proved independently; the undefined choice
halts at the checked root prefix. Only state bounds are exported for the root.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import time
from check_state_branches import ROOT,REPO,sha
from check_affine_wave import source_hashes
from check_late_cycles import cert_text
from generate_pipeline_examples import codes

BUILD=ROOT/'build/state-marker-branch'
INPUT=ROOT/'research/state-marker-branch-input.json'

def generate(data):
 cycles=['  (['+';'.join(map(str,codes(c['machine'])))+'], '+cert_text(c['certificate'])+')' for c in data['cycles']]
 finite=[str(sum(v*17**i for i,v in enumerate(codes(m))))+'%N' for m in data['finite_children']]
 root=';'.join(map(str,codes(data['machine'])))
 return r'''(** Generated by check_state_marker_join.py. Original root: STATE ONLY. *)
From Coq Require Import Arith List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout Pipeline
  StateOnlyCloseout StateBranchJoin CycleBatch StatePipeline RightMarkerState.
From BBB24AffineChildren.MarkerParent Require Import Children.
Import ListNotations.
Definition cycle_rows : CycleRows := [
'''+ ';\n'.join(cycles)+r'''
].
Lemma cycles_checked : cycle_batch_check 4096%N 4096%N cycle_rows = true.
Proof. vm_compute; reflexivity. Qed.
Lemma cycles_state_sound : StateBoardSound (N.to_nat 4096%N) (cycle_board cycle_rows).
Proof.
  intros family Hin tm Hle.
  exact (proj1 (cycle_board_sound _ _ _ cycles_checked family Hin tm Hle)).
Qed.
Definition finite_rows : list N := ['''+';'.join(finite)+r'''].
Definition finite_cert := StateFinite 3 4096 1024 16.
Lemma finite_checked : stp_batch_check 4096%N finite_cert finite_rows = true.
Proof. vm_compute; reflexivity. Qed.
Lemma finite_state_sound : StateBoardSound (N.to_nat 4096%N) (stp_board finite_rows).
Proof. exact (stp_batch_state_sound _ _ _ finite_checked). Qed.
Definition marker_board := [machine_of_codes [5;10;1;3;15;14;0;2]].
Lemma marker_state_sound : StateBoardSound (N.to_nat 4096%N) marker_board.
Proof.
  apply state_board_zero_weaken. intros family Hin tm Hle.
  destruct Hin as [<-|[]].
  exact (state_bound_extend 0 _ _ mr_child_nonhalt mr_child_state_zero Hle).
Qed.
Definition child_boards : list (list TM) := [cycle_board cycle_rows; stp_board finite_rows;
  BBB24AffineChildren.MarkerParent.Children.board; marker_board].
Definition child_board := concat child_boards.
Lemma child_board_state_sound : StateBoardSound (N.to_nat 4096%N) child_board.
Proof.
  apply state_boards_sound.
  apply Forall_cons; [exact cycles_state_sound|].
  apply Forall_cons; [exact finite_state_sound|].
  apply Forall_cons; [exact BBB24AffineChildren.MarkerParent.Children.state_small_sound|].
  apply Forall_cons; [exact marker_state_sound|].
  apply Forall_nil.
Qed.
Definition root_family := machine_of_codes ['''+root+r'''].
Lemma joined_checked : state_branch_lookup_check 4096%N child_board root_family '''+str(data['anchor'])+r''' = true.
Proof. vm_compute; reflexivity. Qed.
Definition branch_state_board := [root_family].
Lemma branch_state_board_small_sound : StateBoardSound (N.to_nat 4096%N) branch_state_board.
Proof.
  intros family Hin tm Hle. destruct Hin as [<-|[]].
  exact (state_branch_lookup_check_sound _ _ _ _ child_board_state_sound joined_checked tm Hle).
Qed.
Lemma branch_state_board_sound : StateBoardSound score branch_state_board.
Proof.
  eapply (state_board_N_weaken 4096%N scoreN).
  - vm_compute; discriminate.
  - exact branch_state_board_small_sound.
Qed.
Lemma pending_checked : forallb (pending_check 9 empty bootstrap) branch_state_board = true.
Proof. vm_compute; reflexivity. Qed.
Lemma branch_state_board_was_pending : forall family,
  In family branch_state_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound. pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_marker_branch_pending := remaining bootstrap_pending branch_state_board.
Theorem bootstrap_marker_branch_coverage : forall tm,
  QHBound score tm \/ bootstrap_marker_branch_pending tm.
Proof. exact (state_closeout_coverage _ _ _ bootstrap_state_coverage branch_state_board_sound). Qed.
Theorem marker_branch_family_discharged : forall family,
  In family branch_state_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ QHBound score tm /\ ~ bootstrap_marker_branch_pending tm.
Proof. exact (state_board_discharge _ _ branch_state_board_was_pending branch_state_board_sound). Qed.
Print Assumptions marker_branch_family_discharged.
'''

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--prepare',action='store_true')
 p.add_argument('--timeout',type=int,default=3600);a=p.parse_args();data=json.loads(INPUT.read_text())
 if data['machine']!='1LB2RA0LB---_3RB3RA0LA0RA' or data['anchor']!=1000:raise ValueError('Unexpected root')
 expected=[]
 for v in range(16):
  table=codes(data['machine']);table[3]=v;expected.append(tuple(table))
 children=[c['machine'] for c in data['cycles']]+data['finite_children']+data['affine_children']+[data['marker_child']]
 if len(children)!=16 or set(map(lambda m:tuple(codes(m)),children))!=set(expected):raise ValueError('Incomplete or duplicate defined-child inventory')
 BUILD.mkdir(parents=True,exist_ok=True);source=BUILD/'MarkerParent.v';source.write_text(generate(data))
 members=BUILD/'machines.txt';members.write_text(data['machine']+'\n')
 flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(ROOT/'build/affine-children'),'BBB24AffineChildren',
        '-Q',str(BUILD),'BBB24StateMarkerBranch'];module='BBB24StateMarkerBranch.MarkerParent'
 commands=[(['coqc','-native-compiler','no',*flags,str(ROOT/'theories/StateBranchJoin.v')],'bridge.log'),
           (['coqc','-w','-abstract-large-number','-native-compiler','no',*flags,str(source)],'compile.log')]
 if not a.prepare:commands.append((['coqchk','-silent','-bytecode-compiler','yes',*flags,module],'coqchk.log'))
 start=time.monotonic()
 for cmd,log in commands:
  with (BUILD/log).open('w') as out:subprocess.run(['nice','-n','10',*cmd],cwd=REPO,stdout=out,stderr=subprocess.STDOUT,check=True,timeout=a.timeout)
 sources=source_hashes()
 todo=['StateBranchJoin','StatePipeline','RightMarkerState','CycleBatch'];seen=set()
 while todo:
  name=todo.pop()
  if name in seen:continue
  seen.add(name);path=ROOT/'theories'/Path(*name.split('.')).with_suffix('.v')
  sources[str(path.relative_to(REPO))]=sha(path)
  for prefix,names in re.findall(r'From\s+(BBB24[\w.]*)\s+Require\s+(?:Import|Export)\s+([\w\s]+)\.',path.read_text()):
   todo.extend('.'.join(prefix.split('.')[1:]+[module]) for module in names.split())
 for tool in ['check_state_marker_join.py','check_affine_children.py','check_late_cycles.py','check_state_branches.py']:
  sources['four/tools/'+tool]=sha(ROOT/'tools'/tool)
 sources['four/build/affine-children/MarkerParent/Children.v']=sha(ROOT/'build/affine-children/MarkerParent/Children.v')
 descriptor=dict(kind='state_only',module=module,board=module+'.branch_state_board',state_sound=module+'.branch_state_board_sound',
  state_small_sound=module+'.branch_state_board_small_sound',was_pending=module+'.branch_state_board_was_pending',
  state_discharge=module+'.marker_branch_family_discharged',state_coverage=module+'.bootstrap_marker_branch_coverage',state_bound=4096,
  members=str(members.relative_to(ROOT)),flags=['-Q','four/theories','BBB24','-Q','four/build/affine-children','BBB24AffineChildren',
    '-Q','four/build/state-marker-branch','BBB24StateMarkerBranch'])
 report=dict(status='queued_for_combined_audit' if a.prepare else 'recursive_coqchk_passed',scope='state_only',families=1,partial=1,concrete=0,
  defined_children=16,halting_choices=1,state_bound=4096,instruction_bound=None,state_census_linked=None if a.prepare else 1,descriptor=descriptor,
  input_sha256=sha(INPUT),affine_input_sha256=sha(ROOT/'research/state-marker-affine-children-input.json'),
  member_ids_sha256=sha(members),generated_source_sha256=sha(source),source_sha256=sources,
  proof_object_sha256={str(x.relative_to(ROOT)):sha(x) for x in [ROOT/'theories/StateBranchJoin.vo',ROOT/'theories/RightMarkerState.vo',source.with_suffix('.vo')]},
  accounting='One original partial family, not sixteen new core IDs. All sixteen defined choices plus the halting choice are covered. No root NonHalt or instruction claim.',
  validation='Compiled all child certificates, marker invariant, root prefix and exact pending membership; '+('queued for combined recursive audit.' if a.prepare else 'recursive coqchk passed.'))
 dest=ROOT/'research'/('state-marker-branch-queued.json' if a.prepare else 'state-marker-branch-checked.json');text=json.dumps(report,indent=2)+'\n'
 if dest.exists() and dest.read_text()!=text:raise ValueError('Frozen marker-branch report differs')
 dest.write_text(text);print(json.dumps(dict(status=report['status'],families=1,seconds=round(time.monotonic()-start,2))))
if __name__=='__main__':main()
