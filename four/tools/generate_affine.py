"""Transcribe untrusted multi-symbol affine certificates into checked Coq examples.

The shared parser/emitters come from the existing block-prefix certificate tool.
This adapter fixes the carrier to two states and four symbols. Search verdicts
and claimed scores are ignored; ir_check must establish every emitted theorem.
"""
import argparse
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    'prefix_cert', ROOT.parent / 'tools/gen_irulesblkpfx_certs.py')
shared = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shared)
shared.SYM = {i: f'S{i}' for i in range(4)}

HEADER = '''(** GENERATED by four/tools/generate_affine.py. Search claims are not trusted. *)
From Coq Require Import NArith ZArith List.
From BBB24 Require Import Statement StatementTr Spec Bounds Census IRuleCensus.
From BBB24.Checkers.IRules Require Import Expr RLE Engine Rules Meta RulesK
 EngineK RulesBlk MetaBlk EngineKS RulesBlkPfx MetaBlkPfx.
Import ListNotations.
Open Scope Z_scope.
Definition mk (w:Sym) (d:Dir) (q:St) := Some (mkTrans w d q).
'''


def emit(path):
    c = shared.parse_cert(path)
    m = c['machine']
    groups = m.split('_')
    if len(groups) != 2 or any(len(g) != 12 for g in groups):
        raise ValueError(f'Expected two states and four symbols: {m}')
    nm = shared.cname(m)
    rows = []
    for q, group in zip('AB', groups):
        for s in range(4):
            t = group[3*s:3*s+3]
            if t == '---':
                value = 'None'
            else:
                if t[0] not in '0123' or t[1] not in 'LR' or t[2] not in 'AB':
                    raise ValueError(f'Invalid transition: {t}')
                value = f'mk S{t[0]} {shared.DIRW[t[1]]} St{t[2]}'
            rows.append(f'  | St{q}, S{s} => {value}')
    tm = '\n'.join(rows)
    return f'''
(** {m}: anchor {c['anchor_step']}, map k -> {c['meta_a']}*k+{c['meta_b']}. *)
Definition tm_{nm} : TM := fun q s => match q,s with
{tm}
  end.
Definition cert_{nm} : BIRCertP := mkBIRCertP
  {c['anchor_step']}%nat ({c['k0']}) ({c['kmin']}) ({c['meta_a']}) ({c['meta_b']})
  St{c['tpl_state']} S{c['tpl_hsym']}
  {shared.emit_blks(c['blk'])}
  {shared.emit_tpl(c['tplL'])}
  {shared.emit_tpl(c['tplR'])}
  {shared.emit_rules(c['rules'], c['pfx'])}.
Lemma checked_{nm} :
  ir_check 4096%N 4096%N tm_{nm} cert_{nm} 200000 300000 = true.
Proof. vm_compute. reflexivity. Qed.
Theorem bounded_{nm} :
  NonHalt tm_{nm} /\\ Bounds 4096%N 4096%N tm_{nm}.
Proof. exact (ir_check_sound _ _ _ _ _ _ checked_{nm}). Qed.
Theorem completions_{nm} : forall tm,
  TM_le tm_{nm} tm -> Bounds 4096%N 4096%N tm.
Proof.
  intros tm Hle. destruct bounded_{nm} as [Hnh Hb].
  eapply extend_bounds; eauto.
Qed.
Print Assumptions completions_{nm}.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--cert-dir', type=Path, default=ROOT/'research/affine')
    parser.add_argument('--output', type=Path, default=ROOT/'theories/AffineExamples.v')
    args = parser.parse_args()
    paths = sorted(args.cert_dir.glob('*.cert'))
    if not paths:
        raise SystemExit('No input certificates')
    output = HEADER + ''.join(emit(p) for p in paths)
    if args.check:
        if args.output.read_text() != output:
            raise SystemExit('Generated affine examples differ')
    else:
        args.output.write_text(output)
    print(f'{len(paths)} affine certificates transcribed; Coq checking is required.')


if __name__ == '__main__':
    main()
