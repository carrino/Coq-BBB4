"""Kernel-check closed cycle/census trees from late_cycles.cpp.

--select RESULTS_JSONL freezes a deterministic certificate batch. Use --limit
for a pilot; zero selects every closed original family. Generated Coq shards
stay under build/. Reports are written only after compilation and coqchk.
An open child tree is never promoted to a closed original family.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import subprocess
import time

from generate_pipeline_examples import codes

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT/'build/late-cycle-proofs'
PROOF_SOURCES = [
    'tools/check_late_cycles.py', 'tools/generate_pipeline_examples.py',
    'theories/Statement.v', 'theories/StatementTr.v', 'theories/Spec.v',
    'theories/CTape.v', 'theories/GTape.v', 'theories/Mirror.v',
    'theories/Instructions.v', 'theories/Bounds.v',
    'theories/Checkers/Cycle.v', 'theories/Checkers/TCycler.v',
    'theories/CycleCensus.v', 'theories/Census.v', 'theories/Bootstrap.v',
    'theories/Closeout.v', 'theories/CertifiedBoard.v',
    'theories/Pipeline.v', 'theories/CycleBatch.v',
]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def cert_text(cert):
    if not isinstance(cert, list) or not cert:
        raise ValueError('Malformed census certificate')
    if cert[0] == 'C' and len(cert) == 5:
        _, mirror, anchor, period, reach = cert
        if mirror not in (0, 1) or any(type(x) is not int or x < 0 for x in (anchor, period, reach)) or period == 0:
            raise ValueError('Invalid cycle tuple')
        return f'Cycle {str(bool(mirror)).lower()} {anchor} {period} {reach}'
    if cert[0] == 'B' and len(cert) == 3:
        _, anchor, children = cert
        if type(anchor) is not int or anchor < 0 or not isinstance(children, list) or len(children) != 16:
            raise ValueError('A census branch must include all sixteen defined children')
        return f'Branch {anchor} [' + ';'.join(cert_text(c) for c in children) + ']'
    raise ValueError('Only closed cycle/branch trees can enter the proof batch')


def select(path, destination, limit, bound):
    rows = [json.loads(line) for line in path.read_text().splitlines()]
    if len(rows) != len({r['machine'] for r in rows}):
        raise ValueError('Duplicate original family in search output')
    accepted = [r for r in rows if r['status'] == 'candidate_closed']
    accepted.sort(key=lambda r: hashlib.sha256(r['machine'].encode()).digest())
    if limit:
        # Include the largest anchors/periods and partial inputs in a pilot.
        special = sorted(accepted, key=lambda r: (r['max_anchor'], r['max_period']), reverse=True)[:limit//4]
        special += [r for r in accepted if r['free_cells']][:limit//4]
        chosen = {r['machine']:r for r in special}
        for r in accepted:
            if len(chosen) >= limit:
                break
            chosen[r['machine']] = r
        accepted = sorted(chosen.values(), key=lambda r: hashlib.sha256(r['machine'].encode()).digest())
    for row in accepted:
        codes(row['machine']); cert_text(row['certificate'])
    data = dict(search_output_sha256=sha(path), search_source_sha256=sha(ROOT/'tools/late_cycles.cpp'),
                input_families=len(rows), input_concrete=sum(r['free_cells']==0 for r in rows),
                input_partial=sum(r['free_cells']>0 for r in rows),
                candidate_families=sum(r['status']=='candidate_closed' for r in rows),
                bound=bound, rows=[[r['machine'],r['certificate']] for r in accepted])
    destination.write_text(json.dumps(data, separators=(',', ':'))+'\n')


def shard_source(rows, bound):
    entries = []
    for machine, cert in rows:
        table = ';'.join(map(str,codes(machine)))
        entries.append(f'  ([{table}], {cert_text(cert)})')
    return f'''(** Generated by check_late_cycles.py; hashes are search aids only. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout CertifiedBoard CycleBatch.
Import ListNotations.
Definition rows : CycleRows := [
''' + ';\n'.join(entries) + f'''
].
Lemma checked : cycle_batch_check {bound}%N {bound}%N rows = true.
Proof. vm_compute. reflexivity. Qed.
Definition board := cycle_board rows.
Lemma small_sound : BoardSound {bound}%N {bound}%N board.
Proof. exact (cycle_board_sound _ _ _ checked). Qed.
Lemma sound : BoardSound scoreN scoreN board.
Proof.
  intros family Hin tm Hle. eapply (bounds_weaken {bound}%N {bound}%N scoreN scoreN tm).
  - vm_compute. discriminate.
  - vm_compute. discriminate.
  - exact (small_sound family Hin tm Hle).
Qed.
Lemma pending_checked : cycle_pending_check rows = true.
Proof. vm_compute. reflexivity. Qed.
Lemma was_pending : forall family, In family board -> bootstrap_pending family.
Proof. exact (cycle_board_was_pending _ pending_checked). Qed.
'''


def forall_proof(modules, name):
    return '\n'.join(f'  apply Forall_cons; [exact {m}.{name}|].' for m in modules)+'\n  apply Forall_nil.'


def aggregate_source(stage, modules, bound):
    return f'''(** Generated by check_late_cycles.py. Counts refer to original families. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout CertifiedBoard.
From BBB24LateCycles.{stage} Require Import {' '.join(modules)}.
Import ListNotations.
Definition boards : list (list TM) := [{';'.join(m+'.board' for m in modules)}].
Definition late_cycle_board := concat boards.
Lemma concat_sound : forall bs bi boards,
  Forall (BoardSound bs bi) boards -> BoardSound bs bi (concat boards).
Proof.
  intros bs bi boards H. induction H; simpl.
  - intros family Hin. contradiction.
  - apply board_sound_app; assumption.
Qed.
Lemma concat_pending : forall boards,
  Forall (fun b => forall family, In family b -> bootstrap_pending family) boards ->
  forall family, In family (concat boards) -> bootstrap_pending family.
Proof.
  intros boards H. induction H; intros family Hin; simpl in Hin.
  - contradiction.
  - apply in_app_iff in Hin as [Hin|Hin]; auto.
Qed.
Lemma late_cycle_board_small_sound : BoardSound {bound}%N {bound}%N late_cycle_board.
Proof. apply concat_sound.
{forall_proof(modules,'small_sound')}
Qed.
Lemma late_cycle_board_sound : BoardSound scoreN scoreN late_cycle_board.
Proof. apply concat_sound.
{forall_proof(modules,'sound')}
Qed.
Lemma late_cycle_board_was_pending : forall family,
  In family late_cycle_board -> bootstrap_pending family.
Proof. apply concat_pending.
{forall_proof(modules,'was_pending')}
Qed.
Definition bootstrap_late_cycle_pending := remaining bootstrap_pending late_cycle_board.
Theorem bootstrap_late_cycle_coverage : forall tm,
  Bounds scoreN scoreN tm \\/ bootstrap_late_cycle_pending tm.
Proof. exact (closeout_coverage _ _ _ _ bootstrap_coverage late_cycle_board_sound). Qed.
Theorem late_cycle_families_discharged : forall family,
  In family late_cycle_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\\ Bounds scoreN scoreN tm /\\ ~ bootstrap_late_cycle_pending tm.
Proof.
  exact (board_families_discharged _ _ _ _ _ late_cycle_board_was_pending late_cycle_board_sound).
Qed.
Print Assumptions late_cycle_families_discharged.
'''


def command(args, log, timeout):
    with log.open('w') as f:
        subprocess.run(args, cwd=ROOT.parent, stdout=f, stderr=subprocess.STDOUT,
                       check=True, timeout=timeout)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage',required=True)
    parser.add_argument('--select',type=Path)
    parser.add_argument('--limit',type=int,default=0)
    parser.add_argument('--bound',type=int,default=4097)
    parser.add_argument('--shard-size',type=int,default=64)
    parser.add_argument('--timeout',type=int,default=600)
    args=parser.parse_args()
    if not re.fullmatch('[a-z][a-z0-9_]*',args.stage) or args.bound<1 or args.limit<0 or args.shard_size<1:
        raise ValueError('Invalid stage name or budget')
    bundle=ROOT/f'research/late-cycles-{args.stage}.json'
    report_path=ROOT/f'research/late-cycles-{args.stage}-checked.json'
    if args.select:
        select(args.select,bundle,args.limit,args.bound)
    data=json.loads(bundle.read_text()); rows=data['rows']; bound=data['bound']
    if not rows or len(rows)!=len({r[0] for r in rows}):
        raise ValueError('Proof batch is empty or repeats an original family')
    for machine,cert in rows: codes(machine); cert_text(cert)
    output=BUILD/args.stage; output.mkdir(parents=True,exist_ok=True)
    flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(BUILD),'BBB24LateCycles']
    modules=[]; sources={}; start=time.monotonic()
    for index in range(0,len(rows),args.shard_size):
        module=f'Cycle{index//args.shard_size:03}'; path=output/f'{module}.v'
        path.write_text(shard_source(rows[index:index+args.shard_size],bound)); modules.append(module)
        command(['coqc','-w','-abstract-large-number','-native-compiler','no',*flags,str(path)],
                path.with_suffix('.log'),args.timeout)
        sources[str(path.relative_to(BUILD))]=sha(path)
        print(f'Checked {min(index+args.shard_size,len(rows))}/{len(rows)} original families',flush=True)
    aggregate=output/'All.v'; aggregate.write_text(aggregate_source(args.stage,modules,bound))
    command(['coqc','-native-compiler','no',*flags,str(aggregate)],output/'aggregate.log',args.timeout)
    sources[str(aggregate.relative_to(BUILD))]=sha(aggregate)
    namespace=f'BBB24LateCycles.{args.stage}.All'
    command(['coqchk','-silent','-bytecode-compiler','yes',*flags,namespace],output/'coqchk.log',args.timeout*len(modules))
    report=dict(families=len(rows),concrete=sum('---' not in r[0] for r in rows),
                partial=sum('---' in r[0] for r in rows),
                certificate_roots=dict(Counter(r[1][0] for r in rows)),
                state_bound=bound,instruction_bound=bound,
                source_sha256={p:sha(ROOT/p) for p in PROOF_SOURCES},
                bundle_sha256=sha(bundle),generated_source_sha256=sources,
                coverage_theorem=namespace+'.bootstrap_late_cycle_coverage',
                discharge_theorem=namespace+'.late_cycle_families_discharged',
                board=namespace+'.late_cycle_board',board_sound=namespace+'.late_cycle_board_sound',
                validation='Every original family checked by Census.verify, empty residue, actual bootstrap pending membership, and recursive coqchk.',
                accounting='Counts original input families, not expanded child leaves; halting None choices covered by Census.verify_cover.')
    serialized=json.dumps(report,indent=2)+'\n'
    if args.select or not report_path.exists(): report_path.write_text(serialized)
    elif report_path.read_text()!=serialized: raise ValueError('Audited batch differs from recorded evidence')
    print(json.dumps({'checked_families':len(rows),'seconds':round(time.monotonic()-start,2)}))


if __name__=='__main__': main()
