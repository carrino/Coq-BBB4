"""Replay the compact closure pilot in Coq; search results are never proof inputs.

The JSON supplies only machine tables and checker parameters. The generated
theorem evaluates every check and attaches every completion to the frozen census.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def codes(machine):
    if not re.fullmatch(r'(?:---|[0-3][LR][AB]){4}_(?:---|[0-3][LR][AB]){4}', machine):
        raise ValueError(f'Invalid machine: {machine}')
    cells = machine.replace('_', '')
    return [16 if cells[i:i+3] == '---' else
            4 * int(cells[i]) + 2 * (cells[i+1] == 'R') + (cells[i+2] == 'B')
            for i in range(0, 24, 3)]


def generate(data):
    rows = data['rows']
    if not rows or len({r['machine'] for r in rows}) != len(rows):
        raise ValueError('Empty or duplicate pilot inventory')
    entries = []
    for row in rows:
        if row['bound'] != 4096:
            raise ValueError('This proof batch uses bound 4096')
        for field in ('size', 'anchor', 'fuel', 'extra'):
            if type(row[field]) is not int or row[field] < 0:
                raise ValueError(f'Invalid parameter: {field}')
        n, t, fuel, extra = (row[k] for k in ('size', 'anchor', 'fuel', 'extra'))
        if row['mode'] == 'ng':
            cert = f'NGram {n} {t} {fuel} {extra}'
        elif row['mode'] == 'rw':
            cert = f'RepeatedWord {n} {extra} {t} {fuel}'
        else:
            raise ValueError('Unknown checker mode')
        table = ';'.join(map(str, codes(row['machine'])))
        entries.append(f'  (* {row["machine"]} *)\n  ([{table}], {cert})')
    body = ';\n'.join(entries)
    return f'''(** GENERATED by four/tools/generate_pipeline_examples.py.
    All search successes in the recorded pilot, replayed in the kernel. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout
  AffineCloseout Pipeline.
Import ListNotations.

Definition pipeline_rows : Batch := [
{body}
].
Lemma pipeline_rows_checked : batch_check 4096%N 4096%N pipeline_rows = true.
Proof. vm_compute. reflexivity. Qed.
Example pipeline_row_count : length pipeline_rows = {len(rows)}.
Proof. reflexivity. Qed.

Definition pipeline_board : list TM :=
  map (fun row => machine_of_codes (fst row)) pipeline_rows.
Lemma pipeline_board_small_sound : BoardSound 4096%N 4096%N pipeline_board.
Proof.
  intros family Hin tm Hle.
  apply in_map_iff in Hin as ([codes cert] & <- & Hin).
  eapply batch_completions; [exact pipeline_rows_checked|exact Hin|exact Hle].
Qed.
Lemma pipeline_board_sound : BoardSound scoreN scoreN pipeline_board.
Proof.
  intros family Hin tm Hle.
  eapply (bounds_weaken 4096%N 4096%N scoreN scoreN tm).
  - vm_compute. discriminate.
  - vm_compute. discriminate.
  - exact (pipeline_board_small_sound family Hin tm Hle).
Qed.
Definition bootstrap_pipeline_pending := remaining bootstrap_affine_pending pipeline_board.
Theorem bootstrap_pipeline_coverage : forall tm,
  Bounds scoreN scoreN tm \\/ bootstrap_pipeline_pending tm.
Proof.
  exact (closeout_coverage _ _ _ _ bootstrap_affine_coverage pipeline_board_sound).
Qed.

Lemma pipeline_board_pending_checked :
  forallb (pending_check 9 empty bootstrap) pipeline_board = true.
Proof. vm_compute. reflexivity. Qed.
Theorem pipeline_families_discharged : forall family,
  In family pipeline_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\\ Bounds scoreN scoreN tm /\\ ~ bootstrap_pipeline_pending tm.
Proof.
  intros family Hin tm Hle. split.
  - assert (Hp : bootstrap_pending family).
    {{ apply pending_check_sound. pose proof pipeline_board_pending_checked as H.
       apply forallb_forall with (x:=family) in H; assumption. }}
    destruct Hp as (leaf & Hleaf & Hlf).
    exists leaf. split; [exact Hleaf|]. eapply closeout_tm_le_trans; eauto.
  - split; [exact (pipeline_board_sound family Hin tm Hle)|].
    intros [_ Hremaining].
    assert (Hhit : board_check pipeline_board tm = true).
    {{ apply existsb_exists. exists family. split; [exact Hin|].
       apply table_leb_spec. exact Hle. }}
    congruence.
Qed.

Print Assumptions bootstrap_pipeline_coverage.
Print Assumptions pipeline_families_discharged.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads((ROOT/'research/pipeline-examples.json').read_text()))
    path = ROOT/'theories/PipelineExamples.v'
    if args.check:
        if path.read_text() != output:
            raise SystemExit('Pipeline examples differ; regenerate and audit them')
    else:
        path.write_text(output)
    print('Pipeline examples reproduced; Coq checking is required.')


if __name__ == '__main__':
    main()
