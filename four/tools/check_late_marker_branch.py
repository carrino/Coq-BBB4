"""Check one late partial root, every defined child, and the halting choice.

The compact prefix projection is evaluated once; the join reuses its theorem.
No instruction bound or root NonHalt assertion is made.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import time
from check_state_branches import ROOT, REPO, sha
from generate_pipeline_examples import codes

BUILD = ROOT/'build/late-marker-branch'
INPUT = ROOT/'research/late-marker-branch-input.json'


def prefix(data):
    return '''(** Generated late undefined-cell witness. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec CTape Pipeline BranchPrefix.
Import ListNotations.
Definition late_family := machine_of_codes [%s].
Definition late_anchor := %s.
Lemma late_prefix_checked : reached_undefined_cell late_family late_anchor = Some (StB,S3).
Proof. vm_compute; reflexivity. Qed.
Theorem late_survives : exists cc, stepn late_family late_anchor InitES = Some cc.
Proof. exact (reached_undefined_survives _ _ _ _ late_prefix_checked). Qed.
Theorem late_halts : stepn late_family (S late_anchor) InitES = None.
Proof. exact (reached_undefined_halts _ _ _ _ late_prefix_checked). Qed.
Print Assumptions late_halts.
''' % (';'.join(map(str, codes(data['machine']))), data['anchor'])


def generate(data):
    potential, trail = [], []
    for row in data['children']:
        packed = sum(v*17**i for i,v in enumerate(row['codes']))
        if row['kind'] == 'potential':
            potential.append('(mkMPRow '+str(packed)+'%N '+str(row['marker_mask'])+'%N '+
                             ' '.join(str(w)+'%N' for w in row['weights'][1:])+')')
        else:
            trail.append('('+str(packed)+'%N, '+str(row['marker_mask'])+'%N)')
    return r'''(** Generated by check_late_marker_branch.py. STATE ONLY. *)
From Coq Require Import Arith List NArith.
From BBB24 Require Import Statement Spec Census Bootstrap Closeout Pipeline
  StateOnlyCloseout StateBranchJoin BranchPrefix MarkerPotential MarkerTrail.
From BBB24LateMarkerBranch Require Import LatePrefix.
Import ListNotations.
Definition potential_rows : list MPRow := ['''+';'.join(potential)+r'''].
Definition trail_rows : list (N*N) := ['''+';'.join(trail)+r'''].
Lemma potential_checked : mp_batch_check potential_rows = true.
Proof. vm_compute; reflexivity. Qed.
Lemma trail_checked : mt_batch_check trail_rows = true.
Proof. vm_compute; reflexivity. Qed.
Definition child_board := concat [mp_board potential_rows; mt_board trail_rows].
Lemma child_zero_sound : StateBoardSound 0 child_board.
Proof.
  apply state_boards_sound.
  apply Forall_cons; [exact (mp_batch_state_sound _ potential_checked)|].
  apply Forall_cons; [exact (mt_batch_state_sound _ trail_checked)|].
  apply Forall_nil.
Qed.
Definition late_bound := '''+str(data['state_bound'])+r'''%N.
Lemma joined_checked : state_branch_lookup_check late_bound child_board late_family late_anchor = true.
Proof. rewrite state_lookup_reached,late_prefix_checked. vm_compute; reflexivity. Qed.
Example halting_choice_requires_exact_budget :
  state_branch_lookup_check (N.of_nat late_anchor) child_board late_family late_anchor = false.
Proof. rewrite state_lookup_reached. rewrite N.ltb_irrefl. reflexivity. Qed.
Example missing_children_rejected :
  state_branch_lookup_check late_bound [] late_family late_anchor = false.
Proof. rewrite state_lookup_reached,late_prefix_checked. vm_compute; reflexivity. Qed.
Definition branch_state_board := [late_family].
Lemma branch_state_board_small_sound : StateBoardSound (N.to_nat late_bound) branch_state_board.
Proof.
  intros family [<-|[]] tm Hle.
  eapply state_branch_lookup_check_sound; [|exact joined_checked|exact Hle].
  apply state_board_zero_weaken. exact child_zero_sound.
Qed.
Lemma branch_state_board_sound : StateBoardSound score branch_state_board.
Proof.
  eapply (state_board_N_weaken late_bound scoreN).
  - vm_compute; discriminate.
  - exact branch_state_board_small_sound.
Qed.
Lemma pending_checked : forallb (pending_check 9 empty bootstrap) branch_state_board = true.
Proof. vm_compute; reflexivity. Qed.
Lemma branch_state_board_was_pending : forall family,
  In family branch_state_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound. pose proof pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Definition bootstrap_late_marker_pending := remaining bootstrap_pending branch_state_board.
Theorem bootstrap_late_marker_state_coverage : forall tm,
  QHBound score tm \/ bootstrap_late_marker_pending tm.
Proof. exact (state_closeout_coverage _ _ _ bootstrap_state_coverage branch_state_board_sound). Qed.
Theorem late_marker_family_discharged : forall family,
  In family branch_state_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ QHBound score tm /\ ~ bootstrap_late_marker_pending tm.
Proof. exact (state_board_discharge _ _ branch_state_board_was_pending branch_state_board_sound). Qed.
Print Assumptions late_marker_family_discharged.
'''


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--prepare',action='store_true')
    p.add_argument('--reuse-prefix',action='store_true',help='Require existing identical compiled prefix')
    p.add_argument('--timeout',type=int,default=3600)
    a=p.parse_args(); data=json.loads(INPUT.read_text()); table=codes(data['machine'])
    if table[7]!=16 or data['undefined_cell']!=7 or data['state_bound']!=data['anchor']+1:
        raise ValueError('Invalid root, undefined cell or halting bound')
    if len(data['children'])!=16:raise ValueError('Sixteen defined choices are required')
    for v,row in enumerate(data['children']):
        expected=table.copy();expected[7]=v
        if row['codes']!=expected or row['kind'] not in {'potential','trail'}:
            raise ValueError('Missing or wrong defined child')
    BUILD.mkdir(parents=True,exist_ok=True)
    pre=BUILD/'LatePrefix.v'; source=BUILD/'LateMarkerBranch.v'
    if a.reuse_prefix and (not pre.with_suffix('.vo').exists() or pre.read_text()!=prefix(data)):
        raise ValueError('Compiled prefix source differs')
    if not a.reuse_prefix:pre.write_text(prefix(data))
    source.write_text(generate(data));members=BUILD/'machines.txt';members.write_text(data['machine']+'\n')
    flags=['-Q',str(ROOT/'theories'),'BBB24','-Q',str(BUILD),'BBB24LateMarkerBranch']
    module='BBB24LateMarkerBranch.LateMarkerBranch'
    commands=[]
    for path in ([source] if a.reuse_prefix else [pre,source]):
        commands.append((['coqc','-w','-abstract-large-number','-native-compiler','no',*flags,str(path)],path.stem+'-compile.log'))
    if not a.prepare:commands.append((['coqchk','-silent','-bytecode-compiler','yes',*flags,module],'coqchk.log'))
    start=time.monotonic()
    for cmd,log in commands:
        with (BUILD/log).open('w') as out:
            subprocess.run(['nice','-n','10',*cmd],cwd=REPO,stdout=out,stderr=subprocess.STDOUT,check=True,timeout=a.timeout)
    sources={};todo=['BranchPrefix','MarkerPotential','MarkerTrail'];seen=set()
    while todo:
        name=todo.pop()
        if name in seen:continue
        seen.add(name);path=ROOT/'theories'/Path(*name.split('.')).with_suffix('.v')
        sources[str(path.relative_to(REPO))]=sha(path)
        for pref,names in re.findall(r'From\s+(BBB24[\w.]*)\s+Require\s+(?:Import|Export)\s+([\w\s]+)\.',path.read_text()):
            todo.extend('.'.join(pref.split('.')[1:]+[m]) for m in names.split())
    for tool in ['check_late_marker_branch.py','generate_pipeline_examples.py','check_state_branches.py']:
        sources['four/tools/'+tool]=sha(ROOT/'tools'/tool)
    descriptor=dict(kind='state_only',module=module,board=module+'.branch_state_board',
        state_sound=module+'.branch_state_board_sound',state_small_sound=module+'.branch_state_board_small_sound',
        was_pending=module+'.branch_state_board_was_pending',state_discharge=module+'.late_marker_family_discharged',
        state_coverage=module+'.bootstrap_late_marker_state_coverage',state_bound=data['state_bound'],
        members=str(members.relative_to(ROOT)),flags=['-Q','four/theories','BBB24','-Q','four/build/late-marker-branch','BBB24LateMarkerBranch'])
    report=dict(status='queued_for_combined_audit' if a.prepare else 'recursive_coqchk_passed',scope='state_only',
        families=1,partial=1,concrete=0,defined_children=16,halting_choices=1,state_bound=data['state_bound'],instruction_bound=None,
        state_census_linked=None if a.prepare else 1,descriptor=descriptor,input_sha256=sha(INPUT),member_ids_sha256=sha(members),
        source_sha256=sources,generated_source_sha256={p.name:sha(p) for p in [pre,source]},
        proof_object_sha256={str(p.with_suffix('.vo').relative_to(ROOT)):sha(p.with_suffix('.vo')) for p in [pre,source]},
        prefix_survival_theorem='BBB24LateMarkerBranch.LatePrefix.late_survives',
        literal_halt_theorem='BBB24LateMarkerBranch.LatePrefix.late_halts',
        accounting='One original partial family and all completions. Sixteen defined choices have state0; the separate halting choice has exact checked prefix3,932,963. No root NonHalt or instruction claim.',
        validation='Compiled prefix, potential/trail checks, exhaustive branch join, negative regressions and original pending membership; '+('queued for combined recursive audit.' if a.prepare else 'recursive coqchk passed.'))
    dest=ROOT/'research'/('late-marker-branch-queued.json' if a.prepare else 'late-marker-branch-checked.json')
    text=json.dumps(report,indent=2)+'\n'
    if dest.exists() and dest.read_text()!=text:raise ValueError('Frozen late branch report differs')
    dest.write_text(text);print(json.dumps(dict(status=report['status'],families=1,seconds=round(time.monotonic()-start,2))))


if __name__=='__main__':main()
