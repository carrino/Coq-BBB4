"""Attach all audited affine families to the frozen census and closure pilot.

Run make -C four check and check_affine_batch.py first. This stage imports the
existing affine proof shards, checks actual pending membership, and audits an
aggregate coverage theorem. It never changes the frozen batch/progress reports.
Use --refresh to write a new report only after successful kernel checking.
"""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import subprocess
import time

import progress

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT/'build/affine-closeout'
REPORT = ROOT/'research/affine-closeout-summary.json'
LEDGER = ROOT/'research/affine-closeout.tsv'
MODULE = 'BBB24AffineCloseout.AffineCloseoutBatch'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load():
    _, baseline, affine, pipeline, _ = progress.load_evidence()
    report = json.loads((ROOT/'research/affine-batch-summary.json').read_text())
    for name, expected in report['shard_sha256'].items():
        path = ROOT/'build/affine-batch'/name
        if not path.exists() or sha(path) != expected or not path.with_suffix('.vo').exists():
            raise ValueError('Missing/stale affine shard; first run four/tools/check_affine_batch.py')
    accepted = {m:r for m,r in affine.items() if r['status'] == 'coq_checked'}
    for machine, row in accepted.items():
        ns, module, theorem = row['theorem'].split('.')
        if (ns != 'BBB24Batch' or not re.fullmatch(r'AffineBatch\d{3}', module)
                or theorem != 'completions_'+machine.replace('-', 'X')):
            raise ValueError(f'Unexpected completion proof: {row["theorem"]}')
    return baseline, accepted, pipeline, report


def generate(accepted):
    entries, modules = [], set()
    for machine, row in sorted(accepted.items()):
        _, module, _ = row['theorem'].split('.')
        modules.add(module)
        name = machine.replace('-', 'X')
        prefix = f'BBB24Batch.{module}'
        entries.append(f'  mkCertifiedFamily 4096%N 4096%N {prefix}.tm_{name}\n'
                       f'    {prefix}.bounded_{name}')
    first_machine = min(accepted)
    first_module = accepted[first_machine]['theorem'].split('.')[1]
    wrong_proof = f'BBB24Batch.{first_module}.bounded_{first_machine.replace("-", "X")}'
    return '''(** GENERATED by four/tools/check_affine_closeout.py. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout
  AffineCloseout Pipeline PipelineExamples CertifiedBoard ClosureBatch.
From BBB24Batch Require Import ''' + ' '.join(sorted(modules)) + '''.
Import ListNotations.

Definition affine_batch_certified : list (CertifiedFamily 4096%N 4096%N) := [
''' + ';\n'.join(entries) + r'''
].
Definition affine_batch_board := certified_board 4096%N 4096%N affine_batch_certified.
Lemma affine_batch_board_small_sound : BoardSound 4096%N 4096%N affine_batch_board.
Proof. apply certified_board_sound. Qed.
Lemma affine_batch_board_nonhalt : forall family,
  In family affine_batch_board -> NonHalt family.
Proof. apply certified_board_nonhalt. Qed.
Lemma affine_batch_board_sound : BoardSound scoreN scoreN affine_batch_board.
Proof.
  intros family Hin tm Hle.
  eapply (bounds_weaken 4096%N 4096%N scoreN scoreN tm).
  - vm_compute. discriminate.
  - vm_compute. discriminate.
  - exact (affine_batch_board_small_sound family Hin tm Hle).
Qed.

Definition bootstrap_affine_batch_pending :=
  remaining bootstrap_pipeline_pending affine_batch_board.
Theorem bootstrap_affine_batch_coverage : forall tm,
  Bounds scoreN scoreN tm \/ bootstrap_affine_batch_pending tm.
Proof.
  exact (closeout_coverage _ _ _ _ bootstrap_pipeline_coverage affine_batch_board_sound).
Qed.
Lemma affine_batch_pending_checked :
  forallb (pending_check 9 empty bootstrap) affine_batch_board = true.
Proof. vm_compute. reflexivity. Qed.
Lemma affine_batch_was_pending : forall family,
  In family affine_batch_board -> bootstrap_pending family.
Proof.
  intros family Hin. apply pending_check_sound.
  pose proof affine_batch_pending_checked as H.
  apply forallb_forall with (x:=family) in H; assumption.
Qed.
Theorem affine_batch_families_discharged : forall family,
  In family affine_batch_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ Bounds scoreN scoreN tm /\ ~ bootstrap_affine_batch_pending tm.
Proof.
  exact (board_families_discharged _ _ _ _ _ affine_batch_was_pending affine_batch_board_sound).
Qed.

Definition sample_board := affine_batch_board ++ pipeline_board.
Lemma sample_board_small_sound : BoardSound 4096%N 4096%N sample_board.
Proof. apply board_sound_app; [apply affine_batch_board_small_sound|apply pipeline_board_small_sound]. Qed.
Lemma sample_board_sound : BoardSound scoreN scoreN sample_board.
Proof. apply board_sound_app; [apply affine_batch_board_sound|apply pipeline_board_sound]. Qed.
Lemma pipeline_board_nonhalt : forall family,
  In family pipeline_board -> NonHalt family.
Proof.
  intros family Hin. apply in_map_iff in Hin as ([codes cert] & <- & Hin).
  eapply ClosureBatch.batch_nonhalt; [exact pipeline_rows_checked|exact Hin].
Qed.
Lemma sample_board_nonhalt : forall family, In family sample_board -> NonHalt family.
Proof.
  intros family Hin. apply in_app_iff in Hin as [Hin|Hin].
  - apply affine_batch_board_nonhalt; exact Hin.
  - apply pipeline_board_nonhalt; exact Hin.
Qed.
Theorem sample_families_discharged : forall family,
  In family sample_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ Bounds scoreN scoreN tm /\ ~ bootstrap_affine_batch_pending tm.
Proof.
  intros family Hin tm Hle. apply in_app_iff in Hin as [Hin|Hin].
  - exact (affine_batch_families_discharged family Hin tm Hle).
  - destruct (pipeline_families_discharged family Hin tm Hle) as [Hp [Hb Hremoved]].
    split; [exact Hp|]. split; [exact Hb|]. intros [H _]. exact (Hremoved H).
Qed.

(** Deliberately attach a proved family's theorem to a different table. *)
Fail Definition wrong_family_link : CertifiedFamily 4096%N 4096%N :=
  mkCertifiedFamily 4096%N 4096%N champion ''' + wrong_proof + '''.
Example unlisted_champion_still_unmatched : board_check sample_board champion = false.
Proof. vm_compute. reflexivity. Qed.

Print Assumptions bootstrap_affine_batch_coverage.
Print Assumptions sample_families_discharged.
'''


def run(args, log, timeout):
    with log.open('w') as f:
        subprocess.run(args, cwd=ROOT.parent, stdout=f, stderr=subprocess.STDOUT,
                       check=True, timeout=timeout)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--timeout', type=int, default=600)
    args = parser.parse_args()
    baseline, accepted, pipeline, affine_report = load()
    BUILD.mkdir(parents=True, exist_ok=True)
    source = BUILD/'AffineCloseoutBatch.v'
    source.write_text(generate(accepted))
    inputs = ['research/affine-batch.tsv', 'research/affine-batch-summary.json',
              'research/progress-verified.json', 'research/pipeline-examples.json',
              'tools/check_affine_closeout.py', 'tools/progress.py',
              'theories/CertifiedBoard.v', 'theories/ClosureBatch.v']
    hashes = {p:sha(ROOT/p) for p in inputs}
    if not args.refresh:
        expected = json.loads(REPORT.read_text())
        if expected['input_sha256'] != hashes or expected['aggregate_source_sha256'] != sha(source):
            raise ValueError('Closeout evidence changed; audit with --refresh before updating the report')
    flags = ['-Q', str(ROOT/'theories'), 'BBB24', '-Q', str(ROOT/'build/affine-batch'),
             'BBB24Batch', '-Q', str(BUILD), 'BBB24AffineCloseout']
    start = time.monotonic()
    run(['coqc', '-time', '-native-compiler', 'no', *flags, str(source)], BUILD/'compile.log', args.timeout)
    print('Affine closeout aggregate compiled; auditing imported proof shards.', flush=True)
    run(['coqchk', '-silent', '-bytecode-compiler', 'yes', *flags, MODULE],
        BUILD/'coqchk.log', args.timeout)
    union = set(accepted) | set(pipeline)
    rows = []
    for machine in sorted(union):
        rows.append(dict(machine=machine, affine_checked='yes' if machine in accepted else 'no',
                         pipeline_checked='yes' if machine in pipeline else 'no',
                         state_bound=4096, instruction_bound=4096,
                         bounds_theorem=MODULE+'.sample_board_small_sound',
                         census_theorem=MODULE+'.sample_families_discharged', census_linked='yes'))
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, list(rows[0]), delimiter='\t', lineterminator='\n')
    writer.writeheader(); writer.writerows(rows)
    old_links = {m for m,r in baseline.items() if r['census_linked'] == 'yes'} | set(pipeline)
    report = dict(
        scope='All accepted affine families in the frozen sample, composed with the checked closure pilot.',
        affine_families=len(accepted), pipeline_families=len(pipeline),
        overlap=len(set(accepted)&set(pipeline)), sample_census_linked=len(union),
        new_sample_census_linked=len(union-old_links),
        sample_still_unproved=len(baseline)-len(union),
        accounting='Distinct input family IDs only; no revised whole-leaf or raw-table cardinality claim.',
        bounds_theorem=MODULE+'.sample_board_small_sound',
        coverage_theorem=MODULE+'.bootstrap_affine_batch_coverage',
        discharge_theorem=MODULE+'.sample_families_discharged',
        residual_predicate=MODULE+'.bootstrap_affine_batch_pending',
        validation='Aggregate coqc plus recursive coqchk of all imported proof shards; negative wrong-family proof association rejected.',
        input_sha256=hashes, aggregate_source_sha256=sha(source),
        ledger_sha256=hashlib.sha256(buffer.getvalue().encode()).hexdigest(),
        affine_shard_sha256=affine_report['shard_sha256'])
    serialized = json.dumps(report, indent=2)+'\n'
    if args.refresh:
        REPORT.write_text(serialized); LEDGER.write_text(buffer.getvalue())
    elif REPORT.read_text() != serialized or LEDGER.read_text() != buffer.getvalue():
        raise ValueError('Closeout report differs from audited proof output')
    print(json.dumps({'sample_census_linked':len(union), 'new_sample_census_linked':len(union-old_links),
                      'checking_seconds':round(time.monotonic()-start,2)}))


if __name__ == '__main__':
    main()
