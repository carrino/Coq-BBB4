"""Audit one combined census closeout and deduplicate its family ledger.

First run the affine/closure batch and family-transport targets. This stage
imports their proved boards, composes coverage, and recursively audits the
combined theorem. Reports count machine-string family IDs, not raw tables.
"""
import argparse
from collections import Counter
import csv
import hashlib
import io
import json
from pathlib import Path
import subprocess

import generate_advanced_examples
import progress
from generate_pipeline_examples import codes
from check_shadow_links import dependency_hashes
from check_family_transport import SHARD_SIZE as TRANSPORT_SHARD_SIZE

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT/'build/wave-closeout'
REPORT = ROOT/'research/wave2-summary.json'
LEDGER = ROOT/'research/wave2-families.tsv'
SAMPLE = ROOT/'research/wave2-sample.tsv'
MODULE = 'BBB24Wave.WaveCloseout'
LOADPATHS = [('theories', 'BBB24'), ('build/affine-batch', 'BBB24Batch'),
             ('build/affine-closeout', 'BBB24AffineCloseout'),
             ('build/closure-batch', 'BBB24ClosureBatch'),
             ('build/family-transport', 'BBB24Transport'),
             ('build/wave-closeout', 'BBB24Wave')]
SOURCE = r'''(** GENERATED by four/tools/check_wave_closeout.py. *)
From Coq Require Import List NArith.
From BBB24 Require Import Statement Spec Bounds Census Bootstrap Closeout
  CertifiedBoard CensusUnion AdvancedExamples.
From BBB24AffineCloseout Require Import AffineCloseoutBatch.
From BBB24ClosureBatch Require Import ClosureBatchAll.
From BBB24Transport Require Import FamilyTransportCloseout.
Import ListNotations.

Definition wave_boards : list (list TM) :=
  [sample_board; closure_batch_board; advanced_pilot_board; transport_board].
Definition wave_board := concat wave_boards.
Lemma wave_board_sound : BoardSound scoreN scoreN wave_board.
Proof.
  apply boards_sound. unfold wave_boards.
  apply Forall_cons; [exact sample_board_sound|].
  apply Forall_cons; [exact closure_batch_board_sound|].
  apply Forall_cons; [exact advanced_pilot_sound|].
  apply Forall_cons; [exact transport_board_sound|].
  apply Forall_nil.
Qed.

Lemma sample_was_pending : forall family,
  In family sample_board -> bootstrap_pending family.
Proof.
  intros family Hin.
  assert (Hle : TM_le family family) by (intros q s; right; reflexivity).
  exact (proj1 (sample_families_discharged family Hin family Hle)).
Qed.
Lemma wave_board_was_pending : forall family,
  In family wave_board -> bootstrap_pending family.
Proof.
  apply boards_pending. unfold wave_boards.
  apply Forall_cons; [exact sample_was_pending|].
  apply Forall_cons; [exact closure_batch_board_pending|].
  apply Forall_cons; [exact advanced_pilot_was_pending|].
  apply Forall_cons; [exact transport_board_was_pending|].
  apply Forall_nil.
Qed.

Definition wave_pending := remaining bootstrap_pending wave_board.
Theorem wave_coverage : forall tm,
  Bounds scoreN scoreN tm \/ wave_pending tm.
Proof. exact (closeout_coverage _ _ _ _ bootstrap_coverage wave_board_sound). Qed.
Theorem wave_families_discharged : forall family,
  In family wave_board -> forall tm, TM_le family tm ->
  bootstrap_pending tm /\ Bounds scoreN scoreN tm /\ ~ wave_pending tm.
Proof.
  exact (board_families_discharged _ _ _ _ _ wave_board_was_pending wave_board_sound).
Qed.
Theorem wave_upper_if_remaining :
  (forall tm, wave_pending tm -> Bounds scoreN scoreN tm) ->
  forall tm, Bounds scoreN scoreN tm.
Proof.
  exact (closeout_upper_if_remaining _ _ _ _ bootstrap_coverage wave_board_sound).
Qed.
Print Assumptions wave_coverage.
Print Assumptions wave_families_discharged.
'''


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checked_rows(path):
    with path.open() as stream:
        rows = list(csv.DictReader(stream, delimiter='\t'))
    if not rows or len(rows) != len({r['machine'] for r in rows}):
        raise ValueError(f'Empty or duplicate ledger: {path}')
    for row in rows:
        codes(row['machine'])
        if row['census_linked'] != 'yes':
            raise ValueError(f'Unlinked family in board ledger: {path}')
    return rows


def checked_hashes(base, hashes):
    for name, expected in hashes.items():
        if sha(base/name) != expected:
            raise ValueError(f'Audited input changed: {name}')


def inputs_and_rows():
    affine = json.loads((ROOT/'research/affine-closeout-summary.json').read_text())
    closure = json.loads((ROOT/'research/closure-batch-summary.json').read_text())
    transport = json.loads((ROOT/'research/family-transport-summary.json').read_text())
    checked_hashes(ROOT, affine['input_sha256'])
    checked_hashes(ROOT.parent, closure['source_sha256'])
    checked_hashes(ROOT, transport['source_sha256'])
    checked_hashes(ROOT/'build/closure-batch', closure['shard_sha256'])
    checked_hashes(ROOT/'build/family-transport', transport['generated_sha256'])
    if sha(ROOT/'build/affine-closeout/AffineCloseoutBatch.v') != affine['aggregate_source_sha256']:
        raise ValueError('Affine aggregate changed after audit')
    if sha(ROOT/'research/closure-batch-input.json') != closure['input_sha256']:
        raise ValueError('Closure batch inputs changed after audit')
    if sha(ROOT/'research/family-transport-input.json') != transport['input_sha256']:
        raise ValueError('Transport inputs changed after audit')
    advanced = json.loads((ROOT/'research/advanced-examples.json').read_text())
    if (ROOT/'theories/AdvancedExamples.v').read_text() != generate_advanced_examples.generate(advanced):
        raise ValueError('Advanced pilot differs from its proof source')
    groups = {
        'affine_and_pilot': checked_rows(ROOT/'research/affine-closeout.tsv'),
        'closure_batch': checked_rows(ROOT/'research/closure-batch.tsv'),
        'transport': checked_rows(ROOT/'research/family-transport.tsv'),
        'advanced_pilot': advanced['rows'],
    }
    if sha(ROOT/'research/affine-closeout.tsv') != affine['ledger_sha256']:
        raise ValueError('Affine closeout ledger differs from its audited report')
    closure_input = json.loads((ROOT/'research/closure-batch-input.json').read_text())
    closure_machines = {row[0] for row in closure_input['rows']}
    if {row['machine'] for row in groups['closure_batch']} != closure_machines:
        raise ValueError('Closure ledger differs from its checked input tables')
    expected_counts = {'affine_and_pilot': affine['sample_census_linked'],
                       'closure_batch': closure['checked_families'],
                       'transport': transport['counts']['census_linked_families']}
    if any(len(groups[k]) != count for k, count in expected_counts.items()):
        raise ValueError('Board ledger count differs from its audit report')
    transport_proofs, transport_expected = {}, {}
    transport_input = json.loads((ROOT/'research/family-transport-input.json').read_text())
    for key, route, stem, bound in [('images', 'symbol_reflection', 'ImageFamilies', 4096),
                                    ('shadow_images', 'blank_prefix_then_symbols', 'ShadowFamilies', 4097)]:
        for index, row in enumerate(transport_input[key]):
            machine = row[0]
            transport_proofs[machine] = f'BBB24Transport.{stem}{index//TRANSPORT_SHARD_SIZE:03}.board_strong'
            transport_expected[machine] = (route, bound)
    if {row['machine'] for row in groups['transport']} != set(transport_expected):
        raise ValueError('Transport ledger differs from its checked input tables')
    for row in groups['transport']:
        route, bound = transport_expected[row['machine']]
        if row['route'] != route or int(row['state_bound']) != bound or int(row['instruction_bound']) != bound:
            raise ValueError('Transport route/bounds differ from the checked proof shard')
    families = {}
    for method, rows in groups.items():
        for row in rows:
            machine = row['machine']; codes(machine)
            bs = int(row.get('state_bound', row.get('bound', 0)))
            bi = int(row.get('instruction_bound', row.get('bound', 0)))
            if bs not in (4096, 4097) or bi != bs:
                raise ValueError('Unexpected recorded score bound')
            theorem = (row['bounds_theorem'] if method == 'affine_and_pilot' else
                       'BBB24ClosureBatch.ClosureBatchAll.closure_batch_board_small_sound'
                       if method == 'closure_batch' else
                       'BBB24.AdvancedExamples.advanced_pilot_small_sound'
                       if method == 'advanced_pilot' else transport_proofs[machine])
            record = families.setdefault(machine, {'machine':machine, 'methods':[],
                'state_bound':bs, 'instruction_bound':bi, 'census_linked':'yes',
                'bounds_theorem':theorem,
                'census_theorem':MODULE+'.wave_families_discharged'})
            record['methods'].append(method)
            if bs < record['state_bound']:
                record['bounds_theorem'] = theorem
            record['state_bound'] = min(record['state_bound'], bs)
            record['instruction_bound'] = min(record['instruction_bound'], bi)
    for row in families.values():
        row['methods'] = ','.join(sorted(row['methods']))
    baseline_outputs, _ = progress.build()
    if (ROOT/'research/progress-sample.tsv').read_text() != baseline_outputs['progress-sample.tsv']:
        raise ValueError('Baseline sample ledger differs from its audited evidence')
    with (ROOT/'research/progress-sample.tsv').open() as stream:
        sample = list(csv.DictReader(stream, delimiter='\t'))
    if len(sample) != 1024 or len({r['machine'] for r in sample}) != 1024:
        raise ValueError('Wrong baseline sample inventory')
    for row in sample:
        if row['machine'] in families:
            proof = families[row['machine']]
            row.update(status='coq_checked', state_bound=proof['state_bound'],
                       instruction_bound=proof['instruction_bound'],
                       census_linked='yes', census_proof=proof['census_theorem'],
                       proof=proof['bounds_theorem'])
        elif row['status'] == 'coq_checked':
            raise ValueError('Combined board lost an existing proved sample family')
    paths = ['research/'+name for name in (
        'affine-closeout-summary.json', 'affine-closeout.tsv',
        'closure-batch-summary.json', 'closure-batch.tsv',
        'family-transport-summary.json', 'family-transport-input.json', 'family-transport.tsv',
        'advanced-examples.json', 'progress-sample.tsv')]
    paths += ['tools/check_wave_closeout.py', 'tools/generate_advanced_examples.py']
    return {name:sha(ROOT/name) for name in paths}, groups, families, sample


def tsv(rows):
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, list(rows[0]), delimiter='\t', lineterminator='\n')
    writer.writeheader(); writer.writerows(rows)
    return buffer.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true')
    parser.add_argument('--timeout', type=int, default=1800)
    args = parser.parse_args()
    # During refresh, proof boards can be audited while the independent board
    # audits finish publishing their reports. No ledger is emitted until all
    # those reports validate against the same, unchanged proof sources.
    evidence = None if args.refresh else inputs_and_rows()
    BUILD.mkdir(parents=True, exist_ok=True)
    source = BUILD/'WaveCloseout.v'; source.write_text(SOURCE)
    flags = [part for path, namespace in LOADPATHS for part in ('-Q', str(ROOT/path), namespace)]
    sources = dependency_hashes([source], flags)
    if not args.refresh:
        inputs, groups, families, sample = evidence
        old = json.loads(REPORT.read_text())
        if old['input_sha256'] != inputs or old['source_sha256'] != sources:
            raise ValueError('Wave evidence changed; --refresh requires a new audit')
    for command, log in [(['coqc', '-native-compiler', 'no', *flags, str(source)], 'compile.log'),
                         (['coqchk', '-silent', '-bytecode-compiler', 'yes', *flags, MODULE], 'coqchk.log')]:
        with (BUILD/log).open('w') as output:
            subprocess.run(command, cwd=ROOT.parent, stdout=output, stderr=subprocess.STDOUT,
                           check=True, timeout=args.timeout)
    if sources != dependency_hashes([source], flags):
        raise ValueError('Proof sources changed during audit')
    inputs, groups, families, sample = inputs_and_rows()
    if evidence is not None and inputs != evidence[0]:
        raise ValueError('Board evidence changed during audit')
    family_text = tsv([families[m] for m in sorted(families)])
    sample_text = tsv(sorted(sample, key=lambda row:row['machine']))
    report = {
        'scope':'Distinct proved family IDs in the frozen survey; not raw-table or whole-leaf cardinalities',
        'census_linked_families':len(families),
        'source_family_counts':{k:len(v) for k,v in groups.items()},
        'sample_size':len(sample),
        'sample_status_counts':dict(sorted(Counter(r['status'] for r in sample).items())),
        'sample_census_linked':sum(r['census_linked']=='yes' for r in sample),
        'coverage_theorem':MODULE+'.wave_coverage',
        'discharge_theorem':MODULE+'.wave_families_discharged',
        'residual_predicate':MODULE+'.wave_pending',
        'validation':'Compilation and recursive coqchk of the combined coverage and discharge theorems',
        'accounting':'Duplicate family IDs are counted once; all completions covered; original structural weights unchanged',
        'input_sha256':inputs, 'source_sha256':sources,
        'families_sha256':hashlib.sha256(family_text.encode()).hexdigest(),
        'sample_sha256':hashlib.sha256(sample_text.encode()).hexdigest(),
    }
    outputs = {REPORT:json.dumps(report, indent=2)+'\n', LEDGER:family_text, SAMPLE:sample_text}
    for path, contents in outputs.items():
        if args.refresh:
            path.write_text(contents)
        elif path.read_text() != contents:
            raise ValueError(f'Wave evidence differs: {path}')
    print(json.dumps({k:report[k] for k in ('census_linked_families','sample_status_counts','sample_census_linked')}))


if __name__ == '__main__':
    main()
