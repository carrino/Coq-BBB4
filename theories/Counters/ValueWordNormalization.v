(** * Unary normalization of the period-three frontier rewrite.

    [vwn_Halt] means eventual arrival at the B0 instruction, not machine
    halting.  It is generated by the exact terminal scan and frontier
    rewrite.  Prefixes P0 and P3 preserve this property.  Normalizing U n
    depends only on n modulo three: it preserves the suffix, adds a
    pending [1010], or reaches B0 independently of the suffix.

    The word lemmas are constructive and independent of any machine.
    [vwn_Halt_sound] interprets a derivation as a positive finite run. *)
From Coq Require Import Arith Lia List.
From BBB4 Require Import BBB4_Statement BBBT4_Statement CTape.
From BBB4.Counters Require Import ValueFrontierTransducer.
Import ListNotations.
Inductive vwn_Halt:list Sym->Prop:=
| vwn_terminal:forall ms n R,vwn_Halt(vft_Ps ms++vft_zig n++S0::R)
| vwn_round:forall ms n R,
 vwn_Halt(vft_Us ms++vft_U n++S1::S0::R)->
 vwn_Halt(vft_Ps ms++vft_Q n++R).
Lemma vwn_P0:forall R,vwn_Halt R->vwn_Halt(vft_P 0++R).
Proof.
 intros R H;induction H as[ms n R|ms n R H IH].
 - change(vwn_Halt(vft_Ps(0::ms)++vft_zig n++S0::R)). apply vwn_terminal.
 - change(vwn_Halt(vft_Ps(0::ms)++vft_Q n++R)). apply vwn_round.
   exact IH.
Qed.
Lemma vwn_U1:forall R,
 vwn_Halt(vft_P 0++vft_zig 2++R)->vwn_Halt(vft_U 1++R).
Proof.
 intros R H. change(vwn_Halt(vft_Ps []++vft_Q 0++S1::S0::R)).
 apply vwn_round. exact H.
Qed.
Lemma vwn_U3:forall R,
 vwn_Halt(vft_P 0++vft_P 0++vft_P 3++R)->vwn_Halt(vft_U 3++R).
Proof.
 intros R H. change(vwn_Halt(vft_Ps []++vft_Q 0++S1::S1::S1::S1::S1::S0::R)).
 apply vwn_round.
 change(vwn_Halt(vft_Ps[0]++vft_Q 1++S1::S1::S0::R)). apply vwn_round.
 change(vwn_Halt(vft_Ps[0]++vft_Q 0++S1::S0::S1::S0::S1::S1::S0::R)).
 apply vwn_round. exact H.
Qed.
Lemma vwn_P3:forall R,vwn_Halt R->vwn_Halt(vft_P 3++R).
Proof.
 intros R H;induction H as[ms n R|ms n R H IH].
 - change(vwn_Halt(vft_Ps(3::ms)++vft_zig n++S0::R)). apply vwn_terminal.
 - change(vwn_Halt(vft_Ps(3::ms)++vft_Q n++R)). apply vwn_round.
   change(vwn_Halt(vft_U 3++(vft_Us ms++vft_U n++S1::S0::R))).
   apply vwn_U3,vwn_P0,vwn_P0. exact IH.
Qed.
Lemma vwn_cycle1:forall R,
 vwn_Halt(vft_zig 1++R)->vwn_Halt(vft_zig 1++repeat S1 6++R).
Proof.
 intros R H.
 change(vwn_Halt(vft_Ps []++vft_Q 1++S1::S1::S1::R)). apply vwn_round.
 change(vwn_Halt(vft_U 1++S1::S0::S1::S1::S1::R)). apply vwn_U1,vwn_P0.
 change(vwn_Halt(vft_Ps []++vft_Q 3++R)). apply vwn_round.
 change(vwn_Halt(vft_U 3++(vft_zig 1++R))).
 apply vwn_U3,vwn_P0,vwn_P0,vwn_P3. exact H.
Qed.
Lemma vwn_cycles1:forall k R,
 vwn_Halt(vft_zig 1++R)->vwn_Halt(vft_zig 1++repeat S1(6*k)++R).
Proof.
 induction k as[|k IH];intros R H;[exact H|].
 replace(6*S k)with(6+6*k)by lia. rewrite repeat_app,<-app_assoc.
 apply vwn_cycle1. now apply IH.
Qed.
Lemma vwn_unary2:forall k R,
 vwn_Halt R->vwn_Halt(repeat S1(6*k+2)++S0::R).
Proof.
 intros k R H;destruct k as[|k].
 - change(vwn_Halt(vft_P 0++R)). now apply vwn_P0.
 - replace(6*S k+2)with(3+(6*k+5))by lia.
   change(vwn_Halt(vft_Ps []++vft_Q 0++repeat S1(6*k+5)++S0::R)).
   apply vwn_round.
   change(vwn_Halt(vft_P 0++(vft_zig 1++repeat S1(6*k+5)++S0::R))).
   apply vwn_P0. rewrite repeat_app,<-app_assoc. apply vwn_cycles1.
   change(vwn_Halt(vft_Ps []++vft_Q 1++S1::S1::S0::R)). apply vwn_round.
   change(vwn_Halt(vft_U 1++S1::S0::S1::S1::S0::R)). apply vwn_U1,vwn_P0.
   change(vwn_Halt(vft_P 3++R)). now apply vwn_P3.
Qed.
Lemma vwn_unary4:forall k R,
 vwn_Halt(vft_zig 2++R)->vwn_Halt(repeat S1(6*k+4)++S0::R).
Proof.
 intros k R H. replace(6*k+4)with(3+(6*k+1))by lia.
 change(vwn_Halt(vft_Ps []++vft_Q 0++repeat S1(6*k+1)++S0::R)).
 apply vwn_round.
 change(vwn_Halt(vft_P 0++(vft_zig 1++repeat S1(6*k+1)++S0::R))).
 apply vwn_P0. rewrite repeat_app,<-app_assoc. apply vwn_cycles1. exact H.
Qed.
Lemma vwn_unary6:forall k R,vwn_Halt(repeat S1(6*k+6)++S0::R).
Proof.
 intros k R. replace(6*k+6)with(3+(6*k+3))by lia.
 change(vwn_Halt(vft_Ps []++vft_Q 0++repeat S1(6*k+3)++S0::R)).
 apply vwn_round.
 change(vwn_Halt(vft_P 0++(vft_zig 1++repeat S1(6*k+3)++S0::R))).
 apply vwn_P0. rewrite repeat_app,<-app_assoc. apply vwn_cycles1.
 change(vwn_Halt(vft_Ps []++vft_Q 1++S0::R)). apply vwn_round.
 change(vwn_Halt(vft_U 1++S1::S0::S0::R)). apply vwn_U1,vwn_P0.
 change(vwn_Halt(vft_Ps []++vft_zig 3++S0::R)). apply vwn_terminal.
Qed.
Theorem vwn_Us0:forall k R,vwn_Halt R->vwn_Halt(vft_U(3*k)++R).
Proof.
 intros k R H. unfold vft_U. rewrite <-app_assoc. cbn[app].
 replace(2*(3*k)+2)with(6*k+2)by lia. now apply vwn_unary2.
Qed.
Theorem vwn_Us1:forall k R,
 vwn_Halt(vft_zig 2++R)->vwn_Halt(vft_U(3*k+1)++R).
Proof.
 intros k R H. unfold vft_U. rewrite <-app_assoc. cbn[app].
 replace(2*(3*k+1)+2)with(6*k+4)by lia. now apply vwn_unary4.
Qed.
Theorem vwn_Us2:forall k R,vwn_Halt(vft_U(3*k+2)++R).
Proof.
 intros k R. unfold vft_U. rewrite <-app_assoc. cbn[app].
 replace(2*(3*k+2)+2)with(6*k+6)by lia. apply vwn_unary6.
Qed.
Section Machine.
Variable tm:TM.
Hypothesis HA0:tm StA S0=Some(mkTrans S1 DR StB).
Hypothesis HA1:tm StA S1=Some(mkTrans S0 DL StC).
Hypothesis HB1:tm StB S1=Some(mkTrans S1 DR StD).
Hypothesis HC0:tm StC S0=Some(mkTrans S1 DL StA).
Hypothesis HC1:tm StC S1=Some(mkTrans S1 DL StC).
Hypothesis HD0:tm StD S0=Some(mkTrans S1 DR StB).
Hypothesis HD1:tm StD S1=Some(mkTrans S0 DR StA).
Theorem vwn_Halt_sound:forall w,vwn_Halt w->
 exists k L R,0<k /\
 stepn tm k(lift(StA,([],S0,w)))=Some(lift(StB,(L,S0,R))).
Proof.
 intros w H;induction H as[ms n R|ms n R H IH].
 - destruct(vft_terminal_explicit tm HA0 HB1 HD0 HD1 ms n [] R)
   as[k[L[Hpos Hk]]]. exists k,L,R. split;[exact Hpos|].
   exact(csteps_lift tm k _ _ Hk).
 - destruct(vft_frontier tm HA0 HA1 HB1 HC0 HC1 HD0 HD1 ms n R)
   as[k[Hpos Hk]]. destruct IH as[j[L[R'[Hpos' Hj]]]].
   exists(k+j),L,R'. split;[lia|]. now rewrite stepn_add,Hk.
Qed.
End Machine.
