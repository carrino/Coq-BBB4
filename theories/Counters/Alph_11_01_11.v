(** * Alph_11_01_11: an INFERRED counter word alphabet.

    Generated by tools/counters/gen_alphabet.py from a family read off the
    tape by tools/counters/alphabet_infer.py.  Every counter alphabet in this
    development ([ILCounter.Ip], [JpCounter.Jp], [KpCounter.Kp],
    [DpCounter.Dp], [MpCounter.Mp], [BpCounter.Bp]) has the shape

      E xH = C        E (xO q) = A ++ E q        E (xI q) = B ++ E q

    and the two decomposition lemmas below are the SAME induction for every
    choice of A, B and C.  Here

      A = [S1; S1]        B = [S0; S1]        C = [S1; S1]

    verified against the machine's own tape for 0 consecutive anchor words
    before this file was generated.  The generator is untrusted: a wrong
    triple does not typecheck, because the lemmas are proved rather than
    assumed.

    Axiom footprint: none (closed under the global context). *)

From Coq Require Import Arith Lia Bool List PArith.
From BBB4 Require Import BBB4_Statement CTape.
From BBB4.Counters Require Import WTape MonoCounter.
Import ListNotations.

Fixpoint Ap_Alph_11_01_11 (p : positive) : list Sym :=
  match p with
  | xH => [S1; S1]
  | xO q => [S1; S1] ++ Ap_Alph_11_01_11 q
  | xI q => [S0; S1] ++ Ap_Alph_11_01_11 q
  end.

(** Interior increment: [j] trailing set bits clear and the first clear bit
    sets, so a run of [B] becomes a run of [A] and the stop digit swaps. *)
Lemma cview_some_Alph_11_01_11 : forall p j q, cview p = (j, Some q) ->
  Ap_Alph_11_01_11 p = rep [S0; S1] j ++ [S1; S1] ++ Ap_Alph_11_01_11 q /\
  Ap_Alph_11_01_11 (Pos.succ p) = rep [S1; S1] j ++ [S0; S1] ++ Ap_Alph_11_01_11 q.
Proof.
  induction p; intros j q H; simpl in H.
  - destruct (cview p) as [j' r] eqn:E. inversion H; subst j r.
    destruct (IHp j' q eq_refl) as (H1 & H2).
    split; simpl; [rewrite H1 | rewrite H2]; reflexivity.
  - inversion H; subst j q. split; reflexivity.
  - discriminate.
Qed.

(** Overflow, [p = 2^(j+1) - 1]: the whole word is a run of [B] over the
    terminator, and the increment turns it into a longer run of [A]. *)
Lemma cview_none_Alph_11_01_11 : forall p j, cview p = (S j, None) ->
  Ap_Alph_11_01_11 p = rep [S0; S1] j ++ [S1; S1] /\
  Ap_Alph_11_01_11 (Pos.succ p) = rep [S1; S1] (S j) ++ [S1; S1].
Proof.
  induction p; intros j H; simpl in H.
  - destruct (cview p) as [j' r] eqn:E. inversion H; subst j' r.
    destruct j as [|j].
    + (* cview p = (0, None) is impossible *)
      exfalso. destruct p; simpl in E.
      * destruct (cview p) as [jj rr]; discriminate.
      * discriminate.
      * discriminate.
    + destruct (IHp j eq_refl) as (H1 & H2).
      split; simpl; [rewrite H1 | rewrite H2]; reflexivity.
  - discriminate.
  - inversion H; subst j. split; reflexivity.
Qed.
